package library_book_service.ratelimit;

import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.security.oauth2.server.resource.authentication.JwtAuthenticationToken;
import org.springframework.stereotype.Component;
import org.springframework.web.servlet.HandlerInterceptor;

/**
 * Enforces {@link RateLimitConfig}'s baked per-endpoint {@code @rateLimit} overrides and per-plan
 * RPM/daily limits for library.BookService.
 *
 * <p>{@code preHandle} consults {@link RateLimitConfig#ENDPOINT_OVERRIDES} via a plain method call
 * on the GENERATED {@link RateLimiter} -- this IS the completed {@code @rateLimit} decorator
 * lowering (D8); no Spring or resilience4j rate-limiting annotation exists anywhere in the
 * generated tree for this concern.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class RateLimitInterceptor implements HandlerInterceptor {

  private static final int DEFAULT_WINDOW_SECONDS = 60;
  private static final String PLAN_HEADER_PREFIX = "X-RateLimit-";

  private final RateLimiter rateLimiter;

  public RateLimitInterceptor(RateLimiter rateLimiter) {
    this.rateLimiter = rateLimiter;
  }

  @Override
  public boolean preHandle(HttpServletRequest request, HttpServletResponse response, Object handler)
      throws IOException {
    String endpointKey = request.getMethod() + ":" + request.getRequestURI();
    String clientKey = clientKey(request);
    RateLimitConfig.EndpointOverride override = RateLimitConfig.ENDPOINT_OVERRIDES.get(endpointKey);

    if (override != null) {
      RateLimiter.LimitResult result =
          this.rateLimiter.checkWindow(clientKey, override.requests(), override.window());
      return applyResult(response, result);
    }

    String planId = resolvePlanId();
    RateLimitConfig.PlanLimit plan = RateLimitConfig.planLimits(planId);
    RateLimiter.LimitResult windowResult =
        this.rateLimiter.checkWindow(clientKey, plan.rpm() + plan.burst(), DEFAULT_WINDOW_SECONDS);
    if (!windowResult.allowed()) {
      return applyResult(response, windowResult);
    }
    RateLimiter.LimitResult dailyResult =
        this.rateLimiter.checkDailyQuota(clientKey + ":" + planId, plan.daily());
    return applyResult(response, dailyResult);
  }

  private boolean applyResult(HttpServletResponse response, RateLimiter.LimitResult result)
      throws IOException {
    response.setHeader(PLAN_HEADER_PREFIX + "Limit", String.valueOf(result.limit()));
    response.setHeader(PLAN_HEADER_PREFIX + "Remaining", String.valueOf(result.remaining()));
    response.setHeader(PLAN_HEADER_PREFIX + "Reset", String.valueOf(result.resetAtEpochSeconds()));
    if (!result.allowed()) {
      response.setHeader("Retry-After", String.valueOf(result.retryAfterSeconds()));
      response.setStatus(429);
      response.setContentType("application/problem+json");
      response
          .getWriter()
          .write(
              "{\"type\":\"urn:datrix:error:rate-limit-exceeded\",\"title\":\"Too Many"
                  + " Requests\",\"status\":429}");
      return false;
    }
    return true;
  }

  private String resolvePlanId() {
    Authentication auth = SecurityContextHolder.getContext().getAuthentication();
    if (auth instanceof JwtAuthenticationToken jwtAuth) {
      Jwt jwt = jwtAuth.getToken();
      for (String claimName : new String[] {"plan", "planId", "plan_id"}) {
        Object value = jwt.getClaim(claimName);
        if (value != null && !String.valueOf(value).isBlank()) {
          return String.valueOf(value);
        }
      }
    }
    return RateLimitConfig.DEFAULT_PLAN_ID;
  }

  private String clientKey(HttpServletRequest request) {
    Authentication auth = SecurityContextHolder.getContext().getAuthentication();
    if (auth instanceof JwtAuthenticationToken jwtAuth) {
      String subject = jwtAuth.getToken().getSubject();
      if (subject != null && !subject.isBlank()) {
        return "u:" + subject;
      }
    }
    String forwarded = request.getHeader("x-forwarded-for");
    if (forwarded != null && !forwarded.isBlank()) {
      return "ip:" + forwarded.split(",")[0].trim();
    }
    return "ip:" + request.getRemoteAddr();
  }
}
