package library_book_service.ratelimit;

import java.util.LinkedHashMap;
import java.util.Map;
import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.InterceptorRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

/**
 * Per-plan and per-endpoint rate-limit constants for library.BookService, plus the {@link
 * RateLimitInterceptor} registration.
 *
 * <p>{@link #ENDPOINT_OVERRIDES} is where the DSL {@code @rateLimit} decorator's lowering completes
 * (D8): its values are read directly by the GENERATED {@link RateLimitInterceptor} -- never a
 * Spring or resilience4j rate-limit annotation on the controller method.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
public class RateLimitConfig implements WebMvcConfigurer {

  /** One configured plan's baked limits: requests/minute, daily quota, burst allowance. */
  public record PlanLimit(int rpm, int daily, int burst) {}

  /** A per-endpoint {@code @rateLimit} override: max requests within a sliding window (seconds). */
  public record EndpointOverride(int requests, int window) {}

  public static final String DEFAULT_PLAN_ID = "default";

  public static final Map<String, PlanLimit> RATE_LIMIT_PLANS = buildPlans();

  public static final Map<String, EndpointOverride> ENDPOINT_OVERRIDES = buildOverrides();

  private final RateLimitInterceptor rateLimitInterceptor;

  public RateLimitConfig(RateLimitInterceptor rateLimitInterceptor) {
    this.rateLimitInterceptor = rateLimitInterceptor;
  }

  @Override
  public void addInterceptors(InterceptorRegistry registry) {
    registry.addInterceptor(this.rateLimitInterceptor);
  }

  private static Map<String, PlanLimit> buildPlans() {
    Map<String, PlanLimit> plans = new LinkedHashMap<>();
    plans.put("default", new PlanLimit(60, 10000, 0));
    return plans;
  }

  private static Map<String, EndpointOverride> buildOverrides() {
    Map<String, EndpointOverride> overrides = new LinkedHashMap<>();
    overrides.put("GET:/api/v1/books/search", new EndpointOverride(100, 60));
    overrides.put("GET:/api/v1/books/catalog", new EndpointOverride(200, 60));
    return overrides;
  }

  /** Return the configured plan id matching {@code planId} case-insensitively. */
  public static String canonicalPlanId(String planId) {
    if (RATE_LIMIT_PLANS.containsKey(planId)) {
      return planId;
    }
    for (String configured : RATE_LIMIT_PLANS.keySet()) {
      if (configured.equalsIgnoreCase(planId)) {
        return configured;
      }
    }
    throw new IllegalArgumentException(
        "Unknown rate-limit plan '" + planId + "'. Available: " + RATE_LIMIT_PLANS.keySet());
  }

  /** Return the baked {@link PlanLimit} for {@code planId} (case-insensitive). */
  public static PlanLimit planLimits(String planId) {
    return RATE_LIMIT_PLANS.get(canonicalPlanId(planId));
  }
}
