package library_member_service;

import io.micrometer.core.instrument.Gauge;
import io.micrometer.core.instrument.MeterRegistry;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;
import org.springframework.stereotype.Component;

/**
 * Shared Micrometer gauges for RDBMS connection-pool monitoring, registered once per service so
 * every per-block {@code DataSourceConfig} reports against the SAME meter names (a duplicate meter
 * name per block would collide in Micrometer's registry) -- Java analog of python's {@code
 * rdbms_metrics.py.j2}.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class RdbmsMetrics {

  private static final String POOL_SIZE_METRIC = "rdbms.pool.size";
  private static final String POOL_CHECKED_OUT_METRIC = "rdbms.pool.checked_out";
  private static final String BLOCK_TAG = "block";

  private final MeterRegistry registry;
  private final ConcurrentHashMap<String, AtomicInteger> poolSizeByBlock =
      new ConcurrentHashMap<>();
  private final ConcurrentHashMap<String, AtomicInteger> checkedOutByBlock =
      new ConcurrentHashMap<>();

  public RdbmsMetrics(MeterRegistry registry) {
    this.registry = registry;
  }

  /** Record the maximum pool size (maximumPoolSize) for one block. */
  public void recordPoolSize(String block, int size) {
    holder(poolSizeByBlock, POOL_SIZE_METRIC, block).set(size);
  }

  /** Record the currently checked-out connection count for one block. */
  public void recordCheckedOut(String block, int checkedOut) {
    holder(checkedOutByBlock, POOL_CHECKED_OUT_METRIC, block).set(checkedOut);
  }

  private AtomicInteger holder(
      ConcurrentHashMap<String, AtomicInteger> gauges, String metricName, String block) {
    return gauges.computeIfAbsent(
        block,
        key -> {
          AtomicInteger value = new AtomicInteger(0);
          Gauge.builder(metricName, value, AtomicInteger::get)
              .tag(BLOCK_TAG, key)
              .register(registry);
          return value;
        });
  }
}
