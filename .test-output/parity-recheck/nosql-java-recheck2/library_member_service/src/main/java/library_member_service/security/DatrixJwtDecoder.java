/**
 * Multi-provider JWKS-based {@link JwtDecoder} for library.MemberService.
 *
 * <p>Mirrors the verification semantics of datrix-codegen-python's {@code
 * identity.py.j2::validate_token_claims}: asymmetric-only algorithms (symmetric HS* and {@code alg:
 * none} are REJECTED before any signature verification is attempted), audience-enforced,
 * fail-closed JWKS refresh (a JWKS fetch/parse failure never silently accepts a token), and
 * issuer+audience provider disambiguation for multiple providers that share one issuer (D9).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
