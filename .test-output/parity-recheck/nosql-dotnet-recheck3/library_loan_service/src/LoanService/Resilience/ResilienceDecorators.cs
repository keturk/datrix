/// <summary>
/// Generated resilience layer for endpoint-level <c>@retry</c> decorators.
/// Auto-generated by datrix-codegen-dotnet. Do not edit manually.
/// </summary>
public static class ResilienceDecorators
{
    /// <summary>
    /// Execute <paramref name="action"/> under an ad-hoc Polly v8 retry
    /// pipeline built from <paramref name="maxAttempts"/> (the decorator's own
    /// literal argument, never a pre-declared resilience profile).
    /// </summary>
    public static async Task<T> RetryAsync<T>(
        int maxAttempts,
        Func<CancellationToken, Task<T>> action,
        CancellationToken cancellationToken = default
    )
    {
        var pipeline = new Polly.ResiliencePipelineBuilder<T>()
            .AddRetry(
                new Polly.Retry.RetryStrategyOptions<T>
                {
                    MaxRetryAttempts = Math.Max(1, maxAttempts) - 1,
                    BackoffType = Polly.DelayBackoffType.Exponential,
                }
            )
            .Build();
        return await pipeline
            .ExecuteAsync(async ct => await action(ct).ConfigureAwait(false), cancellationToken)
            .ConfigureAwait(false);
    }
}
