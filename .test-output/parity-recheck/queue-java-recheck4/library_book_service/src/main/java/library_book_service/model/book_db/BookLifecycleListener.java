package library_book_service.model.book_db;

import jakarta.persistence.PostPersist;
import jakarta.persistence.PostUpdate;
import jakarta.persistence.PrePersist;
import library_book_service.SpringContextHolder;
import library_book_service.enums.BookStatus;
import library_book_service.queue.BookServiceQueueClient;

/**
 * Lifecycle listener for Book.
 *
 * <p>Explicit entity-listener snapshot pattern (never Hibernate dirty-tracking or interceptor SPI)
 * backs isChanged()/oldValue() semantics -- see Book's own {@code datrixOldValues} field /
 * {@code @PostLoad} snapshot.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
public class BookLifecycleListener {

  @PrePersist
  public void onPrePersist(Book target) {
    target.setCatalogNumber(
        "CAT-%s"
            .formatted(
                java.util.concurrent.ThreadLocalRandom.current()
                    .ints(48, 123)
                    .filter(i -> (i <= 57 || i >= 65) && (i <= 90 || i >= 97))
                    .limit(8)
                    .collect(
                        StringBuilder::new, StringBuilder::appendCodePoint, StringBuilder::append)
                    .toString()
                    .toUpperCase()));
  }

  @PostPersist
  public void onPostPersist(Book target) {
    target.setStatus(BookStatus.AVAILABLE);
    SpringContextHolder.getBean(BookServiceQueueClient.class)
        .dispatchIndexBook(target.getId(), target.getTitle(), target.getAuthor());
    SpringContextHolder.getBean(BookServiceQueueClient.class)
        .dispatchGenerateBookCover(target.getId(), target.getTitle());
  }

  @PostUpdate
  public void onPostUpdate(Book target) {
    if (!java.util.Objects.equals(target.getDatrixOldValues().get("status"), target.getStatus())) {
      SpringContextHolder.getBean(BookServiceQueueClient.class)
          .dispatchIndexBook(target.getId(), target.getTitle(), target.getAuthor());
    }
  }
}
