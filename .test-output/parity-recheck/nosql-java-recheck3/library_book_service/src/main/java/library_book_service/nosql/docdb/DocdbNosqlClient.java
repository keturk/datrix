package library_book_service.nosql.docdb;

import static org.bson.codecs.configuration.CodecRegistries.fromProviders;
import static org.bson.codecs.configuration.CodecRegistries.fromRegistries;

import com.mongodb.ConnectionString;
import com.mongodb.MongoClientSettings;
import com.mongodb.client.MongoClient;
import com.mongodb.client.MongoClients;
import com.mongodb.client.MongoDatabase;
import library_book_service.config.RemoteConfig;
import library_book_service.security.SecretsResolver;
import org.bson.codecs.configuration.CodecRegistry;
import org.bson.codecs.pojo.PojoCodecProvider;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * NoSQL client configuration for the 'docdb' block (mongodb).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
public class DocdbNosqlClient {

  @Bean(name = "docdbMongoClient")
  public MongoClient docdbMongoClient(RemoteConfig remoteConfig, SecretsResolver secretsResolver) {
    String uri;
    String host = remoteConfig.getDocdbHost();
    int port = 27017;
    String user = remoteConfig.getDocdbUser();
    String password = secretsResolver.getSecret("docdb_secret-key");
    uri = "mongodb://" + user + ":" + password + "@" + host + ":" + port + "/?authSource=admin";
    CodecRegistry pojoCodecRegistry =
        fromProviders(PojoCodecProvider.builder().automatic(true).build());
    CodecRegistry codecRegistry =
        fromRegistries(MongoClientSettings.getDefaultCodecRegistry(), pojoCodecRegistry);
    MongoClientSettings settings =
        MongoClientSettings.builder()
            .applyConnectionString(new ConnectionString(uri))
            .codecRegistry(codecRegistry)
            .build();
    return MongoClients.create(settings);
  }

  @Bean(name = "docdbMongoDatabase")
  public MongoDatabase docdbMongoDatabase(MongoClient docdbMongoClient, RemoteConfig remoteConfig) {
    String database = remoteConfig.getDocdbDatabase();
    return docdbMongoClient.getDatabase(database);
  }
}
