package library_book_service.ratelimit;

import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.UUID;
import org.springframework.data.redis.core.StringRedisTemplate;
import org.springframework.stereotype.Component;

/**
 * Redis-backed sliding-window rate limiter (ZSET) + daily-quota counter (INCR) for
 * library.BookService.
 *
 * <p>Backed by the {@link StringRedisTemplate} bean Spring Boot auto-configures from {@code
 * spring-boot-starter-data-redis} (the SAME Maven coordinate the service's Redis/Valkey cache block
 * already requires -- {@code datrix_codegen_java.runtime_requirements}).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class RateLimiter {

  private static final long DAY_SECONDS = 86_400L;
  private static final long WINDOW_EXPIRE_SLACK_SECONDS = 5L;

  private final StringRedisTemplate redis;

  public RateLimiter(StringRedisTemplate redis) {
    this.redis = redis;
  }

  /** Outcome of a single rate-limit check. */
  public record LimitResult(
      boolean allowed,
      int limit,
      int remaining,
      long resetAtEpochSeconds,
      long retryAfterSeconds) {}

  /**
   * Sliding-window check: at most {@code maxRequests} within {@code windowSeconds}, keyed by {@code
   * key}. Uses a Redis sorted set (member = timestamp + a random suffix, score = timestamp):
   * expired members are trimmed with {@code ZREMRANGEBYSCORE} before the new member is added, then
   * {@code ZCARD} yields the current count -- the same algorithm python's {@code
   * RedisPlanRateLimiter.check_limit} uses.
   */
  public LimitResult checkWindow(String key, int maxRequests, int windowSeconds) {
    double nowSeconds = Instant.now().toEpochMilli() / 1000.0;
    double windowStart = nowSeconds - windowSeconds;
    String member = nowSeconds + "-" + UUID.randomUUID().toString().substring(0, 7);
    String zsetKey = "ns:rl:win:" + windowSeconds + ":" + maxRequests + ":" + key;

    this.redis.opsForZSet().removeRangeByScore(zsetKey, 0, windowStart);
    this.redis.opsForZSet().add(zsetKey, member, nowSeconds);
    this.redis.expire(zsetKey, Duration.ofSeconds(windowSeconds + WINDOW_EXPIRE_SLACK_SECONDS));
    Long countRaw = this.redis.opsForZSet().zCard(zsetKey);
    int count = countRaw == null ? 0 : countRaw.intValue();
    long resetAtEpochSeconds = (long) nowSeconds + windowSeconds;

    if (count > maxRequests) {
      return new LimitResult(false, maxRequests, 0, resetAtEpochSeconds, windowSeconds);
    }
    return new LimitResult(
        true, maxRequests, Math.max(0, maxRequests - count), resetAtEpochSeconds, 0);
  }

  /**
   * Daily-quota check (plain {@code INCR} against a date-scoped key, independent of {@link
   * #checkWindow}'s sliding window).
   */
  public LimitResult checkDailyQuota(String key, int dailyQuota) {
    String dayKey = "ns:rl:daily:" + key + ":" + LocalDate.now(ZoneOffset.UTC);
    Long countRaw = this.redis.opsForValue().increment(dayKey);
    long count = countRaw == null ? 0L : countRaw;
    if (count == 1L) {
      this.redis.expire(dayKey, Duration.ofSeconds(DAY_SECONDS));
    }
    long resetAtEpochSeconds = Instant.now().getEpochSecond() + DAY_SECONDS;
    if (count > dailyQuota) {
      return new LimitResult(false, dailyQuota, 0, resetAtEpochSeconds, DAY_SECONDS);
    }
    return new LimitResult(
        true, dailyQuota, (int) Math.max(0, dailyQuota - count), resetAtEpochSeconds, 0);
  }
}
