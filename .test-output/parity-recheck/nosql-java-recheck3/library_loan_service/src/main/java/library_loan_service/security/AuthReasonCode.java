package library_loan_service.security;

/**
 * Fixed set of OR8 authentication/authorization failure reason codes.
 *
 * <p>Mirror of {@code datrix_common.identity.audit.AuthReasonCode}, inlined so generated services
 * carry no runtime dependency on the framework package -- same rationale as python's inline {@code
 * _REASON_*} constants in {@code identity.py.j2}.
 *
 * <p>These codes go to logs and metrics ONLY. Client-visible HTTP responses must never include
 * these values -- 401 bodies are opaque (RFC 7807) and 403 bodies carry a stable, role-detail-free
 * message.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
public enum AuthReasonCode {
  MISSING_TOKEN("missing_token"),
  MALFORMED_TOKEN("malformed_token"),
  EXPIRED_TOKEN("expired_token"),
  BAD_SIGNATURE("bad_signature"),
  ISSUER_MISMATCH("issuer_mismatch"),
  AUDIENCE_MISMATCH("audience_mismatch"),
  CLIENT_MISMATCH("client_mismatch"),
  PROVIDER_MISMATCH("provider_mismatch"),
  PRINCIPAL_TYPE_MISMATCH("principal_type_mismatch"),
  ROLE_DENIED("role_denied"),
  PROFILE_UNAVAILABLE("profile_unavailable"),
  JWKS_REFRESH_FAILED("jwks_refresh_failed"),
  DELEGATION_INVALID("delegation_invalid");

  private final String code;

  AuthReasonCode(String code) {
    this.code = code;
  }

  public String code() {
    return this.code;
  }

  @Override
  public String toString() {
    return this.code;
  }
}
