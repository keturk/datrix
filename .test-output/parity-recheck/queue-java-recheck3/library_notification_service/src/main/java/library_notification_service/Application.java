package library_notification_service;

import library_notification_service.workers.NotificationServiceQueueWorker;
import org.springframework.boot.SpringApplication;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;

/**
 * library_notification_service entrypoint.
 *
 * <p>Inspects a single {@code --datrix.run=<mode>} argument BEFORE any Spring bootstrap: {@code
 * migrate:<block>} | {@code seed} | {@code search-init} | {@code job-runner} | {@code queue-worker}
 * | {@code event-consumer:<block>} | {@code serverless:<block>:<kind>} | default (web service). A
 * mode invoked without its generated runner exits non-zero with an actionable message -- never a
 * silent fallthrough to the web app.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@SpringBootApplication
public class Application {

  private static final String RUN_MODE_PREFIX = "--datrix.run=";
  private static final String MODE_MIGRATE_PREFIX = "migrate:";
  private static final String MODE_SEED = "seed";
  private static final String MODE_SEARCH_INIT = "search-init";
  private static final String MODE_JOB_RUNNER = "job-runner";
  private static final String SUPPORTED_MODES_MESSAGE = "default (web service)" + ", job-runner";

  public static void main(String[] args) {
    final String mode = parseRunMode(args);
    if (mode == null) {
      SpringApplication.run(Application.class, args);
      return;
    }
    if (mode.startsWith(MODE_MIGRATE_PREFIX)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_SEED)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_SEARCH_INIT)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_JOB_RUNNER)) {
      runJobRunner(args);
    } else {
      failUnknownMode(mode);
    }
  }

  private static String parseRunMode(String[] args) {
    for (String arg : args) {
      if (arg.startsWith(RUN_MODE_PREFIX)) {
        return arg.substring(RUN_MODE_PREFIX.length());
      }
    }
    return null;
  }

  private static void failUnavailableMode(String mode) {
    System.err.println(
        "--datrix.run="
            + mode
            + " is not available on this image. "
            + "Supported modes: "
            + SUPPORTED_MODES_MESSAGE);
    System.exit(1);
  }

  private static void failUnknownMode(String mode) {
    System.err.println(
        "Unknown --datrix.run mode: "
            + mode
            + ". "
            + "Supported modes: "
            + SUPPORTED_MODES_MESSAGE);
    System.exit(1);
  }

  /**
   * Bootstraps a minimal (non-web) Spring context. This is the ONE non-web dispatch mode that
   * additionally activates {@link #MODE_JOB_RUNNER} as a Spring profile: {@code JobsScheduler}'s
   * {@code @Scheduled} triggers (if this service has scheduled jobs) are
   * {@code @Profile("(!isolated-run) | job-runner")}-gated, so they fire here AND in the default
   * web-app boot, but nowhere else -- job-runner is the dedicated decoupled-mode worker for
   * scheduled jobs. Pubsub listeners remain excluded here (this mode also activates {@link
   * #RUN_PROFILE_ISOLATED} whenever that machinery is needed, same as every other non-web mode).
   * {@link NotificationServiceQueueWorker}'s blocking poll loop then becomes this process's "stay
   * alive" mechanism (its {@code start()} call never returns until {@code stop()} is invoked from
   * the shutdown hook below).
   */
  private static void runJobRunner(String[] args) {
    ConfigurableApplicationContext context =
        new SpringApplicationBuilder(Application.class).web(WebApplicationType.NONE).run(args);
    NotificationServiceQueueWorker queueWorker =
        context.getBean(NotificationServiceQueueWorker.class);
    Runtime.getRuntime()
        .addShutdownHook(
            new Thread(
                () -> {
                  queueWorker.stop();
                  SpringApplication.exit(context);
                }));
    queueWorker.start();
  }
}
