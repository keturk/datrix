package library_notification_service.notif_db;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import javax.sql.DataSource;
import library_notification_service.config.RemoteConfig;
import library_notification_service.security.SecretsResolver;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * HikariCP {@code DataSource} configuration for the 'notifDb' RDBMS block (postgres). Every RDBMS
 * block gets its own explicitly-named bean -- no {@code @Primary} guess across multi-block
 * services.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
public class NotifDbDataSourceConfig {

  @Bean(name = "notif_dbDataSource")
  public DataSource notif_dbDataSource(RemoteConfig remoteConfig, SecretsResolver secretsResolver) {
    String host = remoteConfig.getNotifDbHost();
    int port = remoteConfig.getNotifDbPort();
    String database = remoteConfig.getNotifDbDatabase();
    String username = remoteConfig.getNotifDbUser();

    String jdbcUrl = "jdbc:postgresql://" + host + ":" + port + "/" + database;

    HikariConfig hikariConfig = new HikariConfig();
    hikariConfig.setJdbcUrl(jdbcUrl);
    hikariConfig.setDriverClassName("org.postgresql.Driver");
    hikariConfig.setUsername(username);
    hikariConfig.setPassword(secretsResolver.getSecret("notif_db_password"));
    hikariConfig.setMaximumPoolSize(20);

    return new HikariDataSource(hikariConfig);
  }
}
