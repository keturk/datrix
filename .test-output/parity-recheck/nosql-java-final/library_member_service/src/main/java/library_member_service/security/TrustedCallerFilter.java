package library_member_service.security;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Shared-secret, constant-time inter-service caller filter.
 *
 * <p>Validates the {@code X-Datrix-Trusted-Caller} header via {@link MessageDigest#isEqual(byte[],
 * byte[])} (constant-time byte comparison) against the {@code 'trusted_caller_secret'} secret
 * resolved through {@link SecretsResolver}. A missing header, an unresolved secret, or a mismatched
 * secret all FAIL CLOSED (401) -- an unresolved secret is never treated as "no auth required"
 * (design principle 15).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class TrustedCallerFilter extends OncePerRequestFilter {

  private static final Logger LOG = LoggerFactory.getLogger(TrustedCallerFilter.class);
  private static final String CALLER_SECRET_HEADER = "X-Datrix-Trusted-Caller";
  private static final Set<String> EXEMPT_PATHS = Set.of("/health", "/actuator/health");

  private final SecretsResolver secretsResolver;

  public TrustedCallerFilter(SecretsResolver secretsResolver) {
    this.secretsResolver = secretsResolver;
  }

  @Override
  protected void doFilterInternal(
      HttpServletRequest request, HttpServletResponse response, FilterChain chain)
      throws ServletException, IOException {
    if (EXEMPT_PATHS.contains(request.getRequestURI())) {
      chain.doFilter(request, response);
      return;
    }
    String provided = request.getHeader(CALLER_SECRET_HEADER);
    if (provided == null || provided.isBlank()) {
      LOG.warn("trusted_caller_rejected reason=missing_header path={}", request.getRequestURI());
      response.setStatus(HttpServletResponse.SC_UNAUTHORIZED);
      return;
    }
    String expected = secretsResolver.getSecret("trusted_caller_secret");
    if (expected == null || expected.isBlank()) {
      // FAIL CLOSED: an unresolved secret is never treated as "no auth required".
      LOG.error("trusted_caller_rejected reason=secret_unresolved");
      response.setStatus(HttpServletResponse.SC_UNAUTHORIZED);
      return;
    }
    byte[] providedBytes = provided.getBytes(StandardCharsets.UTF_8);
    byte[] expectedBytes = expected.getBytes(StandardCharsets.UTF_8);
    if (!MessageDigest.isEqual(providedBytes, expectedBytes)) {
      LOG.warn("trusted_caller_rejected reason=secret_mismatch path={}", request.getRequestURI());
      response.setStatus(HttpServletResponse.SC_UNAUTHORIZED);
      return;
    }
    chain.doFilter(request, response);
  }
}
