@SpringBootApplication
public class Application {

  private static final String RUN_MODE_PREFIX = "--datrix.run=";
  private static final String MODE_MIGRATE_PREFIX = "migrate:";
  private static final String MODE_SEED = "seed";
  private static final String MODE_SEARCH_INIT = "search-init";
  private static final String MODE_JOB_RUNNER = "job-runner";
  private static final String MODE_EVENT_CONSUMER_PREFIX = "event-consumer:";

  /**
   * Spring profile explicitly activated by EVERY non-web dispatch mode that must not run pubsub
   * listeners or the {@code JobsScheduler}
   * (migrate/seed/search-init/queue-worker/serverless/event-consumer), AND by {@code runJobRunner}
   * (which additionally activates {@link #MODE_JOB_RUNNER} as a distinct marker so {@code
   * JobsScheduler}'s own {@code @Profile("(!isolated-run) | job-runner")} can tell job-runner apart
   * from every OTHER {@code isolated-run} container -- job-runner is the ONE non-web mode where
   * scheduled jobs are SUPPOSED to run). The generated {@code {Block}KafkaEventConsumer}/ {@code
   * {Block}RabbitEventConsumer} `@Component`s are {@code @Profile("(!isolated-run) |
   * event-consumer-<block>")}-gated the same way. The default web-app boot activates this profile
   * TOO when this service's {@code runtime.consumers} resolves to {@code decoupled} -- see {@code
   * web_hosts_consumers_in_ process} below -- so a decoupled service's web app never redundantly
   * re-runs the scheduler/listeners its dedicated worker/event-consumer containers already run.
   */
  private static final String RUN_PROFILE_ISOLATED = "isolated-run";

  private static final String SUPPORTED_MODES_MESSAGE =
      "default (web service)" + ", job-runner" + ", event-consumer:<block>";

  public static void main(String[] args) {
    final String mode = parseRunMode(args);
    if (mode == null) {
      SpringApplication.run(Application.class, args);
      return;
    }
    if (mode.startsWith(MODE_MIGRATE_PREFIX)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_SEED)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_SEARCH_INIT)) {
      failUnavailableMode(mode);
    } else if (mode.equals(MODE_JOB_RUNNER)) {
      runJobRunner(args);
    } else if (mode.startsWith(MODE_EVENT_CONSUMER_PREFIX)) {
      runEventConsumer(mode.substring(MODE_EVENT_CONSUMER_PREFIX.length()), args);
    } else {
      failUnknownMode(mode);
    }
  }

  private static String parseRunMode(String[] args) {
    for (String arg : args) {
      if (arg.startsWith(RUN_MODE_PREFIX)) {
        return arg.substring(RUN_MODE_PREFIX.length());
      }
    }
    return null;
  }

  private static void failUnavailableMode(String mode) {
    System.err.println(
        "--datrix.run="
            + mode
            + " is not available on this image. "
            + "Supported modes: "
            + SUPPORTED_MODES_MESSAGE);
    System.exit(1);
  }

  private static void failUnknownMode(String mode) {
    System.err.println(
        "Unknown --datrix.run mode: "
            + mode
            + ". "
            + "Supported modes: "
            + SUPPORTED_MODES_MESSAGE);
    System.exit(1);
  }

  /**
   * Bootstraps a minimal (non-web) Spring context. This is the ONE non-web dispatch mode that
   * additionally activates {@link #MODE_JOB_RUNNER} as a Spring profile: {@code JobsScheduler}'s
   * {@code @Scheduled} triggers (if this service has scheduled jobs) are
   * {@code @Profile("(!isolated-run) | job-runner")}-gated, so they fire here AND in the default
   * web-app boot, but nowhere else -- job-runner is the dedicated decoupled-mode worker for
   * scheduled jobs. Pubsub listeners remain excluded here (this mode also activates {@link
   * #RUN_PROFILE_ISOLATED} whenever that machinery is needed, same as every other non-web mode).
   * Blocks until the JVM receives a shutdown signal (SIGTERM) -- unlike {@code runMigrate}/{@code
   * runSeed}, which exit after a single unit of work, a job-runner IS the long-running worker.
   */
  private static void runJobRunner(String[] args) {
    ConfigurableApplicationContext context =
        new SpringApplicationBuilder(Application.class)
            .web(WebApplicationType.NONE)
            .profiles(RUN_PROFILE_ISOLATED, MODE_JOB_RUNNER)
            .run(args);
    Runtime.getRuntime().addShutdownHook(new Thread(() -> SpringApplication.exit(context)));
    blockUntilShutdown();
  }

  /**
   * Bootstraps a minimal (non-web) Spring context activating Spring profile {@code
   * event-consumer-<block>} -- the ONLY profile the generated {@code
   * {Block}KafkaEventConsumer}/{@code {Block}RabbitEventConsumer} `@Component`s for THIS block are
   * `@Profile`-gated to: no other pubsub block's listeners, and no
   * migrate/seed/search-init/job-runner/queue-worker container's context, ever activates them --
   * closing the latent duplicate- consumption bug where those `@KafkaListener`/`@RabbitListener`
   * beans previously activated unconditionally on EVERY non-web container boot. Blocks until
   * shutdown: the listener `@Component` is activated by normal component scanning once its profile
   * is active, so this process has no other "stay alive" work of its own.
   */
  private static void runEventConsumer(String block, String[] args) {
    switch (block) {
      case "mq" -> {}
      default -> {
        System.err.println("Unknown event-consumer block: " + block + ". Known blocks: mq");
        System.exit(1);
        return;
      }
    }
    ConfigurableApplicationContext context =
        new SpringApplicationBuilder(Application.class)
            .web(WebApplicationType.NONE)
            .profiles(RUN_PROFILE_ISOLATED, "event-consumer-" + block)
            .run(args);
    Runtime.getRuntime().addShutdownHook(new Thread(() -> SpringApplication.exit(context)));
    blockUntilShutdown();
  }

  /** Blocks the calling thread until interrupted (non-web worker keep-alive). */
  private static void blockUntilShutdown() {
    Object lock = new Object();
    synchronized (lock) {
      try {
        lock.wait();
      } catch (InterruptedException e) {
        Thread.currentThread().interrupt();
      }
    }
  }
}
