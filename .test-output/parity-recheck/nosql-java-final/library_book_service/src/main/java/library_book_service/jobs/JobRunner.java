  /**
   * Run *body* on a dedicated executor and enforce *timeoutSeconds*. Cancels (best-effort
   * interrupt) the underlying task on timeout and unwraps a job body's runtime exception from
   * {@link ExecutionException} so callers see the SAME exception type the job body threw.
   */
  private static void runWithTimeout(Runnable body, int timeoutSeconds) {
    Future<?> future = EXECUTOR.submit(body);
    try {
      future.get(timeoutSeconds, TimeUnit.SECONDS);
    } catch (TimeoutException e) {
      future.cancel(true);
      throw new IllegalStateException("Job timed out after " + timeoutSeconds + "s", e);
    } catch (ExecutionException e) {
      Throwable cause = e.getCause();
      if (cause instanceof RuntimeException runtimeCause) {
        throw runtimeCause;
      }
      throw new IllegalStateException("Job failed", cause);
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new IllegalStateException("Job interrupted", e);
    }
  }

  private static void sleepBackoff(int attempt, boolean exponential) {
    long delayMs = exponential ? (long) Math.pow(2, attempt) * 1000L : 1000L;
    try {
      Thread.sleep(delayMs);
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
    }
  }
