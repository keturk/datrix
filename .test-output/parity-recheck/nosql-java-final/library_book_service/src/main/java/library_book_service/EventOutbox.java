package library_book_service;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

/**
 * Transaction-scoped event outbox.
 *
 * <p>Domain events dispatched inside a {@code transaction(db) { ... }} unit of work are buffered
 * here and published once, AFTER the transaction commits, instead of once per row in a bulk loop.
 * The buffer lives in a {@link ThreadLocal} so concurrent requests never share or clobber each
 * other's pending events.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
public final class EventOutbox {

  private static final Logger logger = LoggerFactory.getLogger(EventOutbox.class);

  /**
   * Maximum number of publish calls flushed in a single wave. Limiting batch size prevents flooding
   * the broker producer's in-flight buffer when a bulk {@code transaction(db)} upsert buffers
   * thousands of per-row lifecycle events.
   */
  private static final int FLUSH_BATCH_SIZE = 500;

  private static final ThreadLocal<List<Runnable>> BUFFER = new ThreadLocal<>();

  private EventOutbox() {}

  /** True when a transaction-scoped event buffer is collecting events. */
  public static boolean isActive() {
    return BUFFER.get() != null;
  }

  /**
   * Queue a publish to run after the enclosing transaction commits.
   *
   * @throws IllegalStateException if no buffer is active -- guard calls with {@link #isActive()}
   *     before deferring, so a misrouted defer fails loudly instead of silently dropping an event.
   */
  public static void defer(Runnable send) {
    List<Runnable> buffer = BUFFER.get();
    if (buffer == null) {
      throw new IllegalStateException(
          "EventOutbox.defer() called with no active event outbox. "
              + "Guard publish calls with EventOutbox.isActive() before deferring.");
    }
    buffer.add(send);
  }

  /**
   * Buffer events dispatched during {@code unitOfWork} and flush them once, after a clean commit.
   *
   * <p>Re-entrant: a nested {@code withBuffer} call joins the outermost buffer and leaves flushing
   * to it, so a {@code transaction} block nested inside another still yields a single post-commit
   * flush. On rollback nothing is flushed -- the events belonged to a unit of work that never
   * durably committed. Registers a {@link TransactionSynchronization} against the currently active
   * Spring transaction so the flush runs only {@code afterCommit} (never before, never on
   * rollback); post-commit publish failures are logged but never re-raised -- a committed unit of
   * work must not be reported as failed because a side-effect publish failed.
   */
  public static void withBuffer(Runnable unitOfWork) {
    if (isActive()) {
      unitOfWork.run();
      return;
    }
    List<Runnable> buffer = new ArrayList<>();
    BUFFER.set(buffer);
    if (!TransactionSynchronizationManager.isSynchronizationActive()) {
      try {
        unitOfWork.run();
        EventOutbox.flush(buffer);
      } finally {
        BUFFER.remove();
      }
      return;
    }
    TransactionSynchronizationManager.registerSynchronization(
        new TransactionSynchronization() {
          @Override
          public void afterCompletion(int status) {
            BUFFER.remove();
            if (status == TransactionSynchronization.STATUS_COMMITTED) {
              EventOutbox.flush(buffer);
            }
          }
        });
    unitOfWork.run();
  }

  private static void flush(List<Runnable> buffer) {
    int total = buffer.size();
    AtomicInteger published = new AtomicInteger(0);
    AtomicInteger failed = new AtomicInteger(0);
    for (int start = 0; start < total; start += FLUSH_BATCH_SIZE) {
      int end = Math.min(start + FLUSH_BATCH_SIZE, total);
      for (Runnable send : buffer.subList(start, end)) {
        try {
          send.run();
          published.incrementAndGet();
        } catch (RuntimeException e) {
          failed.incrementAndGet();
          logger.error("event_outbox_publish_failed error={}", e.getMessage(), e);
        }
      }
    }
    if (failed.get() > 0) {
      logger.error(
          "event_outbox_flushed_with_failures published={} failed={} total={}",
          published.get(),
          failed.get(),
          total);
    } else {
      logger.info("event_outbox_flushed count={}", published.get());
    }
  }
}
