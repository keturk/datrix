package library_book_service;

import java.util.Optional;
import org.springframework.beans.BeansException;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.context.ApplicationContext;
import org.springframework.context.ApplicationContextAware;
import org.springframework.stereotype.Component;

/**
 * Static bridge to the running {@link ApplicationContext}.
 *
 * <p>Some framework-instantiated classes have no Spring dependency-injection surface: a JPA
 * {@code @EntityListeners} class is instantiated by Hibernate via reflection (never by the Spring
 * container), and a service-level function module ({@code Functions.java}) is a {@code final class}
 * of {@code public static} methods with no instance to inject into. Both still need to reach a
 * Spring-managed collaborator (e.g. the generated {@code KafkaEventProducer}) when a DSL {@code
 * dispatch} statement appears inside them -- {@link #getBean(Class)} resolves it from the live
 * application context instead.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class SpringContextHolder implements ApplicationContextAware {

  private static ApplicationContext context;

  @Override
  public void setApplicationContext(ApplicationContext applicationContext) throws BeansException {
    SpringContextHolder.context = applicationContext;
  }

  /**
   * Resolve a Spring-managed bean by type.
   *
   * @throws IllegalStateException if the application context has not been initialized yet (this
   *     bean must be created before any call site resolves a collaborator through it -- true for
   *     every request/consumer entry point once the Spring context has finished starting).
   */
  public static <T> T getBean(Class<T> type) {
    if (context == null) {
      throw new IllegalStateException(
          "SpringContextHolder.getBean() called before the ApplicationContext "
              + "was initialized. This can only happen if a dispatch(...) call runs "
              + "during application startup, before Spring's context refresh completes.");
    }
    return context.getBean(type);
  }

  /**
   * Resolve a Spring-managed bean by type WITHOUT raising when no such bean is registered (e.g. a
   * spy/test-only bean that is wired only inside a {@code @SpringBootTest}'s
   * {@code @TestConfiguration}, never in the production application context). Used by generated
   * code that must stay inert -- never throw, never require the bean -- in every environment where
   * the bean was never registered.
   */
  public static <T> Optional<T> getOptionalBean(Class<T> type) {
    if (context == null) {
      return Optional.empty();
    }
    ObjectProvider<T> provider = context.getBeanProvider(type);
    return Optional.ofNullable(provider.getIfAvailable());
  }
}
