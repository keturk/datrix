package com.datrix.deploymenttests;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * Deployment readiness proof for service {@code library.MemberService}: after a real {@code docker
 * compose up}, its {@code /health} endpoint (the generated {@code HealthController}) must respond
 * 200 within 5000 ms.
 *
 * <p>Requires the compose stack to already be running -- see {@code
 * deployment-tests/run-tests.ps1}. Never runs as part of an ordinary {@code mvnw test} inside a
 * service's own module.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Tag("deployment")
class MemberServiceReadinessTest {

  private static final String COMPOSE_SERVICE = "library-member-service";
  private static final int PORT = 8002;
  private static final String HEALTH_PATH = "/health";
  private static final long RESPONSE_BOUND_MS = 5000L;

  private static String deployedHost() {
    String host = System.getenv("DATRIX_DEPLOY_HOST");
    return (host == null || host.isBlank()) ? "localhost" : host;
  }

  @Test
  void healthEndpointRespondsWithinBoundAfterDeployment() throws IOException, InterruptedException {
    HttpClient client =
        HttpClient.newBuilder().connectTimeout(Duration.ofMillis(RESPONSE_BOUND_MS)).build();
    URI uri = URI.create("http://" + deployedHost() + ":" + PORT + HEALTH_PATH);
    HttpRequest request =
        HttpRequest.newBuilder(uri).timeout(Duration.ofMillis(RESPONSE_BOUND_MS)).GET().build();

    long start = System.nanoTime();
    HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
    long elapsedMs = (System.nanoTime() - start) / 1_000_000L;

    assertEquals(
        200,
        response.statusCode(),
        "service '"
            + COMPOSE_SERVICE
            + "' health endpoint "
            + uri
            + " must respond 200 once deployed; got "
            + response.statusCode()
            + " body="
            + response.body());
    assertTrue(
        elapsedMs <= RESPONSE_BOUND_MS,
        "service '"
            + COMPOSE_SERVICE
            + "' health endpoint "
            + uri
            + " must respond within "
            + RESPONSE_BOUND_MS
            + " ms; took "
            + elapsedMs
            + " ms");
  }
}
