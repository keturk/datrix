  /**
   * Deterministic RFC 4122 version-5 (SHA-1, name-based) UUID -- python's {@code
   * uuid.uuid5(namespace, name)} par (no JDK builtin: {@link UUID#nameUUIDFromBytes} is version
   * 3/MD5, not version 5).
   */
  private static UUID uuid5(UUID namespace, String name) {
    try {
      MessageDigest sha1 = MessageDigest.getInstance("SHA-1");
      byte[] namespaceBytes = new byte[16];
      long msb = namespace.getMostSignificantBits();
      long lsb = namespace.getLeastSignificantBits();
      for (int i = 0; i < 8; i++) {
        namespaceBytes[i] = (byte) (msb >>> (8 * (7 - i)));
        namespaceBytes[8 + i] = (byte) (lsb >>> (8 * (7 - i)));
      }
      sha1.update(namespaceBytes);
      byte[] hash = sha1.digest(name.getBytes(StandardCharsets.UTF_8));
      hash[6] &= 0x0f;
      hash[6] |= 0x50; // version 5
      hash[8] &= 0x3f;
      hash[8] |= (byte) 0x80; // RFC 4122 variant
      long hashMsb = 0;
      long hashLsb = 0;
      for (int i = 0; i < 8; i++) {
        hashMsb = (hashMsb << 8) | (hash[i] & 0xffL);
      }
      for (int i = 8; i < 16; i++) {
        hashLsb = (hashLsb << 8) | (hash[i] & 0xffL);
      }
      return new UUID(hashMsb, hashLsb);
    } catch (NoSuchAlgorithmException e) {
      throw new IllegalStateException("SHA-1 unavailable for UUID5 derivation.", e);
    }
  }

