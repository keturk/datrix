import { NestFactory } from '@nestjs/core';
import type { Request, Response } from 'express';
import { stripe_webhook } from './handlers/stripe-webhook';

class ServerlessHttpAppModule {}


async function main(): Promise<void> {
  const app = await NestFactory.create(ServerlessHttpAppModule, { logger: ['error', 'warn', 'log'] });
  const expressApp = app.getHttpAdapter().getInstance();

  expressApp.get('/health', (_req: Request, res: Response) => {
    res.status(200).json({ status: 'ok' });
  });

  expressApp.post('/webhooks/stripe', async (req: Request, res: Response) => {
    const body = req.body && typeof req.body === 'object' ? (req.body as Record<string, unknown>) : {};
    try {
      await Promise.race([
        stripe_webhook(
          body['payload'],
        ),
        new Promise<never>((_, reject) => {
          setTimeout(() => reject(new Error('serverless_http_timeout')), 300000);
        }),
      ]);
      res.status(200).json({ status: 'ok' });
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      if (message === 'serverless_http_timeout') {
        console.error(`serverless_http_timeout handler=stripe_webhook timeout_ms=300000`);
        res.status(504).json({ detail: 'Handler timed out' });
        return;
      }
      console.error(`serverless_http_dispatch_failed handler=stripe_webhook error=${message}`);
      res.status(500).json({ detail: 'Internal error' });
    }
  });

  const port = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;
  await app.listen(port);
  console.log(`serverless_http_app_started block=event-handlers port=${port}`);
}

main().catch((err) => {
  console.error('Container serverless http app failed to start', err);
  process.exit(1);
});
