package warehouse_warehouse_service.errors;

import jakarta.servlet.http.HttpServletRequest;
import jakarta.validation.ConstraintViolationException;
import java.net.URI;
import java.util.ArrayList;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;
import org.springframework.web.server.ResponseStatusException;

/**
 * Maps exceptions raised anywhere in this service's REST layer to RFC 7807 {@link ProblemDetail}
 * responses (D8). Every handler returns {@code application/problem+json} explicitly; the catch-all
 * {@link #handleUnexpected} NEVER echoes the exception message or a stack trace, and never lets
 * Spring's whitelabel error page take over (the project scaffold also sets {@code
 * server.error.whitelabel.enabled=false} and {@code spring.mvc.problemdetails.enabled=true} so
 * nothing undeclared can bypass this advice).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@RestControllerAdvice
public class GlobalExceptionHandler {

  private static final Logger logger = LoggerFactory.getLogger(GlobalExceptionHandler.class);

  /**
   * The CRUD-delegation "entity not found by id" path raises a plain {@link
   * ResponseStatusException}, which already implements Spring's {@code ErrorResponse} and carries
   * its own {@link ProblemDetail} body -- this handler forwards that body (adding {@code instance})
   * rather than re-deriving it, and exists chiefly so THIS advice's catch-all does not shadow
   * Spring's native handling (both resolvers run through the same {@code
   * ExceptionHandlerExceptionResolver} chain).
   */
  @ExceptionHandler(ResponseStatusException.class)
  public ResponseEntity<ProblemDetail> handleResponseStatus(
      ResponseStatusException ex, HttpServletRequest request) {
    ProblemDetail body = ex.getBody();
    body.setInstance(URI.create(request.getRequestURI()));
    logger.warn(
        "response_status_exception status={} detail={}", ex.getStatusCode(), body.getDetail());
    return ResponseEntity.status(ex.getStatusCode())
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }

  /**
   * The generated {@code {Entity}Service.delete}'s cascade-restriction check raises a plain {@link
   * IllegalStateException} -- the only way an {@code IllegalStateException} reaches THIS advice at
   * all, since job/consumer scope never routes through {@code @RestControllerAdvice} (D7).
   */
  @ExceptionHandler(IllegalStateException.class)
  public ResponseEntity<ProblemDetail> handleCascadeRestriction(
      IllegalStateException ex, HttpServletRequest request) {
    ProblemDetail body = ProblemDetail.forStatusAndDetail(HttpStatus.CONFLICT, ex.getMessage());
    body.setType(URI.create("urn:datrix:error:cascade-restriction"));
    body.setTitle("Conflict");
    body.setInstance(URI.create(request.getRequestURI()));
    logger.warn("cascade_restriction detail={}", ex.getMessage());
    return ResponseEntity.status(HttpStatus.CONFLICT)
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }

  @ExceptionHandler(ServiceValidationError.class)
  public ResponseEntity<ProblemDetail> handleServiceValidation(
      ServiceValidationError ex, HttpServletRequest request) {
    ProblemDetail body =
        ProblemDetail.forStatusAndDetail(
            HttpStatus.UNPROCESSABLE_ENTITY, "Request validation failed.");
    body.setType(URI.create("urn:datrix:error:validation"));
    body.setTitle("Validation Error");
    body.setInstance(URI.create(request.getRequestURI()));
    List<FieldError> errors = new ArrayList<>();
    int index = 0;
    for (String message : ex.getErrors()) {
      errors.add(new FieldError("body[" + index + "]", message, "validation"));
      index++;
    }
    body.setProperty("errors", errors);
    logger.warn(
        "service_validation_error path={} errors={}", request.getRequestURI(), errors.size());
    return ResponseEntity.status(HttpStatus.UNPROCESSABLE_ENTITY)
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }

  @ExceptionHandler(MethodArgumentNotValidException.class)
  public ResponseEntity<ProblemDetail> handleMethodArgumentNotValid(
      MethodArgumentNotValidException ex, HttpServletRequest request) {
    ProblemDetail body =
        ProblemDetail.forStatusAndDetail(
            HttpStatus.UNPROCESSABLE_ENTITY, "Request validation failed.");
    body.setType(URI.create("urn:datrix:error:request-validation"));
    body.setTitle("Validation Error");
    body.setInstance(URI.create(request.getRequestURI()));
    List<FieldError> errors = new ArrayList<>();
    for (org.springframework.validation.FieldError fe : ex.getBindingResult().getFieldErrors()) {
      String message = fe.getDefaultMessage() != null ? fe.getDefaultMessage() : "invalid value";
      errors.add(new FieldError(fe.getField(), message, "validation"));
    }
    body.setProperty("errors", errors);
    return ResponseEntity.status(HttpStatus.UNPROCESSABLE_ENTITY)
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }

  @ExceptionHandler(ConstraintViolationException.class)
  public ResponseEntity<ProblemDetail> handleConstraintViolation(
      ConstraintViolationException ex, HttpServletRequest request) {
    ProblemDetail body =
        ProblemDetail.forStatusAndDetail(
            HttpStatus.UNPROCESSABLE_ENTITY, "Request validation failed.");
    body.setType(URI.create("urn:datrix:error:request-validation"));
    body.setTitle("Validation Error");
    body.setInstance(URI.create(request.getRequestURI()));
    List<FieldError> errors = new ArrayList<>();
    for (jakarta.validation.ConstraintViolation<?> violation : ex.getConstraintViolations()) {
      errors.add(
          new FieldError(
              violation.getPropertyPath().toString(), violation.getMessage(), "validation"));
    }
    body.setProperty("errors", errors);
    return ResponseEntity.status(HttpStatus.UNPROCESSABLE_ENTITY)
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }

  /**
   * Catch-all -- NEVER echoes {@code ex.getMessage()} or a stack trace in the response body (the
   * real exception is logged server-side only). This is what proves the NEG acceptance property: an
   * undeclared exception type yields the generated taxonomy, never a Spring default whitelabel page
   * or leaked internals.
   */
  @ExceptionHandler(Exception.class)
  public ResponseEntity<ProblemDetail> handleUnexpected(Exception ex, HttpServletRequest request) {
    logger.error("unhandled_error path={}", request.getRequestURI(), ex);
    ProblemDetail body =
        ProblemDetail.forStatusAndDetail(
            HttpStatus.INTERNAL_SERVER_ERROR, "An unexpected error occurred.");
    body.setType(URI.create("urn:datrix:error:internal"));
    body.setTitle("Internal Server Error");
    body.setInstance(URI.create(request.getRequestURI()));
    return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR)
        .contentType(MediaType.APPLICATION_PROBLEM_JSON)
        .body(body);
  }
}
