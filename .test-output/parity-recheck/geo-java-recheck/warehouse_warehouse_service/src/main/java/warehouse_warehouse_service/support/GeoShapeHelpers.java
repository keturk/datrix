  private static JsonNode esriToGeoJson(JsonNode esri) {
    if (esri.has("type") && esri.has("coordinates")) {
      return esri;
    }
    ObjectNode out = MAPPER.createObjectNode();
    if (esri.has("x") && esri.has("y")) {
      out.put("type", "Point");
      ArrayNode coords = MAPPER.createArrayNode();
      coords.add(esri.get("x").asDouble());
      coords.add(esri.get("y").asDouble());
      out.set("coordinates", coords);
      return out;
    }
    if (esri.has("rings")) {
      out.put("type", "Polygon");
      out.set("coordinates", esri.get("rings"));
      return out;
    }
    if (esri.has("paths")) {
      JsonNode paths = esri.get("paths");
      if (paths.size() == 1) {
        out.put("type", "LineString");
        out.set("coordinates", paths.get(0));
      } else {
        out.put("type", "MultiLineString");
        out.set("coordinates", paths);
      }
      return out;
    }
    throw new IllegalArgumentException(
        "Unrecognized Esri JSON geometry: expected x/y, paths, rings, or GeoJSON type/coordinates"
            + " members");
  }

  private static JsonNode readJson(String text) {
    try {
      return MAPPER.readTree(text);
    } catch (JsonProcessingException e) {
      throw new IllegalArgumentException("Cannot parse geometry JSON: " + e.getMessage(), e);
    }
  }
