  /**
   * Convert a GML posList coordinate string to WKT. GML commonly emits latitude/longitude pairs for
   * EPSG:4326; JTS expects x/y (lng/lat) coordinates, so pairs that look like lat/lng are
   * normalized. One pair -> Point, two pairs -> LineString, three or more -> a closed Polygon.
   */
  public static String fromGmlPosList(String posListText) {
    String[] rawParts = posListText.replace(",", " ").trim().split("\\s+");
    if (rawParts.length < 2 || rawParts.length % 2 != 0) {
      throw new IllegalArgumentException("GML posList must contain an even number of coordinates");
    }
    List<Coordinate> coords = new ArrayList<>();
    for (int idx = 0; idx < rawParts.length; idx += 2) {
      double first = Double.parseDouble(rawParts[idx]);
      double second = Double.parseDouble(rawParts[idx + 1]);
      coords.add(
          Math.abs(first) <= 90 && Math.abs(second) <= 180
              ? new Coordinate(second, first)
              : new Coordinate(first, second));
    }
    Geometry geom;
    if (coords.size() == 1) {
      geom = FACTORY.createPoint(coords.get(0));
    } else if (coords.size() == 2) {
      geom = FACTORY.createLineString(coords.toArray(new Coordinate[0]));
    } else {
      List<Coordinate> ring = new ArrayList<>(coords);
      if (!ring.get(0).equals2D(ring.get(ring.size() - 1))) {
        ring.add(ring.get(0));
      }
      geom = FACTORY.createPolygon(ring.toArray(new Coordinate[0]));
    }
    return new WKTWriter().write(geom);
  }

