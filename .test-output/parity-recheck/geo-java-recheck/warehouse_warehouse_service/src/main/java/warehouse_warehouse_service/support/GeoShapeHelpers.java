  private static Geometry geometryFromGeoJson(JsonNode node) {
    String type = node.path("type").asText();
    JsonNode coords = node.path("coordinates");
    return switch (type) {
      case "Point" -> FACTORY.createPoint(coordinateFrom(coords));
      case "LineString" -> FACTORY.createLineString(coordinatesFrom(coords));
      case "Polygon" -> polygonFromCoordinates(coords);
      case "MultiPoint" -> FACTORY.createMultiPointFromCoords(coordinatesFrom(coords));
      case "MultiLineString" -> multiLineStringFrom(coords);
      case "MultiPolygon" -> multiPolygonFrom(coords);
      default -> throw new IllegalArgumentException("Unsupported GeoJSON geometry type: " + type);
    };
  }

  private static Coordinate coordinateFrom(JsonNode arr) {
    return new Coordinate(arr.get(0).asDouble(), arr.get(1).asDouble());
  }

  private static Coordinate[] coordinatesFrom(JsonNode arr) {
    Coordinate[] coords = new Coordinate[arr.size()];
    for (int i = 0; i < arr.size(); i++) {
      coords[i] = coordinateFrom(arr.get(i));
    }
    return coords;
  }

  private static Polygon polygonFromCoordinates(JsonNode ringsNode) {
    var shell = FACTORY.createLinearRing(coordinatesFrom(ringsNode.get(0)));
    var holes = new org.locationtech.jts.geom.LinearRing[Math.max(0, ringsNode.size() - 1)];
    for (int i = 1; i < ringsNode.size(); i++) {
      holes[i - 1] = FACTORY.createLinearRing(coordinatesFrom(ringsNode.get(i)));
    }
    return FACTORY.createPolygon(shell, holes);
  }

  private static MultiLineString multiLineStringFrom(JsonNode pathsNode) {
    LineString[] lines = new LineString[pathsNode.size()];
    for (int i = 0; i < pathsNode.size(); i++) {
      lines[i] = FACTORY.createLineString(coordinatesFrom(pathsNode.get(i)));
    }
    return FACTORY.createMultiLineString(lines);
  }

  private static MultiPolygon multiPolygonFrom(JsonNode polysNode) {
    Polygon[] polys = new Polygon[polysNode.size()];
    for (int i = 0; i < polysNode.size(); i++) {
      polys[i] = polygonFromCoordinates(polysNode.get(i));
    }
    return FACTORY.createMultiPolygon(polys);
  }

  private static ObjectNode geoJsonNodeFrom(Geometry geom) {
    ObjectNode node = MAPPER.createObjectNode();
    node.put("type", geom.getGeometryType());
    node.set("coordinates", coordinatesNodeFrom(geom));
    return node;
  }

  private static JsonNode coordinatesNodeFrom(Geometry geom) {
    if (geom instanceof Point p) {
      return coordToArray(p.getCoordinate());
    }
    if (geom instanceof LineString ls) {
      return coordsToArray(ls.getCoordinates());
    }
    if (geom instanceof Polygon poly) {
      return polygonCoordsToArray(poly);
    }
    if (geom instanceof MultiPolygon mp) {
      ArrayNode arr = MAPPER.createArrayNode();
      for (int i = 0; i < mp.getNumGeometries(); i++) {
        arr.add(polygonCoordsToArray((Polygon) mp.getGeometryN(i)));
      }
      return arr;
    }
    if (geom instanceof MultiLineString mls) {
      ArrayNode arr = MAPPER.createArrayNode();
      for (int i = 0; i < mls.getNumGeometries(); i++) {
        arr.add(coordsToArray(((LineString) mls.getGeometryN(i)).getCoordinates()));
      }
      return arr;
    }
    throw new IllegalArgumentException(
        "Unsupported geometry type for GeoJSON conversion: " + geom.getGeometryType());
  }

  private static ArrayNode coordToArray(Coordinate c) {
    ArrayNode arr = MAPPER.createArrayNode();
    arr.add(c.x);
    arr.add(c.y);
    return arr;
  }

  private static ArrayNode coordsToArray(Coordinate[] cs) {
    ArrayNode arr = MAPPER.createArrayNode();
    for (Coordinate c : cs) {
      arr.add(coordToArray(c));
    }
    return arr;
  }

  private static ArrayNode polygonCoordsToArray(Polygon poly) {
    ArrayNode rings = MAPPER.createArrayNode();
    rings.add(coordsToArray(poly.getExteriorRing().getCoordinates()));
    for (int i = 0; i < poly.getNumInteriorRing(); i++) {
      rings.add(coordsToArray(poly.getInteriorRingN(i).getCoordinates()));
    }
    return rings;
  }

