  /**
   * Coerce a geometry value (a WKT {@link String}, or a JTS {@link Geometry} already resolved by
   * the ORM for a Geometry/Geography entity field) to a JTS {@link Geometry}.
   */
  public static Geometry coerce(Object geometry) {
    if (geometry instanceof Geometry g) {
      return g;
    }
    if (geometry instanceof String s) {
      try {
        return new WKTReader(FACTORY).read(s);
      } catch (ParseException e) {
        throw new IllegalArgumentException("Invalid WKT: " + e.getMessage(), e);
      }
    }
    throw new IllegalArgumentException(
        "Unsupported geometry value type: "
            + (geometry == null ? "null" : geometry.getClass().getName())
            + ". Expected a WKT String or a JTS Geometry.");
  }

  /** Check if a geometry contains the given WGS84 point. */
  public static boolean containsPoint(Object geometry, double lat, double lng) {
    Geometry geom = coerce(geometry);
    Point point = FACTORY.createPoint(new Coordinate(lng, lat));
    return point.within(geom);
  }

  /**
   * Approximate geodetic area in square meters, via an equirectangular approximation (scales the
   * planar-degree area by the WGS-84 meters-per-degree factors at the geometry's own centroid
   * latitude) -- a deliberate simplification over python's pyproj/EPSG:6933 equal-area
   * reprojection: sufficiently accurate for a delivery-zone-scale polygon without adding a full
   * geodesy/reprojection library dependency.
   */
  public static double area(Object geometry) {
    Geometry geom = coerce(geometry);
    double centroidLat = geom.getCentroid().getCoordinate().y;
    double metersPerDegreeLon = METERS_PER_DEGREE_LAT * Math.cos(Math.toRadians(centroidLat));
    return geom.getArea() * METERS_PER_DEGREE_LAT * metersPerDegreeLon;
  }

