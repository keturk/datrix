#: Initial-load retry policy. The FIRST refresh must fetch every profile from the
#: backend before the process accepts a config snapshot. Falling open to
#: generated-defaults-only on the initial load would silently drop every
#: deployment-supplied key that has no generated default (e.g. connection ports),
#: surfacing later as a misleading "declared but has no current value" error on a
#: key that IS provisioned. So the initial load is fail-closed-with-retry
#: regardless of ``fail_open`` (a transient throttle during a mass cold-start is
#: ridden out with a short exponential backoff); ``fail_open`` governs only
#: refreshes AFTER a first good snapshot exists.
_INITIAL_REFRESH_MAX_ATTEMPTS = 4
_INITIAL_REFRESH_BACKOFF_SECONDS = 0.5


class RemoteConfigClient:
    """Typed client over the runtime config store with background polling."""

    def __init__(
        self,
        backend: ConfigBackend,
        defaults: dict[str, dict[str, object]],
        *,
        fail_open: bool,
        poll_seconds: int,
        cache_seconds: int,
    ) -> None:
        self._backend = backend
        self._fail_open = fail_open
        self._poll_seconds = poll_seconds
        self._cache_seconds = cache_seconds
        self._lock = threading.RLock()
        self._stop_event = threading.Event()
        self._poll_thread: threading.Thread | None = None
        # Cache starts as a deep copy of generated defaults; remote values merge over it.
        self._cache: dict[str, dict[str, object]] = {
            profile: dict(values) for profile, values in defaults.items()
        }
        self._defaults: dict[str, dict[str, object]] = {
            profile: dict(values) for profile, values in defaults.items()
        }
        # Monotonic timestamp of the last successful (accepted) refresh per namespace.
        # None until the first accepted refresh for that namespace; the targeted
        # per-key re-read measures poll age against this clock.
        self._last_poll_at: dict[str, float] = {}
        # Profiles whose bulk fetch has been accepted from the backend at least
        # once. Until a profile is in this set it has NO last-good remote snapshot,
        # so a failed fetch cannot fall open to defaults-only (see refresh()).
        self._accepted_profiles: set[str] = set()

    # -- lifecycle ----------------------------------------------------------

    def start(self) -> None:
        """Perform the initial refresh and start the single background poll thread.

        The initial refresh is fail-closed-with-retry regardless of ``fail_open``:
        a transient backend failure during a mass cold-start is ridden out with a
        short exponential backoff, and a persistent failure raises a precise error
        rather than accepting a generated-defaults-only snapshot (which would
        silently omit deployment-supplied keys with no default). ``fail_open``
        governs only the background poll refreshes that run AFTER this first good
        snapshot. The poll thread is started only once the initial refresh is
        accepted -- so a failed start() leaves no background thread behind.

        Raises:
            RemoteConfigError: When the initial refresh cannot fetch every profile
                after ``_INITIAL_REFRESH_MAX_ATTEMPTS`` attempts.
        """
        self._initial_refresh_with_retry()
        if self._poll_thread is not None:
            return
        self._stop_event.clear()
        self._poll_thread = threading.Thread(
            target=self._poll_loop,
            name="datrix-remote-config-poll",
            daemon=True,
        )
        self._poll_thread.start()
        logger.info("remote_config_started poll_seconds=%d", self._poll_seconds)

    def _initial_refresh_with_retry(self) -> None:
        """Run the initial refresh, retrying a transient backend outage.

        Each attempt calls :meth:`refresh`, which fails closed for any profile
        that has never been accepted (no last-good snapshot to fall open to). A
        failed attempt is retried up to ``_INITIAL_REFRESH_MAX_ATTEMPTS`` times
        with exponential backoff; the final failure re-raises as a precise
        :class:`RemoteConfigError` naming the initial-load cause. A profile
        accepted on an earlier attempt is remembered (``_accepted_profiles``), so
        only the still-unreachable profiles keep the load fail-closed.
        """
        last_exc: RemoteConfigError | None = None
        for attempt in range(1, _INITIAL_REFRESH_MAX_ATTEMPTS + 1):
            try:
                self.refresh()
                return
            except RemoteConfigError as exc:
                last_exc = exc
                if attempt >= _INITIAL_REFRESH_MAX_ATTEMPTS:
                    break
                delay = _INITIAL_REFRESH_BACKOFF_SECONDS * (2 ** (attempt - 1))
                logger.warning(
                    "remote_config_initial_refresh_retry attempt=%d/%d delay=%.2fs "
                    "error=%s",
                    attempt,
                    _INITIAL_REFRESH_MAX_ATTEMPTS,
                    delay,
                    exc,
                )
                time.sleep(delay)
        raise RemoteConfigError(
            "Initial config-store refresh failed after "
            f"{_INITIAL_REFRESH_MAX_ATTEMPTS} attempts: {last_exc}. The process "
            "cannot start on a generated-defaults-only snapshot, which omits "
            "deployment-supplied keys that have no default. Verify the config "
            "store is reachable and provisioned, then restart."
        ) from last_exc

    def stop(self) -> None:
        """Stop the background poll thread and wait for it to exit."""
        self._stop_event.set()
        thread = self._poll_thread
        if thread is not None:
            thread.join(timeout=self._poll_seconds + 1)
        self._poll_thread = None
        logger.info("remote_config_stopped")

    def _poll_loop(self) -> None:
        while not self._stop_event.wait(self._poll_seconds):
            try:
                self.refresh()
            except RemoteConfigError as exc:
                logger.warning("remote_config_poll_refresh_failed error=%s", exc)

    # -- refresh ------------------------------------------------------------

    def refresh(self) -> None:
        """Fetch every configured profile once and merge remote values over defaults.

        On any backend or validation failure: when ``fail_open`` is true the
        previous cache is preserved and the error is logged; when ``fail_open``
        is false a :class:`RemoteConfigError` is raised.
        """
        new_cache: dict[str, dict[str, object]] = {}
        # Profiles whose bulk fetch was accepted this cycle; only these advance the
        # per-namespace poll-age clock used by the targeted per-key re-read.
        accepted: list[str] = []
        for profile in PROFILE_NAMES:
            merged = dict(self._defaults.get(profile, {}))
            try:
                remote = self._backend.fetch_profile(profile)
            except Exception as exc:  # backend-specific errors are normalized here
                if not self._fail_open:
                    raise RemoteConfigError(
                        f"Config-store refresh failed for profile {profile!r}: {exc}. "
                        "Set failOpen: true to fall back to the last good cache."
                    ) from exc
                if profile not in self._accepted_profiles:
                    # Initial load for this profile: there is NO last-good remote
                    # snapshot to fall open to, only generated defaults. Serving
                    # those would silently drop deployment-supplied keys with no
                    # default (surfacing later as a misleading "declared but has no
                    # current value"). Fail closed regardless of fail_open;
                    # start()'s retry loop rides out a transient outage, then
                    # raises a precise error.
                    raise RemoteConfigError(
                        f"Initial config-store fetch failed for profile {profile!r}: "
                        f"{exc}. The first refresh must load remote values before "
                        "the process serves config; falling open now would hide "
                        "provisioned keys that have no generated default."
                    ) from exc
                logger.warning(
                    "remote_config_profile_fetch_failed profile=%s error=%s",
                    profile,
                    exc,
                )
                merged = dict(self._cache.get(profile, merged))
                new_cache[profile] = merged
                continue
            self._merge_remote(profile, merged, remote)
            new_cache[profile] = merged
            accepted.append(profile)

        now = time.monotonic()
        with self._lock:
            changed = self._changed_keys(self._cache, new_cache)
            self._cache = new_cache
            for profile in accepted:
                self._last_poll_at[profile] = now
                self._accepted_profiles.add(profile)
        if changed:
            logger.info("remote_config_refreshed changed_keys=%s", changed)

    def _merge_remote(
        self,
        profile: str,
        merged: dict[str, object],
        remote: dict[str, object],
    ) -> None:
        for key, value in remote.items():
            declared_type = _declared_value_type(profile, key)
            if declared_type is None:
                logger.warning(
                    "remote_config_unknown_remote_key profile=%s key=%s", profile, key
                )
                continue
            if not _value_matches_declared_type(declared_type, value):
                if not self._fail_open:
                    raise RemoteConfigError(
                        f"Config-store key {profile}/{key} has remote type "
                        f"{type(value).__name__} but the declared type is "
                        f"{declared_type}. Fix the stored value, or set "
                        "failOpen: true to ignore type mismatches."
                    )
                logger.warning(
                    "remote_config_type_mismatch profile=%s key=%s expected=%s",
                    profile,
                    key,
                    declared_type,
                )
                continue
            merged[key] = value

    @staticmethod
    def _changed_keys(
        old: dict[str, dict[str, object]],
        new: dict[str, dict[str, object]],
    ) -> list[str]:
        changed: list[str] = []
        for profile, values in new.items():
            old_values = old.get(profile, {})
            for key, value in values.items():
                if old_values.get(key) != value:
                    changed.append(f"{profile}/{key}")
        return sorted(changed)

    # -- targeted per-key re-read -------------------------------------------

    def _maybe_targeted_reread(self, namespace: str, key: str) -> None:
        """Force a single-key re-read when the key's TTL is shorter than the poll age.

        A targeted re-read is performed only when:
          * the key declares a ttl_seconds in ``_KEY_TTL_SECONDS``, AND
          * the elapsed time since the last accepted poll for *namespace*
            exceeds that ttl_seconds (or no poll has succeeded yet).

        Failure follows ``failOpen``: ``failOpen=false`` raises
        :class:`RemoteConfigError`; ``failOpen=true`` serves the last-known-good /
        declared default and warns. Under ``failOpen=false`` a stale value older
        than the key TTL is never served.
        """
        ttl = _KEY_TTL_SECONDS.get(namespace, {}).get(key)
        if ttl is None:
            return
        last = self._last_poll_at.get(namespace)
        age = float("inf") if last is None else (time.monotonic() - last)
        if age <= ttl:
            return
        try:
            value = self._backend.fetch_key(namespace, key)
        except Exception as exc:  # backend-specific errors are normalized here
            if not self._fail_open:
                raise RemoteConfigError(
                    f"Targeted re-read of {namespace}/{key} failed and its TTL "
                    f"({ttl}s) has elapsed: {exc}. Set failOpen: true to serve the "
                    "last-known-good value, or fix backend reachability."
                ) from exc
            logger.warning(
                "remote_config_targeted_reread_failed namespace=%s key=%s error=%s",
                namespace,
                key,
                exc,
            )
            return
        declared = _declared_value_type(namespace, key)
        if declared is None or not _value_matches_declared_type(declared, value):
            if not self._fail_open:
                raise RemoteConfigError(
                    f"Targeted re-read of {namespace}/{key} returned a value whose "
                    f"type does not match the declared type {declared!r}."
                )
            logger.warning(
                "remote_config_targeted_reread_type_mismatch namespace=%s key=%s",
                namespace,
                key,
            )
            return
        with self._lock:
            self._cache.setdefault(namespace, {})[key] = value
            self._last_poll_at[namespace] = time.monotonic()

    # -- accessors ----------------------------------------------------------

    def get(self, namespace: str, key: str) -> object:
        """Return the current scalar value for ``namespace``/``key``.

        Raises for unknown namespaces/keys and for keys declared with a secret
        reference (use :meth:`get_secret_ref` for those).
        """
        self._reject_secret_ref(namespace, key)
        self._maybe_targeted_reread(namespace, key)
        with self._lock:
            if namespace not in PROFILE_NAMES:
                raise RemoteConfigError(_unknown_namespace_message(namespace))
            if _declared_value_type(namespace, key) is None:
                raise RemoteConfigError(_unknown_key_message(namespace, key))
            profile = self._cache.get(namespace, {})
            if key not in profile:
                raise RemoteConfigError(_missing_value_message(namespace, key))
            return profile[key]

    def get_bool(self, namespace: str, key: str) -> bool:
        return self._get_typed(namespace, key, bool, "get_bool")

    def get_int(self, namespace: str, key: str) -> int:
        return self._get_typed(namespace, key, int, "get_int")

    def get_float(self, namespace: str, key: str) -> float:
        value = self.get(namespace, key)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise RemoteConfigError(_type_message(namespace, key, "get_float", value))
        return float(value)

    def get_string(self, namespace: str, key: str) -> str:
        return self._get_typed(namespace, key, str, "get_string")

    def get_string_optional(self, namespace: str, key: str) -> str | None:
        """Return the string value for a declared key, or ``None`` if unseeded.

        Unlike :meth:`get_string`, a key that is DECLARED (present in the
        value-type table) but has no value in the store returns ``None`` instead
        of raising. Used for deploy-time-only values that a given platform may
        legitimately leave unseeded -- e.g. the Azure Application Insights
        tracing connection string, seeded only on Azure. Still raises for an
        unknown namespace/key (a real contract error) and for a present value of
        the wrong type.
        """
        self._reject_secret_ref(namespace, key)
        self._maybe_targeted_reread(namespace, key)
        with self._lock:
            if namespace not in PROFILE_NAMES:
                raise RemoteConfigError(_unknown_namespace_message(namespace))
            if _declared_value_type(namespace, key) is None:
                raise RemoteConfigError(_unknown_key_message(namespace, key))
            value = self._cache.get(namespace, {}).get(key)
        if value is None:
            return None
        if not isinstance(value, str):
            raise RemoteConfigError(
                _type_message(namespace, key, "get_string_optional", value)
            )
        return value

    def _get_typed(
        self,
        namespace: str,
        key: str,
        expected: type,
        accessor: str,
    ) -> object:
        value = self.get(namespace, key)
        # ``bool`` is a subclass of ``int``; keep the two distinct for accessors.
        if expected is int and isinstance(value, bool):
            raise RemoteConfigError(_type_message(namespace, key, accessor, value))
        if expected is bool and not isinstance(value, bool):
            raise RemoteConfigError(_type_message(namespace, key, accessor, value))
        if not isinstance(value, expected):
            raise RemoteConfigError(_type_message(namespace, key, accessor, value))
        return value

    def get_namespace(self, namespace: str) -> dict[str, object]:
        """Return a copy of all current scalar values for ``namespace``."""
        with self._lock:
            profile = self._cache.get(namespace)
            if profile is None:
                raise RemoteConfigError(_unknown_namespace_message(namespace))
            return dict(profile)

    def get_secret_ref(self, namespace: str, key: str) -> SecretRef:
        """Return the non-sensitive secret reference for a ``secretRef`` key."""
        refs = _SECRET_REFS.get(namespace)
        if refs is None or key not in refs:
            raise RemoteConfigError(
                f"Config-store key {namespace}/{key} is not declared with a "
                "secretRef. Use get/get_* for scalar values; get_secret_ref is "
                "only valid for secret-reference keys."
            )
        return refs[key]

    def _reject_secret_ref(self, namespace: str, key: str) -> None:
        refs = _SECRET_REFS.get(namespace)
        if refs is not None and key in refs:
            raise RemoteConfigError(
                f"Config-store key {namespace}/{key} is declared with a secretRef "
                "and carries no scalar value. Use get_secret_ref(namespace, key) "
                "to obtain its non-sensitive reference metadata."
            )


def _declared_value_type(namespace: str, key: str) -> str | None:
    return _DECLARED_VALUE_TYPES.get(namespace, {}).get(key)


def _value_matches_declared_type(declared_type: str, value: object) -> bool:
    if declared_type == "Boolean":
        return isinstance(value, bool)
    if declared_type == "Integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if declared_type == "Float":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if declared_type == "String":
        return isinstance(value, str)
    return False


def _unknown_namespace_message(namespace: str) -> str:
    return (
        f"Unknown config-store namespace {namespace!r}. Valid namespaces: "
        f"{sorted(PROFILE_NAMES)}."
    )


def _unknown_key_message(namespace: str, key: str) -> str:
    return (
        f"Unknown config-store key {namespace}/{key}. The key is not declared in "
        f"namespace {namespace!r}; check the configStore profile definition."
    )


def _missing_value_message(namespace: str, key: str) -> str:
    return (
        f"Config-store key {namespace}/{key} is declared but has no current "
        "value. It has no generated default and no accepted remote value has "
        "been loaded yet."
    )


def _type_message(namespace: str, key: str, accessor: str, value: object) -> str:
    return (
        f"Config-store key {namespace}/{key} accessed via {accessor} but its value "
        f"has type {type(value).__name__}. Use the accessor matching the declared "
        "key type."
    )


def build_client() -> RemoteConfigClient:
    """Construct the client from the generated defaults and the selected backend."""
    from library_book_service.config.backends.file_backend import FileConfigBackend

    backend: ConfigBackend = FileConfigBackend()
    return RemoteConfigClient(
        backend,
        _load_defaults(),
        fail_open=False,
        poll_seconds=30,
        cache_seconds=300,
    )
