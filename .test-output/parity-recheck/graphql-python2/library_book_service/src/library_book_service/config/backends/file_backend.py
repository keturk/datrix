"""File-backed JSON config store backend.

Auto-generated by datrix-codegen-python. Do not edit manually.

Reads the baked JSON config profile at the path baked into
``config/_bootstrap.CONFIG_FILE_PATH`` at generation time.  No environment
variable reads, no network calls.

The JSON file is expected to be a mapping of profile name to a mapping of
config key to scalar value:

.. code-block:: json

    {
      "connections": {
        "orders_db_host": "localhost",
        "orders_db_port": 5432
      },
      "featureFlags": {
        "enableCheckout": true
      }
    }

Each call to :meth:`FileConfigBackend.fetch_profile` re-reads the file from
disk so that config changes applied by replacing the mounted JSON file are
picked up on the next poll interval without restarting the service.

Behaviour on missing or malformed file:

- ``FileConfigError`` is raised immediately (fail-loud).  The
  :class:`~remote_config.RemoteConfigClient` propagates this according to its
  ``fail_open`` setting: when ``fail_open=False`` (the default) the error is
  re-raised so the service exits with a clear message; when ``fail_open=True``
  the previous cache is retained.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)


class FileConfigError(RuntimeError):
    """Raised when the baked JSON config file cannot be read or is malformed."""


class FileConfigBackend:
    """Read config-store profiles from the baked JSON file at ``CONFIG_FILE_PATH``.

    The file is read fresh on every :meth:`fetch_profile` call so rolling
    updates (replacing the mounted JSON) are visible within one poll interval.
    """

    def fetch_profile(self, profile: str) -> dict[str, object]:
        """Return the stored scalar values for *profile* keyed by config key name.

        Args:
            profile: Config-store profile (namespace) name to fetch.

        Returns:
            Mapping of key name to scalar value.  Returns an empty mapping
            when the profile is not present in the JSON file (the client falls
            back to generated defaults for absent keys).

        Raises:
            FileConfigError: When ``CONFIG_FILE_PATH`` is not set, the file is
                missing, or its content is not a valid JSON object.
        """
        from library_book_service.config import _bootstrap  # noqa: PLC0415

        file_path: str | None = _bootstrap.CONFIG_FILE_PATH
        if not file_path:
            raise FileConfigError(
                "Config file path is not set. "
                "CONFIG_FILE_PATH must be a non-empty string baked into "
                "config/_bootstrap.py at generation time. "
                "Regenerate the service to fix the baked constant."
            )
        path = Path(file_path)
        if not path.exists():
            raise FileConfigError(
                f"Config file {file_path!r} does not exist. "
                "Mount the baked JSON config file at the path baked into "
                "config/_bootstrap.CONFIG_FILE_PATH before starting the service."
            )
        try:
            with path.open(encoding="utf-8") as handle:
                data = json.load(handle)
        except json.JSONDecodeError as exc:
            raise FileConfigError(
                f"Config file {file_path!r} is not valid JSON: {exc}. "
                "The file must be a JSON object mapping profile name to "
                "key -> scalar value."
            ) from exc
        except OSError as exc:
            raise FileConfigError(
                f"Cannot read config file {file_path!r}: {exc}. "
                "Verify that the file is readable by the service process."
            ) from exc
        if not isinstance(data, dict):
            raise FileConfigError(
                f"Config file {file_path!r} must be a JSON object mapping "
                f"profile name to key -> scalar value; got {type(data).__name__}."
            )
        profile_data = data.get(profile, {})
        if not isinstance(profile_data, dict):
            raise FileConfigError(
                f"Config file {file_path!r} profile {profile!r} must be a "
                f"JSON object of key -> scalar value; got "
                f"{type(profile_data).__name__}."
            )
        logger.debug(
            "file_config_backend_fetched profile=%s keys=%d", profile, len(profile_data)
        )
        return dict(profile_data)

    def fetch_key(self, profile: str, key: str) -> object:
        """Fetch exactly one config key for a targeted per-key TTL re-read.

        The file backend exposes only profile blobs, so it re-reads the profile
        and selects *key*. A missing key raises :class:`FileConfigError` so the
        client applies its ``fail_open`` policy.

        Raises:
            FileConfigError: When the config file is unreadable/malformed (via
                :meth:`fetch_profile`) or *key* is absent from *profile*.
        """
        profile_data = self.fetch_profile(profile)
        if key not in profile_data:
            raise FileConfigError(
                f"Config key {profile}/{key} is not present in the baked JSON "
                "config file. Add the key to the mounted profile, or remove its "
                "ttlSeconds so it is governed by the poll interval alone."
            )
        return profile_data[key]
