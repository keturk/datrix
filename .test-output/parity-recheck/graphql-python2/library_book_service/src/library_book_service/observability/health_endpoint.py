"""Health, readiness, and liveness endpoints.

Three distinct contracts:

* ``/live``   -- process liveness; 200 whenever the process is up. No checks.
* ``/ready``  -- readiness; 503 when any required dependency (or a degraded
                 dependency declared ``readyOnDegraded = false``) is down.
* ``/health`` -- detailed per-dependency report (status / required / health / error),
                 including degraded optional dependencies and cache probes.

Auto-generated by datrix-codegen-python. Do not edit manually.
"""

from __future__ import annotations

import logging

from fastapi import APIRouter, FastAPI, Response

logger = logging.getLogger(__name__)

health_router = APIRouter(tags=["health"])

_STATUS_UP = "up"
_STATUS_DOWN = "down"
_STATUS_DEGRADED = "degraded"
_SERVICE_NAME = "library_book_service"

from library_book_service.book_db.health import check_database_health


async def _check_database() -> dict[str, object]:
    """Probe the primary database; the service's own store is required for readiness."""
    db_health = await check_database_health()
    up = db_health["status"] == "healthy"
    result: dict[str, object] = {
        "status": _STATUS_UP if up else _STATUS_DOWN,
        "required": True,
    }
    if not up and "error" in db_health:
        result["error"] = db_health["error"]
    return result


@health_router.get("/live")
async def liveness_check() -> dict[str, str]:
    """Process liveness. Returns 200 whenever the process is serving requests.

    Performs no dependency checks -- a live process that cannot reach its
    dependencies is still live (use ``/ready`` to gate traffic).
    """
    return {"status": _STATUS_UP, "service": _SERVICE_NAME}


@health_router.get("/ready")
async def readiness_check(response: Response) -> dict[str, object]:
    """Readiness gate. Returns 503 when any readiness-blocking dependency is down.

    A ``required`` dependency, or a ``degraded`` dependency declared
    ``readyOnDegraded = false``, blocks readiness when its probe is down. An
    ``optional`` dependency never blocks readiness.
    """
    blockers: dict[str, str] = {}
    db = await _check_database()
    if db["status"] != _STATUS_UP:
        blockers["database"] = str(db["status"])
    if blockers:
        response.status_code = 503
        logger.warning(
            "readiness_not_ready service=%s blockers=%s", _SERVICE_NAME, blockers
        )
        return {"status": _STATUS_DOWN, "service": _SERVICE_NAME, "blockers": blockers}
    return {"status": _STATUS_UP, "service": _SERVICE_NAME, "blockers": {}}


@health_router.get("/health")
async def health_check(response: Response) -> dict[str, object]:
    """Detailed health report with a per-dependency ``checks`` map.

    Overall status is ``down`` when a required dependency is down, ``degraded``
    when a non-required dependency is down or degraded, else ``up``. Returns 503
    only when a required dependency is down.
    """
    checks: dict[str, dict[str, object]] = {}
    required_down = False
    degraded = False
    checks["database"] = await _check_database()
    if checks["database"]["status"] != _STATUS_UP:
        required_down = True

    if required_down:
        overall = _STATUS_DOWN
        response.status_code = 503
    elif degraded:
        overall = _STATUS_DEGRADED
    else:
        overall = _STATUS_UP

    return {
        "status": overall,
        "service": _SERVICE_NAME,
        "checks": checks,
    }


