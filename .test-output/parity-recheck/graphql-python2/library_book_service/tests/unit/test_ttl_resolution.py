class InMemoryClock:
    """Deterministic, advance-able clock -- real in-memory time source.

    Replaces _now() in the resolver so TTL boundaries are exact and
    reproducible without wall-clock sleeps.
    """

    def __init__(self, start: float = 0.0) -> None:
        self._now: float = start

    def now(self) -> float:
        """Return the current simulated monotonic time."""
        return self._now

    def advance(self, seconds: float) -> None:
        """Advance the simulated clock by *seconds*."""
        self._now += seconds


