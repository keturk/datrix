def test_config_targeted_reread_fail_open() -> None:
    """Per-key TTL re-read failure serves last-known config value (fail-open).

    Tests _maybe_targeted_reread directly with a real RemoteConfigClient
    constructed from in-memory backend + explicit defaults.  The namespace
    used (``"connections"``) is patched into the client's internal cache and
    poll-age clock so the targeted re-read fires -- no reliance on generated
    fixture-specific profile names.
    """
    import time

    from library_book_service.config.remote_config import _KEY_TTL_SECONDS

    config_backend = InMemoryConfigBackend()
    config_backend.profiles["connections"] = {"db_host": "db.local", "db_port": 5432}

    # Build a real RemoteConfigClient with the in-memory backend and explicit defaults.
    defaults: dict[str, dict[str, object]] = {
        "connections": {"db_host": "localhost", "db_port": 5432},
    }
    client = RemoteConfigClient(
        config_backend,
        defaults,
        fail_open=True,
        poll_seconds=60,
        cache_seconds=30,
    )

    # Seed the client cache directly (skip refresh which validates PROFILE_NAMES).
    # This mirrors what a real refresh + merge would produce for this profile.
    with client._lock:  # type: ignore[attr-defined]
        client._cache["connections"] = {"db_host": "db.local", "db_port": 5432}  # type: ignore[attr-defined]
        client._last_poll_at["connections"] = time.monotonic() - 99999  # type: ignore[attr-defined]

    # Simulate backend failure for the targeted re-read.
    config_backend.fail = True

    # Inject a per-key TTL so _maybe_targeted_reread fires for our test key.
    original_connections_ttls = dict(_KEY_TTL_SECONDS.get("connections", {}))
    try:
        _KEY_TTL_SECONDS.setdefault("connections", {})["db_host"] = 1  # type: ignore[index]

        # _maybe_targeted_reread with fail_open=True must NOT raise; it must
        # log a warning and leave the cached value untouched.
        client._maybe_targeted_reread("connections", "db_host")  # type: ignore[attr-defined]

        # After the failed targeted re-read, the last-known value must still be served.
        with client._lock:  # type: ignore[attr-defined]
            cached_val = client._cache.get("connections", {}).get("db_host")  # type: ignore[attr-defined]
    finally:
        # Restore module-level TTL state.
        if original_connections_ttls:
            _KEY_TTL_SECONDS["connections"] = original_connections_ttls  # type: ignore[index]
        elif (
            "connections" in _KEY_TTL_SECONDS
            and "db_host" in _KEY_TTL_SECONDS["connections"]
        ):  # type: ignore[operator]
            del _KEY_TTL_SECONDS["connections"]["db_host"]  # type: ignore[index]

    assert cached_val == "db.local", (
        f"Fail-open targeted re-read must leave last-known-good 'db.local' in cache; "
        f"got {cached_val!r}"
    )
    assert config_backend.read_count >= 1, (
        "Backend must have been contacted for the targeted re-read"
    )
    logger.info(
        "test_config_targeted_reread_fail_open completed cached_val=%s", cached_val
    )


