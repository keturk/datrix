class _RetryTransport(httpx.AsyncBaseTransport):
    """Retry on stale keep-alive ReadError/ReadTimeout/ConnectError.

    httpx ``retries`` only covers connect failures.  This wrapper retries
    at the transport level so every request method (GET, POST, DELETE ...)
    is transparently protected against transient Docker networking errors.
    """

    def __init__(
        self,
        wrapped: httpx.AsyncBaseTransport,
        retries: int = 3,
        delay: float = 1.0,
    ) -> None:
        self._wrapped = wrapped
        self._retries = retries
        self._delay = delay

    async def handle_async_request(self, request: httpx.Request) -> httpx.Response:
        last_exc: httpx.ReadError | httpx.ReadTimeout | httpx.ConnectError | None = None
        for attempt in range(1 + self._retries):
            try:
                return await self._wrapped.handle_async_request(request)
            except (httpx.ReadError, httpx.ReadTimeout, httpx.ConnectError) as exc:
                last_exc = exc
                if attempt < self._retries:
                    logger.warning(
                        "transport_retry attempt=%d/%d error=%s",
                        attempt + 1,
                        self._retries,
                        exc,
                    )
                    await asyncio.sleep(self._delay)
        assert last_exc is not None  # noqa: S101
        raise last_exc

    async def aclose(self) -> None:
        await self._wrapped.aclose()


