package warehouse_warehouse_service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Provides a {@code com.fasterxml.jackson.databind.ObjectMapper} bean.
 *
 * <p>Spring Boot 4.1's OWN Jackson auto-configuration registers the NEW Jackson 3 {@code
 * tools.jackson.databind.ObjectMapper} type (this generator's Spring Boot 4.1 baseline) -- a
 * DIFFERENT class from the classic {@code com.fasterxml.jackson.databind .ObjectMapper} generated
 * pubsub/messaging code (e.g. the Kafka event producer) imports and depends on. This bean bridges
 * that gap so classic-Jackson-typed constructor injection resolves without requiring every
 * generated consumer to migrate to the Jackson 3 API.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
public class JacksonLegacyConfig {

  @Bean
  public ObjectMapper objectMapper() {
    return new ObjectMapper().registerModule(new JavaTimeModule());
  }
}
