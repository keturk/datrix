package ecommerce_user_service.user_db;

import com.zaxxer.hikari.HikariDataSource;
import java.sql.Connection;
import java.sql.SQLException;
import javax.sql.DataSource;
import liquibase.Liquibase;
import liquibase.database.Database;
import liquibase.database.DatabaseFactory;
import liquibase.database.jvm.JdbcConnection;
import liquibase.resource.ClassLoaderResourceAccessor;

/**
 * Applies the {@code user-db} RDBMS block's Liquibase changelog ({@code
 * changelog/user-db/changelog-master.yaml}) against a live connection.
 *
 * <p>Invoked by the {@code --datrix.run=migrate:user-db} entrypoint dispatch. Spring Boot's own
 * Liquibase autoconfiguration is disabled ({@code spring.liquibase.enabled=false}); this is the
 * ONLY execution path that applies this block's migrations.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
public final class UserDbMigrationRunner {

  private static final String CHANGELOG_RESOURCE = "changelog/user-db/changelog-master.yaml";
  private static final int MAX_DATABASE_READY_ATTEMPTS = 3;
  private static final int DATABASE_READY_RETRY_DELAY_SECONDS = 5;

  private UserDbMigrationRunner() {}

  /**
   * Waits for a live connection from *dataSource* (bounded retry -- a managed RDBMS instance has no
   * compose health check standing between this process and the database becoming reachable),
   * applies the changelog, and closes the connection.
   */
  public static void run(DataSource dataSource) throws Exception {
    try (Connection connection = acquireReadyConnection(dataSource)) {
      run(connection);
    }
  }

  /**
   * Retries {@code dataSource.getConnection()} up to {@link #MAX_DATABASE_READY_ATTEMPTS} times,
   * {@link #DATABASE_READY_RETRY_DELAY_SECONDS} apart. On exhaustion throws with the last driver
   * {@link SQLException} as its cause and the JDBC URL and block named in the message, so the
   * operator sees the driver's own diagnosis (connection refused, authentication failure, unknown
   * database) instead of an opaque pool timeout.
   */
  private static Connection acquireReadyConnection(DataSource dataSource) throws Exception {
    SQLException lastFailure = null;
    for (int attempt = 1; attempt <= MAX_DATABASE_READY_ATTEMPTS; attempt++) {
      try {
        return dataSource.getConnection();
      } catch (SQLException e) {
        lastFailure = e;
        if (attempt < MAX_DATABASE_READY_ATTEMPTS) {
          Thread.sleep(DATABASE_READY_RETRY_DELAY_SECONDS * 1000L);
        }
      }
    }
    throw new IllegalStateException(
        "Database was not ready for block user-db after "
            + MAX_DATABASE_READY_ATTEMPTS
            + " attempts (jdbcUrl="
            + jdbcUrlOf(dataSource)
            + ")",
        lastFailure);
  }

  /**
   * The datasource's configured JDBC URL. Built without the password (the password is a separate
   * Hikari property, never embedded in the URL -- see {@code rdbms_datasource_config.java.j2}), so
   * naming it here is safe.
   */
  private static String jdbcUrlOf(DataSource dataSource) {
    if (dataSource instanceof HikariDataSource hikariDataSource) {
      return hikariDataSource.getJdbcUrl();
    }
    return "<unknown>";
  }

  /** Applies the changelog over an already-open *connection* (caller closes it). */
  public static void run(Connection connection) throws Exception {
    Database database =
        DatabaseFactory.getInstance()
            .findCorrectDatabaseImplementation(new JdbcConnection(connection));
    try (Liquibase liquibase =
        new Liquibase(CHANGELOG_RESOURCE, new ClassLoaderResourceAccessor(), database)) {
      liquibase.update("");
    }
  }
}
