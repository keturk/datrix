package ecommerce_notification_service.notification_db;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import ecommerce_notification_service.config.RemoteConfig;
import ecommerce_notification_service.security.SecretsResolver;
import javax.sql.DataSource;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * HikariCP {@code DataSource} configuration for the 'notificationDb' RDBMS block (postgres). Every
 * RDBMS block gets its own explicitly-named bean -- no {@code @Primary} guess across multi-block
 * services.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
public class NotificationDbDataSourceConfig {

  @Bean(name = "notification_dbDataSource")
  public DataSource notification_dbDataSource(
      RemoteConfig remoteConfig, SecretsResolver secretsResolver) {
    String host = remoteConfig.getNotificationDbHost();
    int port = remoteConfig.getNotificationDbPort();
    String database = remoteConfig.getNotificationDbDatabase();
    String username = remoteConfig.getNotificationDbUser();

    String jdbcUrl = "jdbc:postgresql://" + host + ":" + port + "/" + database;

    HikariConfig hikariConfig = new HikariConfig();
    hikariConfig.setJdbcUrl(jdbcUrl);
    hikariConfig.setDriverClassName("org.postgresql.Driver");
    hikariConfig.setUsername(username);
    hikariConfig.setPassword(secretsResolver.getSecret("notification_db_password"));
    hikariConfig.setMaximumPoolSize(20);
    // Initialize the pool lazily: the DataSource bean is created without
    // opening a physical connection, and the first connection is acquired on
    // first use. The application therefore does not require the database to be
    // reachable at startup (parity with the python/TypeScript generators,
    // whose ORM engines connect lazily) -- connectivity is surfaced by the
    // generated health indicator, not by a boot-time crash.
    hikariConfig.setInitializationFailTimeout(-1);

    return new HikariDataSource(hikariConfig);
  }
}
