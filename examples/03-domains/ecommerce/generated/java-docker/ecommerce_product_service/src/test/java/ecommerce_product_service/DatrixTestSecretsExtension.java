package ecommerce_product_service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.concurrent.atomic.AtomicBoolean;
import org.junit.jupiter.api.extension.BeforeAllCallback;
import org.junit.jupiter.api.extension.ExtensionContext;

/**
 * Seeds the mounted-secrets directory every generated full-context test needs, once per test JVM.
 *
 * <p>Auto-registered for the whole module via {@code META-INF/services/org.junit.jupiter
 * .api.extension.Extension} and {@code junit.jupiter.extensions.autodetection.enabled} in {@code
 * junit-platform.properties} -- no test class references it.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
public final class DatrixTestSecretsExtension implements BeforeAllCallback {

  /**
   * The resolver's test seam -- a JVM system property, never an environment variable. Production
   * always uses the baked {@code /run/secrets} default.
   */
  private static final String SECRETS_DIR_PROPERTY = "datrix.secrets.dir";

  /** Dummy value written for every declared handle. Never a real credential. */
  private static final String TEST_SECRET_VALUE = "datrix-test-secret";

  /** Seed exactly once per JVM -- Surefire reuses one JVM across every test class. */
  private static final AtomicBoolean SEEDED = new AtomicBoolean(false);

  @Override
  public void beforeAll(ExtensionContext context) throws IOException {
    if (!SEEDED.compareAndSet(false, true)) {
      return;
    }
    // An explicitly supplied directory always wins. The no-infrastructure
    // unit phase sets nothing, so it gets the dummy values below. The
    // deployment phase runs the SAME module (`mvnw test -Dgroups=spec,
    // integration`) against a live stack on the host, where the real
    // credentials the containers use exist in a real directory -- that
    // caller passes -Ddatrix.secrets.dir and must not have it overwritten
    // with dummies. Where that directory lives is the deployment target's
    // layout, never something this generator may assume.
    if (!System.getProperty(SECRETS_DIR_PROPERTY, "").isEmpty()) {
      return;
    }
    Path secretsDir = Files.createTempDirectory("datrix-test-secrets");
    // Registered BEFORE the files below: deleteOnExit deletes in reverse
    // registration order, so the directory is removed after its contents.
    secretsDir.toFile().deleteOnExit();
    writeSecret(secretsDir, "docdb_secret-key");
    writeSecret(secretsDir, "minio_access_key");
    writeSecret(secretsDir, "minio_secret_key");
    writeSecret(secretsDir, "product_db_password");
    writeSecret(secretsDir, "trusted_caller_secret");
    System.setProperty(SECRETS_DIR_PROPERTY, secretsDir.toString());
  }

  private static void writeSecret(Path secretsDir, String renderedName) throws IOException {
    Path secretFile = secretsDir.resolve(renderedName);
    Files.writeString(secretFile, TEST_SECRET_VALUE);
    secretFile.toFile().deleteOnExit();
  }
}
