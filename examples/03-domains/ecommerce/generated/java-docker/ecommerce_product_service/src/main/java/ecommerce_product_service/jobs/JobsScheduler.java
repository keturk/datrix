package ecommerce_product_service.jobs;

import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Profile;
import org.springframework.scheduling.annotation.EnableScheduling;
import org.springframework.scheduling.annotation.Scheduled;

/**
 * Registers one {@code @Scheduled} cron trigger per job.
 *
 * <p>{@code @Profile}-gated to {@code (!isolated-run) | job-runner}: active in the default web-app
 * boot (no explicit profile -- {@code isolated-run} is unset -- UNLESS this service's {@code
 * runtime.consumers} resolves to {@code decoupled}, in which case {@code Application.java}'s
 * default branch activates {@code isolated-run} too) and in the standalone {@code
 * --datrix.run=job-runner} worker process (which activates the {@code job-runner} profile), but
 * NEVER in migrate/seed/search-init/ queue-worker/event-consumer/serverless containers (all of
 * which activate only {@code isolated-run}) -- closing the latent duplicate-execution bug where
 * this {@code @Configuration} bean previously activated unconditionally on EVERY non-web container
 * boot, N-fold-duplicating every scheduled job across every long-lived worker/consumer container a
 * service happened to also have. The SAME {@link JobRunner} wrapper methods run whether this
 * scheduler is active inside the web-app process (in-process scheduling) or the standalone
 * job-runner worker process: job-body logic never diverges between the two.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
@EnableScheduling
@Profile("(!isolated-run) | job-runner")
public class JobsScheduler {

  private final JobRunner jobRunner;

  public JobsScheduler(JobRunner jobRunner) {
    this.jobRunner = jobRunner;
  }

  /**
   * Job: ReleaseExpiredReservations
   *
   * <p>DSL schedule: {@code *&#47;5 * * * *} -- Spring cron: {@code 0 *&#47;5 * * * *}
   */
  @Scheduled(cron = "0 */5 * * * *")
  public void triggerReleaseExpiredReservations() {
    jobRunner.runReleaseExpiredReservations();
  }

  /**
   * Job: UpdatePopularProducts
   *
   * <p>DSL schedule: {@code 0 * * * *} -- Spring cron: {@code 0 0 * * * *}
   */
  @Scheduled(cron = "0 0 * * * *")
  public void triggerUpdatePopularProducts() {
    jobRunner.runUpdatePopularProducts();
  }
}
