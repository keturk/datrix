  /** List object keys in the images folder. */
  public List<String> listImages(String prefix) throws IOException {
    String fullPrefix = imagesKey(prefix);
    var response =
        bucketClient()
            .listObjectsV2(
                ListObjectsV2Request.builder().bucket(bucket).prefix(fullPrefix).build());
    return response.contents().stream().map(o -> o.key()).toList();
  }

  /**
   * Get the metadata for a file in the images folder -- {@code "metadata"} holds the object's own
   * key/value metadata map, {@code "contentType"} (String) and {@code "contentLength"} (Integer)
   * carry the object's stored content type/size (backs {@code replay_operator.java.j2}'s
   * envelope-field extraction AND its {@code StorageRef} reconstruction, which reads {@code
   * meta.get("metadata")}/{@code "contentType"}/ {@code "contentLength"}).
   */
  public java.util.Map<String, Object> getImagesMetadata(String filename) throws IOException {
    String key = imagesKey(filename);
    java.util.Map<String, Object> result = new java.util.LinkedHashMap<>();
    var response =
        bucketClient().headObject(HeadObjectRequest.builder().bucket(bucket).key(key).build());
    result.put("metadata", new java.util.LinkedHashMap<String, Object>(response.metadata()));
    result.put("contentType", response.contentType());
    result.put(
        "contentLength",
        response.contentLength() != null ? response.contentLength().intValue() : null);
    return result;
  }

