package ecommerce_product_service;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import java.time.Duration;
import org.springframework.stereotype.Component;

/**
 * Shared Micrometer counters/timers for storage operation monitoring.
 *
 * <p>Registered under the framework application-metric names ({@code storage.operation.total}
 * renders as {@code storage_operation_total}, the {@code storage.operation.duration} timer as
 * {@code storage_operation_duration_seconds}, {@code storage.bytes.total} as {@code
 * storage_bytes_total}) with the registry's {@code service}/{@code block}/{@code provider}/{@code
 * operation}[/{@code status}] tag set; the timer publishes the registry's bucket boundaries as
 * service-level objectives so its {@code _bucket} series cuts where every other language cuts.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class StorageMetrics {

  private static final String OPERATION_TOTAL_METRIC = "storage.operation.total";
  private static final String OPERATION_DURATION_METRIC = "storage.operation.duration";
  private static final String BYTES_TOTAL_METRIC = "storage.bytes.total";
  private static final String SERVICE_TAG = "service";
  private static final String BLOCK_TAG = "block";
  private static final String PROVIDER_TAG = "provider";
  private static final String OPERATION_TAG = "operation";
  private static final String STATUS_TAG = "status";
  private static final String SERVICE_NAME = "ecommerce.ProductService";
  public static final String STATUS_SUCCESS = "success";
  public static final String STATUS_ERROR = "error";

  private final MeterRegistry registry;

  public StorageMetrics(MeterRegistry registry) {
    this.registry = registry;
  }

  /** Record one storage operation (upload/download/delete) with its outcome. */
  public void recordOperation(String block, String provider, String operation, String status) {
    Counter.builder(OPERATION_TOTAL_METRIC)
        .tag(SERVICE_TAG, SERVICE_NAME)
        .tag(BLOCK_TAG, block)
        .tag(PROVIDER_TAG, provider)
        .tag(OPERATION_TAG, operation)
        .tag(STATUS_TAG, status)
        .register(registry)
        .increment();
  }

  /** Record the duration of one storage operation, in nanoseconds. */
  public void recordDuration(String block, String provider, String operation, long durationNanos) {
    Timer.builder(OPERATION_DURATION_METRIC)
        .tag(SERVICE_TAG, SERVICE_NAME)
        .tag(BLOCK_TAG, block)
        .tag(PROVIDER_TAG, provider)
        .tag(OPERATION_TAG, operation)
        .serviceLevelObjectives(
            Duration.ofMillis(10),
            Duration.ofMillis(50),
            Duration.ofMillis(100),
            Duration.ofMillis(250),
            Duration.ofMillis(500),
            Duration.ofMillis(1000),
            Duration.ofMillis(2500),
            Duration.ofMillis(5000),
            Duration.ofMillis(10000),
            Duration.ofMillis(30000))
        .register(registry)
        .record(Duration.ofNanos(durationNanos));
  }

  /** Add the bytes one completed upload or download moved. */
  public void recordBytes(String block, String provider, String operation, long bytes) {
    Counter.builder(BYTES_TOTAL_METRIC)
        .tag(SERVICE_TAG, SERVICE_NAME)
        .tag(BLOCK_TAG, block)
        .tag(PROVIDER_TAG, provider)
        .tag(OPERATION_TAG, operation)
        .register(registry)
        .increment(bytes);
  }
}
