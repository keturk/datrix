package ecommerce_product_service.observability;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.DistributionSummary;
import io.micrometer.core.instrument.Gauge;
import io.micrometer.core.instrument.MeterRegistry;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;
import org.springframework.web.servlet.HandlerMapping;

/**
 * Records the framework HTTP request metrics for every request: {@code http_requests_total} and
 * {@code http_errors_total} (counters, labelled by method, endpoint and status code), {@code
 * http_request_duration_seconds} (a histogram in seconds over the framework's shared latency
 * buckets) and {@code http_requests_in_progress} (a gauge of requests currently being served).
 *
 * <p>Registered as {@code http.requests} / {@code http.errors} / {@code
 * http.request.duration.seconds} / {@code http.requests.in_progress}: Micrometer's Prometheus
 * naming renders the counters with a {@code _total} suffix and the summary (which, unlike a Timer,
 * appends no unit of its own) and the gauge under their own names, so the exposition carries
 * exactly the series the shared dashboards read.
 *
 * <p>The endpoint label is the matched route pattern ({@code /api/v1/orders/{id}}), never the raw
 * request URI, so the label set stays bounded.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class HttpMetricsFilter extends OncePerRequestFilter {

  private static final String REQUESTS_METRIC = "http.requests";
  private static final String ERRORS_METRIC = "http.errors";
  private static final String DURATION_METRIC = "http.request.duration.seconds";
  private static final String IN_PROGRESS_METRIC = "http.requests.in_progress";
  private static final String METHOD_TAG = "method";
  private static final String ENDPOINT_TAG = "endpoint";
  private static final String STATUS_CODE_TAG = "status_code";
  private static final int ERROR_STATUS_FLOOR = 400;
  private static final double NANOS_PER_SECOND = 1_000_000_000.0;
  private static final String UNMATCHED_ENDPOINT = "unmatched";

  private final MeterRegistry registry;
  private final ConcurrentHashMap<String, Counter> requestCounters = new ConcurrentHashMap<>();
  private final ConcurrentHashMap<String, Counter> errorCounters = new ConcurrentHashMap<>();
  private final ConcurrentHashMap<String, DistributionSummary> durations =
      new ConcurrentHashMap<>();
  private final ConcurrentHashMap<String, AtomicInteger> inProgress = new ConcurrentHashMap<>();

  public HttpMetricsFilter(MeterRegistry registry) {
    this.registry = registry;
  }

  @Override
  protected void doFilterInternal(
      HttpServletRequest request, HttpServletResponse response, FilterChain chain)
      throws ServletException, IOException {
    long start = System.nanoTime();
    String method = request.getMethod();
    // The route is matched inside the chain, so the in-progress gauge --
    // taken before it -- is keyed by method alone (the registry's label set).
    AtomicInteger inFlight =
        inProgress.computeIfAbsent(
            method,
            k -> {
              AtomicInteger count = new AtomicInteger();
              Gauge.builder(IN_PROGRESS_METRIC, count, AtomicInteger::get)
                  .tag(METHOD_TAG, method)
                  .register(registry);
              return count;
            });
    inFlight.incrementAndGet();
    try {
      chain.doFilter(request, response);
    } finally {
      inFlight.decrementAndGet();
      String endpoint = matchedEndpoint(request);
      String statusCode = Integer.toString(response.getStatus());
      requestCounters
          .computeIfAbsent(
              method + " " + endpoint + " " + statusCode,
              k ->
                  Counter.builder(REQUESTS_METRIC)
                      .tag(METHOD_TAG, method)
                      .tag(ENDPOINT_TAG, endpoint)
                      .tag(STATUS_CODE_TAG, statusCode)
                      .register(registry))
          .increment();
      durations
          .computeIfAbsent(
              method + " " + endpoint,
              k ->
                  DistributionSummary.builder(DURATION_METRIC)
                      .tag(METHOD_TAG, method)
                      .tag(ENDPOINT_TAG, endpoint)
                      .serviceLevelObjectives(
                          0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0)
                      .register(registry))
          .record((System.nanoTime() - start) / NANOS_PER_SECOND);
      if (response.getStatus() >= ERROR_STATUS_FLOOR) {
        errorCounters
            .computeIfAbsent(
                method + " " + endpoint + " " + statusCode,
                k ->
                    Counter.builder(ERRORS_METRIC)
                        .tag(METHOD_TAG, method)
                        .tag(ENDPOINT_TAG, endpoint)
                        .tag(STATUS_CODE_TAG, statusCode)
                        .register(registry))
            .increment();
      }
    }
  }

  private static String matchedEndpoint(HttpServletRequest request) {
    Object pattern = request.getAttribute(HandlerMapping.BEST_MATCHING_PATTERN_ATTRIBUTE);
    return pattern == null ? UNMATCHED_ENDPOINT : pattern.toString();
  }
}
