  private static void runWithTimeout(Runnable body, int timeoutSeconds) {
    Future<?> future = EXECUTOR.submit(body);
    try {
      future.get(timeoutSeconds, TimeUnit.SECONDS);
    } catch (TimeoutException e) {
      future.cancel(true);
      throw new IllegalStateException("Job timed out after " + timeoutSeconds + "s", e);
    } catch (ExecutionException e) {
      Throwable cause = e.getCause();
      if (cause instanceof RuntimeException runtimeCause) {
        throw runtimeCause;
      }
      throw new IllegalStateException("Job failed", cause);
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new IllegalStateException("Job interrupted", e);
    }
  }

