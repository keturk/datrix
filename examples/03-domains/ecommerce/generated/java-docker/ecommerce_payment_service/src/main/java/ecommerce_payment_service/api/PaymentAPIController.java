  @Operation(summary = "post /:id/refund")
  @ApiResponse(responseCode = "201")
  @ResponseStatus(HttpStatus.CREATED)
  @PostMapping("/{id}/refund")
  public RefundResponse postByIdRefund(
      @PathVariable("id") UUID id, @Valid @RequestBody RefundPaymentRequest request) {
    var payment =
        paymentRepository
            .findById(id)
            .orElseThrow(
                () ->
                    new ResponseStatusException(HttpStatus.NOT_FOUND, "Payment not found: " + id));
    if (!payment.getCanRefund()) {
      throw new ResponseStatusException(
          HttpStatus.valueOf(422),
          "Cannot refund payment in status: %s".formatted(payment.getStatus()));
    }
    // Calculate total already refunded to prevent over-refunding
    var totalRefunded = BigDecimal.valueOf(0);
    for (var refund : payment.getRefunds()) {
      if (refund.getIsSuccessful()) {
        totalRefunded = totalRefunded.add(refund.getAmount());
      }
    }
    if ((totalRefunded.add(request.amount()).compareTo(payment.getAmount()) > 0)) {
      throw new ResponseStatusException(
          HttpStatus.valueOf(422), "Refund amount exceeds original payment");
    }
    var refund =
        refundRepository.save(
            Refund.fromMap(
                _datrixOrderedMap(
                    "payment",
                    payment,
                    "amount",
                    request.amount(),
                    "reason",
                    request.reason(),
                    "status",
                    PaymentStatus.PENDING)));
    var success = processRefundViaGateway(payment, refund);
    if (success) {
      refund.setStatus(PaymentStatus.COMPLETED);
      refund.setProcessedAt(OffsetDateTime.now());
      refundRepository.save(refund);
      var newTotalRefunded = totalRefunded.add(request.amount());
      if ((newTotalRefunded.compareTo(payment.getAmount()) >= 0)) {
        payment.setStatus(PaymentStatus.REFUNDED);
        paymentRepository.save(payment);
      }
    } else {
      refund.setStatus(PaymentStatus.FAILED);
      refundRepository.save(refund);
    }
    return new RefundResponse(
        refund.getCreatedAt(),
        refund.getUpdatedAt(),
        refund.getId(),
        refund.getAmount(),
        refund.getReason(),
        refund.getStatus(),
        refund.getRefundTransactionId(),
        refund.getErrorMessage(),
        refund.getProcessedAt(),
        (refund.getPayment() != null ? refund.getPayment().getId() : null),
        refund.getIsSuccessful());
  }
