package ecommerce_payment_service.payment_db;

import jakarta.persistence.EntityManager;
import jakarta.persistence.EntityManagerFactory;
import java.util.HashMap;
import java.util.Map;
import javax.sql.DataSource;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.orm.jpa.JpaTransactionManager;
import org.springframework.orm.jpa.JpaVendorAdapter;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.SharedEntityManagerCreator;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;
import org.springframework.transaction.PlatformTransactionManager;

/**
 * JPA {@code EntityManagerFactory} + {@code PlatformTransactionManager} for the 'paymentDb' RDBMS
 * block (postgres). {@code visit_transaction}/ {@code visit_commit} lower to programmatic {@code
 * TransactionTemplate} blocks against the {@code PlatformTransactionManager} bean exposed here --
 * never {@code @Transactional} annotation magic (design principle 7).
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Configuration
@EnableJpaRepositories(
    basePackages = "ecommerce_payment_service.repositories.payment_db",
    entityManagerFactoryRef = "payment_dbEntityManagerFactory",
    transactionManagerRef = "payment_dbTransactionManager")
public class PaymentDbJpaConfig {

  @Bean(name = "payment_dbEntityManagerFactory")
  public LocalContainerEntityManagerFactoryBean payment_dbEntityManagerFactory(
      @Qualifier("payment_dbDataSource") DataSource dataSource) {
    LocalContainerEntityManagerFactoryBean emf = new LocalContainerEntityManagerFactoryBean();
    emf.setDataSource(dataSource);
    emf.setPackagesToScan("ecommerce_payment_service.model.payment_db");
    emf.setPersistenceUnitName("payment_db");
    JpaVendorAdapter vendorAdapter = new HibernateJpaVendorAdapter();
    emf.setJpaVendorAdapter(vendorAdapter);

    // spring.jpa.hibernate.ddl-auto=none -- rendered literal "none", NEVER a
    // template variable (schema is owned by migrations).
    Map<String, Object> jpaProperties = new HashMap<>();
    jpaProperties.put("hibernate.hbm2ddl.auto", "none");
    // The engine is known at generation time, so bake the dialect in and
    // forbid boot-time JDBC-metadata access: Hibernate then builds the
    // EntityManagerFactory WITHOUT opening a database connection to auto-
    // detect the dialect. This makes the full application context load
    // without a reachable database (parity with the python/TypeScript ORMs,
    // which derive the dialect from the connection URL, never a boot probe);
    // the DataSource itself is lazy (see the datasource config).
    jpaProperties.put("hibernate.dialect", "org.hibernate.dialect.PostgreSQLDialect");
    jpaProperties.put("hibernate.boot.allow_jdbc_metadata_access", false);
    // A hand-rolled LocalContainerEntityManagerFactoryBean (chosen over Boot's
    // auto-configured entityManagerFactory so multiple RDBMS blocks each get
    // their own explicitly-named bean) never picks up Boot's own camelCase ->
    // snake_case column-naming convention -- Hibernate's own DEFAULT physical
    // naming strategy leaves Java field names unconverted, which Postgres then
    // silently lowercases (`customerEmail` -> `customeremail`, never matching a
    // migration-created `customer_email` column). Hibernate's own (Spring-
    // independent) CamelCaseToUnderscoresNamingStrategy performs the same
    // conversion migrations already assume.
    jpaProperties.put(
        "hibernate.physical_naming_strategy",
        "org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy");
    emf.setJpaPropertyMap(jpaProperties);

    return emf;
  }

  @Bean(name = "payment_dbTransactionManager")
  public PlatformTransactionManager payment_dbTransactionManager(
      @Qualifier("payment_dbEntityManagerFactory") EntityManagerFactory entityManagerFactory) {
    return new JpaTransactionManager(entityManagerFactory);
  }

  /**
   * Request-scoped {@code EntityManager} unit of work: a thread-bound, self-scoping proxy (Spring's
   * {@code SharedEntityManagerCreator}) that transparently delegates to the CURRENT
   * transaction-bound {@code EntityManager}, creating a fresh one per unit of work -- the same
   * delegate {@code @PersistenceContext} injection resolves to under the hood.
   */
  @Bean(name = "payment_dbEntityManager")
  public EntityManager payment_dbEntityManager(
      @Qualifier("payment_dbEntityManagerFactory") EntityManagerFactory entityManagerFactory) {
    return SharedEntityManagerCreator.createSharedEntityManager(entityManagerFactory);
  }
}
