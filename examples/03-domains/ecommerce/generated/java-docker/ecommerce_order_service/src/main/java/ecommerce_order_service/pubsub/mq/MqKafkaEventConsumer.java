  private void handlePaymentEventsPaymentProcessed(PaymentProcessed payload) {
    logger.debug(
        "event_received event={} topic={}",
        "PaymentProcessed",
        "ecommerce_payment_service.mq.payment_events");
    var paymentId = payload.paymentId();
    var orderId = payload.orderId();
    var amount = payload.amount();
    var order =
        orderRepository
            .findById(orderId)
            .orElseThrow(
                () ->
                    new ResponseStatusException(
                        HttpStatus.NOT_FOUND, "Order not found: " + orderId));
    order_dbTransactionTemplate.executeWithoutResult(
        status -> {
          EventOutbox.withBuffer(
              () -> {
                order.setPaymentId(paymentId);
                order.setStatus(OrderStatus.CONFIRMED);
                orderRepository.save(order);
              });
        });
    logger.info("Order confirmed after payment");
    SettlePaymentPayload __settlePaymentPayload =
        new SettlePaymentPayload(paymentId, "ECOM-DEMO-MERCHANT", amount);
    SpringContextHolder.getBean(OrderServiceQueueClient.class)
        .dispatchSettlePayment(paymentId, "ECOM-DEMO-MERCHANT", amount);
    SpringContextHolder.getOptionalBean(EventSpyRecorder.class)
        .ifPresent(__spy -> __spy.record(__settlePaymentPayload));
  }

