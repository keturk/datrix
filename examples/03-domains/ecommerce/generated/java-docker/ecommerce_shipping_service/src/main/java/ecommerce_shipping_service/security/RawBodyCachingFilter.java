package ecommerce_shipping_service.security;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;
import org.springframework.web.util.ContentCachingRequestWrapper;

/**
 * Wraps every SIGNATURE/HMAC webhook request in a {@link ContentCachingRequestWrapper} before
 * {@code DispatcherServlet} resolves {@code @RequestBody}. Spring's own body read (Jackson
 * deserializing the endpoint's DTO parameter) populates the wrapper's cache; the controller-layer
 * verification prelude reads it back via {@code getContentAsByteArray()} -- the servlet input
 * stream is consumed exactly once, by that read, never twice.
 *
 * <p>Auto-generated by datrix-codegen-java. Do not edit manually.
 */
@Component
public class RawBodyCachingFilter extends OncePerRequestFilter {

  /**
   * Upper bound on the bytes {@link ContentCachingRequestWrapper} buffers per request (its two-arg
   * constructor requires an explicit limit -- the single-arg, unbounded-cache constructor is not
   * available). 10 MiB comfortably covers any realistic webhook payload while bounding the
   * per-request memory an oversized/malicious body could consume.
   */
  private static final int MAX_CACHED_BODY_BYTES = 10 * 1024 * 1024;

  @Override
  protected boolean shouldNotFilter(HttpServletRequest request) {
    String path = request.getRequestURI();
    String method = request.getMethod();
    if (method.equals("POST") && pathMatches(path, "/api/v1/shipments/webhook/fedex")) {
      return false;
    }
    return true;
  }

  /**
   * Matches a concrete request path against a possibly-{@code {param}}/{@code **}-suffixed pattern.
   */
  private static boolean pathMatches(String actual, String pattern) {
    if (pattern.endsWith("/**")) {
      String prefix = pattern.substring(0, pattern.length() - 3);
      return actual.equals(prefix) || actual.startsWith(prefix + "/");
    }
    if (!pattern.contains("{")) {
      return actual.equals(pattern);
    }
    String regex = pattern.replaceAll("\\{[^/]+\\}", "[^/]+");
    return actual.matches(regex);
  }

  @Override
  protected void doFilterInternal(
      HttpServletRequest request, HttpServletResponse response, FilterChain chain)
      throws ServletException, IOException {
    chain.doFilter(new ContentCachingRequestWrapper(request, MAX_CACHED_BODY_BYTES), response);
  }
}
