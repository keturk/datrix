import { KafkaConnection } from '../mq/connection';
import {
  KafkaEventProducer,
  setProducerInstance as mqSetProducerInstance,
} from '../mq/producer';

let _bootstrapped = false;

export async function bootstrapRuntime(): Promise<void> {
  if (_bootstrapped) {
    return;
  }
  mqSetProducerInstance(
    new KafkaEventProducer(new KafkaConnection()),
  );
  _bootstrapped = true;
}

export async function shutdownRuntime(): Promise<void> {
  if (!_bootstrapped) {
    return;
  }
  mqSetProducerInstance(null);
  _bootstrapped = false;
}
