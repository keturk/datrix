type ParsedBody =
  | { readonly ok: true; readonly fields: Record<string, unknown> }
  | { readonly ok: false; readonly detail: string };

/**
 * The request's JSON body fields, from the raw text the body parser read: an
 * absent or empty body has none; a body that is not valid JSON, or not a JSON
 * object (an array, a scalar, `null`), is refused so the caller answers 400
 * before the handler runs.
 */
function parseJsonBody(raw: unknown): ParsedBody {
  if (typeof raw !== 'string' || raw === '') {
    return { ok: true, fields: {} };
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return { ok: false, detail: 'Request body is not valid JSON' };
  }
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    return { ok: false, detail: 'Request body must be a JSON object' };
  }
  return { ok: true, fields: parsed as Record<string, unknown> };
}

/**
 * Run the auth chain for one route: authenticate the request (an API key of a
 * provider the route admits, else the bearer token; nothing presented is an
 * anonymous request only for an `auth(optional)` route, and a presented
 * credential that fails is always a 401), then require an allowed provider
 * (when the route declares providers), then an admitted principal type (when
 * it declares types), then one of the route's roles (when it declares roles).
 * Answers 401 for a missing (non-optional) or invalid credential, 403 for a
 * provider, principal-type or role denial, 429 (with Retry-After) for a
 * rate-limited key and 503 when a key cannot be verified. Any other failure
 * (a plan-load or configuration error) answers 500 -- it never allows the
 * request. Returns `true` only when the request may proceed.
 */
async function requireAuth(
  req: Request,
  res: Response,
  admittedApiKeyProviders: ReadonlyArray<string>,
  requiredProviders: ReadonlyArray<string>,
  requiredRoles: ReadonlyArray<string>,
  requiredPrincipalTypes: ReadonlyArray<string>,
  optional: boolean,
): Promise<boolean> {
  try {
    const principal = optional
      ? await authenticateOptionalRouteRequest(req.headers, admittedApiKeyProviders)
      : await authenticateRouteRequest(req.headers, admittedApiKeyProviders);
    if (principal === undefined) {
      return true;
    }
    if (requiredProviders.length > 0) {
      requireProviders(principal, requiredProviders);
    }
    if (requiredPrincipalTypes.length > 0) {
      requirePrincipalTypes(principal, requiredPrincipalTypes);
    }
    if (requiredRoles.length > 0) {
      requireRoles(principal, requiredRoles);
    }
    return true;
  } catch (err) {
    if (err instanceof AuthChainError) {
      res.status(err.status).set(authChainFailureHeaders(err)).json({ detail: authChainFailureDetail(err) });
      return false;
    }
    const message = err instanceof Error ? err.message : String(err);
    console.error(`serverless_http_auth_error path=${req.path} error=${message}`);
    res.status(500).json({ detail: 'Internal error' });
    return false;
  }
}

