/**
 * IdentitySurfaceGuard — per-surface authorization guard.
 *
 * Resolves the surface from the loaded identity provider plan using the
 * generation-time ``surfaceId`` constant carried on the endpoint metadata
 * (NEVER a hardcoded provider name). The token issuer selects the matching
 * allowed provider (set semantics, no fallback order); an issuer that matches
 * no allowed provider yields 401 with reason ``provider_mismatch`` in logs only.
 *
 * Enforces (in order): provider resolution → principal-type → roles (flat
 * any-of) → profile loading. Client-visible bodies are opaque RFC 7807:
 * 401 omits issuer/audience/client detail; 403 carries no role/claim detail.
 * The fixed-set reason code is logged server-side only, never returned.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import {
  CanActivate,
  ExecutionContext,
  ForbiddenException,
  Injectable,
  Logger,
  UnauthorizedException,
} from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import type { Request } from 'express';
import { IS_PUBLIC_KEY } from './public.decorator';
import { ROLES_KEY } from './roles.decorator';
import { verifyIdentityToken } from './identity';
import type { IdentityPrincipal } from './identity';

/** Surface ID key in the endpoint metadata (set by the route generator). */
export const SURFACE_ID_KEY = 'surface_id';

/** Profile-load mode key in the endpoint metadata. */
export const PROFILE_MODE_KEY = 'profile_mode';

/** Allowed principal types key in the endpoint metadata (from AuthContract). */
export const PRINCIPAL_TYPES_KEY = 'principal_types';

/** Default surface ID used when no surface metadata is present. */
const DEFAULT_SURFACE_ID = 'product-service';

/**
 * Fixed-set OR8 reason codes. Logged server-side only; never returned in a
 * client body. Mirrors ``AuthReasonCode`` from datrix-common.
 */
const REASON_MISSING_TOKEN = 'missing_token';
const REASON_PRINCIPAL_TYPE_MISMATCH = 'principal_type_mismatch';
const REASON_ROLE_DENIED = 'role_denied';
const REASON_PROFILE_UNAVAILABLE = 'profile_unavailable';
const REASON_PROVIDER_MISMATCH = 'provider_mismatch';

/** Opaque RFC 7807 problem-detail bodies. No issuer/audience/role/claim leakage. */
const UNAUTHORIZED_PROBLEM = {
  type: 'about:blank',
  title: 'Unauthorized',
  status: 401,
} as const;

const FORBIDDEN_PROBLEM = {
  type: 'about:blank',
  title: 'Forbidden',
  status: 403,
} as const;

@Injectable()
export class IdentitySurfaceGuard implements CanActivate {
  private readonly logger = new Logger(IdentitySurfaceGuard.name);

  constructor(private readonly reflector: Reflector) {}

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const isPublic = this.reflector.getAllAndOverride<boolean>(IS_PUBLIC_KEY, [
      context.getHandler(),
      context.getClass(),
    ]);
    if (isPublic) {
      return true;
    }

    const request = context.switchToHttp().getRequest<Request>();
    const surfaceId =
      this.reflector.getAllAndOverride<string>(SURFACE_ID_KEY, [
        context.getHandler(),
        context.getClass(),
      ]) ?? DEFAULT_SURFACE_ID;

    const token = this.extractTokenFromHeader(request);
    if (!token) {
      this.logFailure(REASON_MISSING_TOKEN, surfaceId);
      throw new UnauthorizedException(UNAUTHORIZED_PROBLEM);
    }

    // Per-surface provider resolution: issuer selects the provider entry.
    let principal: IdentityPrincipal;
    try {
      principal = await verifyIdentityToken(token, surfaceId);
    } catch (err) {
      this.logFailure(this.classifyReason(err), surfaceId);
      throw new UnauthorizedException(UNAUTHORIZED_PROBLEM);
    }

    // Principal-type enforcement (human/machine) from the surface contract.
    const allowedPrincipalTypes =
      this.reflector.getAllAndOverride<string[]>(PRINCIPAL_TYPES_KEY, [
        context.getHandler(),
        context.getClass(),
      ]) ?? [];
    if (
      allowedPrincipalTypes.length > 0 &&
      !allowedPrincipalTypes.includes(principal.principalType)
    ) {
      this.logFailure(REASON_PRINCIPAL_TYPE_MISMATCH, surfaceId);
      throw new ForbiddenException(FORBIDDEN_PROBLEM);
    }

    // Flat any-of role check; required-vs-actual detail stays in logs.
    const requiredRoles = this.reflector.getAllAndOverride<string[]>(ROLES_KEY, [
      context.getHandler(),
      context.getClass(),
    ]);
    if (requiredRoles && requiredRoles.length > 0) {
      const hasRole = requiredRoles.some((role) =>
        principal.roles.includes(role),
      );
      if (!hasRole) {
        this.logger.warn(
          `identity_role_or_policy_denied reason=${REASON_ROLE_DENIED} ` +
            `surface=${surfaceId} required=${requiredRoles.join(',')} ` +
            `held=${principal.roles.join(',')}`,
        );
        throw new ForbiddenException(FORBIDDEN_PROBLEM);
      }
    }

    // Profile projection per the surface contract (none | optional | required).
    const profileMode =
      this.reflector.getAllAndOverride<string>(PROFILE_MODE_KEY, [
        context.getHandler(),
        context.getClass(),
      ]) ?? 'none';
    // No provider in this service uses projected mode — profile service is not emitted.
    // identityProfile is always null; a surface requiring profile: required is a generation error.
    if (profileMode === 'required') {
      this.logFailure(REASON_PROFILE_UNAVAILABLE, surfaceId);
      throw new ForbiddenException(FORBIDDEN_PROBLEM);
    }
    (request as unknown as Record<string, unknown>)['identityProfile'] = null;

    (request as unknown as Record<string, unknown>)['user'] = principal;
    this.logger.debug(
      `identity_token_verified surface=${surfaceId} provider=${principal.provider}`,
    );
    return true;
  }

  private extractTokenFromHeader(request: Request): string | undefined {
    const authHeader = request.headers.authorization;
    if (!authHeader) {
      return undefined;
    }
    const [type, value] = authHeader.split(' ');
    return type === 'Bearer' ? value : undefined;
  }

  /** Map a verification error message to a fixed-set reason code (logs only). */
  private classifyReason(err: unknown): string {
    const message = err instanceof Error ? err.message : String(err);
    if (message.includes(':')) {
      return message.split(':')[0].trim();
    }
    return REASON_PROVIDER_MISMATCH;
  }

  /** Log a structured failure with the reason code; never logs the raw token. */
  private logFailure(reasonCode: string, surfaceId: string): void {
    this.logger.warn(
      `identity_token_validation_failed reason=${reasonCode} surface=${surfaceId}`,
    );
  }
}
