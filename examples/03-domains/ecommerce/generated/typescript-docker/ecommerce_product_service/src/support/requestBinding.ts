/**
 * Validation of a serverless HTTP request against its route's declared
 * parameters.
 *
 * `bindRequest()` takes the request's merged query, body and path
 * parameters and the route's request class (a `class-validator` class whose
 * properties are the declared parameters under their wire names). A required
 * parameter the request does not carry, a value that does not satisfy its
 * declared type and a key no parameter declares are each refused, with the
 * name of the offending field and never its value. What it answers is the
 * handler's positional arguments in declared order. The container app, the
 * Lambda adapter and the Azure Functions registration bind a request through
 * it, so the three answer the same request the same way.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import { plainToInstance } from 'class-transformer';
import { validate, ValidationError } from 'class-validator';

/** The `loc` prefix: a serverless request's parameters are read from the merged query, body and path. */
const REQUEST_LOCATION = 'request';

/** The error type and message a key no parameter declares is refused with. */
const UNDECLARED_KEY_TYPE = 'extra_forbidden';
const UNDECLARED_KEY_MESSAGE = 'Extra inputs are not permitted';

/** One refused field: which constraint it broke, where, and why -- never the value. */
export interface RequestFieldError {
  readonly type: string;
  readonly loc: ReadonlyArray<string | number>;
  readonly msg: string;
}

export type BoundRequest =
  | { readonly ok: true; readonly args: unknown[] }
  | { readonly ok: false; readonly detail: RequestFieldError[] };

function fieldErrors(
  errors: ReadonlyArray<ValidationError>,
  path: ReadonlyArray<string | number>,
): RequestFieldError[] {
  const found: RequestFieldError[] = [];
  for (const error of errors) {
    const loc = [...path, error.property];
    for (const [type, msg] of Object.entries(error.constraints ?? {})) {
      found.push({ type, loc, msg });
    }
    found.push(...fieldErrors(error.children ?? [], loc));
  }
  return found;
}

/**
 * Bind one request: validate its merged parameters against `cls` and return
 * the handler's arguments, in `fieldNames` (declared) order.
 *
 * @param cls The route's request class.
 * @param fieldNames The declared parameters' wire names, in declared order.
 * @param sources The request's parameter sources in rising precedence -- a key
 *   in a later source replaces the same key in an earlier one, so the caller
 *   puts the routed path parameters last.
 */
export async function bindRequest<T extends object>(
  cls: new () => T,
  fieldNames: ReadonlyArray<string>,
  sources: ReadonlyArray<Record<string, unknown>>,
): Promise<BoundRequest> {
  // A Map keeps a `__proto__` key (JSON.parse creates it as an own property)
  // an ordinary entry, so it is refused as undeclared like any other.
  const merged = new Map<string, unknown>();
  for (const source of sources) {
    for (const [key, value] of Object.entries(source)) {
      merged.set(key, value);
    }
  }
  const declared = new Set(fieldNames);
  const errors: RequestFieldError[] = [];
  for (const key of merged.keys()) {
    if (!declared.has(key)) {
      errors.push({ type: UNDECLARED_KEY_TYPE, loc: [REQUEST_LOCATION, key], msg: UNDECLARED_KEY_MESSAGE });
    }
  }
  const declaredValues: Record<string, unknown> = {};
  for (const name of fieldNames) {
    if (merged.has(name)) {
      declaredValues[name] = merged.get(name);
    }
  }
  const instance = plainToInstance(cls, declaredValues);
  if (fieldNames.length > 0) {
    const violations = await validate(instance, {
      whitelist: true,
      forbidNonWhitelisted: true,
      forbidUnknownValues: false,
    });
    errors.push(...fieldErrors(violations, [REQUEST_LOCATION]));
  }
  if (errors.length > 0) {
    return { ok: false, detail: errors };
  }
  const values = instance as unknown as Record<string, unknown>;
  return { ok: true, args: fieldNames.map((name) => values[name]) };
}
