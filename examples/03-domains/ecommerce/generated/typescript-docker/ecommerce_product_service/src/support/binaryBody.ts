/**
 * The HTTP response of a binary route (`-> Bytes` / `-> Bytes?`): the
 * unencoded bytes with the declared media type, the fixed status and the
 * fixed security header set, or No Content for a nullable route's null value.
 *
 * `binaryBody()` is the framework-free core: it validates the value a
 * route body returns and builds the WHOLE response -- status, headers and
 * body -- WITHOUT writing it, at the point of the `return`. So a contract
 * violation throws before anything is written, a `return` inside a
 * transaction answers only after the transaction has committed, and every
 * host renders the same answer: the REST controller and the container
 * serverless app hand the result to `sendBinaryBody()`, and each cloud
 * serverless adapter (Lambda, Azure Functions) maps it onto its platform's
 * response object.
 *
 * `sendBinaryBody()` owns the whole response through the injected `@Res()`
 * (without passthrough): Nest's ExpressAdapter.reply() would otherwise
 * JSON-encode a Buffer, and in passthrough mode it overwrites the status with
 * the route's static one -- so neither the 204 of a nullable null nor a 200 on
 * a POST or DELETE route could be expressed.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */

export class BinaryBodyContractViolation extends Error {}

interface BinaryRouteMeta {
  mediaType: string;
  nullable: boolean;
}

/** The security headers every binary answer carries, with or without a body. */
const SECURITY_HEADERS: Readonly<Record<string, string>> = {
  'X-Content-Type-Options': 'nosniff',
  'Content-Security-Policy': 'default-src \'none\'; sandbox',
  'Content-Disposition': 'attachment',
};

/**
 * A built binary-route response. Only `binaryBody()` constructs one, so
 * a route body declared to produce it cannot return raw bytes by mistake.
 * `body` is `undefined` exactly when `status` is No Content.
 */
export class BinaryBodyResult {
  private constructor(
    readonly status: 200 | 204,
    readonly body: Buffer | undefined,
    readonly headers: Readonly<Record<string, string>>,
  ) {}

  static ok(bytes: Buffer, mediaType: string): BinaryBodyResult {
    return new BinaryBodyResult(200, bytes, { ...SECURITY_HEADERS, 'Content-Type': mediaType });
  }

  static noContent(): BinaryBodyResult {
    return new BinaryBodyResult(204, undefined, { ...SECURITY_HEADERS });
  }
}

export function binaryBody(value: unknown, route: BinaryRouteMeta): BinaryBodyResult {
  if (value === null || value === undefined) {
    if (!route.nullable) {
      throw new BinaryBodyContractViolation(
        "A route declared '-> Bytes' returned null. Declare it '-> Bytes?' to " +
          'answer 204 No Content for a missing body, or return bytes.',
      );
    }
    return BinaryBodyResult.noContent();
  }
  if (!(value instanceof Buffer) && !(value instanceof Uint8Array)) {
    throw new BinaryBodyContractViolation(
      "A route declared '-> Bytes' returned a non-bytes value. Encode text " +
        'with String.toBytes before returning it.',
    );
  }
  const buffer = Buffer.isBuffer(value) ? value : Buffer.from(value);
  return BinaryBodyResult.ok(buffer, route.mediaType);
}

/**
 * The part of an HTTP response writer `sendBinaryBody()` uses. Express's
 * `Response` satisfies it; naming only these members keeps this module free
 * of any web-framework import.
 */
export interface BinaryResponseWriter {
  setHeader(name: string, value: string): unknown;
  status(code: number): { end(): unknown; send(body: Buffer): unknown };
}

export function sendBinaryBody(res: BinaryResponseWriter, result: BinaryBodyResult): void {
  for (const [name, value] of Object.entries(result.headers)) {
    res.setHeader(name, value);
  }
  if (result.body === undefined) {
    res.status(result.status).end();
    return;
  }
  res.status(result.status).send(result.body);
}
