/**
 * Rate limit guard: per-plan limits keyed on the verified principal.
 *
 * Listed after `AuthGuard` in the controller-level (and GraphQL resolver)
 * `@UseGuards(AuthGuard, RateLimitGuard)`, so it runs after the auth chain has
 * verified the credential. The plan ceiling is the verified principal's
 * `request.user.plan` and the bucket is its `request.user.sub`; a route with no
 * principal (public, webhook, an anonymous optional request) is keyed on the
 * client address under the default plan. No claim is ever decoded here.
 *
 * Coexists with @nestjs/throttler IP limits: throttler stays on endpoints;
 * this guard enforces per-plan limits counted in Redis. There is no switch that
 * turns it off: a store it cannot reach fails the request, never admits it.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import {
  CanActivate,
  ExecutionContext,
  HttpException,
  HttpStatus,
  Injectable,
  Logger,
} from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import type { Request, Response } from 'express';
import { RateLimitService, type RateLimitOverride } from './rate-limit.service';
import { RATE_LIMIT_KEY } from './rate-limit.decorator';
import type { IdentityPrincipal } from '../auth/identity';

const RATE_LIMIT_HEADER_LIMIT = 'X-RateLimit-Limit';
const RATE_LIMIT_HEADER_REMAINING = 'X-RateLimit-Remaining';
const RATE_LIMIT_HEADER_RESET = 'X-RateLimit-Reset';

const DEFAULT_PLAN_ID = "";

// True when the application declared no `gateway.rateLimitPlans`: there are no
// subscription tiers, so there is no plan-based ceiling to enforce. Per-endpoint
// `@RateLimit` overrides are a separate, independently declared surface and
// still apply.
const HAS_RATE_LIMIT_PLANS = false;

/** The plan ceiling to enforce: the verified principal's plan, else the default plan. */
function planIdOf(principal: IdentityPrincipal | undefined): string {
  if (principal === undefined || principal.plan === '') {
    return DEFAULT_PLAN_ID;
  }
  return principal.plan;
}

/**
 * The bucket owner: the verified principal's subject, else the client address.
 * A caller cannot choose its bucket by editing a token -- only verified claims
 * reach here.
 */
function clientKey(principal: IdentityPrincipal | undefined, req: Request): string {
  const sub = principal?.sub.trim() ?? '';
  if (sub !== '') {
    return `u:${sub}`;
  }
  const xff = req.get('X-Forwarded-For');
  if (xff) {
    return `ip:${xff.split(',')[0].trim()}`;
  }
  const h = req.ip !== undefined && req.ip !== '' ? req.ip : req.socket?.remoteAddress;
  if (h !== undefined && h !== null && String(h).trim() !== '') {
    return `ip:${String(h).trim()}`;
  }
  return 'ip:unknown';
}

@Injectable()
export class RateLimitGuard implements CanActivate {
  private readonly logger = new Logger(RateLimitGuard.name);

  constructor(
    private readonly rateLimitService: RateLimitService,
    private readonly reflector: Reflector,
  ) {}

  private resolveHttp(
    context: ExecutionContext,
  ): { req: Request; res: Response } | null {
    const type = context.getType<string>();
    if (type === 'graphql') {
      return null;
    }
    const http = context.switchToHttp();
    return {
      req: http.getRequest<Request>(),
      res: http.getResponse<Response>(),
    };
  }

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const pair = this.resolveHttp(context);
    if (pair === null) {
      return true;
    }
    const { req, res } = pair;

    const endpointOverride = this.reflector.get<RateLimitOverride | undefined>(
      RATE_LIMIT_KEY,
      context.getHandler(),
    );

    if (!HAS_RATE_LIMIT_PLANS && endpointOverride === undefined) {
      // Nothing declared a limit for this route: no plan table and no
      // `@RateLimit` override. Enforce nothing rather than invent a ceiling.
      return true;
    }

    // `AuthGuard` runs first in the same guard list and sets `request.user` only after the
    // full auth chain verified the credential; a route with no principal (public, webhook,
    // an anonymous optional request) has none and is keyed on the client address.
    const principal = req.user;
    const planId = planIdOf(principal);
    const ckey = clientKey(principal, req);

    let result: Awaited<ReturnType<RateLimitService['checkLimit']>>;
    try {
      result = await this.rateLimitService.checkLimit(ckey, planId, endpointOverride);
    } catch (e: unknown) {
      if (e instanceof Error && e.message.startsWith('Not found.')) {
        throw new HttpException(e.message, HttpStatus.INTERNAL_SERVER_ERROR);
      }
      throw e;
    }

    res.setHeader(RATE_LIMIT_HEADER_LIMIT, String(result.limit));
    res.setHeader(RATE_LIMIT_HEADER_REMAINING, String(Math.max(0, result.remaining)));
    res.setHeader(RATE_LIMIT_HEADER_RESET, String(result.resetAtEpochSeconds));

    if (!result.allowed) {
      this.logger.warn(
        'rate_limit_exceeded plan_id=%s client_key=%s limit=%s remaining=%s',
        planId,
        ckey,
        String(result.limit),
        String(result.remaining),
      );
      const nowSec = Math.floor(Date.now() / 1000);
      throw new HttpException(
        {
          statusCode: HttpStatus.TOO_MANY_REQUESTS,
          message: 'Rate limit exceeded. Please try again later.',
          retryAfterSeconds: result.resetAtEpochSeconds - nowSec,
        },
        HttpStatus.TOO_MANY_REQUESTS,
      );
    }

    return true;
  }
}
