/**
 * Gateway JWT verification endpoint.
 *
 * Lightweight endpoint used by nginx `auth_request` to validate client JWTs
 * before proxying requests to upstream services. Returns 200 when the token is
 * valid, 401 otherwise — nginx treats any 2xx as "allow" and 401/403 as "deny".
 *
 * The asymmetric public key is resolved from the mounted key file
 * (`JWT_PUBLIC_KEY_FILE`) at request time (RESOLVE_ON_ACCESS); it is never baked
 * into generated source. An unset key path fails loud rather than silently
 * accepting every token. Verification pins the configured signing algorithm, so
 * symmetric (`HS*`) and `alg:none` tokens are rejected by construction.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import {
  Controller,
  Get,
  HttpCode,
  Logger,
  Req,
  UnauthorizedException,
} from '@nestjs/common';
import { ApiExcludeEndpoint } from '@nestjs/swagger';
import type { Request } from 'express';
import { readFile } from 'node:fs/promises';
import { importSPKI, jwtVerify } from 'jose';

const JWT_ALGORITHM = 'RS256';
const PUBLIC_KEY_FILE_ENV = 'JWT_PUBLIC_KEY_FILE';
const BEARER_PREFIX = 'Bearer ';

let _publicKey: Awaited<ReturnType<typeof importSPKI>> | null = null;

/**
 * Resolve the asymmetric public key from the mounted key file on first use.
 * The path is read from JWT_PUBLIC_KEY_FILE at request time; an unset or empty
 * path throws (fail loud) instead of accepting unverifiable tokens.
 */
async function loadPublicKey(): Promise<Awaited<ReturnType<typeof importSPKI>>> {
  if (_publicKey !== null) {
    return _publicKey;
  }
  const keyPath = process.env[PUBLIC_KEY_FILE_ENV];
  if (keyPath === undefined || keyPath.trim() === '') {
    throw new Error(
      `Environment variable ${PUBLIC_KEY_FILE_ENV} is not set. Set it to the ` +
        `path of the gateway JWT public key (PEM) so client tokens can be verified.`,
    );
  }
  const pem = await readFile(keyPath, 'utf-8');
  _publicKey = await importSPKI(pem, JWT_ALGORITHM);
  return _publicKey;
}

@Controller()
export class GatewayJwtVerifyController {
  private readonly logger = new Logger(GatewayJwtVerifyController.name);

  @Get('internal/jwt-verify')
  @HttpCode(200)
  @ApiExcludeEndpoint()
  async verify(@Req() request: Request): Promise<void> {
    const authHeader = request.headers.authorization ?? '';
    if (!authHeader.startsWith(BEARER_PREFIX)) {
      throw new UnauthorizedException();
    }
    const token = authHeader.slice(BEARER_PREFIX.length);
    try {
      const key = await loadPublicKey();
      await jwtVerify(token, key, { algorithms: [JWT_ALGORITHM] });
    } catch (err) {
      const reason = err instanceof Error ? err.message : String(err);
      this.logger.debug(`gateway_jwt_verify_rejected reason=${reason}`);
      throw new UnauthorizedException();
    }
  }
}
