import type { MikroOrmModuleOptions } from '@mikro-orm/nestjs';
import { PostgreSqlDriver } from '@mikro-orm/postgresql';
import { ConfigService } from '@nestjs/config';
import { buildClient, RemoteConfigClient } from '../config/remoteConfig';
import { SecretsService } from '../ecommerce_order_service/secrets/secrets.service';

export async function getDatabaseConfig(
  configService: ConfigService,
  secrets: SecretsService = new SecretsService(),
  configClient: RemoteConfigClient = buildClient(),
): Promise<MikroOrmModuleOptions> {
  await configClient.start();
  const host = configClient.getString('connections', 'order_db_host');
  const port = configClient.getInt('connections', 'order_db_port');
  const database = configClient.getString('connections', 'order_db_database');
  const user = configClient.getString('connections', 'order_db_user');
  const password = await secrets.getSecret('order_db_password');

  return {
    driver: PostgreSqlDriver,
    entities: [
      __dirname + '/../ecommerce_order_service/entities/order_db/**/*.entity{.ts,.js}',
    ],
    allowGlobalContext: true,
    debug: configService.get<boolean>('DATABASE_LOGGING', false),
    pool: {
      max: 20,
    },
    migrations: {
      path: __dirname + '/../migrations/order-db',
      emit: 'ts',
    },
    host,
    port,
    user,
    password,
    dbName: database,
  };
}
