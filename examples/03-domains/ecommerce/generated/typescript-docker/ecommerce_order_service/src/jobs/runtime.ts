import { type DynamicModule, type INestApplicationContext, Module } from '@nestjs/common';
import { ModuleRef, NestFactory } from '@nestjs/core';
import { MikroOrmModule } from '@mikro-orm/nestjs';
import { OrderDbDatabaseModule } from '../order-db/database.module';
import { IdempotencyKey } from '../ecommerce_order_service/entities/order_db/idempotency-key.entity';

/** One registration per MikroORM context the jobs reach, imported and re-exported. */
const ENTITY_FEATURES: DynamicModule[] = [
  MikroOrmModule.forFeature([IdempotencyKey]),
];

@Module({
  imports: [
    OrderDbDatabaseModule,
    ...ENTITY_FEATURES,
  ],
  providers: [
  ],
  exports: [
    ...ENTITY_FEATURES,
  ],
})
export class JobsRuntimeModule {}

/** The root of the standalone jobs context: the runtime plus what AppModule would supply. */
@Module({
  imports: [
    JobsRuntimeModule,
  ],
})
class JobsHostModule {}

let hostContext: Promise<INestApplicationContext> | undefined;

/**
 * The standalone jobs context's root injector, created once per process.
 *
 * The promise is memoized, not its resolved value, so two concurrent first
 * invocations await one bootstrap instead of racing to build two.
 */
export async function jobsRuntimeModuleRef(): Promise<ModuleRef> {
  hostContext ??= NestFactory.createApplicationContext(JobsHostModule, { logger: false });
  const context = await hostContext;
  return context.get(ModuleRef, { strict: true });
}
