/**
 * IdentityWebSocketGateway — Socket.IO handshake authentication.
 *
 * The initial Socket.IO handshake validates the bearer token through the SAME
 * shared ``verifyIdentityToken`` jose path used by the HTTP guards (no separate
 * WS verifier). Token-extraction precedence:
 *   1. ``Authorization: Bearer`` header (server-side WS handshake).
 *   2. Socket.IO ``handshake.auth.token``.
 *   3. A query parameter — ONLY when the surface is explicitly opted in as a
 *      browser-WebSocket surface that cannot send headers. Never the default,
 *      never logged.
 * The header wins on conflict.
 *
 * Close codes use the RFC 6455 private-use range (4000-4999):
 *   - 4401: authentication failed or expired (no sensitive detail in reason).
 *   - 4403: forbidden (principal type / role denied).
 * When the token TTL is reached mid-connection, the socket is closed 4401 and
 * all per-connection ``Auth.*`` / room / channel state is cleared.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import { Logger } from '@nestjs/common';
import {
  OnGatewayConnection,
  OnGatewayDisconnect,
  WebSocketGateway,
} from '@nestjs/websockets';
import type { Socket } from 'socket.io';
import { verifyIdentityToken } from './identity';
import type { IdentityPrincipal } from './identity';

/** Surface identity validated by this gateway (generation-time constant). */
const WEBSOCKET_SURFACE_ID = 'order-service';

/**
 * When ``true`` the surface is an opted-in browser-WebSocket surface whose
 * client cannot attach an Authorization header, so a query-param token is
 * accepted as the last-resort precedence step. Never default; never logged.
 */
const ALLOW_QUERY_PARAM_TOKEN = false;

/** Query parameter name carrying the token when ALLOW_QUERY_PARAM_TOKEN is set. */
const QUERY_PARAM_TOKEN_KEY = 'access_token';

/**
 * Principal types permitted on this WebSocket surface (from the AuthContract).
 * Empty means any authenticated principal type is accepted.
 */
const ALLOWED_PRINCIPAL_TYPES: ReadonlyArray<string> = [  'human',  'machine',];

/** Close codes — RFC 6455 private-use range (4000-4999). */
const CLOSE_AUTH_FAILED = 4401;
const CLOSE_FORBIDDEN = 4403;

/** Non-sensitive close reasons (no issuer/audience/role/claim/token detail). */
const CLOSE_REASON_AUTH = 'authentication required';
const CLOSE_REASON_FORBIDDEN = 'forbidden';

@WebSocketGateway()
export class IdentityWebSocketGateway
  implements OnGatewayConnection, OnGatewayDisconnect
{
  private readonly logger = new Logger(IdentityWebSocketGateway.name);

  /** Per-connection auth state keyed by Socket.IO socket id. */
  private readonly connectionState = new Map<
    string,
    { principal: IdentityPrincipal; expiresAt: number; timer: NodeJS.Timeout }
  >();

  async handleConnection(client: Socket): Promise<void> {
    const token = this.extractToken(client);
    if (!token) {
      this.closeWithAuthFailure(client, 'missing_token');
      return;
    }

    let principal: IdentityPrincipal;
    try {
      principal = await verifyIdentityToken(token, WEBSOCKET_SURFACE_ID);
    } catch (err) {
      const reasonCode = this.classifyReason(err);
      this.closeWithAuthFailure(client, reasonCode);
      return;
    }

    // Principal-type enforcement from the surface contract (4403 on mismatch).
    if (
      ALLOWED_PRINCIPAL_TYPES.length > 0 &&
      !ALLOWED_PRINCIPAL_TYPES.includes(principal.principalType)
    ) {
      this.closeForbidden(client, 'principal_type_mismatch');
      return;
    }

    // Schedule TTL-driven expiry: on reaching exp, close 4401 + clear state.
    const expClaim = principal.claims.exp;
    const expiresAt = typeof expClaim === 'number' ? expClaim * 1000 : 0;
    const timer = this.scheduleExpiry(client, expiresAt);

    this.connectionState.set(client.id, { principal, expiresAt, timer });
    (client.data as Record<string, unknown>)['user'] = principal;
    this.logger.debug(
      `identity_websocket_authenticated surface=${WEBSOCKET_SURFACE_ID} provider=${principal.provider}`,
    );
  }

  handleDisconnect(client: Socket): void {
    this.clearConnectionState(client);
  }

  /** Token extraction with header > auth.token > opt-in query precedence. */
  private extractToken(client: Socket): string | undefined {
    const authHeader = client.handshake.headers.authorization;
    if (authHeader) {
      const [type, value] = authHeader.split(' ');
      if (type === 'Bearer' && value) {
        return value;
      }
      // Malformed header present — do not silently fall through to weaker
      // sources; header wins on conflict.
      return undefined;
    }
    const authToken = client.handshake.auth?.token;
    if (typeof authToken === 'string' && authToken.length > 0) {
      return authToken;
    }
    if (ALLOW_QUERY_PARAM_TOKEN) {
      const queryToken = client.handshake.query?.[QUERY_PARAM_TOKEN_KEY];
      if (typeof queryToken === 'string' && queryToken.length > 0) {
        return queryToken;
      }
    }
    return undefined;
  }

  private scheduleExpiry(client: Socket, expiresAt: number): NodeJS.Timeout {
    const now = Date.now();
    const delay = expiresAt > now ? expiresAt - now : 0;
    return setTimeout(() => {
      this.logger.warn(
        `identity.websocket_auth.expired surface=${WEBSOCKET_SURFACE_ID} socket=${client.id}`,
      );
      this.clearConnectionState(client);
      client.disconnect(true);
      this.closeSocket(client, CLOSE_AUTH_FAILED, CLOSE_REASON_AUTH);
    }, delay);
  }

  private closeWithAuthFailure(client: Socket, reasonCode: string): void {
    this.logger.warn(
      `identity_websocket_auth_failed reason=${reasonCode} surface=${WEBSOCKET_SURFACE_ID}`,
    );
    this.closeSocket(client, CLOSE_AUTH_FAILED, CLOSE_REASON_AUTH);
  }

  private closeForbidden(client: Socket, reasonCode: string): void {
    this.logger.warn(
      `identity_websocket_forbidden reason=${reasonCode} surface=${WEBSOCKET_SURFACE_ID}`,
    );
    this.closeSocket(client, CLOSE_FORBIDDEN, CLOSE_REASON_FORBIDDEN);
  }

  /** Emit the close code/reason and terminate the underlying socket. */
  private closeSocket(client: Socket, code: number, reason: string): void {
    client.emit('auth_error', { code, reason });
    client.disconnect(true);
  }

  /** Clear all per-connection room/channel/Auth.* state on expiry/disconnect. */
  private clearConnectionState(client: Socket): void {
    const state = this.connectionState.get(client.id);
    if (state !== undefined) {
      clearTimeout(state.timer);
      this.connectionState.delete(client.id);
    }
    const data = client.data as Record<string, unknown>;
    delete data['user'];
    for (const room of Array.from(client.rooms)) {
      if (room !== client.id) {
        client.leave(room);
      }
    }
  }

  /** Map a verification error message to a fixed-set reason code (logs only). */
  private classifyReason(err: unknown): string {
    const message = err instanceof Error ? err.message : String(err);
    if (message.includes(':')) {
      return message.split(':')[0].trim();
    }
    return 'provider_mismatch';
  }
}
