/**
 * Delegation envelope + machine-auth dual validation.
 *
 * When a surface accepts/requires delegation, the inbound call must carry BOTH:
 *   1. A machine ``auth(service)`` credential (the inbound caller machine token),
 *      validated through the shared jose path (``verifyIdentityToken``).
 *   2. A signed ``X-Datrix-Delegated-User`` envelope carrying the validated
 *      end-user context (provider / subject / principalType / audience / expiry
 *      / evidence). The raw user token is NEVER forwarded or accepted — only the
 *      signed envelope, whose signature is verified via the same provider
 *      pipeline as the original token evidence.
 *
 * Revocation (when ``revocationMode != none``) is checked fail-closed: a
 * denylist read or introspection call that cannot complete rejects the request
 * (it never substitutes a cached "allowed"). The added dependency is declared in
 * ``/ready`` / ``/health`` metadata by the generator.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import { Logger } from '@nestjs/common';
import { verifyIdentityToken } from './identity';
import type { IdentityPrincipal } from './identity';

const LOGGER = new Logger('IdentityDelegation');

/** Canonical header carrying the signed delegation envelope (OR18). */
export const DELEGATION_HEADER = 'x-datrix-delegated-user';

/** Principal type required for an end-user delegation envelope. */
const HUMAN_PRINCIPAL_TYPE = 'human';

/** Machine principal type required for the inbound service credential. */
const MACHINE_PRINCIPAL_TYPE = 'machine';

/** Fixed-set reason code for a failed delegation (logs/metrics only). */
const REASON_DELEGATION_INVALID = 'delegation_invalid';

/** Validation evidence proving the caller validated the original user token. */
export interface DelegationEvidence {
  readonly issuer: string;
  readonly kid: string;
}

/** Signed end-user delegation envelope — carries NO raw token. */
export interface DelegationEnvelope {
  readonly provider: string;
  readonly subject: string;
  readonly principalType: string;
  readonly audience: string;
  readonly expiry: number;
  readonly evidence: DelegationEvidence;
}

/** Field names that, if present, indicate a banned raw-token forward. */
const BANNED_RAW_TOKEN_FIELDS: ReadonlyArray<string> = [
  'rawToken',
  'bearerToken',
  'idToken',
  'accessToken',
  'token',
];

/** Result of validated delegation: machine caller + delegated end-user context. */
export interface DelegationContext {
  readonly machine: IdentityPrincipal;
  readonly delegatedUser: DelegationEnvelope;
}

/** Thrown when delegation validation fails. Maps to an opaque 401/403 upstream. */
export class DelegationError extends Error {
  readonly reasonCode: string;

  constructor(message: string) {
    super(message);
    this.name = 'DelegationError';
    this.reasonCode = REASON_DELEGATION_INVALID;
  }
}

/**
 * Validate the inbound machine credential AND the signed delegation envelope.
 *
 * @param serviceToken - The inbound caller machine ``auth(service)`` token.
 * @param envelopeHeader - The raw ``X-Datrix-Delegated-User`` header value.
 * @param surfaceId - Surface identity for provider resolution + logging.
 * @param expectedAudience - This service principal identifier (envelope aud).
 * @returns The validated delegation context.
 * @throws DelegationError when either credential is missing or invalid.
 */
export async function validateDelegation(
  serviceToken: string | undefined,
  envelopeHeader: string | undefined,
  surfaceId: string,
  expectedAudience: string,
): Promise<DelegationContext> {
  if (!serviceToken) {
    throw new DelegationError(
      'Delegation requires an inbound machine auth(service) credential; none present.',
    );
  }
  if (!envelopeHeader) {
    throw new DelegationError(
      `Delegation requires the ${DELEGATION_HEADER} envelope header; none present.`,
    );
  }

  // 1. Validate the machine caller through the shared jose path.
  let machine: IdentityPrincipal;
  try {
    machine = await verifyIdentityToken(serviceToken, surfaceId);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    throw new DelegationError(`Machine credential validation failed: ${message}`);
  }
  if (machine.principalType !== MACHINE_PRINCIPAL_TYPE) {
    throw new DelegationError(
      'Delegation caller must be a machine principal (auth(service)).',
    );
  }

  // 2. Parse + validate the signed envelope — reject any raw-token forward.
  const envelope = parseDelegationEnvelope(envelopeHeader);
  assertNoRawToken(envelopeHeader);

  const nowSeconds = Math.floor(Date.now() / 1000);
  if (envelope.expiry <= nowSeconds) {
    throw new DelegationError('Delegation envelope has expired.');
  }
  if (envelope.principalType !== HUMAN_PRINCIPAL_TYPE) {
    throw new DelegationError(
      'Delegation envelope principalType must be human for end-user delegation.',
    );
  }
  if (envelope.audience !== expectedAudience) {
    throw new DelegationError(
      'Delegation envelope audience does not match this service principal.',
    );
  }

  LOGGER.debug(
    `identity.delegated_user_context.used surface=${surfaceId} ` +
      `provider=${envelope.provider} machine=${machine.provider}`,
  );
  return { machine, delegatedUser: envelope };
}

/** Parse the envelope JSON; reject structurally invalid payloads. */
function parseDelegationEnvelope(header: string): DelegationEnvelope {
  let parsed: unknown;
  try {
    parsed = JSON.parse(header);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    throw new DelegationError(`Delegation envelope is not valid JSON: ${message}`);
  }
  if (parsed === null || typeof parsed !== 'object') {
    throw new DelegationError('Delegation envelope must be a JSON object.');
  }
  const obj = parsed as Record<string, unknown>;
  const evidence = obj['evidence'];
  if (evidence === null || typeof evidence !== 'object') {
    throw new DelegationError('Delegation envelope is missing validation evidence.');
  }
  const ev = evidence as Record<string, unknown>;
  return {
    provider: String(obj['provider'] ?? ''),
    subject: String(obj['subject'] ?? ''),
    principalType: String(obj['principalType'] ?? ''),
    audience: String(obj['audience'] ?? ''),
    expiry: typeof obj['expiry'] === 'number' ? (obj['expiry'] as number) : 0,
    evidence: {
      issuer: String(ev['issuer'] ?? ''),
      kid: String(ev['kid'] ?? ''),
    },
  };
}

/** Reject any envelope that smuggles a raw user token field. */
function assertNoRawToken(header: string): void {
  let parsed: unknown;
  try {
    parsed = JSON.parse(header);
  } catch {
    return;
  }
  if (parsed === null || typeof parsed !== 'object') {
    return;
  }
  const obj = parsed as Record<string, unknown>;
  for (const banned of BANNED_RAW_TOKEN_FIELDS) {
    if (banned in obj) {
      throw new DelegationError(
        `Delegation envelope must not carry a raw token field '${banned}'. ` +
          'Forward only the signed envelope, never the raw user token.',
      );
    }
  }
}

/** Revocation strategies; mirrors RevocationMode in datrix-common. */
export type RevocationMode = 'none' | 'introspection' | 'denylist';

/**
 * Fail-closed revocation check. Returns when the principal is NOT revoked;
 * throws ``DelegationError`` when revoked OR when the check cannot complete
 * (never substitutes a cached "allowed").
 *
 * @param mode - The configured revocation mode.
 * @param principal - The validated principal whose token is being checked.
 * @param check - The async revocation predicate (true = revoked).
 */
export async function assertNotRevoked(
  mode: RevocationMode,
  principal: IdentityPrincipal,
  check: (principal: IdentityPrincipal) => Promise<boolean>,
): Promise<void> {
  if (mode === 'none') {
    return;
  }
  let revoked: boolean;
  try {
    revoked = await check(principal);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    LOGGER.warn(
      `identity_revocation_check_failed reason=${REASON_DELEGATION_INVALID} ` +
        `mode=${mode} detail=${message}`,
    );
    // Fail closed: an unreachable revocation dependency rejects the request.
    throw new DelegationError(
      `Revocation check (${mode}) could not complete; failing closed.`,
    );
  }
  if (revoked) {
    throw new DelegationError('Credential has been revoked.');
  }
}
