// Token verification
// ---------------------------------------------------------------------------

/**
 * Verify a Bearer token against the loaded identity provider plan.
 *
 * Resolves the provider by matching the token issuer against plan entries.
 * Uses `createRemoteJWKSet` + `jwtVerify` for full JWKS validation.
 * JWKS refresh failure throws with reason code `jwks_refresh_failed`.
 *
 * @param token - Raw Bearer token (without 'Bearer ' prefix).
 * @param surfaceId - Provider plan surface ID for the endpoint being guarded.
 * @returns Resolved IdentityPrincipal on success.
 * @throws Error with a reason code string on validation failure.
 */
export async function verifyIdentityToken(
  token: string,
  surfaceId: string,
): Promise<IdentityPrincipal> {
  const plan = loadIdentityPlan();

  const surface = plan.surfaces[surfaceId];
  if (!surface) {
    throw new Error(`provider_mismatch: surface '${surfaceId}' not found in identity plan.`);
  }

  // Try each provider listed in the surface until one verifies the token.
  let lastError: unknown = null;
  for (const providerName of surface.providers) {
    const providerEntry = plan.providers[providerName];
    if (!providerEntry) {
      LOGGER.warn(`identity_provider_missing provider=${providerName}`);
      continue;
    }

    // Guard: reject symmetric algorithms before touching the key set.
    try {
      assertAlgorithmsAreAsymmetric(providerEntry.allowedAlgorithms, providerName);
    } catch (err) {
      throw new Error(
        `bad_signature: ${err instanceof Error ? err.message : String(err)}`,
      );
    }

    // Union the static allow-list with the env-resolved late-bound audiences.
    // Throws (fail closed) when a declared ref cannot be resolved — never caught
    // by the per-provider classifier below, since it is a deployment
    // misconfiguration and not a property of the token.
    const effectiveAudiences = resolveEffectiveAudiences(providerEntry);

    const jwks = getJwksSetForProvider(providerEntry);

    let result: JWTVerifyResult;
    try {
      result = await jwtVerify(token, jwks, {
        issuer: providerEntry.issuer,
        audience: effectiveAudiences.length > 0
          ? (effectiveAudiences as string[])
          : undefined,
        algorithms: providerEntry.allowedAlgorithms as string[],
      });
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      // Classify jose error messages into plan-level reason codes.
      //
      // Claim failures are matched on the QUOTED claim name as jose writes it
      // (`"exp" claim timestamp check failed`, `unexpected "aud" claim value`).
      // Matching the bare claim name would misclassify: exp is a substring of
      // the word unexpected that jose uses, so every audience and issuer
      // mismatch would be reported as expired_token.
      if (
        message.includes('JWKS') ||
        message.includes('fetch') ||
        message.includes('network') ||
        message.includes('connect')
      ) {
        LOGGER.warn(`identity_jwks_refresh_failed provider=${providerName} reason=${message}`);
        lastError = new Error(`jwks_refresh_failed: ${message}`);
        // JWKS refresh failure — fail closed, do not try next provider.
        throw lastError;
      }
      if (message.includes('"exp"') || message.includes('expired')) {
        lastError = new Error(`expired_token: ${message}`);
        continue;
      }
      if (message.includes('"iss"') || message.includes('issuer')) {
        lastError = new Error(`issuer_mismatch: ${message}`);
        continue;
      }
      if (message.includes('"aud"') || message.includes('audience')) {
        lastError = new Error(`audience_mismatch: ${message}`);
        continue;
      }
      if (message.includes('signature') || message.includes('verify') || message.includes('JWS')) {
        lastError = new Error(`bad_signature: ${message}`);
        continue;
      }
      lastError = new Error(`malformed_token: ${message}`);
      continue;
    }

    const claims = result.payload;
    const roles = extractRolesFromClaims(claims, providerEntry);
    const sub = typeof claims.sub === 'string' ? claims.sub : '';

    // Resolve the stable local user id from the plan localIdentity strategy.
    // projected mode: userId is '' here — the surface guard overwrites it after profile resolution.
    const localMode = providerEntry.localIdentity.mode;
    const userId = localMode === 'projected' ? '' : resolveLocalUserId(providerEntry, sub);

    LOGGER.debug(
      `identity_token_verified provider=${providerName} surface=${surfaceId}`,
    );

    return {
      sub,
      userId,
      provider: providerName,
      roles,
      principalType: providerEntry.principalType,
      claims,
    };
  }

  // No provider matched.
  const reasonMessage =
    lastError instanceof Error ? lastError.message : 'provider_mismatch: no provider verified the token';
  throw new Error(reasonMessage);
}
