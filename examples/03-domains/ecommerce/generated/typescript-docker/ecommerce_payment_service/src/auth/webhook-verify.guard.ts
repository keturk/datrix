/**
 * WebhookVerifyGuard — per-endpoint webhook authenticity verification.
 *
 * Supported modes:
 *   signature:    HMAC over raw request body using a per-provider secret env var.
 *   sharedSecret: Constant-time header comparison against a shared secret env var.
 *   mtls:         Mutual TLS — peer certificate or forwarded-cert header presence.
 *   hmac:         Sender-generic keyed hash over the raw request body, with a
 *                 declared header/algorithm/encoding (no provider registry).
 *
 * Failures return opaque 401/400 responses; the real reason is logged via the
 * Nest Logger so secrets never leak to the client.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import { createHmac, timingSafeEqual } from 'crypto';
import {
  CanActivate,
  ExecutionContext,
  HttpException,
  HttpStatus,
  Injectable,
  Logger,
  SetMetadata,
} from '@nestjs/common';
import type { Request } from 'express';

export const WEBHOOK_VERIFY_KEY = 'webhookVerify';

export type WebhookVerifyMode = 'signature' | 'sharedSecret' | 'mtls' | 'hmac';

export type SignatureHeaderLayout = 'prefixed' | 'keyed-list';
export type SignatureTimestampSource = 'none' | 'signature-header' | 'separate-header';

export interface WebhookVerifyConfig {
  mode: WebhookVerifyMode;
  signatureHeader?: string;
  algorithm?: 'sha256' | 'sha1' | 'sha512';
  secretEnvVar?: string;
  header?: string;
  encoding?: 'hex' | 'base64';
  /*
   * Signature-mode scheme, declared per provider. Not one registered provider
   * sends a bare hex digest over the raw body, which is what this guard used to
   * compare against -- so every genuine webhook was rejected with 401 on all
   * three. These fields carry the provider's real scheme.
   */
  headerLayout?: SignatureHeaderLayout;
  signaturePrefix?: string;
  elementSeparator?: string;
  signatureKey?: string;
  timestampKey?: string;
  timestampSource?: SignatureTimestampSource;
  timestampHeader?: string;
  /* Exact bytes that are HMAC'd, as '{timestamp}'/'{body}' placeholders. */
  signedPayloadTemplate?: string;
  toleranceSeconds?: number;
}

export const WebhookVerify = (config: WebhookVerifyConfig) =>
  SetMetadata(WEBHOOK_VERIFY_KEY, config);

const VERIFICATION_FAILED = 'Webhook verification failed';
const VERIFICATION_UNAVAILABLE = 'Webhook verification unavailable';
const SHARED_SECRET_HEADER = 'x-webhook-secret';
const CLIENT_CERT_HEADER = 'x-client-cert';

@Injectable()
export class WebhookVerifyGuard implements CanActivate {
  private readonly logger = new Logger(WebhookVerifyGuard.name);

  constructor(private readonly config: WebhookVerifyConfig) {}

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const request = context.switchToHttp().getRequest<Request>();
    switch (this.config.mode) {
      case 'signature':
        return this.verifySignature(request);
      case 'sharedSecret':
        return this.verifySharedSecret(request);
      case 'mtls':
        return this.verifyMtls(request);
      case 'hmac':
        return this.verifyHmac(request);
      default: {
        this.logger.error(`Unhandled webhook verify mode: ${this.config.mode}`);
        throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
      }
    }
  }

  private requireSecret(): string {
    const envVar = this.config.secretEnvVar;
    if (!envVar) {
      this.logger.error('Webhook verify config missing secretEnvVar');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    const secret = process.env[envVar];
    if (!secret) {
      this.logger.error(`Webhook secret env var not configured: ${envVar}`);
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    return secret;
  }

  private constantTimeEquals(a: string, b: string): boolean {
    const bufferA = Buffer.from(a);
    const bufferB = Buffer.from(b);
    if (bufferA.length !== bufferB.length) {
      return false;
    }
    return timingSafeEqual(bufferA, bufferB);
  }

  private hasPeerCertificate(cert: unknown): boolean {
    if (!cert) {
      return false;
    }
    if (typeof cert === 'object' && Object.keys(cert as Record<string, unknown>).length === 0) {
      return false;
    }
    return true;
  }

  private verifySignature(request: Request): boolean {
    const header = this.config.signatureHeader;
    const algorithm = this.config.algorithm;
    if (!header || !algorithm) {
      this.logger.error('Signature webhook verify config missing header/algorithm');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    const provided = request.header(header);
    if (!provided) {
      this.logger.warn(`Webhook signature header missing: ${header}`);
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    const secret = this.requireSecret();
    const rawBody = (request as Request & { rawBody?: Buffer }).rawBody;
    if (!rawBody) {
      this.logger.error('Raw request body unavailable for signature verification');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }

    const fields = this.parseSignatureHeader(provided);
    const signatures = this.extractSignatures(provided, fields);
    const timestamp = this.resolveSignatureTimestamp(request, fields);
    const signedPayload = this.buildSignedPayload(rawBody, timestamp);

    const expected = createHmac(algorithm, secret).update(signedPayload).digest('hex');
    /*
     * ANY declared digest may match. Stripe emits one signature per active
     * secret while an endpoint secret is being rolled, so requiring the first
     * to match would reject valid traffic for the whole overlap window.
     */
    if (!signatures.some((candidate) => this.constantTimeEquals(expected, candidate))) {
      this.logger.warn('Webhook signature mismatch');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.UNAUTHORIZED);
    }
    return true;
  }

  /* Parse a keyed-list signature header into key -> values. Empty otherwise. */
  private parseSignatureHeader(provided: string): Map<string, string[]> {
    const fields = new Map<string, string[]>();
    if (this.config.headerLayout !== 'keyed-list') {
      return fields;
    }
    const separator = this.config.elementSeparator ?? ',';
    for (const element of provided.split(separator)) {
      const trimmed = element.trim();
      const index = trimmed.indexOf('=');
      if (index < 0) {
        continue;
      }
      const key = trimmed.slice(0, index);
      const value = trimmed.slice(index + 1);
      const existing = fields.get(key);
      if (existing) {
        existing.push(value);
      } else {
        fields.set(key, [value]);
      }
    }
    return fields;
  }

  private extractSignatures(provided: string, fields: Map<string, string[]>): string[] {
    if (this.config.headerLayout === 'keyed-list') {
      /*
       * Only the declared signature key is collected; every other key is
       * discarded. That is what makes a lower/fake scheme carried in the same
       * header (Stripe's test-only v0) unusable as a downgrade.
       */
      const key = this.config.signatureKey;
      if (!key) {
        this.logger.error('Signature webhook verify config missing signatureKey');
        throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
      }
      const signatures = fields.get(key) ?? [];
      if (signatures.length === 0) {
        this.logger.warn('Webhook signature header carries no usable signature');
        throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
      }
      return signatures;
    }
    const prefix = this.config.signaturePrefix;
    if (!prefix) {
      this.logger.error('Signature webhook verify config missing signaturePrefix');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    if (!provided.startsWith(prefix)) {
      this.logger.warn('Webhook signature header malformed');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    return [provided.slice(prefix.length)];
  }

  /* Resolve and bound the replay timestamp; null when the scheme has none. */
  private resolveSignatureTimestamp(
    request: Request,
    fields: Map<string, string[]>,
  ): number | null {
    const source = this.config.timestampSource ?? 'none';
    if (source === 'none') {
      return null;
    }
    let raw: string | undefined;
    if (source === 'separate-header') {
      raw = request.header(this.config.timestampHeader ?? '');
    } else {
      raw = (fields.get(this.config.timestampKey ?? '') ?? [])[0];
    }
    if (!raw) {
      this.logger.warn('Webhook timestamp missing');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    const timestamp = Number.parseInt(raw, 10);
    if (Number.isNaN(timestamp)) {
      this.logger.warn('Webhook timestamp is not an integer');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    const tolerance = this.config.toleranceSeconds;
    if (!tolerance) {
      this.logger.error('Signature webhook verify config missing toleranceSeconds');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    if (Math.abs(Math.floor(Date.now() / 1000) - timestamp) > tolerance) {
      this.logger.warn(`Webhook timestamp outside tolerance seconds=${tolerance}`);
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    return timestamp;
  }

  /*
   * Build the exact bytes that are HMAC'd, from the provider's declared
   * template. The body is spliced in as raw bytes rather than decoded: any
   * mutation of the raw body (re-encoding, whitespace, key reordering) breaks
   * verification.
   */
  private buildSignedPayload(rawBody: Buffer, timestamp: number | null): Buffer {
    const template = this.config.signedPayloadTemplate ?? '{body}';
    const bodyIndex = template.indexOf('{body}');
    if (bodyIndex < 0) {
      this.logger.error('Signature webhook verify config signs a payload excluding the body');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    const render = (fragment: string): Buffer =>
      Buffer.from(fragment.replace('{timestamp}', timestamp === null ? '' : String(timestamp)), 'utf8');
    return Buffer.concat([
      render(template.slice(0, bodyIndex)),
      rawBody,
      render(template.slice(bodyIndex + '{body}'.length)),
    ]);
  }

  private verifySharedSecret(request: Request): boolean {
    const provided = request.header(SHARED_SECRET_HEADER);
    if (!provided) {
      this.logger.warn('Webhook shared-secret header missing');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    const secret = this.requireSecret();
    if (!this.constantTimeEquals(provided, secret)) {
      this.logger.warn('Webhook shared-secret mismatch');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.UNAUTHORIZED);
    }
    return true;
  }

  private verifyMtls(request: Request): boolean {
    const peerCert = (request.socket as { getPeerCertificate?: () => unknown }).getPeerCertificate?.();
    const forwardedCert = request.header(CLIENT_CERT_HEADER);
    if (!this.hasPeerCertificate(peerCert) && !forwardedCert) {
      this.logger.warn('Webhook mTLS client certificate absent');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.UNAUTHORIZED);
    }
    return true;
  }

  private verifyHmac(request: Request): boolean {
    const header = this.config.header;
    const algorithm = this.config.algorithm;
    if (!header || !algorithm) {
      this.logger.error('HMAC webhook verify config missing header/algorithm');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    const provided = request.header(header);
    if (!provided) {
      this.logger.warn(`Webhook hmac signature header missing: ${header}`);
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.BAD_REQUEST);
    }
    const secret = this.requireSecret();
    const rawBody = (request as Request & { rawBody?: Buffer }).rawBody;
    if (!rawBody) {
      this.logger.error('Raw request body unavailable for hmac verification');
      throw new HttpException(VERIFICATION_UNAVAILABLE, HttpStatus.INTERNAL_SERVER_ERROR);
    }
    const digest = createHmac(algorithm, secret).update(rawBody);
    const expected =
      this.config.encoding === 'base64' ? digest.digest('base64') : digest.digest('hex');
    if (!this.constantTimeEquals(expected, provided)) {
      this.logger.warn('Webhook hmac signature mismatch');
      throw new HttpException(VERIFICATION_FAILED, HttpStatus.UNAUTHORIZED);
    }
    return true;
  }
}
