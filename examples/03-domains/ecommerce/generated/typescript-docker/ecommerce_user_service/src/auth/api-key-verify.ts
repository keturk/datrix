/**
 * True when the stored hash is exactly the presented one, compared in constant
 * time. The lookup's equality is the database's, which a column collation may
 * fold (case, trailing padding); a row is accepted only on an exact match.
 */
function storedHashMatches(stored: unknown, keyHash: string): boolean {
  if (typeof stored !== 'string') {
    return false;
  }
  const storedBytes = Buffer.from(stored, 'utf8');
  const presentedBytes = Buffer.from(keyHash, 'utf8');
  return storedBytes.length === presentedBytes.length && timingSafeEqual(storedBytes, presentedBytes);
}

/** A stored timestamp as a Date; null stays null. */
function toDateOrNull(provider: string, column: string, value: unknown): Date | null {
  if (value === null || value === undefined) {
    return null;
  }
  const date = value instanceof Date ? value : new Date(value as string | number);
  if (Number.isNaN(date.getTime())) {
    throw new Error(
      `API-key provider '${provider}': column '${column}' holds a value that is not a timestamp.`,
    );
  }
  return date;
}

