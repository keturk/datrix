/** The only accepted wire form of a key hash: a SHA-256 digest in lower-case hex. */
const KEY_HASH_PATTERN = /^[0-9a-f]{64}$/;
/** Log-only reason codes; a caller only ever sees the undifferentiated outcome. */
const REASON_NO_ROW = 'no_row';
const REASON_INACTIVE = 'inactive';
const REASON_EXPIRED = 'expired';
const REASON_RATE_LIMITED = 'rate_limited';
const MILLISECONDS_PER_SECOND = 1000;
/** Seconds a window's counter outlives the window, so a late INCR never lands on an expired key. */
const RATE_LIMIT_COUNTER_TTL_MARGIN_SECONDS = 5;
const LOGGER = new Logger('ApiKeyVerify');

