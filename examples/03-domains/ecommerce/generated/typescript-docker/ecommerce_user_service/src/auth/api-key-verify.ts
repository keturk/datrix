/** The stored per-key request budget; anything but a non-negative integer is corrupt data. */
function toRateLimit(provider: string, column: string, value: unknown): number {
  const limit = typeof value === 'string' ? Number(value) : value;
  if (typeof limit !== 'number' || !Number.isInteger(limit) || limit < 0) {
    throw new Error(
      `API-key provider '${provider}': column '${column}' does not hold a non-negative integer.`,
    );
  }
  return limit;
}

/**
 * Count one request against a key's fixed window and decide whether it is over budget.
 *
 * INCR and EXPIRE travel in ONE MULTI/EXEC transaction: the counter can never
 * be incremented without its expiry, and concurrent requests are counted
 * exactly. Any failure of the store is ApiKeyRateLimitUnavailableError.
 */
async function countRequest(
  provider: string,
  keyId: string,
  limit: number,
  windowSeconds: number,
): Promise<VerifyRateLimitedResult | null> {
  const redis = rateLimitClients.get(provider);
  if (redis === undefined) {
    throw new ApiKeyRateLimitUnavailableError(
      provider,
      'no Redis client is bound; main.ts calls bindApiKeyRateLimitRedis at bootstrap',
    );
  }
  const nowSeconds = Math.floor(Date.now() / MILLISECONDS_PER_SECOND);
  const counterKey = `apikey:rl:${provider}:${keyId}:${Math.floor(nowSeconds / windowSeconds)}`;
  let results: Array<[Error | null, unknown]> | null;
  try {
    results = await redis
      .multi()
      .incr(counterKey)
      .expire(counterKey, windowSeconds + RATE_LIMIT_COUNTER_TTL_MARGIN_SECONDS)
      .exec();
  } catch (err) {
    throw new ApiKeyRateLimitUnavailableError(provider, err);
  }
  if (results === null || results.length !== 2) {
    throw new ApiKeyRateLimitUnavailableError(provider, 'the rate-limit transaction did not execute');
  }
  const [incrError, count] = results[0];
  const [expireError] = results[1];
  if (incrError !== null || expireError !== null || typeof count !== 'number') {
    throw new ApiKeyRateLimitUnavailableError(provider, incrError ?? expireError);
  }
  if (count > limit) {
    return { outcome: 'rateLimited', retryAfterSeconds: windowSeconds - (nowSeconds % windowSeconds) };
  }
  return null;
}

/** Verify a key hash of API-key provider "customerKeys" against ApiKey. */
async function verifyCustomerKeys(keyHash: string): Promise<VerifyOutcome> {
  const provider = "customerKeys";
  const forkedEm = requireEntityManager(provider).fork();
  const found = await forkedEm.findOne("ApiKey", {
    keyHash: keyHash,
  });
  if (found === null || !storedHashMatches((found as StoredRow)["keyHash"], keyHash)) {
    LOGGER.log(`api_key_verify_denied provider=${provider} reason=${REASON_NO_ROW}`);
    return { outcome: 'invalid' };
  }
  const row = found as StoredRow;
  const keyId = String(row["id"]);
  if (row["isActive"] !== true) {
    LOGGER.log(`api_key_verify_denied provider=${provider} key_id=${keyId} reason=${REASON_INACTIVE}`);
    return { outcome: 'invalid' };
  }
  const now = new Date();
  const expiresAt = toDateOrNull(provider, "expiresAt", row["expiresAt"]);
  if (expiresAt !== null && expiresAt.getTime() <= now.getTime()) {
    LOGGER.log(`api_key_verify_denied provider=${provider} key_id=${keyId} reason=${REASON_EXPIRED}`);
    return { outcome: 'invalid' };
  }
  const scopes = toScopes(provider, "scopes", row["scopes"]);
  const limit = toRateLimit(provider, "rateLimit", row["rateLimit"]);
  const rateLimited = await countRequest(provider, keyId, limit, 60);
  if (rateLimited !== null) {
    LOGGER.log(`api_key_verify_denied provider=${provider} key_id=${keyId} reason=${REASON_RATE_LIMITED}`);
    return rateLimited;
  }
  // One conditional write per request: lastUsedAt moves at most once per
  // resolution window, however many requests the key makes inside it.
  const resolutionMs = 60 * MILLISECONDS_PER_SECOND;
  await forkedEm.nativeUpdate(
    "ApiKey",
    {
      id: row["id"],
      $or: [
        { lastUsedAt: null },
        { lastUsedAt: { $lt: new Date(now.getTime() - resolutionMs) } },
      ],
    },
    { lastUsedAt: now },
  );
  LOGGER.log(`api_key_verify_ok provider=${provider} key_id=${keyId}`);
  return {
    outcome: 'ok',
    keyId,
    ownerId: String(row["ownerId"]),
    tenantId: null,
    scopes,
    expiresAt: expiresAt === null ? null : expiresAt.toISOString(),
  };
}

/**
 * Verify the SHA-256 hash of a presented key for *provider*.
 *
 * The one verification path of this service. It throws
 * ApiKeyRateLimitUnavailableError when a mapped rate limit cannot be counted,
 * and an Error for a provider this service does not store -- never a coerced
 * outcome.
 */
export async function verifyApiKeyHash(provider: string, keyHash: string): Promise<VerifyOutcome> {
  // The key lookup is unscoped: the tenant is an output of the lookup, never an input.
  console.log('cross_tenant_access handler=%s kind=%s', 'verifyApiKeyHash', 'service function');

  switch (provider) {
    case "customerKeys":
      return verifyCustomerKeys(keyHash);
    default:
      throw new Error(
        `'${provider}' is not an API-key provider this service stores. ` +
          `Stored providers: customerKeys.`,
      );
  }
}

/**
 * Answer one call of *provider*'s internal verify route.
 *
 * 400 for a key hash that is not 64 lower-case hex characters (checked before
 * anything is looked up), 401 without an authentication challenge for an
 * invalid key, 429 with retryAfterSeconds
 * (sent as the Retry-After header) for a rate-limited key, 503 when the
 * key store or the rate-limit store is unavailable, and the verified identity otherwise.
 */
export async function answerApiKeyVerifyRequest(
  provider: string,
  keyHash: unknown,
): Promise<ApiKeyVerifyResponse> {
  if (typeof keyHash !== 'string' || !KEY_HASH_PATTERN.test(keyHash)) {
    throw new BadRequestException('Malformed key hash.');
  }
  let outcome: VerifyOutcome;
  try {
    outcome = await verifyApiKeyHash(provider, keyHash);
  } catch (err) {
    if (err instanceof ApiKeyRateLimitUnavailableError) {
      LOGGER.error(`api_key_verify_unavailable provider=${provider} reason=rate_limit_store`);
      throw new ServiceUnavailableException('Service temporarily unavailable.');
    }
    if (err instanceof DriverException) {
      LOGGER.error(`api_key_verify_unavailable provider=${provider} reason=key_store`);
      throw new ServiceUnavailableException('Service temporarily unavailable.');
    }
    throw err;
  }
  if (outcome.outcome === 'invalid') {
    // No authentication challenge: this 401 is the verdict on the key. A
    // calling service reads a 401 carrying WWW-Authenticate as its own machine
    // credential refused by the route's guard, never as an invalid key.
    throw new UnauthorizedException('Invalid key.');
  }
  if (outcome.outcome === 'rateLimited') {
    throw new HttpException(
      {
        statusCode: HttpStatus.TOO_MANY_REQUESTS,
        message: 'Too Many Requests',
        retryAfterSeconds: outcome.retryAfterSeconds,
      },
      HttpStatus.TOO_MANY_REQUESTS,
    );
  }
  return {
    keyId: outcome.keyId,
    ownerId: outcome.ownerId,
    tenantId: outcome.tenantId,
    scopes: outcome.scopes,
    expiresAt: outcome.expiresAt,
  };
}
