export const REASON_MALFORMED_TOKEN = "malformed_token";
export const REASON_EXPIRED_TOKEN = "expired_token";
export const REASON_BAD_SIGNATURE = "bad_signature";
export const REASON_ISSUER_MISMATCH = "issuer_mismatch";
export const REASON_AUDIENCE_MISMATCH = "audience_mismatch";
export const REASON_JWKS_REFRESH_FAILED = "jwks_refresh_failed";

/**
 * The vocabulary code that classifies a failed `jose` verification.
 *
 * Claim failures are matched on the QUOTED claim name as `jose` writes it
 * (`"exp" claim timestamp check failed`, `unexpected "aud" claim value`).
 * Matching the bare claim name would misclassify: `exp` is a substring of the
 * word `unexpected` that `jose` uses, so every audience and issuer mismatch
 * would be reported as an expired token.
 *
 * The code is the ONLY thing derived from the exception; its text is never
 * returned, logged as a reason or placed on a thrown error.
 */
export function reasonCodeForVerificationFailure(failure: unknown): string {
  const message = failure instanceof Error ? failure.message : String(failure);
  if (
    message.includes('JWKS') ||
    message.includes('fetch') ||
    message.includes('network') ||
    message.includes('connect')
  ) {
    return REASON_JWKS_REFRESH_FAILED;
  }
  if (message.includes('"exp"') || message.includes('expired')) {
    return REASON_EXPIRED_TOKEN;
  }
  if (message.includes('"iss"') || message.includes('issuer')) {
    return REASON_ISSUER_MISMATCH;
  }
  if (message.includes('"aud"') || message.includes('audience')) {
    return REASON_AUDIENCE_MISMATCH;
  }
  if (message.includes('signature') || message.includes('verify') || message.includes('JWS')) {
    return REASON_BAD_SIGNATURE;
  }
  return REASON_MALFORMED_TOKEN;
}
export const REASON_PROVIDER_MISMATCH = "provider_mismatch";

/**
 * A token that failed verification. `reasonCode` is the shared-vocabulary code
 * (logged server-side, never returned to a caller); the message IS the code, so
 * no exception text travels with it.
 *
 * Everything else this module throws -- a missing or unreadable plan, an
 * unsupported schema version, an invalid `localIdentity` mode, an unresolved
 * `allowedAudienceRefs` entry -- is a deployment or configuration defect, not a
 * property of the token, and stays a plain `Error`: the auth chain maps it to the
 * provider-config-error code.
 */
export class IdentityVerificationError extends Error {
  constructor(readonly reasonCode: string) {
    super(reasonCode);
    this.name = 'IdentityVerificationError';
  }
}

