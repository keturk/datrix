/**
 * Authentication chain shared by every authenticated entrypoint of this
 * service: the REST AuthGuard, the container serverless HTTP app, the cloud
 * serverless HTTP adapters, and every websocket_api / GraphQL subscription
 * handshake.
 *
 * authenticateToken  -> 401 on an invalid token; projects the local profile
 *   for a projected-mode provider (403 when it cannot) and runs the app-owned
 *   identity write-back. Every handshake calls it with the credential it read.
 * authenticateBearer -> parses the `Authorization` header (401 when missing or
 *   malformed) and delegates to authenticateToken.
 * authenticateOptionalBearer -> `auth(optional)`: an absent header is an
 *   anonymous request (undefined); a presented one runs authenticateBearer.
 * authenticateRouteRequest -> the one bearer-or-API-key decision of a request
 *   to a route: a presented header of an API-key provider the route admits is
 *   resolved by resolveApiKeyPrincipal, and that outcome is final; otherwise the
 *   bearer chain runs.
 * authenticateRouteApiKey -> the API-key principal of a request to a route
 *   (undefined when no admitted key header is presented); the REST AuthGuard
 *   resolves a key here, in the same stage as the bearer chain.
 * authenticateOptionalRouteRequest -> `auth(optional)` over a route's request:
 *   nothing presented is anonymous (undefined); anything presented runs
 *   authenticateRouteRequest, so a failing credential is a 401.
 * requireProviders   -> 403 when the verified principal's provider is not in
 *   the route's allow-list.
 * requireRoles       -> 403 when the principal holds none of the route's roles
 *   (flat any-of, no role hierarchy).
 * requirePrincipalTypes -> 403 when the principal's type is not admitted.
 * bearerTokenOrForbidden -> the principal's forwardable bearer token, or 403
 *   when it holds none (an API-key principal).
 *
 * Reason codes are logged server-side only; callers return opaque bodies.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import { ForbiddenException, Logger } from '@nestjs/common';
import { IdentityVerificationError, verifyIdentityToken } from './identity';
import type { IdentityPrincipal } from './identity';
// The malformed-token code lives with the identity core's classifier; the WebSocket
// upgrade router imports it from here.
export { REASON_MALFORMED_TOKEN } from './identity';

const LOGGER = new Logger('AuthChain');

export const REASON_MISSING_TOKEN = "missing_token";
export const REASON_PROVIDER_NOT_ALLOWED = "provider_not_allowed";
export const REASON_ROLE_DENIED = "role_denied";
export const REASON_PRINCIPAL_TYPE_MISMATCH = "principal_type_mismatch";
export const REASON_PROFILE_UNAVAILABLE = "profile_unavailable";
export const REASON_PROVIDER_CONFIG_ERROR = "provider_config_error";
export const REASON_NO_FORWARDABLE_TOKEN = "no_forwardable_token";

/**
 * The status of a failed auth-chain step: 401 (authentication), 403
 * (authorization), 429 (a rate-limited API key) or 503 (an API key whose
 * verification could not complete -- fail closed).
 */
export type AuthChainStatus = 401 | 403 | 429 | 503;

/** A failed auth-chain step, carrying the status every caller answers with. */
export class AuthChainError extends Error {
  constructor(
    readonly status: AuthChainStatus,
    readonly reasonCode: string,
  ) {
    super(reasonCode);
    this.name = 'AuthChainError';
  }
}

/** A rate-limited API key: 429, told when to come back through `Retry-After`. */
export class AuthChainRateLimitedError extends AuthChainError {
  constructor(
    reasonCode: string,
    readonly retryAfterSeconds: number,
  ) {
    super(429, reasonCode);
    this.name = 'AuthChainRateLimitedError';
  }
}

/** The opaque detail every non-Nest entrypoint answers a failed step with, by status. */
const FAILURE_DETAILS: Readonly<Record<AuthChainStatus, string>> = {
  401: 'Authentication required',
  403: 'Insufficient permissions',
  429: 'Too many requests',
  503: 'Service temporarily unavailable',
};

/** The opaque response detail of a failed step -- never its reason code. */
export function authChainFailureDetail(err: AuthChainError): string {
  return FAILURE_DETAILS[err.status];
}

/** The response headers a failed step answers with: `Retry-After` for a rate-limited key. */
export function authChainFailureHeaders(err: AuthChainError): Record<string, string> {
  return err instanceof AuthChainRateLimitedError
    ? { 'Retry-After': String(err.retryAfterSeconds) }
    : {};
}

/**
 * Request headers as every entrypoint holds them: Node's lower-cased
 * `IncomingHttpHeaders`, a Lambda proxy event's caller-cased map, or the
 * entries of a Fetch `Headers`. Every read below is case-insensitive.
 */
export type RequestHeaders = Readonly<Record<string, string | ReadonlyArray<string> | undefined>>;

/** Every value of header *name* in *headers*, whatever its casing. */
function headerValues(headers: RequestHeaders, name: string): string[] {
  const wanted = name.toLowerCase();
  const values: string[] = [];
  for (const [key, value] of Object.entries(headers)) {
    if (key.toLowerCase() !== wanted || value === undefined) {
      continue;
    }
    if (typeof value === 'string') {
      values.push(value);
    } else {
      values.push(...value);
    }
  }
  return values;
}

/**
 * The single value of header *name*; two differing copies are ambiguous and
 * yield none, so the chain denies instead of picking one.
 */
function singleHeaderValue(headers: RequestHeaders, name: string): string | undefined {
  const distinct = new Set(headerValues(headers, name));
  return distinct.size === 1 ? [...distinct][0] : undefined;
}

/** The header a bearer token is presented in. */
const AUTHORIZATION_HEADER = 'authorization';

function bearerToken(authorization: string | undefined | null): string | undefined {
  if (!authorization) {
    return undefined;
  }
  const [type, value] = authorization.split(' ');
  return type === 'Bearer' && value ? value : undefined;
}

/**
 * The vocabulary code of a failed verification.
 *
 * A typed `IdentityVerificationError` carries its code. Any other error is a
 * deployment or configuration defect (an unreadable plan, an unset audience
 * ref) -- it is refused like any failed credential (401) under the
 * provider-config-error code and logged as a configuration error, never
 * mistaken for a token failure and never allowed.
 */
function reasonOf(err: unknown): string {
  if (err instanceof IdentityVerificationError) {
    return err.reasonCode;
  }
  LOGGER.error(
    `identity_auth_config_error reason_code=${REASON_PROVIDER_CONFIG_ERROR}`,
    err instanceof Error ? err.stack : undefined,
  );
  return REASON_PROVIDER_CONFIG_ERROR;
}

/**
 * Verify the bearer token and resolve the application principal.
 *
 * @param authorization - The raw `Authorization` header value (may be absent).
 * @returns The verified principal, with `userId` resolved from the profile
 *   store for a projected-mode provider.
 * @throws AuthChainError 401 for a missing/invalid token; 403 when a
 *   projected-mode principal's profile cannot be resolved.
 */
export async function authenticateBearer(
  authorization: string | undefined | null,
): Promise<IdentityPrincipal> {
  const token = bearerToken(authorization);
  if (token === undefined) {
    LOGGER.warn(`identity_auth_failed reason_code=${REASON_MISSING_TOKEN}`);
    throw new AuthChainError(401, REASON_MISSING_TOKEN);
  }
  return authenticateToken(token);
}

/**
 * `auth(optional)`: an absent `Authorization` header is an anonymous request
 * (`undefined`); a presented one runs the full bearer chain, so a credential
 * that fails verification is a 401, never an anonymous request.
 */
export async function authenticateOptionalBearer(
  authorization: string | undefined | null,
): Promise<IdentityPrincipal | undefined> {
  if (authorization === undefined || authorization === null) {
    return undefined;
  }
  return authenticateBearer(authorization);
}

/**
 * Verify a credential and resolve the application principal -- every step the
 * bearer chain runs after the credential is extracted: signature, expiry,
 * issuer, audience and algorithm (`verifyIdentityToken`), the projected-mode
 * profile lookup that turns a projected principal's empty `userId` into its
 * profile id, and the app-owned identity write-back.
 *
 * @param token - The credential, already extracted from its source.
 * @returns The verified principal, with `userId` resolved from the profile
 *   store for a projected-mode provider.
 * @throws AuthChainError 401 for an invalid token; 403 when a projected-mode
 *   principal's profile cannot be resolved.
 */
export async function authenticateToken(token: string): Promise<IdentityPrincipal> {
  let principal: IdentityPrincipal;
  try {
    principal = await verifyIdentityToken(token);
  } catch (err) {
    const reason = reasonOf(err);
    LOGGER.warn(`identity_auth_failed reason_code=${reason}`);
    throw new AuthChainError(401, reason);
  }
  if (principal.localIdentityMode === 'projected') {
    // No provider of this service resolves to projected mode, so no profile
    // store is emitted: a projected principal can never be resolved here and
    // is denied rather than passed through with an empty user id.
    LOGGER.warn(
      `identity_auth_failed reason_code=${REASON_PROFILE_UNAVAILABLE} provider=${principal.provider}`,
    );
    throw new AuthChainError(403, REASON_PROFILE_UNAVAILABLE);
  }
  LOGGER.debug(`identity_token_verified provider=${principal.provider}`);
  return principal;
}

/**
 * Return the bearer token a principal was authenticated with, or deny (403).
 *
 * A JWT-authenticated principal always carries the token it was verified with.
 * A principal with no forwardable credential (an API-key principal) carries
 * `token: null` by construction -- forwarding the raw API key downstream is
 * forbidden, so this throws rather than returning anything.
 *
 * @throws ForbiddenException when the principal carries no forwardable token.
 */
export function bearerTokenOrForbidden(principal: IdentityPrincipal): string {
  if (principal.token === null) {
    LOGGER.warn(
      `identity_auth_failed reason_code=${REASON_NO_FORWARDABLE_TOKEN} provider=${principal.provider}`,
    );
    throw new ForbiddenException('No forwardable credential for this principal.');
  }
  return principal.token;
}

/**
 * Authenticate one request to a route: the single bearer-or-API-key decision.
 *
 * When the request presents the header of an API-key provider the route
 * admits, the key is resolved by resolveApiKeyPrincipal and its outcome is
 * final (401/429/503 propagate; the bearer chain never runs to report a
 * misleading missing token). Otherwise the `Authorization` bearer chain runs.
 *
 * @param headers - The request's headers, in any casing.
 * @param admittedApiKeyProviders - The API-key providers the route admits,
 *   rendered per route at generation time; empty for a route admitting none.
 * @throws AuthChainError with the status the caller answers with.
 */
export async function authenticateRouteRequest(
  headers: RequestHeaders,
  admittedApiKeyProviders: ReadonlyArray<string>,
): Promise<IdentityPrincipal> {
  if (admittedApiKeyProviders.length > 0) {
    throw new Error(
      `A route admits the API-key providers ${admittedApiKeyProviders.join(', ')}, but this ` +
        'service renders no API-key chain. Regenerate the service so both agree.',
    );
  }
  return authenticateBearer(singleHeaderValue(headers, AUTHORIZATION_HEADER));
}

/**
 * `auth(optional)` over a route's request: no credential presented -- no
 * `Authorization` header and no header of an admitted API-key provider -- is an
 * anonymous request (`undefined`); anything presented runs
 * authenticateRouteRequest, so a credential that fails verification (or is
 * ambiguous) is a 401, never an anonymous request.
 *
 * @param headers - The request's headers, in any casing.
 * @param admittedApiKeyProviders - The API-key providers the route admits.
 * @throws AuthChainError with the status the caller answers with.
 */
export async function authenticateOptionalRouteRequest(
  headers: RequestHeaders,
  admittedApiKeyProviders: ReadonlyArray<string>,
): Promise<IdentityPrincipal | undefined> {
  if (headerValues(headers, AUTHORIZATION_HEADER).length === 0 && admittedApiKeyProviders.length === 0) {
    return undefined;
  }
  return authenticateRouteRequest(headers, admittedApiKeyProviders);
}

/** This service renders no API-key chain: no provider of a route allow-list is an API-key provider. */
export function routeApiKeyProviders(_routeProviders: ReadonlyArray<string>): string[] {
  return [];
}

/** This service renders no API-key chain: no request presents an API key. */
export function presentsRouteApiKey(
  _headers: RequestHeaders,
  _routeProviders: ReadonlyArray<string>,
): boolean {
  return false;
}

/** This service renders no API-key chain: no request carries an API-key principal. */
export async function authenticateRouteApiKey(
  _headers: RequestHeaders,
  _routeProviders: ReadonlyArray<string>,
): Promise<IdentityPrincipal | undefined> {
  return undefined;
}

/**
 * Deny (403) a principal whose provider is not in `allowed`.
 *
 * @throws AuthChainError 403 with reason `provider_not_allowed`.
 */
export function requireProviders(principal: IdentityPrincipal, allowed: ReadonlyArray<string>): void {
  if (!allowed.includes(principal.provider)) {
    LOGGER.warn(`identity_provider_denied reason_code=${REASON_PROVIDER_NOT_ALLOWED}`);
    throw new AuthChainError(403, REASON_PROVIDER_NOT_ALLOWED);
  }
}

/**
 * Deny (403) a principal holding none of `required` (flat any-of).
 *
 * @throws AuthChainError 403 with reason `role_denied`.
 */
export function requireRoles(principal: IdentityPrincipal, required: ReadonlyArray<string>): void {
  if (!required.some((role) => principal.roles.includes(role))) {
    LOGGER.warn(`identity_role_denied reason_code=${REASON_ROLE_DENIED}`);
    throw new AuthChainError(403, REASON_ROLE_DENIED);
  }
}

/**
 * Deny (403) a principal whose type (its provider's plan `principalType`) is
 * not in `allowed`.
 *
 * @throws AuthChainError 403 with reason `principal_type_mismatch`.
 */
export function requirePrincipalTypes(
  principal: IdentityPrincipal,
  allowed: ReadonlyArray<string>,
): void {
  if (!allowed.includes(principal.principalType)) {
    LOGGER.warn(`identity_principal_type_denied reason_code=${REASON_PRINCIPAL_TYPE_MISMATCH}`);
    throw new AuthChainError(403, REASON_PRINCIPAL_TYPE_MISMATCH);
  }
}
