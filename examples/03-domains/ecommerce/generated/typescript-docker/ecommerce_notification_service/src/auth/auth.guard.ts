/**
 * AuthGuard — the REST and GraphQL adapter over the shared auth chain (`auth-chain.ts`).
 *
 * The guard runs for every route not marked `@Public()`:
 *   1. the principal: the API-key principal of a key presented to a route whose
 *      `@Providers(...)` list admits an API-key provider
 *      (`authenticateRouteApiKey`; a presented key's outcome is final: 401, 429
 *      with `Retry-After`, or 503), or else `authenticateBearer` — 401 on a
 *      missing or invalid token. A route marked `@OptionalAuth()` reads the
 *      bearer through `authenticateOptionalBearer`: an absent credential is
 *      served as an anonymous request (no `request.user`); a presented one runs
 *      the full chain and a credential that fails verification is still a 401.
 *   2. `requireProviders`      — 403 when the route's `@Providers(...)` allow-list
 *      does not name the principal's provider.
 *   3. `requirePrincipalTypes` — 403 when the route's `@PrincipalTypes(...)`
 *      does not admit the principal's type.
 *   4. `requireRoles`          — 403 when the principal holds none of the route's
 *      `@Roles(...)` (flat any-of, no role hierarchy).
 * Both principal kinds pass through steps 2 to 4 unchanged.
 *
 * The request is the HTTP request of a REST route.
 * Any other execution context carries no credential and is refused.
 *
 * Response bodies are opaque RFC 7807 problems; the reason code is logged
 * server-side only. An error that is not an auth-chain denial (a plan-load
 * or configuration failure) is rethrown and never turns into an allow.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import {
  CanActivate,
  ExecutionContext,
  ForbiddenException,
  HttpException,
  HttpStatus,
  Injectable,
  ServiceUnavailableException,
  UnauthorizedException,
} from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import type { Request, Response } from 'express';
import { IS_PUBLIC_KEY } from './public.decorator';
import { ROLES_KEY } from './roles.decorator';
import { PROVIDERS_KEY } from './providers.decorator';
import { OPTIONAL_AUTH_KEY, PRINCIPAL_TYPES_KEY } from './optional-auth.decorator';
import {
  AuthChainError,
  AuthChainRateLimitedError,
  authenticateBearer,
  authenticateOptionalBearer,
  authenticateRouteApiKey,
  requirePrincipalTypes,
  requireProviders,
  requireRoles,
  REASON_MISSING_TOKEN,
} from './auth-chain';

const CHALLENGE_HEADER = 'WWW-Authenticate';
/** RFC 6750 challenge of a request that carried no bearer credential. */
const MISSING_CREDENTIAL_CHALLENGE = 'Bearer';
/** RFC 6750 challenge of a refused bearer credential. */
const REFUSED_CREDENTIAL_CHALLENGE = 'Bearer error="invalid_token"';

const UNAUTHORIZED_PROBLEM = { type: 'about:blank', title: 'Unauthorized', status: 401 } as const;
const FORBIDDEN_PROBLEM = { type: 'about:blank', title: 'Forbidden', status: 403 } as const;
const TOO_MANY_REQUESTS_PROBLEM = { type: 'about:blank', title: 'Too Many Requests', status: 429 } as const;
const SERVICE_UNAVAILABLE_PROBLEM = {
  type: 'about:blank',
  title: 'Service Unavailable',
  status: 503,
} as const;

/**
 * The Nest exception a failed auth-chain step answers with. A rate-limited
 * key's 429 carries `retryAfterSeconds`, which the global exception filter
 * sends as the `Retry-After` header.
 */
export function authChainHttpException(err: AuthChainError): HttpException {
  if (err instanceof AuthChainRateLimitedError) {
    return new HttpException(
      { ...TOO_MANY_REQUESTS_PROBLEM, retryAfterSeconds: err.retryAfterSeconds },
      HttpStatus.TOO_MANY_REQUESTS,
    );
  }
  switch (err.status) {
    case 401:
      return new UnauthorizedException(UNAUTHORIZED_PROBLEM);
    case 503:
      return new ServiceUnavailableException(SERVICE_UNAVAILABLE_PROBLEM);
    default:
      return new ForbiddenException(FORBIDDEN_PROBLEM);
  }
}

/**
 * Set the RFC 6750 challenge on the response of an HTTP route that refused its
 * credential with a 401, so a calling service tells "my credential was refused"
 * apart from a route's own 401 verdict on the request (an API-key verify
 * route's invalid key carries no challenge). Any other step, and any non-HTTP
 * execution context, carries none.
 */
function challengeRefusedCredential(context: ExecutionContext, err: AuthChainError): void {
  if (err.status !== 401 || context.getType<string>() !== 'http') {
    return;
  }
  const challenge =
    err.reasonCode === REASON_MISSING_TOKEN
      ? MISSING_CREDENTIAL_CHALLENGE
      : REFUSED_CREDENTIAL_CHALLENGE;
  context.switchToHttp().getResponse<Response>().setHeader(CHALLENGE_HEADER, challenge);
}

@Injectable()
export class AuthGuard implements CanActivate {
  constructor(private readonly reflector: Reflector) {}

  /**
   * The request this guard authenticates. A GraphQL resolver's request lives in
   * the GraphQL context, not the HTTP argument slot; any other execution
   * context carries no credential, so it is refused (fail closed).
   */
  private resolveRequest(context: ExecutionContext): Request {
    const type = context.getType<string>();
    if (type !== 'http') {
      throw new UnauthorizedException(UNAUTHORIZED_PROBLEM);
    }
    return context.switchToHttp().getRequest<Request>();
  }

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const targets = [context.getHandler(), context.getClass()];
    if (this.reflector.getAllAndOverride<boolean>(IS_PUBLIC_KEY, targets)) {
      return true;
    }
    const request = this.resolveRequest(context);
    const optional = this.reflector.getAllAndOverride<boolean>(OPTIONAL_AUTH_KEY, targets) === true;
    try {
      const providers = this.reflector.getAllAndOverride<string[]>(PROVIDERS_KEY, targets) ?? [];
      // A key is read from an HTTP request only, and only for a provider this route admits.
      const keyPrincipal =
        context.getType<string>() === 'http'
          ? await authenticateRouteApiKey(request.headers, providers)
          : undefined;
      const principal =
        keyPrincipal ??
        (optional
          ? await authenticateOptionalBearer(request.headers.authorization)
          : await authenticateBearer(request.headers.authorization));
      if (principal === undefined) {
        // auth(optional): no credential was presented, so the request is anonymous.
        return true;
      }
      if (providers.length > 0) {
        requireProviders(principal, providers);
      }
      const types = this.reflector.getAllAndOverride<string[]>(PRINCIPAL_TYPES_KEY, targets) ?? [];
      if (types.length > 0) {
        requirePrincipalTypes(principal, types);
      }
      const roles = this.reflector.getAllAndOverride<string[]>(ROLES_KEY, targets) ?? [];
      if (roles.length > 0) {
        requireRoles(principal, roles);
      }
      request.user = principal;
      return true;
    } catch (err) {
      if (err instanceof AuthChainError) {
        challengeRefusedCredential(context, err);
        throw authChainHttpException(err);
      }
      throw err;
    }
  }
}
