/**
 * Gateway credential verification endpoint.
 *
 * Used by the gateway's nginx `auth_request` to decide whether a request may be
 * forwarded: it answers 200 for a valid bearer JWT, or for a request carrying no
 * `Authorization` header and exactly one admitted API-key header whose value is
 * within the presented-key bounds; 401 otherwise. nginx treats any 2xx as
 * "allow" and 401/403 as "deny". The gateway forwards only the key headers the
 * requested route admits, so a key reaches this check only on such a route. The
 * edge checks a key's presence, never its validity: the service's own credential
 * chain verifies the key on the next hop.
 *
 * Static key: a bearer is verified against the asymmetric public key the secrets
 * resolver returns for `jwt_public_key`, resolved on every request; it is never
 * baked into generated source, read from a file path or an environment variable,
 * or cached. An unset or malformed key is a configuration fault and fails loud
 * (500, which nginx also denies) rather than accepting every token. Verification
 * pins the configured asymmetric signing algorithm and requires an `exp` claim,
 * so symmetric (`HS*`) and `alg:none` tokens and tokens that never expire are
 * rejected by construction.
 * A presented key is never logged.
 *
 * Auto-generated by datrix-codegen-typescript. Do not edit manually.
 */
import {
  Controller,
  Get,
  HttpCode,
  Logger,
  Req,
  UnauthorizedException,
} from '@nestjs/common';
import { ApiExcludeEndpoint } from '@nestjs/swagger';
import type { Request } from 'express';
import { importSPKI, jwtVerify } from 'jose';
import { SecretsService } from './secrets/secrets.service';

const JWT_ALGORITHM = 'RS256';
const BEARER_PREFIX = 'Bearer ';

/** Presented-key bounds: 32 to 256 printable ASCII characters (0x21-0x7E). */
const API_KEY_MIN_LENGTH = 32;
const API_KEY_MAX_LENGTH = 256;
const API_KEY_PATTERN = /^[\x21-\x7e]+$/;

/** Every API-key header a credential-checked gateway route admits, lower-cased. */
const API_KEY_HEADERS: readonly string[] = [
  "x-customer-api-key",
];

/** True when *value* is 32-256 printable ASCII characters. Never logs the value. */
function presentedKeyInBounds(value: string): boolean {
  return (
    value.length >= API_KEY_MIN_LENGTH &&
    value.length <= API_KEY_MAX_LENGTH &&
    API_KEY_PATTERN.test(value)
  );
}

/**
 * True when exactly one admitted key header is present, sent once, with an
 * in-bounds value. Two admitted key headers, or one sent twice, are ambiguous
 * and refused, exactly as the service's own credential chain refuses them.
 */
function admittedKeyPresented(request: Request): boolean {
  const presented: string[] = [];
  for (const headerName of API_KEY_HEADERS) {
    const value = request.headers[headerName];
    if (Array.isArray(value)) {
      return false;
    }
    if (value !== undefined && value !== '') {
      presented.push(value);
    }
  }
  if (presented.length !== 1) {
    return false;
  }
  return presentedKeyInBounds(presented[0]);
}

@Controller()
export class GatewayJwtVerifyController {
  private readonly logger = new Logger(GatewayJwtVerifyController.name);

  constructor(private readonly secrets: SecretsService) {}

  /**
   * Decide one gateway `auth_request`: 200 allows the request, 401 denies it.
   *
   * A request carrying `Authorization` is decided by its bearer token alone --
   * a key header beside it never rescues an invalid or non-bearer
   * `Authorization`. A request without `Authorization` is allowed only when it
   * presents exactly one admitted, in-bounds key header.
   * Only a token that fails verification answers 401; a key fault propagates.
   */
  @Get("internal/credential-verify")
  @HttpCode(200)
  @ApiExcludeEndpoint()
  async verify(@Req() request: Request): Promise<void> {
    const authHeader = request.headers.authorization;
    if (authHeader === undefined) {
      if (admittedKeyPresented(request)) {
        return;
      }
      this.logger.debug('gateway_credential_verify_rejected reason=no_admitted_credential');
      throw new UnauthorizedException();
    }
    if (!authHeader.startsWith(BEARER_PREFIX)) {
      this.logger.debug('gateway_credential_verify_rejected reason=non_bearer_authorization');
      throw new UnauthorizedException();
    }
    const token = authHeader.slice(BEARER_PREFIX.length);
    // A missing or blank secret or a malformed key is a configuration fault: it
    // propagates (a 500, which nginx also denies) and is never read as a 401.
    const publicKeyPem = await this.secrets.getSecret('jwt_public_key');
    const publicKey = await importSPKI(publicKeyPem, JWT_ALGORITHM);
    try {
      await jwtVerify(token, publicKey, {
        algorithms: [JWT_ALGORITHM],
        requiredClaims: ['exp'],
      });
    } catch (err) {
      const reason = err instanceof Error ? err.name : 'unknown';
      this.logger.debug(`gateway_credential_verify_rejected reason=${reason}`);
      throw new UnauthorizedException();
    }
  }
}
