def _policy_for(dependency: str) -> DependencyPolicy:
    """Return the resolved policy for ``dependency`` or raise (no implicit default)."""
    policy = DEPENDENCY_POLICIES.get(dependency)
    if policy is None:
        known = sorted(DEPENDENCY_POLICIES)
        raise KeyError(
            f"no resolved resilience policy for dependency {dependency!r}. "
            f"Known dependencies: {known}. This is a generation invariant "
            f"violation -- every policy-managed dependency is emitted."
        )
    return policy


def _operation_policy(dependency: str, operation: str) -> OperationPolicy:
    """Return the resolved operation policy or raise (no implicit default)."""
    policy = _policy_for(dependency)
    operations = policy["operations"]
    op_policy = operations.get(operation)
    if op_policy is None:
        known = sorted(operations)
        raise KeyError(
            f"dependency {dependency!r} has no resolved decision for operation "
            f"{operation!r}. Resolved operations: {known}. This is a generation "
            f"invariant violation -- every policy-managed operation is emitted."
        )
    return op_policy


def _on_failure(op_policy: OperationPolicy) -> str:
    """Return the resolved ``on_failure`` action or raise (no implicit default)."""
    action = op_policy.get("on_failure")
    if action is None:
        raise KeyError(
            f"resolved operation policy {op_policy!r} carries no on_failure "
            f"action; this is a generation invariant violation."
        )
    return action


def _deny_status_for(category: str) -> tuple[int, int | None]:
    """Return ``(status_code, retry_after_seconds)`` for a ``deny`` action.

    The 503-vs-429 distinction is keyed on the operation *category*, never guessed:
    a rate-limit counter-store outage (the limiter could not be enforced) returns
    503 + Retry-After; auth/session denial returns 401; lock acquisition returns
    409. A genuine over-limit (the limiter worked) is signalled by the limiter's
    own 429 path, not through this outage helper.

    The counter-store outage status (``_STATUS_SERVICE_UNAVAILABLE``) and its
    ``Retry-After`` (``_DEFAULT_RETRY_AFTER_SECONDS``) are module constants the
    policy owner may override in place.
    """
    if category == CATEGORY_COUNTER_INCREMENT:
        return _STATUS_SERVICE_UNAVAILABLE, _DEFAULT_RETRY_AFTER_SECONDS
    if category in (CATEGORY_READ, CATEGORY_WRITE, CATEGORY_DELETE):
        return _STATUS_UNAUTHORIZED, None
    if category in (CATEGORY_LOCK_ACQUIRE, CATEGORY_LOCK_RELEASE):
        return _STATUS_CONFLICT, None
    raise KeyError(
        f"deny action requested for unknown operation category {category!r}; "
        f"this is a generation invariant violation."
    )


async def _run_dependency_operation(
    *,
    dependency: str,
    operation: str,
    category: str,
    action: Callable[[], Awaitable[T]],
    source_of_truth_committed: bool = False,
) -> T | None:
    """Execute a policy-managed dependency operation under its resolved policy.

    Args:
        dependency: stable dependency identity (the ``DEPENDENCY_POLICIES`` key).
        operation: operation name (the policy ``operations`` key).
        category: operation category wire value (drives the ``deny`` status code).
        action: the async operation to execute.
        source_of_truth_committed: whether the authoritative write already
            committed. A ``degrade`` action softens only when this is ``True``;
            otherwise it stays ``raise``.

    Returns:
        The action's result, or ``None`` on a ``degrade`` / ``warn`` path (the
        request continues).

    Raises:
        DependencyUnavailable: a ``raise`` action or an unmarked ``degrade`` write
            -- original cause preserved.
        DependencyOperationDenied: a ``deny`` action -- original cause preserved.
    """
    op_policy = _operation_policy(dependency, operation)
    on_failure = _on_failure(op_policy)
    try:
        return await action()
    except _TRANSIENT_ERRORS as exc:
        _dependency_operation_failures.labels(
            dependency=dependency, operation=operation, action=on_failure
        ).inc()
        return await _handle_failure(
            dependency=dependency,
            operation=operation,
            category=category,
            on_failure=on_failure,
            op_policy=op_policy,
            source_of_truth_committed=source_of_truth_committed,
            exc=exc,
        )


async def _handle_failure(
    *,
    dependency: str,
    operation: str,
    category: str,
    on_failure: str,
    op_policy: OperationPolicy,
    source_of_truth_committed: bool,
    exc: BaseException,
) -> T | None:
    """Apply the resolved failure action, preserving the original exception context."""
    if on_failure == _ACTION_RAISE:
        raise DependencyUnavailable(dependency=dependency, operation=operation) from exc
    if on_failure == _ACTION_DENY:
        status_code, retry_after = _deny_status_for(category)
        logger.warning(
            "dependency_operation_denied dependency=%s operation=%s "
            "category=%s status=%d cause=%s",
            dependency,
            operation,
            category,
            status_code,
            exc,
        )
        raise DependencyOperationDenied(
            dependency=dependency,
            operation=operation,
            status_code=status_code,
            retry_after_seconds=retry_after,
        ) from exc
    if on_failure == _ACTION_DEGRADE:
        if not source_of_truth_committed:
            # An unmarked degrade stays raise -- the declaration alone
            # never softens a write whose source-of-truth has not committed.
            raise DependencyUnavailable(
                dependency=dependency, operation=operation
            ) from exc
        logger.warning(
            "dependency_operation_degraded dependency=%s operation=%s cause=%s",
            dependency,
            operation,
            exc,
        )
        return None
    if on_failure == _ACTION_WARN:
        logger.warning(
            "dependency_operation_warn dependency=%s operation=%s cause=%s",
            dependency,
            operation,
            exc,
        )
        return None
    raise KeyError(
        f"unknown on_failure action {on_failure!r} for dependency {dependency!r} "
        f"operation {operation!r}; this is a generation invariant violation."
    )
