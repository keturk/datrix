"""Per-operation resilience helper for policy-managed dependency operations.

Auto-generated by datrix-codegen-python. Do not edit manually.

``_run_dependency_operation`` reads the resolved policy for a dependency operation
from :data:`DEPENDENCY_POLICIES`, executes the operation, handles known transient
provider exceptions, and applies the resolved failure action -- ``raise`` /
``deny`` / ``degrade`` / ``warn`` -- emitting structured logs and Prometheus
metrics. Fail-loud paths (``raise`` / ``deny`` / unmarked ``degrade``) re-raise
preserving the original exception context (``raise ... from exc``).

There are no implicit defaults: a policy-managed operation with no resolved
decision in :data:`DEPENDENCY_POLICIES` raises -- the generator emits a decision
for every policy-managed operation, so a miss here is a generation invariant
violation, never a silent fallback.

Deny response codes:

* a genuine over-limit (the limiter worked) stays ``429 Too Many Requests``;
* a rate-limit counter-store outage under fail-closed ``deny`` returns
  ``503 Service Unavailable`` with ``Retry-After`` -- "we cannot enforce the limit
  right now" is distinct from "you are limited" -- and the outage status is
  overridable per policy;
* auth/session required-check failure -> 401/403 only when semantically correct;
* lock acquisition -> 409/503.

Post-commit gate: a ``degrade``-declared write softens only when the
caller proves the source-of-truth already committed (``source_of_truth_committed``
is ``True``). Otherwise it stays ``raise`` -- the declaration alone never softens.
"""

