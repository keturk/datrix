MAX_DATABASE_READY_ATTEMPTS = 3
DATABASE_READY_RETRY_DELAY_SECONDS = 5

#: The failures that mean "the database is not accepting connections YET" -- the
#: one condition a bounded retry can resolve. ``OSError`` covers the socket-level
#: cases (connection refused, DNS failure, timeout -- ``TimeoutError`` is an
#: ``OSError`` subclass); SQLAlchemy wraps a driver's own connect failure in
#: ``InterfaceError`` / ``OperationalError``.
#:
#: Every other failure is a REFUSAL, not an outage: something -- an absent
#: config-store key, an unresolvable secret, a migration-environment guard --
#: deliberately declined while the database itself was answering. A refusal is
#: deterministic, so retrying it spends the whole bound to reach the same answer
#: and then reports it under a headline ("Database was not ready") that is FALSE,
#: sending the operator after networking, DNS, or the workload identity while the
#: refusal's own diagnosis sits buried in an attempt log. Refusals therefore
#: propagate on the first attempt, unwrapped.
_RETRYABLE_CONNECT_ERRORS: tuple[type[BaseException], ...] = (
    sa.exc.InterfaceError,
    sa.exc.OperationalError,
    OSError,
)


