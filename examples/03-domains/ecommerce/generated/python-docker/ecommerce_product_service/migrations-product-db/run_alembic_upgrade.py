async def _probe_database_connection(engine: AsyncEngine) -> None:
    """Open one connection and run the cheapest statement that proves it live."""
    async with engine.connect() as connection:
        await connection.execute(sa.text("SELECT 1"))


async def _retry_until_connected(engine: AsyncEngine) -> None:
    """Retry the connection probe, and ONLY a connection failure, up to the bound."""
    for attempt in range(1, MAX_DATABASE_READY_ATTEMPTS + 1):
        try:
            await _probe_database_connection(engine)
            return
        except _RETRYABLE_CONNECT_ERRORS as exc:
            if attempt == MAX_DATABASE_READY_ATTEMPTS:
                raise RuntimeError(
                    "Database was not ready for Alembic after "
                    + str(MAX_DATABASE_READY_ATTEMPTS)
                    + " attempts for service ecommerce.ProductService block "
                    "product-db: " + str(exc)
                ) from exc
            logger.warning(
                "migration_database_ready_retry attempt=%d/%d error=%s",
                attempt,
                MAX_DATABASE_READY_ATTEMPTS,
                exc,
            )
            await asyncio.sleep(DATABASE_READY_RETRY_DELAY_SECONDS)


async def _wait_for_database_ready() -> None:
    """Wait until the database accepts a connection, running no Alembic command.

    Answering "is the database reachable?" with ``alembic current`` looks
    read-only and is not: that command loads ``env.py``, which opens the
    migration environment, runs its provisioning steps, and executes every guard
    in it. Those guards exist precisely to REFUSE a database that is fully
    reachable, so a probe built on one cannot tell "unreachable" from "refused" --
    it retried a permanent refusal to exhaustion and then reported it as a
    connectivity problem, with the refusal's own diagnosis discarded by the
    process that asked for it. A connection and ``SELECT 1`` answer the readiness
    question and nothing else; the migration environment is loaded once, by the
    upgrade that follows.
    """
    engine = await _open_block_engine()
    try:
        await _retry_until_connected(engine)
    finally:
        # The probe's engine has no further use: the upgrade runs in its own
        # subprocess with its own engine. An async pool left holding a connection
        # past its event loop is reported at interpreter exit as a destroyed
        # pending task, which reads like a fault in a run that succeeded.
        await engine.dispose()


