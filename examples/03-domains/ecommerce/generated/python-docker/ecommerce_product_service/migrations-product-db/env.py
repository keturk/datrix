#: Alembic commands the retired-head guard below lets through. Both are the
#: operator's route OUT of a retired head, and refusing either removes the only
#: supervised way to resolve one:
#:
#: * ``stamp`` moves the recorded pointer to a revision the operator named
#:   explicitly, having verified schema equivalence as the refusal instructs. It
#:   runs no DDL, and it is the recovery the refusal itself prescribes.
#: * ``current`` only READS the recorded pointer. It is the first command anyone
#:   runs to see what state a database is actually in, and the refusal's own
#:   remediation text tells the operator to verify state before stamping --
#:   which a guard that refuses ``current`` prevents them from doing through the
#:   toolchain at all. Refusing a read to protect a write is backwards.
#:
#: ``upgrade`` and ``downgrade`` stay refused: those are the operations that
#: would apply, or silently skip, DDL against a chain the database never ran.
_GUARD_EXEMPT_ALEMBIC_COMMANDS: frozenset[str] = frozenset({"stamp", "current"})


