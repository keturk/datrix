def _guard_superseded_head(connection: object) -> None:
    """Refuse when this block's own history table records a retired revision.

    Runs before Alembic reads the head. Alembic compares the recorded head only
    against the revision files shipped beside it, so a retired head produces one
    of two wrong outcomes and never the right one: if the id survives in the
    current chain it reads as applied and the run is a silent no-op, and if it
    does not, the failure names a revision id with no explanation of where it
    went.

    The exemptions in ``_GUARD_EXEMPT_ALEMBIC_COMMANDS`` are load-bearing.
    Alembic routes every command through this same ``env.py``, so refusing them
    all would leave a database on a retired head neither migratable NOR
    correctable through the toolchain -- the only remaining routes being dropping
    the database or hand-editing its history table, which is exactly the
    unsupervised surgery this machinery exists to prevent. Upgrade and downgrade
    stay refused, because those are the operations that would silently skip DDL.

    Offline (``--sql``) runs have no connection and cannot perform this check; an
    operator applying generated SQL must confirm the target database's recorded
    head themselves.
    """
    if not SUPERSEDED_REVISIONS:
        return
    if _invoked_alembic_command() in _GUARD_EXEMPT_ALEMBIC_COMMANDS:
        return
    inspector = sa.inspect(connection)
    if not inspector.has_table(VERSION_TABLE, schema=VERSION_TABLE_SCHEMA):
        return
    table_ref = _history_table_ref(connection, VERSION_TABLE)
    heads = tuple(
        str(row[0])
        for row in connection.execute(
            sa.text("SELECT version_num FROM " + table_ref)
        ).fetchall()
    )
    for head in heads:
        if head in SUPERSEDED_REVISIONS:
            raise _superseded_head_error(head, table_ref, _known_revisions())


def _history_table_description() -> str:
    """Describe both history-table names, schema-qualified when one applies."""
    prefix = "" if VERSION_TABLE_SCHEMA is None else VERSION_TABLE_SCHEMA + "."
