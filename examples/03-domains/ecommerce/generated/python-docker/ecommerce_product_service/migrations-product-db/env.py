def _plan_version_table_adoption(
    *,
    version_table_exists: bool,
    legacy_table_exists: bool,
    legacy_heads: tuple[str, ...],
    known_revisions: frozenset[str],
    owned_tables_present: tuple[str, ...],
    superseded_revisions: frozenset[str],
) -> bool:
    """Decide whether the legacy history table belongs to this chain.

    Pure decision function over the facts read from the database, kept
    separate from the statements that read and act on them so the rules are
    checkable without a live server.

    A recorded head falls into exactly three buckets, not two: in the current
    chain (carry it across), in the retired set (this block, migrated under a
    chain that was rebaselined away -- refuse with that cause), or neither (a
    different block sharing this location). Collapsing the first two made every
    retired head report as a foreign block.

    Returns:
        ``True`` when the legacy table must be renamed onto ``VERSION_TABLE``;
        ``False`` when there is nothing to carry across.

    Raises:
        RuntimeError: The database's state cannot be reconciled with this chain
            without guessing. Guessing either replays a baseline over live
            tables or records a head this chain never reached, so this refuses
            and names exactly what it found.
    """
    if version_table_exists:
        return False
    if not legacy_table_exists or not legacy_heads:
        if owned_tables_present:
            raise _unrecorded_schema_error(owned_tables_present)
        return False
    legacy_ref = (
        LEGACY_VERSION_TABLE
        if VERSION_TABLE_SCHEMA is None
        else VERSION_TABLE_SCHEMA + "." + LEGACY_VERSION_TABLE
    )
    if len(legacy_heads) > 1:
        raise RuntimeError(
            "Cannot carry the recorded migration head from "
            + legacy_ref
            + " onto this block's own history table "
            + VERSION_TABLE
            + ": it records "
            + str(len(legacy_heads))
            + " heads ("
            + ", ".join(sorted(legacy_heads))
            + "), so which revision this chain reached is ambiguous. Expected "
            "exactly one version_num row. Fix: delete the rows that do not "
            "belong to this block's chain, leaving the single head this "
            "database actually reached, then re-run the migration."
        )
    head = legacy_heads[0]
    if head in superseded_revisions:
        raise _superseded_head_error(head, legacy_ref, known_revisions)
    if head not in known_revisions:
        raise RuntimeError(
            "Cannot carry the recorded migration head from "
            + legacy_ref
            + " onto this block's own history table "
            + VERSION_TABLE
            + ": its recorded head '"
            + head
            + "' is not a revision in this block's chain ("
            + ", ".join(sorted(known_revisions))
            + "), so that table belongs to a different RDBMS block sharing "
            "this location. Fix: give each block its own schema, or rename "
            "that block's history table to its own per-block name, before "
            "re-running this migration."
        )
    if not owned_tables_present:
        raise RuntimeError(
            "Cannot carry the recorded migration head from "
            + legacy_ref
            + " onto this block's own history table "
            + VERSION_TABLE
            + ": head '"
            + head
            + "' names a revision in this chain, but none of this block's "
            + str(len(target_metadata.sorted_tables))
            + " tables exist there, so the head was recorded by a different "
            "RDBMS block sharing this location. Fix: give each block its own "
            "schema, or rename that block's history table to its own "
            "per-block name, before re-running this migration."
        )
    return True


def _adopt_legacy_version_table(connection: object) -> None:
    """Move a pre-existing Alembic head onto this block's own history table.

    Idempotent and one-shot: once ``VERSION_TABLE`` exists this returns on its
    first probe. The carry-over is an ``ALTER TABLE ... RENAME``, so the
    recorded head moves atomically inside the migration's own transaction --
    a create-then-copy could leave two history tables disagreeing if it failed
    between the two statements.

    Offline (``--sql``) runs cannot do this: they have no connection and no view
    of the target database. An operator applying generated SQL to a database
    migrated under the legacy name must rename that table first.
    """
    inspector = sa.inspect(connection)
    if inspector.has_table(VERSION_TABLE, schema=VERSION_TABLE_SCHEMA):
        return
    legacy_table_exists = inspector.has_table(
        LEGACY_VERSION_TABLE, schema=VERSION_TABLE_SCHEMA
    )
    legacy_heads: tuple[str, ...] = ()
    if legacy_table_exists:
        legacy_heads = tuple(
            str(row[0])
            for row in connection.execute(
                sa.text(
                    "SELECT version_num FROM "
                    + _history_table_ref(connection, LEGACY_VERSION_TABLE)
                )
            ).fetchall()
        )
    if not _plan_version_table_adoption(
        version_table_exists=False,
        legacy_table_exists=legacy_table_exists,
        legacy_heads=legacy_heads,
        known_revisions=_known_revisions() if legacy_heads else frozenset(),
        owned_tables_present=_owned_tables_present(connection),
        superseded_revisions=SUPERSEDED_REVISIONS,
    ):
        return
    preparer = connection.dialect.identifier_preparer
    connection.execute(
        sa.text(
            "ALTER TABLE "
            + _history_table_ref(connection, LEGACY_VERSION_TABLE)
            + " RENAME TO "
            + preparer.quote(VERSION_TABLE)
        )
    )
    logger.info(
        "alembic_version_table_adopted from=%s to=%s schema=%s head=%s",
        LEGACY_VERSION_TABLE,
        VERSION_TABLE,
        VERSION_TABLE_SCHEMA,
        legacy_heads[0],
    )


async def _assemble_db_url_async() -> str:
    """Assemble the database URL from config store and secrets (no env).

    Composes the URL at operation time from the non-secret connection
    components on :class:`AppSettings` and the password resolved through the
    secrets resolver by its logical handle — never from a frozen
    password-bearing setting. This one-shot migration helper is short-lived, so
    it resolves the credential on use (resolve-on-access).

    Returns:
        Composed database URL string.

    Raises:
        RuntimeError: When a required config-store key or secret is absent.
    """
    config_client = _build_config_client()
    config_client.start()
    settings = await assemble_settings(config_client, _secrets_resolver)
    _user = str(settings.product_db_user)
    _host = str(settings.product_db_host)
    _port = int(settings.product_db_port)
    _database = str(settings.product_db_database)
    _driver = str(settings.product_db_async_driver)
    _password = await _secrets_resolver.get_secret(
        str(settings.product_db_password_handle)
    )
    if _password:
        return f"{_driver}://{_user}:{_password}@{_host}:{_port}/{_database}"
