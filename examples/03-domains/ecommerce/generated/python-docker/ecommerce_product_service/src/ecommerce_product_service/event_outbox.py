"""Transaction-scoped event outbox.

Auto-generated by datrix-codegen-python. Do not edit manually.

Domain events dispatched inside a ``transaction(db) { ... }`` unit of work are
buffered here and published once, *after* the transaction commits, instead of
once per row in a bulk loop. The buffer lives in a :class:`ContextVar` so
concurrent requests never share or clobber each other's pending events.

Delivery contract (best-effort, at-most-once, LOUD): a committed unit of work is
never turned into an HTTP 5xx by a post-commit delivery failure, so the flush
never re-raises. But a failed publish is NOT silent: each publish is retried with
bounded backoff, and a publish that still fails is logged with its event type and
topic and counted in :func:`outbox_dropped_event_count` so operators and health
checks can see accumulating losses. The buffer is process-local memory, so an
event still does not survive a crash between commit and flush -- durable delivery
across process death requires a persisted outbox table (a schema-affecting change
scheduled separately), not this in-memory batcher.

The body below is inlined verbatim from
datrix_codegen_python/runtime/event_outbox.py. It is a real module so the
delivery contract above is unit tested by calling it, rather than by executing
this rendered file.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
from collections.abc import AsyncIterator, Awaitable, Callable
from contextvars import ContextVar
from dataclasses import dataclass

logger = logging.getLogger(__name__)


@dataclass(frozen=True, slots=True)
class DeferredPublish:
    """One publish deferred to the post-commit outbox flush.

    ``send`` performs the delivery; ``event_type`` and ``topic`` identify the
    event so a drop can be logged against a concrete event rather than an opaque
    callable.

    ``payload`` and ``send_batch`` are the optional batched-delivery contract. A
    broker whose client cannot be driven concurrently -- or simply bills and
    round-trips per operation -- supplies both, and the flush hands that topic's
    whole wave to ``send_batch`` in one call instead of issuing one concurrent
    ``send`` per event. ``send_batch`` returns one delivery flag per payload, in
    order, so a partial delivery is neither re-sent (which would duplicate the
    payloads already accepted) nor counted as complete. A broker whose client is
    safe to drive concurrently leaves both ``None`` and keeps the per-event path.

    Two requirements the flush depends on and cannot verify for itself. First,
    ``send_batch`` owns its own bounded retry/recycle policy: a false flag means
    that policy is spent, which is why the flush records one whole delivery
    attempt per dropped event rather than starting a retry ladder over payloads a
    partial send may already have accepted. Second, it does not raise -- the
    flush guards the call anyway, but an implementation leaning on that guard
    reports every event in the group dropped for a fault its own recycle would
    have absorbed.
    """

    send: Callable[[], Awaitable[None]]
    event_type: str
    topic: str
    payload: bytes | None = None
    send_batch: Callable[[str, list[bytes]], Awaitable[list[bool]]] | None = None


@dataclass(slots=True)
class _BatchGroup:
    """One topic's batchable deferrals, with their payloads already extracted.

    Grouping by topic alone is sound: a topic belongs to exactly one pub/sub
    block, so every deferral for it comes from that block's producer and carries
    the same bound ``send_batch``.
    """

    send_batch: Callable[[str, list[bytes]], Awaitable[list[bool]]]
    items: list[DeferredPublish]
    payloads: list[bytes]


_event_outbox: ContextVar[list[DeferredPublish] | None] = ContextVar(
    "_datrix_event_outbox", default=None
)

# Maximum number of concurrent publish calls issued in a single flush wave.
# Limiting concurrency prevents flooding the broker producer's in-flight buffer
# when a bulk transaction(db) upsert buffers thousands of per-row lifecycle events.
#: How many buffered publishes are drained concurrently per wave. A default
#: only: the emitted module re-assigns this to the value its project declares,
#: AFTER this source is inlined, and every reader resolves it at call time.
_OUTBOX_FLUSH_BATCH_SIZE: int = 32

# Per-publish retry policy for the post-commit flush. A transient broker error
# (a dropped link, a momentary outage) is retried a few times with exponential
# backoff before the event is declared dropped. Kept small so the backoff cannot
# add more than a fraction of a second to the request that triggered the flush.
_OUTBOX_MAX_PUBLISH_ATTEMPTS: int = 3
_OUTBOX_RETRY_BASE_SECONDS: float = 0.1

# Count of events that exhausted their retries and were dropped, since process
# start. Exposed via outbox_dropped_event_count() for health/metrics surfaces so
# accumulating silent losses become observable.
_dropped_event_count: int = 0


def outbox_dropped_event_count() -> int:
    """Return the number of events dropped by the outbox since process start.

    A non-zero, growing value means publishes are failing past their retries and
    events are being lost -- surface it on a health/metrics endpoint so an
    operator is alerted instead of discovering the loss from missing downstream
    effects.
    """
    return _dropped_event_count


def outbox_active() -> bool:
    """Return True when a transaction-scoped event buffer is collecting events."""
    return _event_outbox.get() is not None


def defer_event(
    send: Callable[[], Awaitable[None]],
    *,
    event_type: str,
    topic: str,
    payload: bytes | None = None,
    send_batch: Callable[[str, list[bytes]], Awaitable[list[bool]]] | None = None,
) -> None:
    """Queue a publish to run after the enclosing transaction commits.

    Guard calls with :func:`outbox_active`; this raises if no buffer is active
    so a misrouted defer fails loudly instead of silently dropping an event.
    ``event_type`` and ``topic`` identify the event if its delivery is later
    dropped at flush time. Supplying both ``payload`` and ``send_batch`` opts this
    event into the batched flush path (see :class:`DeferredPublish`); supplying
    only one of the pair is a caller error and raises rather than silently
    degrading a whole wave to the per-event path.
    """
    buffer = _event_outbox.get()
    if buffer is None:
        raise RuntimeError(
            "defer_event() called with no active event outbox. Guard publish "
            "calls with outbox_active() before deferring."
        )
    if (payload is None) != (send_batch is None):
        raise ValueError(
            f"defer_event(event_type={event_type!r}, topic={topic!r}) received "
            f"payload={'set' if payload is not None else 'None'} and "
            f"send_batch={'set' if send_batch is not None else 'None'}. Batched "
            f"delivery needs both or neither: pass the serialized payload "
            f"alongside the producer's batch sender, or omit both to use the "
            f"per-event send."
        )
    buffer.append(
        DeferredPublish(
            send=send,
            event_type=event_type,
            topic=topic,
            payload=payload,
            send_batch=send_batch,
        )
    )


def _record_drop(
    item: DeferredPublish, error: BaseException | None, attempts: int
) -> None:
    """Log and count one event whose delivery did not land.

    The single home for the drop accounting both flush paths share, so a dropped
    event is reported identically whether it went out per-event or in a batch.
    """
    global _dropped_event_count
    _dropped_event_count += 1
    logger.error(
        "event_outbox_publish_dropped event_type=%s topic=%s attempts=%d error=%r",
        item.event_type,
        item.topic,
        attempts,
        error,
    )


async def _publish_one(item: DeferredPublish) -> bool:
    """Attempt one deferred publish, retrying transient failures with backoff.

    Returns ``True`` on success. On the final failure the dropped event's type
    and topic are logged, :data:`_dropped_event_count` is incremented, and
    ``False`` is returned -- never raises, so one dead publish neither aborts the
    rest of the wave nor turns a committed unit of work into a 5xx.
    """
    last_error: BaseException | None = None
    for attempt in range(_OUTBOX_MAX_PUBLISH_ATTEMPTS):
        try:
            await item.send()
            return True
        except Exception as exc:  # noqa: BLE001 -- outbox flush must never re-raise
            last_error = exc
            if attempt + 1 < _OUTBOX_MAX_PUBLISH_ATTEMPTS:
                await asyncio.sleep(_OUTBOX_RETRY_BASE_SECONDS * (2**attempt))
    _record_drop(item, last_error, _OUTBOX_MAX_PUBLISH_ATTEMPTS)
    return False


def _partition_buffer(
    buffer: list[DeferredPublish],
) -> tuple[dict[str, _BatchGroup], list[DeferredPublish]]:
    """Split *buffer* into per-topic batchable groups and per-event deferrals."""
    groups: dict[str, _BatchGroup] = {}
    singles: list[DeferredPublish] = []
    for item in buffer:
        payload = item.payload
        send_batch = item.send_batch
        if payload is None or send_batch is None:
            singles.append(item)
            continue
        group = groups.get(item.topic)
        if group is None:
            group = _BatchGroup(send_batch=send_batch, items=[], payloads=[])
            groups[item.topic] = group
        group.items.append(item)
        group.payloads.append(payload)
    return groups, singles


async def _publish_group(topic: str, group: _BatchGroup) -> int:
    """Deliver one topic's wave in a single batched send; return how many landed.

    The batch sender reports per-payload delivery, so each event that did not land
    is logged and counted individually -- exactly as the per-event path does --
    while the ones that did are never re-sent. Never raises: a batch sender that
    fails outright leaves the whole group counted as dropped.
    """
    error: BaseException | None = None
    outcomes: list[bool] = []
    try:
        outcomes = await group.send_batch(topic, group.payloads)
    except Exception as exc:  # noqa: BLE001 -- outbox flush must never re-raise
        error = exc
    if len(outcomes) != len(group.items):
        outcomes = [False] * len(group.items)
    published = 0
    for item, landed in zip(group.items, outcomes, strict=True):
        if landed:
            published += 1
        else:
            # Per the send_batch contract the sender's own bounded retry/recycle
            # is spent by the time a flag comes back false, so this is one whole
            # delivery attempt, not the start of a retry ladder. Re-sending here
            # would duplicate whatever a partial batch already had accepted.
            _record_drop(item, error, 1)
    return published


async def _flush_buffered_events(buffer: list[DeferredPublish]) -> None:
    """Drain *buffer*, retrying and logging failures, never re-raising.

    Deferrals carrying a batch sender are grouped by topic and each group is
    delivered in one batched call; the groups run concurrently, since distinct
    topics are distinct links. The remaining per-event deferrals are issued in
    waves of at most :data:`_OUTBOX_FLUSH_BATCH_SIZE` concurrent calls, each
    retried with backoff by :func:`_publish_one`, which swallows its final failure
    so a broker outage in one wave does not abort the rest. Dropped events are
    logged individually (with event type and topic) and counted; the function
    always returns normally so a post-commit outbox failure never turns a
    durably-committed unit of work into an HTTP 5xx.
    """
    total = len(buffer)
    published = 0
    groups, singles = _partition_buffer(buffer)
    if groups:
        group_results = await asyncio.gather(
            *(_publish_group(topic, group) for topic, group in groups.items())
        )
        published += sum(group_results)
    for start in range(0, len(singles), _OUTBOX_FLUSH_BATCH_SIZE):
        wave = singles[start : start + _OUTBOX_FLUSH_BATCH_SIZE]
        results = await asyncio.gather(*(_publish_one(item) for item in wave))
        published += sum(1 for delivered in results if delivered)
    failed = total - published
    if failed:
        logger.error(
            "event_outbox_flushed_with_failures published=%d failed=%d total=%d "
            "dropped_total=%d",
            published,
            failed,
            total,
            _dropped_event_count,
        )
    else:
        logger.info("event_outbox_flushed count=%d", published)


@contextlib.asynccontextmanager
async def buffer_events() -> AsyncIterator[None]:
    """Buffer dispatched events and flush them once, after a clean exit.

    Re-entrant: a nested ``buffer_events()`` joins the outermost buffer and
    leaves flushing to it, so a ``transaction`` block nested inside another
    still yields a single post-commit flush. On exception nothing is flushed --
    the events belonged to a unit of work that rolled back. The buffer is
    cleared before flushing, so publishes performed during the flush send
    immediately rather than re-buffering.

    The flush runs inside the ``finally`` on the success path (guarded by
    ``committed``), so it is not skipped by a death in the window between
    resetting the ContextVar and flushing. A body that raised leaves
    ``committed`` False, so a rolled-back unit of work still flushes nothing.

    Buffered publishes are drained in waves of :data:`_OUTBOX_FLUSH_BATCH_SIZE`
    concurrent calls so bulk upserts that buffer thousands of per-row lifecycle
    events do not flood the broker's in-flight limits.  Post-commit publish
    failures are retried, then logged and counted but never re-raised -- a
    committed unit of work must not be reported as failed because a side-effect
    delivery failed.
    """
    if _event_outbox.get() is not None:
        # Already buffering in an enclosing scope; it owns the flush.
        yield
        return
    buffer: list[DeferredPublish] = []
    token = _event_outbox.set(buffer)
    committed = False
    try:
        yield
        committed = True
    finally:
        _event_outbox.reset(token)
        if committed and buffer:
            await _flush_buffered_events(buffer)


