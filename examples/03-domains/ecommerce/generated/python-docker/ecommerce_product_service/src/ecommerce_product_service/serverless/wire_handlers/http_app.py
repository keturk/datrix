def json_object_body(raw: str | bytes | None) -> dict[str, object]:
    """The request body as a JSON object; an absent or empty body is ``{}``.

    Raises:
        RequestRejected: ``400`` when the body is not valid JSON (UTF-8 text
            included) or is JSON but not an object.
    """
    if not raw:
        return {}
    try:
        body = json.loads(raw)
    except ValueError as exc:
        raise RequestRejected(
            BAD_REQUEST_STATUS, "Request body is not valid JSON"
        ) from exc
