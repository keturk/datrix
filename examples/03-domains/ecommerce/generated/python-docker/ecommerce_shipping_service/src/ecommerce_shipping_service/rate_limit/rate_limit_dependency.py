async def _enforce_endpoint_override(
    override: EndpointRateLimit,
    client: str,
    redis_obj: object,
    response: Response,
) -> None:
    """Enforce a per-endpoint sliding-window rate limit instead of the plan RPM.

    Uses the same Redis sorted-set approach as the plan limiter but with
    the endpoint-specific requests/window parameters.
    """
    from redis.asyncio import Redis

    redis: Redis[object] = redis_obj  # type: ignore[assignment]
    now = time.time()
    now_int = int(now)
    window_start = now - override.window
    ep_key = f"ns:rl:ep:{client}:{override.requests}:{override.window}"
    member = f"{now:.3f}-{uuid.uuid4().hex[:7]}"

    await redis.zremrangebyscore(ep_key, 0, window_start)
    await redis.zadd(ep_key, {member: now})
    await redis.expire(ep_key, override.window + 5)
    count_raw = await redis.zcard(ep_key)
    count = int(count_raw) if isinstance(count_raw, int) else 0
    reset_at = now_int + override.window

    if count > override.requests:
        headers = {
            "X-RateLimit-Limit": str(override.requests),
            "X-RateLimit-Remaining": "0",
            "X-RateLimit-Reset": str(reset_at),
            "Retry-After": str(override.window),
        }
        raise HTTPException(
            status_code=429,
            detail="Rate limit exceeded.",
            headers=headers,
        )
    remaining = max(0, override.requests - count)
    response.headers["X-RateLimit-Limit"] = str(override.requests)
    response.headers["X-RateLimit-Remaining"] = str(remaining)
    response.headers["X-RateLimit-Reset"] = str(reset_at)


