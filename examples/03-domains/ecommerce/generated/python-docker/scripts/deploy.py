# Compose / env seam
# ---------------------------------------------------------------------------
# Inlined from datrix_codegen_docker/deploy_runtime.py. Pure text parsing --
# no filesystem, no subprocess -- so the generator's own suite tests it by
# calling it. Reading the files and raising DeployError stays in this script.
#: A compose ``${VAR}`` / ``${VAR:?msg}`` reference. The optional group
#: captures the separator, which is what distinguishes a reference that NEEDS a
#: value from one carrying its own default:
#:   ${VAR}        -> required; unset expands to empty, silently
#:   ${VAR:?msg}   -> required; unset aborts interpolation
#:   ${VAR:-x}     -> NOT required; unset falls back to x
#:   ${VAR-x}      -> NOT required; same, for the unset-only form
COMPOSE_VAR_REF = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(:?[-?+])?")

#: Reference forms that still require a value to be supplied.
REQUIRING_SEPARATORS = (None, ":?", "?")

#: The subset of requiring forms for which compose treats an EMPTY value as
#: unset and aborts. ``${VAR:?msg}`` is the documented one; ``${VAR?msg}`` is
#: the unset-only variant, which compose accepts empty -- so a blank assignment
#: satisfies it, and only the ``:?`` form is mandatory-non-empty.
MANDATORY_NON_EMPTY_SEPARATORS = (":?",)


def compose_required_variables(compose_text: str) -> list[str]:
    """Every variable the compose file needs a value for, in first-seen order.

    Reads the CONSUMER side of the seam directly instead of a documentation
    block, so a variable is covered whether or not anything remembered to
    document it -- which is the case that actually bit: a plain ``${VAR}`` for
    an extern service's token appeared in no ``# Required:`` block at all and
    expanded to a blank string with nothing but a warning.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names, first-seen order preserved so the report reads in the
        order an operator would find them.
    """
    seen: dict[str, None] = {}
    for match in COMPOSE_VAR_REF.finditer(compose_text):
        if match.group(2) in REQUIRING_SEPARATORS:
            seen.setdefault(match.group(1), None)
    return list(seen)


def compose_mandatory_variables(compose_text: str) -> list[str]:
    """Every variable the compose file aborts on when unset OR EMPTY.

    The ``${VAR:?msg}`` subset of :func:`compose_required_variables`. A blank
    assignment satisfies a plain ``${VAR}`` (compose reads an empty string) but
    not this form, so the two are reported differently: a plain one is missing
    only when no assignment exists at all, a mandatory one also when the
    assignment is blank.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names, first-seen order preserved.
    """
    seen: dict[str, None] = {}
    for match in COMPOSE_VAR_REF.finditer(compose_text):
        if match.group(2) in MANDATORY_NON_EMPTY_SEPARATORS:
            seen.setdefault(match.group(1), None)
    return list(seen)


def assigned_env_values(env_text: str) -> dict[str, str]:
    """Every ``KEY=value`` assignment in an environment file, last one wins.

    A blank assignment is kept as an empty string rather than dropped: ``KEY=``
    does supply a value to compose -- an empty one -- and whether that is
    acceptable depends on the form the compose file references the key in,
    which :func:`unsatisfied_env_variables` decides per variable.

    Args:
        env_text: The environment file's text.

    Returns:
        Assigned keys mapped to their raw values.
    """
    values: dict[str, str] = {}
    for line in env_text.splitlines():
        if "=" not in line or line.lstrip().startswith("#"):
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def unsatisfied_env_variables(
    compose_text: str,
    env_text: str,
    process_env: Mapping[str, str],
) -> tuple[list[str], list[str]]:
    """Compute ``required − supplied`` across the compose/environment seam.

    The effective value of a variable is the process environment's when it is
    set there (compose gives it precedence) and the environment file's
    otherwise. A variable is reported in one of two lists, each with a
    different fix:

    - **missing** -- no assignment anywhere. A plain ``${VAR}`` would expand to
      an empty string and the service would start on it; a ``${VAR:?}`` would
      abort interpolation.
    - **blank** -- assigned, but empty, and referenced in the ``${VAR:?}`` form,
      which compose treats exactly like unset. This is the case a copy of a
      template that documents a key by assigning it nothing produces, and it
      used to pass this check because a key-set comparison saw the assignment.

    A variable an environment-sourced compose secret reads
    (:func:`compose_environment_secret_variables`) is required AND
    mandatory-non-empty: compose refuses an unset one at ``up``, and a blank
    one mounts an empty credential the service starts on.

    Args:
        compose_text: The compose file's text.
        env_text: The environment file's text.
        process_env: The process environment compose will read.

    Returns:
        ``(missing, blank)``, each in the compose file's first-seen order --
        interpolated variables first, then secret-sourced ones.
    """
    assigned = assigned_env_values(env_text)
    secret_variables = compose_environment_secret_variables(compose_text)
    mandatory = set(compose_mandatory_variables(compose_text)) | set(secret_variables)
    required: dict[str, None] = {}
    for name in [*compose_required_variables(compose_text), *secret_variables]:
        required.setdefault(name, None)
    missing: list[str] = []
    blank: list[str] = []
    for name in required:
        if name in process_env:
            effective = process_env[name]
        elif name in assigned:
            effective = assigned[name]
        else:
            missing.append(name)
            continue
        if name in mandatory and not effective.strip():
            blank.append(name)
    return missing, blank


