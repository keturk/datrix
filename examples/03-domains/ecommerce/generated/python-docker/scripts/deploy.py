def _normalize_argv(argv: list[str], switch_aliases: dict[str, str]) -> list[str]:
    """Translate PowerShell-style switches into this script's own flags.

    Only whole arguments are translated, and only when they match a declared
    alias case-insensitively: a value that merely looks like a switch (a path,
    a negative number, an argument to another flag) passes through untouched.

    Args:
        argv: The arguments as the shell handed them over.
        switch_aliases: PowerShell switch spelling -> this script's own flag.

    Returns:
        The same arguments with every recognized PowerShell switch replaced by
        this script's own flag spelling.
    """
    return [switch_aliases.get(token.lower(), token) for token in argv]


def _help_block(heading: str, entries: dict[str, str]) -> list[str]:
    """Render one aligned ``name  description`` block for the --help epilog.

    Args:
        heading: The block's heading line.
        entries: Name -> description, in the order they should be listed.

    Returns:
        The block's lines, or an empty list when there is nothing to list.
    """
    if not entries:
        return []
    width = max(len(name) for name in entries)
    return ["", heading] + [
        f"  {name.ljust(width)}  {text}" for name, text in entries.items()
    ]


def _lifecycle_epilog(
    verb_help: dict[str, str],
    unrealized_verbs: dict[str, str],
    extra_commands: dict[str, str] | None = None,
) -> str:
    """Return the --help epilog: what this profile does, and what it does not.

    The unrealized half is the part that matters. The vocabulary is shared
    across every Datrix target, so an operator arriving from another profile
    will type verbs this one does not implement; telling them WHY, and what to
    use instead, is the difference between a usable CLI and a dead end.

    Args:
        verb_help: One help line per realized lifecycle verb.
        unrealized_verbs: Vocabulary verb -> why this profile lacks it.
        extra_commands: Platform-specific commands this CLI also accepts, which
            are NOT lifecycle verbs -- a read-only check, a partial rollout, an
            escape hatch. Listed separately so the shared vocabulary stays
            recognizable next to them.

    Returns:
        The epilog text.
    """
    lines = _help_block("lifecycle commands:", dict(verb_help))[1:]
    lines += _help_block("platform-specific commands:", extra_commands or {})
    lines += _help_block(
        "not implemented on this deployment profile:", unrealized_verbs
    )
    return "\n".join(lines)


def _build_lifecycle_parser(
    program_name: str,
    default_verb: str,
    realized_verbs: tuple[str, ...],
    verb_help: dict[str, str],
    unrealized_verbs: dict[str, str],
    description: str,
    extra_commands: dict[str, str] | None = None,
    positional_help: str | None = None,
    extra_epilog: str | None = None,
) -> argparse.ArgumentParser:
    """Build the argument parser carrying the shared lifecycle surface.

    The caller adds whatever FLAGS are specific to its own platform; the
    command positional, ``--force`` and the epilog are the same everywhere.

    Args:
        program_name: The ``prog`` argparse reports in usage.
        default_verb: The verb used when the operator names none. Always the
            safe end of the blast-radius order.
        realized_verbs: The verbs this profile implements, in order.
        verb_help: One help line per realized verb.
        unrealized_verbs: Vocabulary verb -> why this profile lacks it.
        description: One-line description of this deployment, shown by --help.
        extra_commands: Platform-specific commands (name -> help line) accepted
            alongside the lifecycle verbs. They widen the choice set, so a
            platform command is rejected by name on a profile that has none --
            never silently accepted and ignored.
        positional_help: When a platform command takes positional arguments,
            the help line for them. Omitted entirely when none does, so a stray
            argument is an error rather than something quietly collected.
        extra_epilog: Further --help text for this platform (environment
            overrides and the like), appended after the command listing.

    Returns:
        A parser accepting this profile's realized verbs plus any extras.
    """
    epilog = _lifecycle_epilog(verb_help, unrealized_verbs, extra_commands)
    if extra_epilog is not None:
        epilog = f"{epilog}\n\n{extra_epilog}"
    parser = argparse.ArgumentParser(
        prog=program_name,
        description=description,
        epilog=epilog,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "command",
        nargs="?",
        default=default_verb,
        choices=(*realized_verbs, *(extra_commands or {})),
        help=f"what to do (default: {default_verb})",
    )
    if positional_help is not None:
        parser.add_argument("args", nargs="*", help=positional_help)
    parser.add_argument(
        "--force",
        action="store_true",
        help="skip the confirmation prompt for a destructive command.",
    )
    return parser


def force_requested(parsed_force: bool) -> bool:
    """True when the operator has waived the confirmation prompt.

    Args:
        parsed_force: Whether ``--force`` was given on the command line.

    Returns:
        True when the prompt is waived, by the flag or by the environment.
    """
    return (
        parsed_force
        or os.environ.get(FORCE_ENV_VAR, "").strip().lower() in _TRUTHY_FORCE_VALUES
    )


def confirm_destructive(verb: str, what_is_lost: str, token: str, forced: bool) -> bool:
    """Gate a destructive command behind an explicit, typed confirmation.

    Fails CLOSED. When the prompt cannot be shown -- no terminal on stdin, as in
    a pipeline or a remote run-command channel -- this refuses rather than
    assuming consent, and names the flag that grants it deliberately. A
    destructive default that proceeds because nobody could answer is the worst
    possible reading of silence.

    Args:
        verb: The lifecycle verb being confirmed, for the message.
        what_is_lost: Plain description of what this removes, listed before the
            prompt so the operator confirms against facts rather than a verb.
        token: The exact string the operator must type. Deliberately the name of
            the thing being destroyed, so muscle memory cannot answer for them.
        forced: Whether --force (or the FORCE environment variable) was given.

    Returns:
        True when the command may proceed, False when the operator declined.
    """
    if forced:
        print(f"==> '{verb}' confirmed by --force. {what_is_lost}", flush=True)
        return True
    print("", flush=True)
    print(f"WARNING: '{verb}' is irreversible. {what_is_lost}", flush=True)
    if not sys.stdin.isatty():
        print(
            f"ERROR: '{verb}' needs confirmation, but there is no terminal to "
            f"ask at (stdin is not a TTY). Nothing has been changed. Re-run "
            f"with --force (PowerShell: -Force), or set "
            f"{FORCE_ENV_VAR}=true, to state the intent explicitly.",
            file=sys.stderr,
        )
        return False
    answer = input(f"Type '{token}' to confirm: ").strip()
    if answer != token:
        print("Aborted. Nothing has been changed.", flush=True)
        return False
    return True


