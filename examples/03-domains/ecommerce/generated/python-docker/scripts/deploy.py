"""Manage this application's Docker Compose deployment: deploy | down | reset.

Generated by Datrix -- do not edit manually.

Run it through the generated shell entrypoints, which activate the project
virtual environment first::

    scripts/deploy.sh  [command] [options]     # bash / zsh
    .\\scripts\\deploy.ps1 [command] [options]   # PowerShell

This module is the ONE implementation of the deployment; both entrypoints are
thin wrappers around it, so a bash operator and a PowerShell operator run
byte-identical logic. It uses only the Python standard library and drives
``docker`` as a subprocess.

The command vocabulary is shared with every other Datrix-generated deployment
CLI, whichever platform emitted it, so the same word means the same thing on
every profile. ``--help`` lists what this one implements and what it does not.
"""

