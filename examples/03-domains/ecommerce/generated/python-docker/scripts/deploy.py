class DeployError(RuntimeError):
    """A fatal, operator-actionable deployment failure."""


class CommandResult(NamedTuple):
    """Outcome of one external command."""

    returncode: int
    output: str

    @property
    def succeeded(self) -> bool:
        """True when the command exited zero."""
        return self.returncode == 0


def step(message: str) -> None:
    """Announce a new phase of the deployment."""
    print(f"==> {message}", flush=True)


def resolve_docker() -> str:
    """Return the absolute path of the docker executable, or fail loud.

    Raises:
        DeployError: If docker is not on PATH.
    """
    resolved = shutil.which("docker")
    if resolved is None:
        raise DeployError("'docker' not found. Install Docker.")
    return resolved


def docker(*args: str, capture: bool = True) -> CommandResult:
    """Run one ``docker`` invocation from the project root."""
    completed = subprocess.run(
        [resolve_docker(), *args],
        capture_output=capture,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=PROJECT_ROOT,
    )
    if not capture:
        return CommandResult(returncode=completed.returncode, output="")
    parts = (completed.stdout or "", completed.stderr or "")
    return CommandResult(
        returncode=completed.returncode,
        output="\n".join(part.strip() for part in parts if part.strip()),
    )


def require_compose() -> None:
    """Fail loud unless Docker Compose v2 is available.

    Raises:
        DeployError: If the compose plugin is missing.
    """
    if docker("compose", "version").succeeded:
        return
    raise DeployError(
        "'docker compose' is not available. Install Docker Compose v2 (it ships "
        "with Docker Desktop and as the 'docker-compose-plugin' package)."
    )


def require_env_file() -> None:
    """Fail loud unless the compose environment file exists.

    Raises:
        DeployError: If it is missing, naming the template to copy when there
            is one.
    """
    if (PROJECT_ROOT / ENV_FILE).is_file():
        return
    if (PROJECT_ROOT / ENV_TEMPLATE).is_file():
        raise DeployError(
            f"'{ENV_FILE}' not found. Start from the template, then supply a "
            f"value for every key it lists under '# Required:' -- those are "
            f"deployment-owned, so the template documents them instead of "
            f"assigning them, and copying it alone leaves each one unset:\n"
            f"  cp {ENV_TEMPLATE} {ENV_FILE}"
        )
    raise DeployError(
        f"'{ENV_FILE}' not found, and there is no '{ENV_TEMPLATE}' to copy from."
    )


# ---------------------------------------------------------------------------
# Compose / env seam
# ---------------------------------------------------------------------------
# Inlined from datrix_codegen_docker/deploy_runtime.py. Pure text parsing --
# no filesystem, no subprocess -- so the generator's own suite tests it by
# calling it. Reading the files and raising DeployError stays in this script.
#: A compose ``${VAR}`` / ``${VAR:?msg}`` reference. The optional group
#: captures the separator, which is what distinguishes a reference that NEEDS a
#: value from one carrying its own default:
#:   ${VAR}        -> required; unset expands to empty, silently
#:   ${VAR:?msg}   -> required; unset aborts interpolation
#:   ${VAR:-x}     -> NOT required; unset falls back to x
#:   ${VAR-x}      -> NOT required; same, for the unset-only form
COMPOSE_VAR_REF = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(:?[-?+])?")

#: Reference forms that still require a value to be supplied.
REQUIRING_SEPARATORS = (None, ":?", "?")


def compose_required_variables(compose_text: str) -> list[str]:
    """Every variable the compose file needs a value for, in first-seen order.

    Reads the CONSUMER side of the seam directly instead of a documentation
    block, so a variable is covered whether or not anything remembered to
    document it -- which is the case that actually bit: a plain ``${VAR}`` for
    an extern service's token appeared in no ``# Required:`` block at all and
    expanded to a blank string with nothing but a warning.

    Args:
        compose_text: The compose file's text.

    Returns:
        Variable names, first-seen order preserved so the report reads in the
        order an operator would find them.
    """
    seen: dict[str, None] = {}
    for match in COMPOSE_VAR_REF.finditer(compose_text):
        if match.group(2) in REQUIRING_SEPARATORS:
            seen.setdefault(match.group(1), None)
    return list(seen)


def assigned_env_keys(env_text: str) -> set[str]:
    """Keys the environment file assigns, blank assignments included.

    A blank assignment counts: ``KEY=`` supplies a value, and treating it as
    absent would report a variable missing that compose will happily read as an
    empty string. Whether an empty value is ACCEPTABLE is a separate question
    the caller answers.

    Args:
        env_text: The environment file's text.

    Returns:
        Every assigned key.
    """
    return {
        line.split("=", 1)[0].strip()
        for line in env_text.splitlines()
        if "=" in line and not line.lstrip().startswith("#")
    }


def require_env_keys() -> None:
    """Fail loud when a variable compose needs has no value anywhere.

    THE SEAM THIS CLOSES: ``docker-compose.yml`` CONSUMES variables, ``.env``
    (plus the process environment) PRODUCES them, and nothing compared the two
    on the machine that runs compose.

    Both failure modes were live. A plain ``${VAR}`` expands to an empty string
    and only warns -- a service starts with a blank credential and looks
    healthy. A ``${VAR:?}`` aborts, but at interpolation time: after the
    archive shipped, after images built, tens of minutes into a release,
    naming one variable. ``.env`` deliberately survives redeployment so an
    operator's values are never overwritten, which also means a variable
    introduced by a later regeneration is simply absent until someone adds it.

    This runs before any of that and names every missing variable at once.

    Raises:
        DeployError: If the compose file cannot be read, if no variable
            reference can be parsed out of it (the check would otherwise verify
            nothing), or if any required variable has no value.
    """
    compose_path = PROJECT_ROOT / COMPOSE_FILE
    if not compose_path.is_file():
        raise DeployError(
            f"'{COMPOSE_FILE}' not found in '{PROJECT_ROOT}' -- nothing to "
            f"deploy. Fix: regenerate the project."
        )
    compose_text = compose_path.read_text(encoding="utf-8")
    required = compose_required_variables(compose_text)
    if not required:
        if "${" in compose_text:
            raise DeployError(
                f"'{COMPOSE_FILE}' interpolates variables, but none could be "
                f"parsed out of it -- so this check would pass without "
                f"verifying anything. Its format has changed and this check "
                f"must be updated to match it."
            )
        return
    supplied = assigned_env_keys(
        (PROJECT_ROOT / ENV_FILE).read_text(encoding="utf-8")
    ) | set(os.environ)
    missing = [name for name in required if name not in supplied]
    if not missing:
        return
    listing = "\n".join(f"  {name}=" for name in missing)
    raise DeployError(
        f"{len(missing)} of the {len(required)} variable(s) "
        f"'{COMPOSE_FILE}' requires have no value in '{ENV_FILE}' or the "
        f"process environment:\n{listing}\n\n"
        f"These are deployment-owned: '{ENV_TEMPLATE}' names them and "
        f"deliberately assigns no value, and '{ENV_FILE}' is never refreshed "
        f"from it. Fix: append each line above with a real value. Left unset, "
        f"a variable either aborts compose at interpolation or -- worse -- "
        f"expands to an empty string and the service starts with a blank "
        f"credential."
    )


def build_base_image() -> None:
    """Build the shared base image when the local daemon does not have it.

    Every service Dockerfile is ``FROM`` this tag, and compose never builds a
    ``FROM`` image -- so the base must exist locally BEFORE the services build.
    The tag is a content hash of the dependency union, so this rebuilds only
    when that union changes, which makes it idempotent.

    Raises:
        DeployError: If the build failed.
    """
    if BASE_IMAGE_TAG is None or BASE_IMAGE_DIR is None:
        return
    if docker("image", "inspect", BASE_IMAGE_TAG).succeeded:
        return
    step(f"Building shared base image {BASE_IMAGE_TAG}")
    result = docker("build", "-t", BASE_IMAGE_TAG, f"./{BASE_IMAGE_DIR}", capture=False)
    if not result.succeeded:
        raise DeployError(
            f"Building the shared base image '{BASE_IMAGE_TAG}' failed (docker "
            f"exited {result.returncode}). Every service image is FROM this tag, "
            f"so the deployment cannot proceed."
        )


#: Lines of container log to print for each failed container. Enough to carry a
#: stack trace and the statement that produced it, without burying the report.
_FAILED_CONTAINER_LOG_LINES = "200"


def _failed_service_names() -> list[str]:
    """Return the compose services whose container exited non-zero.

    Returns:
        Service names, in the order compose reports them; empty when none
        failed or when their state could not be read.
    """
    result = docker("compose", "ps", "--all", "--format", "json")
    if not result.succeeded:
        return []
    names: list[str] = []
    for line in result.output.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            entry = json.loads(line)
        except ValueError:
            continue
        if not isinstance(entry, dict):
            continue
        exit_code = entry.get("ExitCode")
        name = entry.get("Service") or entry.get("Name")
        if isinstance(exit_code, int) and exit_code != 0 and name:
            names.append(str(name))
    return names


def _report_failed_container_logs() -> list[str]:
    """Print the logs of every container that exited non-zero.

    ``docker compose up`` reports a one-shot container's failure as nothing but
    ``didn't complete successfully: exit 1``. The reason it failed -- the
    migration error, the connection refusal, the traceback -- is in that
    container's own log, which compose does not print. Without this, a failed
    deployment reports which container died and says nothing about why, and the
    cause takes another round trip to the host to read.

    Returns:
        The names of the failed services, so the caller can name them.
    """
    failed = _failed_service_names()
    if not failed:
        return []
    for name in failed:
        step(f"Logs for failed container '{name}'")
        docker(
            "compose",
            "logs",
            "--no-color",
            "--tail",
            _FAILED_CONTAINER_LOG_LINES,
            name,
            capture=False,
        )
    return failed


def compose_up() -> None:
    """Build and start every service, then report their status.

    Raises:
        DeployError: If compose could not bring the services up.
    """
    step("Building and starting services")
    result = docker("compose", "up", "-d", "--build", capture=False)
    if not result.succeeded:
        failed = _report_failed_container_logs()
        detail = (
            f" The failing container(s) were: {', '.join(failed)}; their logs are "
            f"above."
            if failed
            else " No container reported a non-zero exit, so the failure is in "
            "the build or in compose itself; review the output above."
        )
        raise DeployError(
            f"'docker compose up' failed (exit {result.returncode}).{detail}"
        )
    step("Service status")
    docker("compose", "ps", capture=False)


