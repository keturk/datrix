#: Bring the deployment to its declared state. Idempotent.
VERB_DEPLOY = "deploy"

#: Stop the running workload. All data survives.
VERB_DOWN = "down"

#: Remove the workload and the data stores this project provisioned. The infrastructure hosting them stays.
VERB_RESET = "reset"

#: Delete the provisioned infrastructure itself.
VERB_DESTROY = "destroy"

#: The verbs THIS profile implements, in increasing blast-radius order. This is
