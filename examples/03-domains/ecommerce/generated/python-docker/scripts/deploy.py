def command_deploy(forced: bool) -> None:
    """Check the prerequisites, build what compose cannot, and start the stack.

    Args:
        forced: Unused -- ``deploy`` removes nothing and needs no confirmation.
            Accepted so every command shares one signature.
    """
    del forced
    resolve_docker()
    require_compose()
    require_env_file()
    require_env_keys()
    build_base_image()
    compose_up()
    print("Deployment complete. Follow logs with:  docker compose logs -f")


def command_down(forced: bool) -> None:
    """Stop and remove the containers, keeping every byte of data.

    Volumes, images and the environment file all survive, so ``deploy`` brings
    the same stack back with the same data. This is the reversible one.

    Args:
        forced: Unused -- ``down`` destroys nothing and needs no confirmation.

    Raises:
        DeployError: If compose could not stop the services.
    """
    del forced
    resolve_docker()
    require_compose()
    step("Stopping services")
    result = docker("compose", "down", "--remove-orphans", capture=False)
    if not result.succeeded:
        raise DeployError(
            f"'docker compose down' failed (exit {result.returncode}). The "
            f"stack may be partially stopped; review the output above."
        )
    print(
        f"Stopped. Volumes, images and '{ENV_FILE}' are untouched -- "
        f"'{SCRIPT_NAME} {VERB_DEPLOY}' brings the same data back."
    )


def command_reset(forced: bool) -> None:
    """Remove the containers, their volumes and the images built for them.

    Irreversible: every named volume this project's compose file declares is
    deleted, and with it every database, cache and uploaded file living inside
    the stack.

    ``.env`` is deliberately NOT removed. It holds operator-authored secrets
    that no regeneration can reproduce -- the generator writes '.env.example'
    and never overwrites '.env' for exactly that reason -- and it is
    configuration rather than provisioned state, so removing it would destroy
    something this command never created.

    Args:
        forced: Whether the operator waived the confirmation prompt.

    Raises:
        DeployError: If compose could not tear the stack down.
    """
    resolve_docker()
    require_compose()
    project = compose_project_name()
    lost = (
        f"Every named volume of compose project '{project}' is deleted, with "
        f"every database, cache and uploaded file inside the stack, plus the "
        f"images built for it."
    )
    if not confirm_destructive(VERB_RESET, lost, project, forced):
        raise DeployError(
            f"'{VERB_RESET}' was not confirmed. Nothing has been changed."
        )
    step("Removing containers, volumes and locally-built images")
    result = docker(
        "compose",
        "down",
        "--volumes",
        "--remove-orphans",
        "--rmi",
        "local",
        capture=False,
    )
    if not result.succeeded:
        raise DeployError(
            f"'docker compose down --volumes' failed (exit "
            f"{result.returncode}). The stack may be partially removed; review "
            f"the output above and re-run once the cause is fixed."
        )
    print(f"Compose project '{project}' removed, volumes and images included.")
    print(f"Kept: '{ENV_FILE}' -- it holds values only you have.")
    if EXTERNAL_TEARDOWN_SCRIPT is not None:
        print(
            f"NOT removed: this project also provisions infrastructure outside "
            f"compose (host databases, their application role, object storage). "
            f"That half lives on the host carrying it and is removed there, by "
            f"the counterpart of the script that created it:\n"
            f"  {EXTERNAL_TEARDOWN_SCRIPT}"
        )


#: This profile's realized verbs, bound to their implementations. The keys are
#: exactly REALIZED_VERBS -- ``require_command_coverage`` proves it on every
#: run, so a verb the parser accepts can never reach a missing implementation.
COMMANDS: dict[str, Callable[[bool], None]] = {
    VERB_DEPLOY: command_deploy,
    VERB_DOWN: command_down,
    VERB_RESET: command_reset,
}


def require_command_coverage() -> None:
    """Fail loud unless every accepted verb has an implementation, and vice versa.

    The parser's choice set and this dispatch table are two sides of one seam:
    argparse decides what is accepted, ``COMMANDS`` decides what happens. A verb
    in one and not the other is a KeyError at the worst possible moment -- after
    an operator confirmed a destructive command -- or a verb that quietly cannot
    be reached at all. Comparing the two sets costs nothing and runs before any
    argument is parsed.

    Raises:
        DeployError: If the two sets differ, naming the verbs on each side.
    """
    accepted = set(REALIZED_VERBS)
    implemented = set(COMMANDS)
    if accepted == implemented:
        return
    raise DeployError(
        f"This script accepts {sorted(accepted)} but implements "
        f"{sorted(implemented)}. Accepted-but-missing: "
        f"{sorted(accepted - implemented)}; implemented-but-unreachable: "
        f"{sorted(implemented - accepted)}. This is a generator defect, not "
        f"something to work around here -- regenerate the project."
    )


def main(argv: list[str] | None = None) -> int:
    """Entry point: dispatch the requested lifecycle command.

    Every argument is a command or a flag this script declares. A verb it does
    not implement is rejected by name, with ``--help`` explaining what this
    profile has instead -- never answered by silently deploying, which is the
    most dangerous shape a fallback can take: the action performed is not the
    action requested, and the output looks like success.

    Args:
        argv: Arguments to parse; ``sys.argv[1:]`` when omitted.

    Returns:
        Process exit code -- 0 on success, 1 on any operator-actionable failure.
    """
    arguments = normalize_argv(list(sys.argv[1:] if argv is None else argv))
    try:
        require_command_coverage()
    except DeployError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    parser = build_lifecycle_parser(
        "Manage this application's Docker Compose deployment."
    )
    parsed = parser.parse_args(arguments)
    try:
        COMMANDS[parsed.command](force_requested(parsed.force))
    except DeployError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nInterrupted.", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
