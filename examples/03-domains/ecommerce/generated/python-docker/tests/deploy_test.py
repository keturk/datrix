# Transient failure patterns (infrastructure issues, not logic bugs)
_TRANSIENT_ERROR_PATTERNS = [
    "connection was closed in the middle of operation",
    "ConnectionDoesNotExistError",
    "WinError 64",
    "ConnectionResetError",
    "ConnectionRefusedError",
    "BrokenPipeError",
    "timeout",
    "timed out",
    "no such container",
    "container is not running",
    "network error",
    "OSError",
    "PermissionError",
    "RemoteDisconnected",
    "ConnectionError",
    "cannot schedule new futures after shutdown",
]


def _classify_error(message: str) -> str:
    """Classify error message as 'transient' or 'logic'.

    Transient errors are infrastructure/environment issues (network, container, timeouts).
    Logic errors are code bugs, validation failures, or business logic issues.
    """
    msg_lower = message.lower()
    for pattern in _TRANSIENT_ERROR_PATTERNS:
        if pattern.lower() in msg_lower:
            return "transient"
    return "logic"


def _parse_junit_failures(xml_path: Path, phase: str) -> list[dict[str, object]]:
    """Extract failed / errored testcases from a pytest junitxml file."""
    if not xml_path.is_file():
        return []
    try:
        tree = ET.parse(xml_path)
    except ET.ParseError:
        return []
    root = tree.getroot()
    out: list[dict[str, object]] = []
    for el in root.iter():
        if _local_xml_tag(el.tag) != "testcase":
            continue
        classname = el.get("classname") or ""
        name = el.get("name") or ""
        for child in el:
            ct = _local_xml_tag(child.tag)
            if ct not in ("failure", "error"):
                continue
            msg = (child.get("message") or (child.text or "")).strip()
            failure_type = _classify_error(msg)
            out.append(
                {
                    "service": phase,
                    "testFilePath": classname,
                    "fullName": f"{classname}::{name}" if classname else name,
                    "message": msg[:8000],
                    "failureType": failure_type,
                }
            )
    return out


def _write_deploy_failures_artifacts(
    results_dir: Path, project_dir: Path
) -> tuple[int, int]:
    """Aggregate pytest junit files into failures.json and categorized text reports.

    Returns:
        Tuple of (logic_failure_count, transient_failure_count)
    """
    failures: list[dict[str, object]] = []
    for xml_path in sorted(results_dir.glob("pytest-*.xml")):
        phase = xml_path.stem.replace("pytest-", "")
        failures.extend(_parse_junit_failures(xml_path, phase))

    # Categorize failures
    logic_failures = [f for f in failures if f.get("failureType") == "logic"]
    transient_failures = [f for f in failures if f.get("failureType") == "transient"]

    # Write full failures.json with all failures
    payload = {
        "project": str(project_dir.resolve()),
        "generatedAt": datetime.now().isoformat(),
        "failures": failures,
        "summary": {
            "total": len(failures),
            "logic": len(logic_failures),
            "transient": len(transient_failures),
        },
    }
    (results_dir / "failures.json").write_text(
        json.dumps(payload, indent=2) + "\n",
        encoding="utf-8",
    )

    # Write categorized text reports
    if logic_failures:
        blocks = []
        for f in logic_failures:
            head = f"{f.get('testFilePath', '')} — {f.get('fullName', '')}"
            body = str(f.get("message") or "").split("\n")[:14]
            blocks.append(head + "\n" + "\n".join(body))
        (results_dir / "deploy-failures-logic.log").write_text(
            "\n\n---\n\n".join(blocks) + "\n",
            encoding="utf-8",
        )

    if transient_failures:
        blocks = []
        for f in transient_failures:
            head = f"{f.get('testFilePath', '')} — {f.get('fullName', '')}"
            body = str(f.get("message") or "").split("\n")[:14]
            blocks.append(head + "\n" + "\n".join(body))
        (results_dir / "deploy-failures-transient.log").write_text(
            "# Transient Infrastructure Failures\n\n"
            "These failures are likely due to infrastructure/environment issues,\n"
            "not code bugs. Common causes:\n"
            "- Container networking issues\n"
            "- Database connection drops\n"
            "- Timing/race conditions in container startup\n"
            "- Host system resource constraints\n\n"
            "Recommendation: Re-run tests to verify if these are reproducible.\n\n"
            "---\n\n" + "\n\n---\n\n".join(blocks) + "\n",
            encoding="utf-8",
        )

    return len(logic_failures), len(transient_failures)


#: Where the compose deployment writes each service's config store and its
