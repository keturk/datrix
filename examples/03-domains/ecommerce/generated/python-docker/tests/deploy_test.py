def _resolve_test_storage_credentials(
    storage_container: dict[str, object] | None, project_dir: Path
) -> tuple[str, str] | None:
    """Read the provisioner-written MinIO root credentials for host-run tests.

    The compose generator writes the SAME file-backend secrets the deployed
    container reads (``secrets/<compose_service>/minio_access_key`` /
    ``minio_secret_key``, a fixed root user plus a generation-time random
    password) alongside the compose file -- no ``docker compose`` call needed,
    unlike the endpoint's host-port resolution, since these are plain files
    already on disk once generation has run.

    Returns ``None`` when the service has no self-hosted MinIO storage block,
    or when either secret file has not been written -- the caller falls back
    to the baked (invalid, out-of-band) test placeholder, which is a 403
    against a real running server rather than a silent bypass.
    """
    if not storage_container:
        return None
    compose_service = str(storage_container["compose_service"])
    secrets_dir = project_dir / "secrets" / compose_service
    access_key_file = secrets_dir / "minio_access_key"
    secret_key_file = secrets_dir / "minio_secret_key"
    if not access_key_file.is_file() or not secret_key_file.is_file():
        logger.warning(
            "minio_credential_files_missing access_key_file=%s secret_key_file=%s",
            access_key_file,
            secret_key_file,
        )
        return None
    return (
        access_key_file.read_text(encoding="utf-8").strip(),
        secret_key_file.read_text(encoding="utf-8").strip(),
    )


def _seed_storage_fixtures(compose: list[str], project_dir: Path) -> int:
    """PUT every authored storage fixture object into its bucket before the tests run.

    A generated service carries the fixture objects authored beside its
    config at ``<service dir>/<fixtures_dir>/<block alias>/<relative key>``.
    A spec test whose DSL body reads an object (``<block>.download(key)``)
    needs that object to exist first, and the DSL cannot construct ``Bytes``
    to upload it itself -- so the harness seeds each file into the block's
    bucket at exactly its relative key, over the same host-mapped endpoint and
    provisioner-written root credentials the tests themselves use.

    Fails closed: a fixture directory whose alias maps to no bucket, an
    unresolvable endpoint or credential pair, a bucket the running server does
    not hold, or a refused PUT each raise -- a spec test failing later with a
    missing key would only hide which of them it was. Logs carry counts and
    keys, never credentials or content.

    Returns:
        The number of objects seeded across every service.
    """
    seeded = 0
    for service in SERVICES:
        storage_container = service.get("storage_container")
        if not isinstance(storage_container, dict):
            continue
        seeded += _seed_service_storage_fixtures(
            compose, project_dir, service, storage_container
        )
    return seeded


def _seed_service_storage_fixtures(
    compose: list[str],
    project_dir: Path,
    service: dict[str, object],
    storage_container: dict[str, object],
) -> int:
    """Seed one service's fixture objects; see ``_seed_storage_fixtures``."""
    import boto3

    service_name = str(service["name"])
    fixtures_root = (
        project_dir / str(service["dir"]) / str(storage_container["fixtures_dir"])
    )
    block_dirs = (
        sorted(p for p in fixtures_root.iterdir() if p.is_dir())
        if fixtures_root.is_dir()
        else []
    )
    if not block_dirs:
        logger.info(
            "storage_fixtures_none service=%s dir=%s", service_name, fixtures_root
        )
        return 0
    buckets = storage_container["buckets"]
    if not isinstance(buckets, dict):
        raise RuntimeError(
            f"storage_container for service {service_name!r} carries no bucket map"
        )
    endpoint = _resolve_test_storage_endpoint(compose, storage_container, project_dir)
    if endpoint is None:
        raise RuntimeError(
            f"Storage fixtures exist under {fixtures_root} but the MinIO host endpoint "
            f"could not be resolved for service {service_name!r}; see the "
            f"docker_compose_port_failed warning above."
        )
    credentials = _resolve_test_storage_credentials(storage_container, project_dir)
    if credentials is None:
        raise RuntimeError(
            f"Storage fixtures exist under {fixtures_root} but the provisioner-written "
            f"MinIO credential files are missing for service {service_name!r}; see "
            f"the minio_credential_files_missing warning above."
        )
    client = boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=credentials[0],
        aws_secret_access_key=credentials[1],
    )
    seeded = 0
    for block_dir in block_dirs:
        alias = block_dir.name
        if alias not in buckets:
            raise RuntimeError(
                f"Storage fixtures directory {block_dir} names block {alias!r}, but "
                f"service {service_name!r} has no host-reachable bucket for it "
                f"(known: {sorted(buckets)}). Only a self-hosted MinIO block can be seeded."
            )
        seeded += _seed_block_storage_fixtures(
            client, service_name, alias, str(buckets[alias]), block_dir, endpoint
        )
    return seeded


def _seed_block_storage_fixtures(
    client: object,
    service_name: str,
    alias: str,
    bucket: str,
    block_dir: Path,
    endpoint: str,
) -> int:
    """PUT every file under *block_dir* into *bucket* at its block-relative key."""
    from botocore.exceptions import BotoCoreError, ClientError

    try:
        client.head_bucket(Bucket=bucket)
    except (ClientError, BotoCoreError) as exc:
        raise RuntimeError(
            f"Bucket {bucket!r} for storage block {alias!r} is not reachable at "
            f"{endpoint}: {type(exc).__name__}. The compose init container creates "
            f"it before the services start; check its logs."
        ) from exc
    seeded = 0
    for fixture_path in sorted(p for p in block_dir.rglob("*") if p.is_file()):
        key = fixture_path.relative_to(block_dir).as_posix()
        try:
            client.put_object(Bucket=bucket, Key=key, Body=fixture_path.read_bytes())
        except (ClientError, BotoCoreError) as exc:
            raise RuntimeError(
                f"PUT of storage fixture {fixture_path} to bucket {bucket!r} key "
                f"{key!r} failed: {type(exc).__name__}"
            ) from exc
        seeded += 1
        logger.info(
            "storage_fixture_seeded service=%s block=%s bucket=%s key=%s",
            service_name,
            alias,
            bucket,
            key,
        )
    return seeded


def _resolve_test_mq_brokers(
    compose: list[str], mq_container: dict[str, object] | None, project_dir: Path
) -> str | None:
    """Resolve the host-accessible Kafka bootstrap servers for tests run outside Compose.

    The broker's EXTERNAL listener is published to an ephemeral host port; this
    resolves that port via ``docker compose port`` and returns ``localhost:<port>``
    -- the address the broker advertises on that listener, so a host client that
    bootstraps there stays reachable for the follow-up producer connection.
    """
    if not mq_container:
        return None
    container_key = str(mq_container["key"])
    external_container_port = int(mq_container["external_container_port"])
    result = subprocess.run(
        [*compose, "port", container_key, str(external_container_port)],
        capture_output=True,
        text=True,
        check=False,
        cwd=str(project_dir),
    )
    if result.returncode != 0 or not result.stdout.strip():
        logger.warning(
            "docker_compose_port_failed container=%s port=%s",
            container_key,
            external_container_port,
        )
        return None
    host_mapping = result.stdout.strip().splitlines()[0]
    host_port = host_mapping.rsplit(":", 1)[-1]
    return f"localhost:{host_port}"


def _resolve_service_base_url(
    compose: list[str],
    service: dict[str, object],
    *,
    cwd: str | None = None,
) -> str:
    """Resolve the host URL for a compose service with dynamic port publishing."""
    compose_key = str(
        service.get("compose_key") or str(service["dir"]).replace("_", "-")
    )
    container_port = int(service["port"])
    port_result = subprocess.run(
        [*compose, "port", compose_key, str(container_port)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
        cwd=cwd,
        timeout=30,
    )
    if port_result.returncode != 0 or not port_result.stdout.strip():
        logger.warning(
            "docker_compose_service_port_unresolved service=%s compose_key=%s port=%s stderr=%s",
            service["name"],
            compose_key,
            container_port,
            (port_result.stderr or "").strip(),
        )
        return f"http://localhost:{container_port}"
    host_mapping = port_result.stdout.strip().splitlines()[0]
    host_port = host_mapping.rsplit(":", 1)[-1]
    return f"http://localhost:{host_port}"


_SHELL_DEFAULT_RE = re.compile(r"\$\{(\w+):-([^}]*)\}")


def _resolve_shell_default(value: str) -> str:
    """Resolve ``${VAR:-default}`` syntax to match Docker Compose behavior.

    If the referenced environment variable is set in the host environment its
    value is used; otherwise the inline default is returned.  Values that do
    not use this syntax are returned unchanged.
    """
    match = _SHELL_DEFAULT_RE.fullmatch(value)
    if match:
        var_name, default = match.group(1), match.group(2)
        return os.environ.get(var_name, default)
    return value


def _redacted(url: str) -> str:
    """Return *url* with any embedded password replaced by '***' for logging.

    Only the credential segment of a `scheme://user:password@host:port/db`
    connection URL is masked -- host/port/database stay visible, since they
    are legitimate operator-debugging information, not a credential.
    """
    return re.sub(r"://([^:/@]+):([^@]+)@", r"://\1:***@", url)


def run_spec_tests(
    *,
    compose: list[str],
    db_containers_by_service: dict[str, list[dict[str, object]]],
    service_url_env: dict[str, str],
    results_dir: Path,
    verbose: bool = False,
) -> int:
    """Run specification tests for all services.

    ``service_url_env`` maps ``<SERVICE_DIR>_URL`` to each service's
    host-accessible base URL. A service that ``uses`` a peer reads that peer's
    base URL from its config store, and the generated conftest seeds it from this
    map, so every service's URL is exported -- not only the one under test.

    Returns the number of failures (0 = all passed).
    """
    project_dir = Path(__file__).parent.parent
    env_file = project_dir / ".env"

    # Load .env values
    env = dict(os.environ)
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                env.setdefault(key.strip(), _resolve_shell_default(value.strip()))
    env.update(service_url_env)
    failures = 0
    for service in SERVICES:
        service_dir = str(service["dir"])
        spec_dir = project_dir / service_dir / "tests" / "spec"

        if not spec_dir.exists():
            logger.info(
                "spec_tests_skipped service=%s reason=no_spec_directory",
                service["name"],
            )
            continue

        logger.info("spec_tests_started service=%s", service["name"])

        # Set up environment with database URL if available
        svc_env = dict(env)
        svc_env["PYTHONPATH"] = "src" + os.pathsep + svc_env.get("PYTHONPATH", "")

        db_containers = db_containers_by_service.get(str(service["name"]), [])
        for db_env_var, db_url in _resolve_test_database_urls(
            compose, db_containers, project_dir
        ).items():
            svc_env[db_env_var] = db_url
            logger.info(
                "test_database_url_resolved service=%s var=%s url=%s",
                service["name"],
                db_env_var,
                _redacted(db_url),
            )
        test_redis_url = _resolve_test_redis_url(
            compose,
            service.get("cache_container"),
            project_dir,
        )
        if test_redis_url:
            svc_env["REDIS_URL"] = test_redis_url
            logger.info(
                "test_redis_url_resolved service=%s url=%s",
                service["name"],
                test_redis_url,
            )
        test_storage_endpoint = _resolve_test_storage_endpoint(
            compose,
            service.get("storage_container"),
            project_dir,
        )
        if test_storage_endpoint:
            svc_env["STORAGE_ENDPOINT_URL"] = test_storage_endpoint
            logger.info(
                "test_storage_endpoint_resolved service=%s url=%s",
                service["name"],
                test_storage_endpoint,
            )
        test_storage_credentials = _resolve_test_storage_credentials(
            service.get("storage_container"), project_dir
        )
        if test_storage_credentials:
            svc_env["STORAGE_ACCESS_KEY"], svc_env["STORAGE_SECRET_KEY"] = (
                test_storage_credentials
            )
            logger.info("test_storage_credentials_resolved service=%s", service["name"])

        safe = str(service["dir"]).replace("/", "_").replace("\\", "_")
        junit_path = results_dir / f"pytest-spec-{safe}.xml"
        # Run spec tests
        if not _run_pytest(
            ["tests/spec"],
            svc_env,
            verbose=verbose,
            cwd=project_dir / service_dir,
            junit_path=junit_path,
        ):
            logger.error("spec_tests_failed service=%s", service["name"])
            failures += 1
        else:
            logger.info("spec_tests_passed service=%s", service["name"])

    return failures


def run_integration_tests(
    service_dir: str,
    base_url: str,
    *,
    compose: list[str],
    service_url_env: dict[str, str],
    db_containers: list[dict[str, object]] | None = None,
    cache_container: dict[str, object] | None = None,
    mq_container: dict[str, object] | None = None,
    storage_container: dict[str, object] | None = None,
    verbose: bool = False,
    results_dir: Path,
    expose_http: bool = True,
) -> bool:
    """Run project-level and per-service integration tests against deployed endpoint.

    Runs as separate pytest invocations to avoid conftest module-name collisions
    between the project-level tests/ and per-service {service}/tests/ directories.

    When ``expose_http`` is False the service publishes no host HTTP port
    (NONE-ingress, data-only): BASE_URL is left unset and the host-side project
    test (``tests/test_{service}.py``) is not run -- it is not generated for such
    a service. The DB-backed ``{service}/tests`` integration suite still runs,
    reaching the database over its own published port.

    ``service_url_env`` maps ``<SERVICE_DIR>_URL`` to each service's
    host-accessible base URL. A service that ``uses`` a peer reads that peer's
    base URL from its config store, and the generated conftest seeds it from this
    map, so every service's URL is exported -- not only the one under test.
    """
    env = dict(os.environ)
    env.update(service_url_env)
    if expose_http:
        env["BASE_URL"] = base_url
        env[f"{service_dir.upper()}_URL"] = base_url
    # Enable payment gateway test mode for integration tests (mock Stripe/payment SDKs)
    env["PAYMENT_TEST_MODE"] = "true"
    project_dir = Path(__file__).parent.parent
    # Load .env values so tests use the same secrets as Docker containers.
    env_file = project_dir / ".env"
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                env.setdefault(key.strip(), _resolve_shell_default(value.strip()))
    redis_url = _resolve_test_redis_url(compose, cache_container, project_dir)
    if redis_url:
        env["REDIS_URL"] = redis_url
        logger.info("test_redis_url_resolved url=%s", redis_url)
    mq_brokers = _resolve_test_mq_brokers(compose, mq_container, project_dir)
    if mq_brokers:
        env["MQ_BROKERS_URL"] = mq_brokers
        logger.info("test_mq_brokers_resolved url=%s", mq_brokers)
    storage_endpoint = _resolve_test_storage_endpoint(
        compose, storage_container, project_dir
    )
    if storage_endpoint:
        env["STORAGE_ENDPOINT_URL"] = storage_endpoint
        logger.info("test_storage_endpoint_resolved url=%s", storage_endpoint)
    storage_credentials = _resolve_test_storage_credentials(
        storage_container, project_dir
    )
    if storage_credentials:
        env["STORAGE_ACCESS_KEY"], env["STORAGE_SECRET_KEY"] = storage_credentials
        logger.info("test_storage_credentials_resolved")
    for db_env_var, db_url in _resolve_test_database_urls(
        compose, db_containers or [], project_dir
    ).items():
        env[db_env_var] = db_url
        logger.info(
            "test_database_url_resolved var=%s url=%s", db_env_var, _redacted(db_url)
        )
    safe = service_dir.replace("/", "_").replace("\\", "_")
    passed = True
    if expose_http:
        passed = _run_pytest(
            [f"tests/test_{service_dir}.py"],
            env,
            verbose=verbose,
            junit_path=results_dir / f"pytest-integration-{safe}-project.xml",
        )
    svc_tests_dir = Path(service_dir) / "tests"
    if svc_tests_dir.exists():
        svc_env = dict(env)
        svc_env["PYTHONPATH"] = "src" + os.pathsep + svc_env.get("PYTHONPATH", "")
        if not _run_pytest(
            ["tests"],
            svc_env,
            verbose=verbose,
            extra_args=["-o", "addopts=", "-m", "integration and not kafka"],
            cwd=service_dir,
            junit_path=results_dir / f"pytest-integration-{safe}-service.xml",
        ):
            passed = False
    return passed


def run_docker_cmd(
    cmd: list[str], *, verbose: bool = False, label: str = "", cwd: str | None = None
) -> subprocess.CompletedProcess[str]:
    """Run a docker command, capturing output unless verbose."""
    if verbose:
        return subprocess.run(cmd, check=False, cwd=cwd)
    result = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
        cwd=cwd,
    )
    if result.returncode != 0 and label:
        logger.error(
            "%s output:\n%s%s", label, result.stdout or "", result.stderr or ""
        )
    return result


#: The Docker daemon's diagnosis when a published host port is already bound
#: on the machine. Deterministic -- the same holder answers a retry.
_HOST_PORT_ALLOCATED_MARKER = "port is already allocated"


def _is_host_port_allocation_failure(result: subprocess.CompletedProcess[str]) -> bool:
    """True when a failed ``compose up`` died on a host port held by another process.

    Reads the captured output; in verbose mode nothing is captured (output
    streams to the terminal) and the failure is classified as unknown, so the
    generic retry path still applies there.
    """
    text = (result.stdout or "") + (result.stderr or "")
    return _HOST_PORT_ALLOCATED_MARKER in text


def _sanitize_container_name(name: str) -> str:
    """Replace characters invalid in filenames with underscore."""
    invalid_chars = '/\\:*?"<>|'
    result = name
    for ch in invalid_chars:
        result = result.replace(ch, "_")
    return result or "container"


def _check_container_exit_codes(
    compose: list[str],
    *,
    cwd: str | None = None,
) -> bool:
    """Check all containers for failed exit codes.

    Init containers should have exited with code 0.
    Service containers should be running.

    Returns:
        True if all containers are healthy, False if any failures detected.
    """
    try:
        ps_result = subprocess.run(
            [*compose, "ps", "-a", "--format", "json"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
            cwd=cwd,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        logger.error("docker_compose_ps_timeout")
        return False

    if ps_result.returncode != 0:
        logger.error("docker_compose_ps_failed rc=%s", ps_result.returncode)
        return False

    if not ps_result.stdout.strip():
        logger.warning("docker_compose_ps_no_containers")
        return True

    # Parse JSON output (one JSON object per line)
    containers = []
    for line in ps_result.stdout.strip().splitlines():
        try:
            containers.append(json.loads(line))
        except json.JSONDecodeError:
            logger.warning("docker_compose_ps_invalid_json line=%s", line)
            continue

    failed = False
    for container in containers:
        name = container.get("Name", "unknown")
        state = container.get("State", "")
        exit_code = container.get("ExitCode", 0)

        # Containers that exited with non-zero code are failures
        if state == "exited" and exit_code != 0:
            logger.error(
                "container_failed name=%s state=%s exit_code=%s", name, state, exit_code
            )
            failed = True
        # Running containers are OK
        elif state in ("running", "healthy"):
            logger.debug("container_healthy name=%s state=%s", name, state)
        # Exited with 0 (init containers) are OK
        elif state == "exited" and exit_code == 0:
            logger.debug("container_completed name=%s", name)
        else:
            logger.warning(
                "container_unexpected_state name=%s state=%s exit_code=%s",
                name,
                state,
                exit_code,
            )

    return not failed


def _validate_database_connectivity(
    compose: list[str],
    db_containers_by_service: dict[str, list[dict[str, object]]],
    project_dir: Path,
) -> bool:
    """Validate that database containers are accepting connections.

    Attempts to resolve and connect to database URLs to catch transient
    connection issues before running tests.

    Returns:
        True if all database connections are healthy, False otherwise.
    """
    all_healthy = True
    for service_name, db_containers in db_containers_by_service.items():
        if not db_containers:
            continue

        # Check EVERY RDBMS block, not just the first: a service with a second
        # database on its own container would otherwise never be probed.
        # Resolution fails closed (RuntimeError) on any missing piece rather
        # than silently skipping the block.
        resolved = _resolve_test_database_urls(compose, db_containers, project_dir)
        block_urls = {
            var: url for var, url in resolved.items() if var != "TEST_DATABASE_URL"
        }

        for db_env_var, test_db_url in sorted(block_urls.items()):
            # Quick connectivity test: try to parse URL and verify reachability
            try:
                parsed = urlparse(test_db_url)
                host_port = parsed.netloc.split("@")[-1]  # Extract host:port
                host = host_port.split(":")[0]
                port = int(host_port.split(":")[1]) if ":" in host_port else 5432

                # Test TCP connection (quick check without full DB driver)
                sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                sock.settimeout(5)
                result = sock.connect_ex((host, port))
                sock.close()

                if result == 0:
                    logger.info(
                        "database_connectivity_check_passed service=%s var=%s host=%s port=%s",
                        service_name,
                        db_env_var,
                        host,
                        port,
                    )
                else:
                    logger.error(
                        "database_connectivity_check_failed service=%s var=%s host=%s port=%s error_code=%s",
                        service_name,
                        db_env_var,
                        host,
                        port,
                        result,
                    )
                    all_healthy = False
            except Exception as e:
                logger.error(
                    "database_connectivity_check_error service=%s var=%s error=%s",
                    service_name,
                    db_env_var,
                    str(e),
                )
                all_healthy = False

    return all_healthy


def _save_docker_logs(
    compose: list[str],
    results_dir: Path,
    *,
    cwd: str | None = None,
) -> None:
    """Save logs from all Docker Compose containers to results_dir/docker-logs/.

    Must be called BEFORE tearing down containers, otherwise there are no
    containers to collect logs from.

    Uses two capture strategies:

    1. ``docker compose logs --no-color`` (primary) — captures logs from ALL
       services including crashed/exited containers that may not appear in
       ``docker compose ps -a`` output (race between crash and project state
       registration).  The combined output is saved as
       ``docker-logs/all-services.log`` and also parsed to produce individual
       ``docker-logs/{service}.log`` files so the structured log writer can
       reference them by container name.

    2. ``docker compose ps -a`` + per-container ``docker logs`` (supplemental)
       — fills in any containers not captured by strategy 1.
    """
    docker_logs_dir = results_dir / "docker-logs"
    docker_logs_dir.mkdir(parents=True, exist_ok=True)

    # --- Strategy 1: docker compose logs (reliable for crashed containers) ---
    captured_services: set[str] = set()
    try:
        compose_logs_result = subprocess.run(
            [*compose, "logs", "--no-color"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
            cwd=cwd,
            timeout=120,
        )
        compose_logs_content = (compose_logs_result.stdout or "") + (
            compose_logs_result.stderr or ""
        )
        if compose_logs_content.strip():
            all_log_file = docker_logs_dir / "all-services.log"
            all_log_file.write_text(compose_logs_content, encoding="utf-8")
            logger.info("docker_compose_logs_saved path=%s", all_log_file)

            # Parse "{service}  | {content}" lines into per-service files so
            # deploy_test_log_writer can locate docker-logs/{container}.log.
            service_lines: dict[str, list[str]] = {}
            for line in compose_logs_content.splitlines():
                for sep in ("  | ", " | "):
                    if sep in line:
                        idx = line.index(sep)
                        svc = line[:idx].strip()
                        content = line[idx + len(sep) :]
                        if svc:
                            service_lines.setdefault(svc, []).append(content)
                        break
            for svc_name, svc_lines in service_lines.items():
                safe_name = _sanitize_container_name(svc_name)
                svc_log_file = docker_logs_dir / f"{safe_name}.log"
                svc_log_file.write_text("\n".join(svc_lines) + "\n", encoding="utf-8")
                captured_services.add(safe_name)
                logger.info(
                    "docker_service_log_saved service=%s path=%s",
                    svc_name,
                    svc_log_file,
                )
    except subprocess.TimeoutExpired:
        logger.warning("docker_compose_logs_all_timeout")

    # --- Strategy 2: per-container docker logs (supplemental) ---
    try:
        ps_result = subprocess.run(
            [*compose, "ps", "-a", "--format", "{{.Name}}"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
            cwd=cwd,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        logger.warning("docker_compose_ps_timeout")
        return

    if ps_result.returncode != 0 or not ps_result.stdout.strip():
        logger.warning("docker_compose_ps_failed rc=%s", ps_result.returncode)
        return

    containers = [n.strip() for n in ps_result.stdout.splitlines() if n.strip()]
    for container_name in containers:
        safe_name = _sanitize_container_name(container_name)
        # Skip containers already captured by strategy 1 to avoid overwriting
        # richer per-service logs with potentially duplicated content.
        if safe_name in captured_services:
            continue
        log_file = docker_logs_dir / f"{safe_name}.log"
        try:
            log_result = subprocess.run(
                ["docker", "logs", container_name],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=False,
                timeout=60,
            )
            content = (log_result.stdout or "") + (log_result.stderr or "")
            log_file.write_text(content, encoding="utf-8")
            logger.info(
                "docker_log_saved container=%s path=%s", container_name, log_file
            )
        except subprocess.TimeoutExpired:
            logger.warning("docker_log_timeout container=%s", container_name)


GATEWAY_COMPOSE_KEY = "ecommerce-api-gateway"
GATEWAY_INTERNAL_PORT = 80


def _generate_test_jwt(env: dict[str, str]) -> str | None:
    """Generate a short-lived test JWT for gateway auth testing.

    Uses RS256 JWT_PRIVATE_KEY or JWT_PRIVATE_KEY_FILE from the environment.
    Returns None when key material is unavailable or PyJWT is not installed.
    """
    jwt_private_key = env.get("JWT_PRIVATE_KEY")
    private_key_file = env.get("JWT_PRIVATE_KEY_FILE")
    if not jwt_private_key and private_key_file:
        try:
            jwt_private_key = Path(private_key_file).read_text(encoding="utf-8")
        except OSError as exc:
            logger.warning(
                "gateway_test_jwt_unavailable reason=private_key_file_unreadable error=%s",
                exc,
            )
            return None
    if not jwt_private_key:
        logger.warning(
            "gateway_test_jwt_unavailable reason=JWT_PRIVATE_KEY_not_configured"
        )
        return None
    try:
        import jwt
    except ImportError:
        logger.warning("gateway_test_jwt_unavailable reason=PyJWT_not_installed")
        return None
    payload = {
        "sub": "deploy-test-runner",
        "iat": int(time.time()),
        "exp": int(time.time()) + 3600,
    }
    algorithm = env["JWT_ALGORITHM"]
    return jwt.encode(payload, jwt_private_key, algorithm=algorithm)


def run_gateway_auth_tests(
    *,
    compose: list[str],
    service_urls: dict[str, str],
    env: dict[str, str],
    results_dir: Path,
    verbose: bool = False,
    cwd: str | None = None,
) -> int:
    """Run gateway JWT authentication and route-proxying tests.

    Phase 1 -- /internal/credential-verify on the auth provider service (direct, not via gateway):
        * Valid token -> 200
        * Missing token -> 401

    Phase 2 -- Gateway route auth:
        * Any route without token -> 401
        * Any route with valid token -> not 500/502

    Returns the number of failures (0 = all passed).
    """
    failures = 0
    token = _generate_test_jwt(env)
    if token is None:
        logger.error("gateway_auth_tests_skipped reason=no_jwt_token")
        return 1

    # Phase 1: the credential-verify endpoint on the auth provider service only
    auth_provider_urls = {
        name: url
        for name, url in service_urls.items()
        if name in _AUTH_PROVIDER_COMPOSE_KEYS
    }
    for service_name, base_url in auth_provider_urls.items():
        verify_url = f"{base_url}/internal/credential-verify"

        # Valid token -> 200
        try:
            req = request.Request(
                verify_url, headers={"Authorization": f"Bearer {token}"}
            )
            with request.urlopen(req, timeout=10) as resp:
                if resp.status == 200:
                    logger.info(
                        "credential_verify_valid_token_passed service=%s", service_name
                    )
                else:
                    logger.error(
                        "credential_verify_valid_token_unexpected service=%s status=%s",
                        service_name,
                        resp.status,
                    )
                    failures += 1
        except error.HTTPError as e:
            logger.error(
                "credential_verify_valid_token_failed service=%s status=%s",
                service_name,
                e.code,
            )
            failures += 1
        except (error.URLError, OSError) as e:
            logger.error(
                "credential_verify_valid_token_error service=%s error=%s",
                service_name,
                e,
            )
            failures += 1

        # Missing token -> 401
        try:
            req = request.Request(verify_url)
            with request.urlopen(req, timeout=10) as resp:
                logger.error(
                    "credential_verify_no_token_should_reject service=%s status=%s",
                    service_name,
                    resp.status,
                )
                failures += 1
        except error.HTTPError as e:
            if e.code == 401:
                logger.info(
                    "credential_verify_no_token_passed service=%s", service_name
                )
            else:
                logger.error(
                    "credential_verify_no_token_unexpected service=%s status=%s",
                    service_name,
                    e.code,
                )
                failures += 1
        except (error.URLError, OSError) as e:
            logger.error(
                "credential_verify_no_token_error service=%s error=%s",
                service_name,
                e,
            )
            failures += 1

    # Phase 2: Gateway route auth
    try:
        port_result = subprocess.run(
            [*compose, "port", GATEWAY_COMPOSE_KEY, str(GATEWAY_INTERNAL_PORT)],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
            cwd=cwd,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        logger.error("gateway_port_resolution_timeout")
        return failures + 1

    if port_result.returncode != 0 or not port_result.stdout.strip():
        logger.error(
            "gateway_port_unresolved compose_key=%s stderr=%s",
            GATEWAY_COMPOSE_KEY,
            (port_result.stderr or "").strip(),
        )
        return failures + 1

    host_mapping = port_result.stdout.strip().splitlines()[0]
    host_port = host_mapping.rsplit(":", 1)[-1]
    gateway_url = f"http://localhost:{host_port}"
    logger.info("gateway_url_resolved url=%s", gateway_url)

    # Reload nginx to refresh upstream DNS resolution
    try:
        subprocess.run(
            [*compose, "exec", "-T", GATEWAY_COMPOSE_KEY, "nginx", "-s", "reload"],
            capture_output=True,
            check=False,
            cwd=cwd,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        logger.warning("nginx_reload_timeout")
    time.sleep(2)

    # Pick any API path — /api/v1/ prefix triggers auth_request in nginx.
    # A non-existent sub-path is fine: auth failure -> 401, auth pass -> 404.
    test_path = f"{gateway_url}/api/v1/_deploy_test_auth_probe"

    # No token -> 401
    try:
        req = request.Request(test_path)
        with request.urlopen(req, timeout=10) as resp:
            # If we get 200/2xx, this route may be public (no auth_request).
            # Not a failure — just means this path was not behind auth.
            logger.info(
                "gateway_no_token_test result=route_is_public status=%s",
                resp.status,
            )
    except error.HTTPError as e:
        if e.code == 401 or e.code == 403:
            logger.info("gateway_no_token_test result=auth_required_as_expected")
        elif e.code >= 500:
            logger.error("gateway_no_token_test result=server_error status=%s", e.code)
            failures += 1
        else:
            # 404 etc. — route exists but no auth required (acceptable)
            logger.info(
                "gateway_no_token_test result=no_auth_required status=%s", e.code
            )
    except (error.URLError, OSError) as e:
        logger.error("gateway_no_token_test result=connection_error error=%s", e)
        failures += 1

    # Valid token -> not 500/502 (the critical regression check for Fix 10a)
    try:
        req = request.Request(test_path, headers={"Authorization": f"Bearer {token}"})
        with request.urlopen(req, timeout=10) as resp:
            logger.info(
                "gateway_valid_token_test result=success status=%s", resp.status
            )
    except error.HTTPError as e:
        if e.code >= 500:
            logger.error(
                "gateway_valid_token_test result=server_error status=%s", e.code
            )
            failures += 1
        else:
            # 4xx (401 re-auth, 404 not found) means auth subrequest itself
            # did not crash — acceptable for a synthetic probe path.
            logger.info("gateway_valid_token_test result=auth_passed status=%s", e.code)
    except (error.URLError, OSError) as e:
        logger.error("gateway_valid_token_test result=connection_error error=%s", e)
        failures += 1

    return failures


# ---------------------------------------------------------------------------
# The container runtime's own pre-start checks, called in-process.
# The runtime that emits docker-compose.yml also emits the deployment script an
# operator runs, and that script owns the checks that must pass before the
# stack starts: the environment file exists, every variable compose requires
# has a value, every secret file compose mounts exists. This harness calls the
# SAME functions rather than carrying a second implementation of them --
# the script's path, the function names and its error class are declared by
# the runtime and rendered here, never re-typed.
# ---------------------------------------------------------------------------
DEPLOY_PREFLIGHT_SCRIPT = "scripts/deploy.py"
DEPLOY_PREFLIGHT_FUNCTIONS: tuple[str, ...] = (
    "require_env_file",
    "require_env_keys",
    "require_secret_files",
)
DEPLOY_PREFLIGHT_ERROR_CLASS = "DeployError"

#: Module name the deployment script is imported under. Anything but
#: ``"__main__"``: the script guards its command line behind that name, so
#: importing it defines its functions and runs nothing.
_DEPLOY_PREFLIGHT_MODULE_NAME = "datrix_deploy_preflight"


def _load_deploy_script(project_dir: Path) -> ModuleType:
    """Import the runtime's deployment script as a module, without running it.

    Loaded from its emitted path so the script's own project-root anchor
    (relative to its file) resolves to this project, and under a name that is
    not ``__main__`` so its command line is never parsed here.

    Raises:
        ValueError: When the script is absent (the runtime emits it beside the
            compose file, so an absent one is a generation defect) or cannot
            be loaded.
    """
    script_path = project_dir / DEPLOY_PREFLIGHT_SCRIPT
    if not script_path.is_file():
        raise ValueError(
            "DeployPreflight failed: deployment script %s not found under %s -- "
            "the container runtime emits it beside docker-compose.yml, so the "
            "two are generated together. Fix: regenerate the project."
            % (DEPLOY_PREFLIGHT_SCRIPT, project_dir)
        )
    spec = importlib.util.spec_from_file_location(
        _DEPLOY_PREFLIGHT_MODULE_NAME, script_path
    )
    if spec is None or spec.loader is None:
        raise ValueError(
            "DeployPreflight failed: deployment script %s cannot be loaded as a "
            "Python module (no import spec). Fix: regenerate the project." % script_path
        )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _deploy_preflight_error_class(module: ModuleType) -> type[BaseException]:
    """The exception class the deployment script raises on a failed check."""
    error_class = getattr(module, DEPLOY_PREFLIGHT_ERROR_CLASS, None)
    if not (isinstance(error_class, type) and issubclass(error_class, BaseException)):
        raise ValueError(
            "DeployPreflight failed: deployment script %s defines no exception "
            "class named %s, which the runtime declared its checks raise. The "
            "declaration and the script are generated together, so this is a "
            "generation defect. Fix: regenerate the project."
            % (DEPLOY_PREFLIGHT_SCRIPT, DEPLOY_PREFLIGHT_ERROR_CLASS)
        )
    return error_class


def _run_deploy_preflight(project_dir: Path) -> None:
    """Run the deployment script's declared pre-start checks, in declared order.

    Each check is the script's own -- what refuses ``deploy`` on the
    operator's machine refuses this harness for the same reason, with the
    same message naming every unsatisfied variable and every absent secret
    file at once. A failed check is raised as ``ValueError`` so it lands on
    the harness's existing preflight-failure path, with the script's own
    message intact.

    Raises:
        ValueError: When a declared function is not defined by the script (a
            generation defect), or when a check fails.
    """
    module = _load_deploy_script(project_dir)
    error_class = _deploy_preflight_error_class(module)
    for name in DEPLOY_PREFLIGHT_FUNCTIONS:
        check = getattr(module, name, None)
        if not callable(check):
            raise ValueError(
                "DeployPreflight failed: deployment script %s defines no function "
                "%s, which the runtime declared as a pre-start check. The "
                "declaration and the script are generated together, so this is "
                "a generation defect. Fix: regenerate the project."
                % (DEPLOY_PREFLIGHT_SCRIPT, name)
            )
        logger.info("deploy_preflight_check_started name=%s", name)
        try:
            check()
        except error_class as exc:
            raise ValueError("DeployPreflight failed in %s: %s" % (name, exc)) from exc
    logger.info(
        "deploy_preflight_passed script=%s checks=%d",
        DEPLOY_PREFLIGHT_SCRIPT,
        len(DEPLOY_PREFLIGHT_FUNCTIONS),
    )


# ---------------------------------------------------------------------------
# Fixed host-port bindings the stack makes. docker compose aborts the WHOLE
# start-up when any one of them is already held by an unrelated process on
# this machine, after every image is built and every other container has
# started -- so each is probed here, before anything starts. Declared by the
# container runtime that emits the compose file, never re-typed here.
# ---------------------------------------------------------------------------
FIXED_HOST_PORT_BINDINGS: list[dict[str, object]] = [
    {
        "label": "nginx gateway",
        "service_key": "ecommerce-api-gateway",
        "host_port": 8080,
        "host_port_env_var": "GATEWAY_PORT",
    },
    {
        "label": "Zitadel identity server",
        "service_key": "ecommerce-zitadel",
        "host_port": 8085,
        "host_port_env_var": "ZITADEL_HOST_PORT",
    },
]

#: Errno values that mean "another socket already owns this address". Python
#: maps the Windows Sockets codes onto the same names, so this is portable.
_PORT_HELD_ERRNOS: frozenset[int] = frozenset({errno.EADDRINUSE, errno.EACCES})

#: How long a loopback connect may take before the port counts as free. A
#: listener answers within milliseconds; a closed port is refused at once on
#: most stacks and after a short SYN retry on Windows.
_PORT_CONNECT_TIMEOUT_SECONDS = 2.0


def _host_port_is_held(port: int) -> bool:
    """Whether another process already owns TCP *port* on this machine.

    Two probes, because neither alone is trustworthy everywhere. A bind on all
    interfaces fails where the holder bound exclusively -- what the container
    engine's own bind will hit on Linux and macOS. A loopback connect succeeds
    wherever something is LISTENING, including a holder that bound with
    address reuse (a desktop container engine's port proxy on Windows does),
    which lets a fresh bind through and then fails the engine's bind anyway.
    Held if either says so.
    """
    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        probe.bind(("0.0.0.0", port))
    except OSError as exc:
        if exc.errno in _PORT_HELD_ERRNOS:
            return True
        raise
    finally:
        probe.close()
    client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    client.settimeout(_PORT_CONNECT_TIMEOUT_SECONDS)
    try:
        client.connect(("127.0.0.1", port))
    except OSError:
        return False
    finally:
        client.close()
    return True


def _read_env_file_values(env_file: Path) -> dict[str, str]:
    """Read ``KEY=value`` lines from the ``.env`` file compose interpolates from."""
    values: dict[str, str] = {}
    if not env_file.exists():
        return values
    for raw_line in env_file.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def _effective_fixed_host_port(
    binding: dict[str, object], env_values: dict[str, str]
) -> int:
    """Resolve the host port compose will bind for *binding*, the way compose does.

    A binding with an override variable takes the shell environment first, the
    project ``.env`` file second, and its default last -- compose's own
    precedence for ``${VAR:-default}``. A binding without one is a literal.
    """
    env_var = binding["host_port_env_var"]
    default_port = int(str(binding["host_port"]))
    if env_var is None:
        return default_port
    raw = os.environ.get(str(env_var)) or env_values.get(str(env_var))
    if raw is None or raw == "":
        return default_port
    try:
        return int(raw)
    except ValueError as exc:
        raise ValueError(
            "Host port override %s=%r is not an integer. Expected a TCP port "
            "number (1-65535); fix the value in the shell environment or .env."
            % (env_var, raw)
        ) from exc


def _port_holder_description(port: int) -> str:
    """Name what holds *port*: a container, if Docker knows one, else the OS."""
    try:
        result = subprocess.run(
            ["docker", "ps", "--filter", f"publish={port}", "--format", "{{.Names}}"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return "a process outside Docker (docker ps could not be consulted)"
    names = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    if names:
        return "container(s) %s" % ", ".join(names)
    return (
        "a process outside Docker (find it with `netstat -ano | findstr :%d` on "
        "Windows or `lsof -i :%d` elsewhere)" % (port, port)
    )


def _assert_fixed_host_ports_free(project_dir: Path) -> None:
    """Probe every fixed host port the stack binds, BEFORE ``docker compose up``.

    A port that is already held is reported with the container that wanted it,
    what holds it, and the variable that moves it -- the whole diagnosis
    compose's own ``port is already allocated`` never carries, minutes earlier
    than compose would produce it.

    Raises:
        ValueError: When any fixed host port is already held, listing every
            held port at once so one run reports the whole set.
    """
    env_values = _read_env_file_values(project_dir / ".env")
    held: list[str] = []
    for binding in FIXED_HOST_PORT_BINDINGS:
        port = _effective_fixed_host_port(binding, env_values)
        if not _host_port_is_held(port):
            continue
        remedy = (
            "set %s to a free port (shell environment or .env)"
            % binding["host_port_env_var"]
            if binding["host_port_env_var"] is not None
            else "stop whatever holds it (the port is the service's declared contract)"
        )
        held.append(
            "host port %d for %s (compose service %r) is held by %s -- %s"
            % (
                port,
                binding["label"],
                binding["service_key"],
                _port_holder_description(port),
                remedy,
            )
        )
    if held:
        raise ValueError(
            "HostPortPreflight failed: docker compose would abort with 'port is "
            "already allocated'.\n  " + "\n  ".join(held)
        )
    logger.info("host_port_preflight_passed bindings=%d", len(FIXED_HOST_PORT_BINDINGS))


def main() -> int:
    """Build, deploy, and run integration tests."""
    parser = argparse.ArgumentParser(description="Docker deployment test runner")
    parser.add_argument(
        "--keep-running", action="store_true", help="Keep containers running"
    )
    parser.add_argument("--debug", action="store_true", help="Enable debug logging")
    parser.add_argument(
        "--verbose", action="store_true", help="Show detailed output (INFO level logs)"
    )
    parser.add_argument(
        "--fresh-build",
        action="store_true",
        help="Force fresh build (--no-cache, no layer cache)",
    )
    parser.add_argument(
        "--results-dir",
        type=str,
        default=None,
        help="Directory for test results and docker logs",
    )
    args = parser.parse_args()

    # Check environment variable as alternative to --fresh-build flag
    fresh_build = (
        args.fresh_build or os.environ.get("DEPLOY_TEST_FRESH_BUILD") == "true"
    )

    # Logging levels: DEBUG -> INFO -> WARNING -> ERROR
    # Default: WARNING (quiet mode)
    # --verbose: INFO (show progress)
    # --debug: DEBUG (show everything)
    if args.debug:
        log_level = logging.DEBUG
    elif args.verbose:
        log_level = logging.INFO
    else:
        log_level = logging.WARNING

    logging.basicConfig(
        level=log_level,
        format="%(asctime)s %(levelname)s %(message)s",
    )

    config = load_config()
    health_timeout = read_int_config(
        config, "deploy", "health_check_timeout", DEFAULT_HEALTH_TIMEOUT_SECONDS
    )
    max_failures = read_int_config(
        config, "deploy", "max_failures", DEFAULT_MAX_FAILURES
    )
    compose = [*get_docker_compose_cmd(), "-p", COMPOSE_PROJECT_NAME]

    # Always refresh .env from .env.example so container gets current vars (e.g. DEBUG, JWT_*)
    project_dir = Path(__file__).parent.parent
    env_file = project_dir / ".env"
    env_example = project_dir / ".env.example"
    if env_example.exists():
        shutil.copy2(env_example, env_file)
        logger.info("copied_env_example path=%s", env_file)
        # Disable gateway rate limiting during deploy tests to prevent
        # 429 failures when many tests share the same JWT subject identity.
        with open(env_file, "a", encoding="utf-8") as fh:
            fh.write("\nDISABLE_RATE_LIMIT=true\n")
        logger.info("rate_limiting_disabled_for_tests")

    verbose = args.debug

    # Run all compose commands from project dir so compose file and .env are used
    compose_cwd = str(project_dir)

    # Create test results directory for docker logs
    if args.results_dir:
        results_dir = Path(args.results_dir)
    else:
        timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        results_dir = project_dir / ".test_results" / f"deploy-test-{timestamp}"
    results_dir.mkdir(parents=True, exist_ok=True)
    _write_deploy_environment_json(results_dir, project_dir)

    # Pre-run cleanup: tear down any leftover containers from previous runs
    logger.info("docker_pre_cleanup_started project=%s", COMPOSE_PROJECT_NAME)
    run_docker_cmd(
        [*compose, "down", "-v", "--rmi", "local", "--remove-orphans"],
        verbose=verbose,
        label="docker_pre_cleanup",
        cwd=compose_cwd,
    )

    # Remove orphaned volumes from interrupted previous runs (compose down -v only
    # removes volumes it tracks; crashed runs can leave orphaned named volumes).
    vol_result = subprocess.run(
        [
            "docker",
            "volume",
            "ls",
            "--filter",
            f"name={COMPOSE_PROJECT_NAME}",
            "--quiet",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if vol_result.returncode == 0 and vol_result.stdout.strip():
        for vol_name in vol_result.stdout.strip().splitlines():
            subprocess.run(
                ["docker", "volume", "rm", vol_name.strip()],
                capture_output=True,
                check=False,
            )
            logger.info("removed_orphan_volume name=%s", vol_name.strip())

    # ---- Shared per-system base image ----
    # Every service Dockerfile is ``FROM ecommerce-python-base:ad3cae475305``.  ``docker compose build``
    # never builds a ``FROM`` image (it only builds services defined in the compose file),
    # so the base image must exist in the local daemon BEFORE ``compose build`` is called.
    # The tag is a content hash of the union of all services' dependencies, so the build is
    # idempotent: when the union is unchanged the tag already exists and the step is a no-op.
    base_image_build_flags = ["--no-cache"] if fresh_build else []
    if not fresh_build:
        _inspect = subprocess.run(
            ["docker", "image", "inspect", "ecommerce-python-base:ad3cae475305"],
            capture_output=True,
            check=False,
        )
        _base_already_present = _inspect.returncode == 0
    else:
        _base_already_present = False
    if not _base_already_present:
        logger.info(
            "base_image_build_started tag=%s", "ecommerce-python-base:ad3cae475305"
        )
        base_build = run_docker_cmd(
            [
                "docker",
                "build",
                *base_image_build_flags,
                "-t",
                "ecommerce-python-base:ad3cae475305",
                "./python-base",
            ],
            verbose=verbose,
            label="base_image_build",
            cwd=compose_cwd,
        )
        if base_build.returncode != 0:
            logger.error("base_image_build_failed exit_code=%s", base_build.returncode)
            return 1
        logger.info(
            "base_image_build_completed tag=%s", "ecommerce-python-base:ad3cae475305"
        )
    else:
        logger.info(
            "base_image_already_present tag=%s", "ecommerce-python-base:ad3cae475305"
        )
    logger.info("docker_build_started")
    build_flags = ["--no-cache"] if fresh_build else []
    build = run_docker_cmd(
        [*compose, "build", *build_flags],
        verbose=verbose,
        label="docker_build",
        cwd=compose_cwd,
    )
    if build.returncode != 0:
        logger.error("docker_build_failed exit_code=%s", build.returncode)
        return 1
    logger.info("docker_build_completed")

    # Run the container runtime's own pre-start checks, then probe the fixed
    # host ports, BEFORE compose up. Ordering contract:
    # env refresh → runtime preflight → host ports → docker compose up.
    # The runtime's deployment script (DEPLOY_PREFLIGHT_SCRIPT) is imported and
    # its declared checks called in-process -- every variable compose requires,
    # every secret file it mounts -- so a missing value or absent secret file
    # is caught here, by the same check that refuses `deploy`, and not at
    # compose interpolation after every other container has started.
    try:
        _run_deploy_preflight(project_dir)
        _assert_fixed_host_ports_free(project_dir)
    except (ValueError, RuntimeError) as exc:
        logger.error("local_preflight_failed error=%s", exc)
        return 1

    # From compose-up onwards, ensure containers are torn down on any exit path
    failures = 0
    try:
        up = run_docker_cmd(
            [*compose, "up", "-d"], verbose=verbose, label="docker_up", cwd=compose_cwd
        )
        if up.returncode != 0 and _is_host_port_allocation_failure(up):
            # A held host port is deterministic: the same process holds it on
            # the retry. The preflight names the port and the override
            # variable; compose only names the port.
            logger.error("docker_up_failed reason=host_port_already_allocated")
            return 1
        if up.returncode != 0:
            # Infrastructure containers with restart policies may recover from
            # transient startup failures (e.g. MongoDB port-bind race in
            # docker-entrypoint.sh).  Wait for restarts, then retry once.
            logger.warning("docker_up_retrying reason=dependency_may_need_restart")
            time.sleep(15)
            up = run_docker_cmd(
                [*compose, "up", "-d"],
                verbose=verbose,
                label="docker_up_retry",
                cwd=compose_cwd,
            )
        if up.returncode != 0:
            logger.error("docker_up_failed exit_code=%s", up.returncode)
            return 1

        # Validate all containers (including init containers) are healthy
        logger.info("docker_container_health_check_started")
        if not _check_container_exit_codes(compose, cwd=compose_cwd):
            logger.error("docker_container_health_check_failed")
            failures += 1
            if failures >= max_failures:
                return 1

        # Validate database connectivity before running tests
        logger.info("database_connectivity_validation_started")
        db_containers_by_service = {
            str(service["name"]): service.get("db_containers", [])
            for service in SERVICES
        }
        if not _validate_database_connectivity(
            compose, db_containers_by_service, project_dir
        ):
            logger.warning(
                "database_connectivity_validation_failed "
                "reason=transient_infrastructure_issue "
                "recommendation=rerun_tests"
            )
            # Don't fail immediately - attempt to run tests anyway
            # but flag this as a potential transient issue

        # Wait for all services to be healthy
        service_urls: dict[str, str] = {}
        for service in SERVICES:
            name = str(service["name"])
            # NONE-ingress (data-only) services publish no host HTTP port: their
            # readiness is gated by the container HEALTHCHECK (probed inside the
            # container) and _check_container_exit_codes above, not a host probe.
            if not service.get("expose_http", True):
                logger.info(
                    "service_health_wait_skipped name=%s reason=no_host_http_ingress",
                    name,
                )
                continue
            base_url = _resolve_service_base_url(compose, service, cwd=compose_cwd)
            logger.info("service_waiting name=%s base_url=%s", name, base_url)
            if not wait_for_health(base_url, health_timeout):
                logger.error(
                    "service_health_timeout name=%s timeout_seconds=%s",
                    name,
                    health_timeout,
                )
                failures += 1
                if failures >= max_failures:
                    break
                continue
            service_urls[name] = base_url
        # Every service's host URL, keyed the way the generated per-service
        # conftest looks it up. A service that `uses` a peer reads that peer's
        # base URL from its config store, so each pytest phase needs the whole
        # map -- not just the URL of the service under test.
        service_url_env = {
            f"{str(svc['dir']).upper()}_URL": service_urls[str(svc["name"])]
            for svc in SERVICES
            if str(svc["name"]) in service_urls
        }

        # Gateway JWT auth and route-proxying tests
        if failures < max_failures:
            logger.info("gateway_auth_tests_phase_started")
            gw_env: dict[str, str] = dict(os.environ)
            if env_file.exists():
                for line in env_file.read_text(encoding="utf-8").splitlines():
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        key, _, value = line.partition("=")
                        gw_env.setdefault(
                            key.strip(), _resolve_shell_default(value.strip())
                        )
            gw_failures = run_gateway_auth_tests(
                compose=compose,
                service_urls=service_urls,
                env=gw_env,
                results_dir=results_dir,
                verbose=args.debug,
                cwd=compose_cwd,
            )
            failures += gw_failures
            if gw_failures > 0:
                logger.error("gateway_auth_tests_phase_failed failures=%s", gw_failures)
            else:
                logger.info("gateway_auth_tests_phase_passed")

        # Seed every authored storage fixture object into its bucket BEFORE the
        # spec and integration phases: a test body that reads an object needs
        # it to exist first. A seeding failure ends the run here -- the tests
        # would otherwise fail on a missing key that hides the real cause.
        if failures < max_failures:
            logger.info("storage_fixture_seeding_started")
            try:
                seeded_objects = _seed_storage_fixtures(compose, project_dir)
            except RuntimeError as exc:
                logger.error("storage_fixture_seeding_failed error=%s", exc)
                return 1
            logger.info("storage_fixture_seeding_completed objects=%s", seeded_objects)

        if failures < max_failures:
            # Run spec tests first (if any services have them)
            logger.info("spec_tests_phase_started")
            spec_failures = run_spec_tests(
                compose=compose,
                db_containers_by_service=db_containers_by_service,
                service_url_env=service_url_env,
                results_dir=results_dir,
                verbose=args.debug,
            )
            failures += spec_failures
            if spec_failures > 0:
                logger.error("spec_tests_phase_failed failures=%s", spec_failures)
            else:
                logger.info("spec_tests_phase_passed")

        # Run integration tests
        if failures < max_failures:
            logger.info("integration_tests_phase_started")
            for service in SERVICES:
                name = str(service["name"])
                service_dir = str(service["dir"])
                expose_http = bool(service.get("expose_http", True))
                base_url = (
                    _resolve_service_base_url(compose, service, cwd=compose_cwd)
                    if expose_http
                    else ""
                )
                logger.info("service_integration_tests_started name=%s", name)
                db_containers = service.get("db_containers")
                if not run_integration_tests(
                    service_dir,
                    base_url,
                    compose=compose,
                    service_url_env=service_url_env,
                    db_containers=db_containers,
                    cache_container=service.get("cache_container"),
                    mq_container=service.get("mq_container"),
                    storage_container=service.get("storage_container"),
                    verbose=args.debug,
                    results_dir=results_dir,
                    expose_http=expose_http,
                ):
                    logger.error("service_integration_tests_failed name=%s", name)
                    failures += 1
                    if failures >= max_failures:
                        break
    finally:
        # Save docker logs BEFORE teardown so containers still exist
        _save_docker_logs(compose, results_dir, cwd=compose_cwd)
        if not args.keep_running:
            logger.info("docker_teardown_started")
            run_docker_cmd(
                [*compose, "down", "-v", "--rmi", "local", "--remove-orphans"],
                verbose=verbose,
                cwd=compose_cwd,
            )

    # Categorize and report failures
    logic_failures, transient_failures = _write_deploy_failures_artifacts(
        results_dir, project_dir
    )

    # Print summary with visual markers
    print("\n" + "=" * 80)
    print("DEPLOYMENT TEST SUMMARY")
    print("=" * 80)
    if logic_failures == 0 and transient_failures == 0:
        # ASCII-only: Windows cp1252 consoles cannot encode checkmark/bullets.
        print("[OK] All tests passed")
        logger.info("deployment_tests_passed")
        return 0
    else:
        if logic_failures > 0:
            print(f"[FAIL] LOGIC FAILURES: {logic_failures}")
            print("  -> Code bugs or validation issues")
            print(f"  -> See: {results_dir / 'deploy-failures-logic.log'}")
        if transient_failures > 0:
            print(f"[WARN] TRANSIENT FAILURES: {transient_failures}")
            print("  -> Infrastructure/environment issues")
            print("  -> Recommendation: Re-run tests to verify reproducibility")
            print(f"  -> See: {results_dir / 'deploy-failures-transient.log'}")
        print(f"\nFull details: {results_dir / 'failures.json'}")
        print("=" * 80 + "\n")

        # Exit code strategy:
        # - 1 = Logic failures (code bugs) - must be fixed
        # - 2 = Only transient failures (infrastructure) - can retry
        if logic_failures > 0:
            logger.error(
                "deployment_tests_failed logic_failures=%s transient_failures=%s exit_code=1",
                logic_failures,
                transient_failures,
            )
            return 1
        else:
            logger.warning(
                "deployment_tests_transient_failures transient_failures=%s exit_code=2",
                transient_failures,
            )
            return 2


if __name__ == "__main__":
    sys.exit(main())
