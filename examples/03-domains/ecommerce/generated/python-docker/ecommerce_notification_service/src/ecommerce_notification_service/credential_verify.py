"""Gateway credential verification endpoint.

Auto-generated by datrix-codegen-python. Do not edit manually.

Used by the gateway's ``auth_request`` to decide whether a request may be
forwarded: it answers 200 for a valid bearer JWT, or for a request carrying no
``Authorization`` header and exactly one admitted API-key header whose value is
within the presented-key bounds. The gateway forwards only the key headers the
requested route admits, so a key reaches this check only on such a route. The
edge checks a key's presence, never its validity: the service's own credential
chain verifies the key on the next hop, so a key costs one owner round trip,
not two.

A bearer is verified by the gateway's declared JWT model: the service's own
auth chain when verification is delegated to this service, otherwise the
asymmetric key the secrets resolver returns for ``jwt_public_key``.
"""

