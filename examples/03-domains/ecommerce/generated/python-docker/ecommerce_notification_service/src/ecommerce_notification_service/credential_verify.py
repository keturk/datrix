_BEARER_PREFIX: str = "Bearer "
_STATUS_ALLOW: int = 200
_STATUS_DENY: int = 401
_STATUS_FORBIDDEN: int = 403

#: Presented-key bounds: 32 to 256 printable ASCII characters (0x21-0x7E).
_KEY_MIN_LENGTH: int = 32
_KEY_MAX_LENGTH: int = 256
_KEY_MIN_CHAR: int = 0x21
_KEY_MAX_CHAR: int = 0x7E

#: Every API-key header a credential-checked gateway route admits, lower-cased.
_API_KEY_HEADERS: frozenset[str] = frozenset(
    {
        "x-customer-api-key",
    }
)


def _presented_key_in_bounds(value: str) -> bool:
    """True when *value* is 32-256 printable ASCII characters. Never logs the value."""
    if not _KEY_MIN_LENGTH <= len(value) <= _KEY_MAX_LENGTH:
        return False
    return all(_KEY_MIN_CHAR <= ord(char) <= _KEY_MAX_CHAR for char in value)


def _admitted_key_presented(request: Request) -> bool:
    """True when exactly one admitted key header is present, sent once, with an in-bounds value.

    Two admitted key headers, or one sent more than once, are ambiguous and
    refused, exactly as the service's own credential chain refuses them.
    """
    presented: list[str] = []
    for header_name in _API_KEY_HEADERS:
        values = request.headers.getlist(header_name)
        if len(values) > 1:
            return False
        if values and values[0]:
            presented.append(values[0])
    if len(presented) != 1:
        return False
    return _presented_key_in_bounds(presented[0])


_REJECTED_ALG_PREFIXES: tuple[str, ...] = ("HS",)
_REJECTED_ALG_NONE: str = "none"


def _algorithm_is_asymmetric(algorithm: str) -> bool:
    """False for a symmetric (HS*) or ``none`` algorithm: a public key must never be an HMAC secret."""
    if algorithm.lower() == _REJECTED_ALG_NONE:
        return False
    return not any(algorithm.startswith(prefix) for prefix in _REJECTED_ALG_PREFIXES)


async def _bearer_status(token: str, request: Request) -> int:
    """The gateway status for *token*: allow, deny (401) or forbidden (403)."""
    algorithm = get_settings().jwt_algorithm
    if not _algorithm_is_asymmetric(algorithm):
        # Fail closed: a configuration that cannot verify safely verifies nothing.
        logger.error(
            "gateway_credential_verify_config_error reason_code=%s algorithm=%s",
            "provider_config_error",
            algorithm,
        )
        return _STATUS_DENY
    try:
        # Resolved through the secrets resolver on every verification
        # (RESOLVE_ON_ACCESS); never snapshotted into frozen settings, never
        # read from an environment variable or a file path.
        public_key = await get_secret("jwt_public_key")
    except (KeyError, RuntimeError, ImportError) as exc:
        logger.error(
            "gateway_credential_verify_config_error reason_code=%s error=%s",
            "provider_config_error",
            type(exc).__name__,
        )
        return _STATUS_DENY
    try:
        jwt.decode(
            token,
            public_key,
            algorithms=[algorithm],
            options={"verify_exp": True, "require": ["exp"]},
        )
    except InvalidTokenError as exc:
        logger.debug("gateway_credential_verify_rejected error=%s", type(exc).__name__)
        return _STATUS_DENY
    return _STATUS_ALLOW


@_credential_verify_router.get("/internal/credential-verify", include_in_schema=False)
async def credential_verify(request: Request) -> Response:
    """Decide one gateway ``auth_request``: 200 allows the request, 401 denies it.

    A request carrying ``Authorization`` is decided by its bearer token alone --
    a key header beside it never rescues an invalid or non-bearer
    ``Authorization``. A request without ``Authorization`` is allowed only when
    it presents exactly one admitted, in-bounds key header. A bearer that
    verifies but whose principal the auth chain refuses answers 403.
    """
    auth_header = request.headers.get("authorization")
    if auth_header is not None:
        if not auth_header.startswith(_BEARER_PREFIX):
            return Response(status_code=_STATUS_DENY)
        token = auth_header[len(_BEARER_PREFIX) :]
        return Response(status_code=await _bearer_status(token, request))
    if _admitted_key_presented(request):
        return Response(status_code=_STATUS_ALLOW)
    logger.debug("gateway_credential_verify_rejected reason=no_admitted_credential")
    return Response(status_code=_STATUS_DENY)


