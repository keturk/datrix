from __future__ import annotations

import contextvars
import uuid

from starlette.requests import Request
from starlette.types import ASGIApp, Receive, Scope, Send

_current_request: contextvars.ContextVar[Request | None] = contextvars.ContextVar(
    "datrix_current_request", default=None
)


class RequestContextMiddleware:
    """Bind the active HTTP request to the request-context variable."""

    def __init__(self, app: ASGIApp) -> None:
        self._app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self._app(scope, receive, send)
            return
        token = _current_request.set(Request(scope))
        try:
            await self._app(scope, receive, send)
        finally:
            _current_request.reset(token)


def current_request() -> Request:
    """Return the HTTP request being served on this call path.

    Raises:
        RuntimeError: When no HTTP request is active -- the caller is a job, a
            consumer, or startup code, where request context does not exist.
    """
    request = _current_request.get()
    if request is None:
        raise RuntimeError(
            "No active HTTP request: a Request.* accessor was evaluated outside "
            "an HTTP request (a job, a consumer, or startup). Request context "
            "exists only on the call path of a route handler; pass the value in "
            "as a parameter when the function must also run elsewhere."
        )
    return request


def current_user_id() -> str | None:
    """Resolved id of the authenticated principal, or ``None`` on an anonymous request.

    ``request.state.user_id`` is written by the auth dependency for a user token
    and for a service token alike; an anonymous request never sets it.
    """
    return getattr(current_request().state, "user_id", None)


def current_tenant_id() -> uuid.UUID | None:
    """Tenant of the active request, or ``None`` when tenancy did not resolve one."""
    return getattr(current_request().state, "tenant_id", None)


def current_client_ip() -> str:
    """Remote address of the active request; empty when the transport reports none."""
    client = current_request().client
    if client is None:
        return ""
    return client.host
