async def _create_enum_types(engine_conn: AsyncConnection, metadata: MetaData) -> None:
    """Create PostgreSQL enum types for columns with suppressed DDL events.

    Entity models use ``_create_events=False`` so Alembic manages type DDL
    in production.  ``metadata.create_all()`` skips those types, causing
    ``CREATE TABLE`` to fail when the column references an enum type that
    does not exist yet.  This helper creates them explicitly before table
    creation using a duplicate-safe wrapper.
    """
    seen: set[tuple[str | None, str]] = set()
    for table in metadata.sorted_tables:
        for col in table.columns:
            if not isinstance(col.type, SAEnum) or not col.type.name:
                continue
            type_name = col.type.name
            type_schema = col.type.schema
            key = (type_schema, type_name)
            if key in seen:
                continue
            seen.add(key)
            # Schema-qualify the type when the enum declares a schema, so the
            # test database creates it in the same schema the models reference
            # (matching the migration-generated CREATE TYPE), not wherever the
            # connection search_path points.
            qualified = (
                f'"{type_schema}"."{type_name}"' if type_schema else f'"{type_name}"'
            )
            values = ", ".join(f"'{v}'" for v in col.type.enums)
            await engine_conn.execute(
                text(
                    f"DO $$ BEGIN CREATE TYPE {qualified} AS ENUM ({values}); "
                    f"EXCEPTION WHEN duplicate_object OR unique_violation THEN null; END $$;"
                )
            )


