    if not host:
        raise RuntimeError(
            "SMTP host resolved empty for secret handle 'smtp_host'. Ensure the "
            "secret is provisioned with a non-empty value in the secrets backend."
        )
    port_raw = await get_secret("smtp_port")
    if not port_raw:
        raise RuntimeError(
            "SMTP port resolved empty for secret handle 'smtp_port'. Ensure the "
            "secret is provisioned with a non-empty value (e.g. '587') in the "
            "secrets backend."
        )
    try:
        port = int(port_raw)
    except ValueError as exc:
        raise RuntimeError(
            "SMTP port secret handle 'smtp_port' resolved to a non-numeric value. "
            "Expected an integer port number (e.g. '587'); provision a numeric "
            "value in the secrets backend."
        ) from exc
