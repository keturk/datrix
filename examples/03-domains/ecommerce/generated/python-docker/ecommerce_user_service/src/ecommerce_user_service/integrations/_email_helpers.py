def _email_send_smtp_background(payload: dict[str, object]) -> None:
    """Send email via SMTP in a background thread (fire-and-forget for sync contexts).

    The thread owns its own event loop, so the async settings resolution runs there
    rather than on the caller's (synchronous) stack. Delivery is best-effort: every
    failure is logged and swallowed, matching the fire-and-forget contract of the
    lifecycle-hook call sites this serves.
    """

    def _send() -> None:
        try:
            asyncio.run(_email_send_smtp(payload))
        except Exception as exc:
            _logger.warning(
                "email_send_failed provider=smtp to=%s error=%s", payload.get("to"), exc
            )

    thread = threading.Thread(target=_send, daemon=True)
    thread.start()


async def _email_send_smtp(payload: dict[str, object]) -> bool:
    """Send email via SMTP.

    A delivery failure propagates: an awaited DSL call site wraps this in its own
    try/catch and must be able to record the true Sent/Failed outcome. The
    fire-and-forget ``_email_send_smtp_background`` variant owns its own swallow.
    """
    from email.message import EmailMessage

    import aiosmtplib

    smtp_host, smtp_port, smtp_username, smtp_password = await _smtp_settings()

    to = str(payload["to"])
    subject = str(payload.get("subject", ""))
    body = str(payload.get("body", ""))
    options = {k: v for k, v in payload.items() if k not in ("to", "subject", "body")}

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = _get_sender(options)
    msg["To"] = to
    msg.set_content(body)
    await aiosmtplib.send(
        msg,
        hostname=smtp_host,
        port=smtp_port,
        username=smtp_username or None,
        password=smtp_password or None,
    )
    return True


async def _email_send_template_smtp(payload: dict[str, object]) -> bool:
    """Render an inline Jinja2 template and send via SMTP.

    Failures propagate to the awaited DSL call site (see ``_email_send_smtp``).
    """
    from jinja2 import StrictUndefined, Template

    logical = str(payload.get("template", ""))
    if logical not in _EMAIL_INLINE_TEMPLATES:
        raise KeyError(
            f"Unknown email template {logical!r}. "
            f"Available: {sorted(_EMAIL_INLINE_TEMPLATES)!r}"
        )
    data_raw = payload.get("data", {})
    data: dict[str, object] = data_raw if isinstance(data_raw, dict) else {}
    source = _EMAIL_INLINE_TEMPLATES[logical]
    rendered = Template(source, undefined=StrictUndefined).render(**data)
    subject = str(payload.get("subject", logical))
    return await _email_send_smtp(
        {"to": payload["to"], "subject": subject, "body": rendered}
    )


async def _email_send_bulk_smtp(
    recipients: list[str],
    subject: str,
    body: str,
) -> list[bool]:
    results: list[bool] = []
    for r in recipients:
        results.append(
            await _email_send_smtp({"to": r, "subject": subject, "body": body})
        )
    return results
