def _public_path_matches(pattern: str, request_path: str) -> bool:
    """Return True when request_path matches the DSL-declared public path pattern.

    Segment-level match only: the pattern must describe the exact path depth.
    Segments prefixed with ``:`` are path parameters that match any non-empty
    segment.  No prefix matching — ``/api/v1/books`` does NOT match
    ``/api/v1/books/{id}/sub-resource``, preventing protected sub-resource
    endpoints from being accidentally excluded by a shorter public pattern.

    Args:
        pattern: DSL path pattern, e.g. ``"/api/v1/books/:id"`` or
            ``"/api/v1/books"``.
        request_path: Actual URL path from the request.
    """
    pattern_parts = pattern.split("/")
    request_parts = request_path.split("/")
    if len(pattern_parts) != len(request_parts):
        return False
    return all(
        _public_segment_matches(p, r) for p, r in zip(pattern_parts, request_parts)
    )


def _public_segment_matches(pattern_segment: str, request_segment: str) -> bool:
    """Return True when one request segment matches one DSL pattern segment.

    A literal segment matches only itself.  A ``:name`` segment matches any
    non-empty segment; ``:name.ext`` additionally requires the request segment
    to carry that exact extension after a non-empty value.
    """
    if not pattern_segment.startswith(":"):
        return pattern_segment == request_segment
    _name, dot, extension = pattern_segment.partition(".")
    if not dot:
        return True
    suffix = dot + extension
    return request_segment.endswith(suffix) and len(request_segment) > len(suffix)


def is_path_excluded(request_method: str, request_path: str) -> bool:
    """Return True if this request should bypass JWT auth.

    Infra paths (``_EXCLUDE_INFRA_PATHS``) bypass auth for every HTTP method
    using prefix matching (sub-paths of infra routes are also infra).
    DSL public paths (``_EXCLUDE_PUBLIC_METHOD_PATHS``) bypass auth only for the
    exact HTTP method declared ``auth(public)`` in the DSL, and only when the
    request path matches the declared pattern at segment level (``:``: prefix
    segments match any single path segment).  No prefix matching is applied to
    public routes, so ``/api/v1/books`` does not accidentally exclude
    ``/api/v1/books/{id}/book_tags``.

    Static-before-param precedence: a request whose path exactly matches a
    registered STATIC route (``_STATIC_ROUTE_METHOD_PATHS``) is that route, and a
    PUBLIC ``:param`` pattern must never shadow it -- FastAPI resolves the static
    route first. So ``GET /products/recommended`` reaches JWT validation even
    though the public ``GET /products/:id`` pattern would otherwise match its
    ``:id`` wildcard against the ``recommended`` segment.

    Args:
        request_method: HTTP method string (e.g. ``"GET"``); compared
            case-insensitively.
        request_path: URL path from the request (e.g. ``"/api/v1/books"``).
    """
    for pattern in _EXCLUDE_INFRA_PATHS:
        if request_path == pattern or request_path.startswith(pattern + "/"):
            return True
    method = request_method.lower()
    request_route = (method, request_path)
    # An exact PUBLIC path (static, e.g. GET /products or GET /products/search) is
    # excluded regardless of any sibling wildcard.
    if request_route in _EXCLUDE_PUBLIC_METHOD_PATHS:
        return True
    # A request that exactly matches a registered STATIC route is that route, not a
    # ``:param`` sibling: FastAPI resolves static before ``/{param}``. Never let a
    # PUBLIC ``:param`` pattern shadow a protected static route.
    if request_route in _STATIC_ROUTE_METHOD_PATHS:
        return False
    # PUBLIC ``:param`` patterns -- reached only when the request path is not itself
    # a registered static route.
    for path_method, pattern in _EXCLUDE_PUBLIC_METHOD_PATHS:
        if method == path_method and _public_path_matches(pattern, request_path):
            return True
    return False


