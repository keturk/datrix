"""Resolve every client runtime config's late-bound client id.

Generated by Datrix -- do not edit manually.

A one-shot compose job. A public client the local identity provider provisions
has no id until its applier mints one, so the generated runtime config names
the reference the id is written under. This job runs after the applier and
writes each config's deployed copy with the minted id in place of the
reference -- the only copy a static site serves or a mobile build embeds. A
missing id fails the job, and every site that depends on it never starts:
there is no fallback id.
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Callable
from pathlib import Path

#: The runtime config's identity block and its two client-id members -- the
#: same names `client_runtime_config` declares.
RUNTIME_CONFIG_IDENTITY_KEY = "identity"
RUNTIME_CONFIG_CLIENT_ID_KEY = "clientId"
RUNTIME_CONFIG_CLIENT_ID_REF_KEY = "clientIdRef"

#: What a provisioned OAuth2 client id may look like before it is written into
#: a file a browser loads: a GUID, a Cognito app-client id, a Zitadel
#: `<digits>@<project>` id. Anything else -- whitespace, a quote, markup, an
#: empty value -- is refused rather than served.
_PROVISIONED_CLIENT_ID_SHAPE = re.compile(r"[A-Za-z0-9][A-Za-z0-9@._:-]{0,255}")


class ClientRuntimeResolutionError(RuntimeError):
    """A runtime config's late-bound client id could not be resolved."""


def resolve_client_runtime_config(
    generated_path: Path,
    resolved_path: Path,
    lookup_client_id: Callable[[str], str | None],
) -> str | None:
    """Write *resolved_path*: *generated_path* with its client-id reference resolved.

    A config whose identity block already carries a client id (a declared,
    external registration), or that has no identity block, is copied
    unchanged, so every client is always handed the deployed copy.

    Args:
        generated_path: The generated runtime config.
        resolved_path: Where the deployed copy is written (parents created).
        lookup_client_id: Returns the id the platform provisioned under the
            given reference, or ``None`` when it publishes none.

    Returns:
        The reference that was resolved, or ``None`` when there was none.

    Raises:
        ClientRuntimeResolutionError: The generated config is missing or is
            not a JSON object, carries both or neither of the client id and
            its reference, or the platform publishes no well-formed id under
            the reference.
    """
    if not generated_path.is_file():
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' does not exist. It is produced by "
            "generation; regenerate the project before deploying."
        )
    try:
        config = json.loads(generated_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' is not valid JSON ({exc}). "
            "Regenerate the project; never edit the generated file by hand."
        ) from exc
    if not isinstance(config, dict):
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' is not a JSON object. Regenerate "
            "the project; never edit the generated file by hand."
        )
    reference = _resolve_identity_block(generated_path, config, lookup_client_id)
    resolved_path.parent.mkdir(parents=True, exist_ok=True)
    resolved_path.write_text(
        json.dumps(config, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return reference


def _resolve_identity_block(
    generated_path: Path,
    config: dict[str, object],
    lookup_client_id: Callable[[str], str | None],
) -> str | None:
    """Replace the identity block's reference with the provisioned id, in place."""
    identity = config.get(RUNTIME_CONFIG_IDENTITY_KEY)
    if identity is None:
        return None
    if not isinstance(identity, dict):
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' has a non-object "
            f"'{RUNTIME_CONFIG_IDENTITY_KEY}' block. Regenerate the project."
        )
    has_id = RUNTIME_CONFIG_CLIENT_ID_KEY in identity
    has_ref = RUNTIME_CONFIG_CLIENT_ID_REF_KEY in identity
    if has_id == has_ref:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' carries "
            f"{'both' if has_id else 'neither'} of '{RUNTIME_CONFIG_CLIENT_ID_KEY}' "
            f"and '{RUNTIME_CONFIG_CLIENT_ID_REF_KEY}'; exactly one is required. "
            "Regenerate the project."
        )
    if has_id:
        return None
    reference = identity.pop(RUNTIME_CONFIG_CLIENT_ID_REF_KEY)
    if not isinstance(reference, str) or not reference:
        raise ClientRuntimeResolutionError(
            f"Runtime config '{generated_path}' names no client-id reference. "
            "Regenerate the project."
        )
    client_id = lookup_client_id(reference)
    if client_id is None or not _PROVISIONED_CLIENT_ID_SHAPE.fullmatch(client_id):
        found = "nothing" if client_id is None else "a malformed value"
        raise ClientRuntimeResolutionError(
            f"The platform published {found} under '{reference}', the client id "
            f"runtime config '{generated_path}' signs users in with. The "
            "registration is provisioned by this deployment's infrastructure; "
            "deploy the infrastructure first, and check that it created the "
            "registration. No client is deployed without its provisioned id."
        )
    identity[RUNTIME_CONFIG_CLIENT_ID_KEY] = client_id
    return reference


#: Where the applier writes each minted client id, one file per reference.
MINTED_CLIENT_ID_DIR = Path("/identity-clients")
#: The generated runtime configs (read-only) and their deployed copies.
GENERATED_DIR = Path("/runtime-config/generated")
RESOLVED_DIR = Path("/runtime-config/resolved")
#: Every runtime config generated for this profile.
RUNTIME_CONFIG_FILES: tuple[str, ...] = (
    "client-runtime-storefront-angular.test.json",
    "client-runtime-storefront-flutter.test.json",
    "client-runtime-admin-angular.test.json",
)

#: A reference is an alphanumeric identifier; anything else is refused rather
#: than joined onto a path.
_REFERENCE_SHAPE = re.compile(r"[A-Za-z][A-Za-z0-9]*")


def minted_client_id(reference: str) -> str | None:
    """The id the applier wrote under *reference*, or ``None``."""
    if not _REFERENCE_SHAPE.fullmatch(reference):
        return None
    path = MINTED_CLIENT_ID_DIR / reference
    if not path.is_file():
        return None
    return path.read_text(encoding="utf-8").strip()


def main() -> int:
    """Resolve every runtime config; exit non-zero on the first failure."""
    for name in RUNTIME_CONFIG_FILES:
        try:
            reference = resolve_client_runtime_config(
                GENERATED_DIR / name, RESOLVED_DIR / name, minted_client_id
            )
        except ClientRuntimeResolutionError as exc:
            print(f"ERROR: {name}: {exc}", file=sys.stderr)
            return 1
        source = (
            f"client id from '{reference}'" if reference else "no late-bound client id"
        )
        print(f"resolved {name} ({source})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
