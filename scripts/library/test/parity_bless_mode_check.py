"""Regression gate: multi-language-single-process blessing must produce the
SAME manifests as blessing each language in total isolation (its own process).

WHY THIS EXISTS
----------------
``cmd_bless`` (:mod:`reference_example_parity`) generates an example once per
registered language, all in ONE process, in a loop. A shared, non-process-
isolated scratch/cache path let two concurrent invocations of that process
interleave writes into the same physical directory, producing a manifest that
was a corrupted hybrid of two runs -- silently, with exit code 0. That defect
corrupted at least seven committed baselines before it was found by hand
(comparing a suspiciously-small blessed manifest against a fresh isolated
regeneration). Nothing had ever compared the two blessing modes automatically,
which is why it went undetected. This gate is that comparison, made permanent.

It generates ONE example two ways -- once with every registered language in a
single process (mirrors ``cmd_bless``/``cmd_check`` exactly), once with each
language generated by its own freshly-spawned process (true isolation, no
shared Python-level or OS-level state at all) -- and asserts the two produce
byte-identical manifests, per language. A divergence here means the two
blessing modes disagree, which is exactly the shape of the corruption this
gate exists to catch before it reaches a committed baseline again.

Not a pytest suite (the showcase repo hosts none) -- a script under
``scripts/test``, run through its ``.ps1`` wrapper like every other repo-level
gate in this file's package.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

_LIBRARY_DIR = Path(__file__).resolve().parent.parent
if _LIBRARY_DIR.exists() and str(_LIBRARY_DIR) not in sys.path:
    sys.path.insert(0, str(_LIBRARY_DIR))

from test.reference_example_parity import (  # noqa: E402
    EXAMPLES_ROOT,
    PARITY_EXAMPLE_RELPATH,
    WORKSPACE_ROOT,
    build_manifest,
    generate_example,
    target_languages,
)

EXIT_OK = 0
EXIT_FAIL = 1
EXIT_USAGE = 2

#: Scratch root for this gate's own generated trees -- never CACHE_ROOT/
#: SCRATCH_ROOT (those belong to the module under test; sharing them here
#: would undermine the very isolation being proven).
_SCRATCH_ROOT: Path = WORKSPACE_ROOT / ".test-output" / "parity-bless-mode-check"


def _run_isolated(system_dtrx: Path, language: str, out_manifest: Path) -> None:
    """Generate ``system_dtrx`` for ONE language and write its manifest as JSON.

    Invoked as this module's own ``--isolated-language`` entry point, in a
    freshly-spawned subprocess -- so it shares no Python-level state (module
    caches, plugin-registry singletons) and no OS-level state (open handles,
    the parent's scratch directories) with any other language's generation.

    Args:
        system_dtrx: Absolute path to the example's ``system.dtrx``.
        language: The single registered language to generate.
        out_manifest: Where to write the resulting manifest as JSON.
    """
    from datrix_language.registration import register_all

    register_all()
    tree = _SCRATCH_ROOT / "isolated" / language
    generate_example(system_dtrx, tree, language)
    manifest = build_manifest(tree)
    out_manifest.parent.mkdir(parents=True, exist_ok=True)
    out_manifest.write_text(json.dumps(manifest), encoding="utf-8")


def _generate_isolated_manifest(system_dtrx: Path, language: str) -> dict[str, str]:
    """Spawn a fresh process to generate *language* alone, return its manifest.

    Args:
        system_dtrx: Absolute path to the example's ``system.dtrx``.
        language: The registered language to generate in isolation.

    Returns:
        The freshly generated tree's manifest (relative path -> sha256).

    Raises:
        RuntimeError: If the isolated subprocess exits non-zero.
    """
    out_manifest = _SCRATCH_ROOT / "isolated-out" / f"{language}.json"
    out_manifest.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [
            sys.executable,
            str(Path(__file__).resolve()),
            "--isolated-language",
            language,
            "--example-dtrx",
            str(system_dtrx),
            "--out",
            str(out_manifest),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"Isolated generation subprocess for language={language!r} exited "
            f"{result.returncode}.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
    return dict(json.loads(out_manifest.read_text(encoding="utf-8")))


def _generate_combined_manifests(
    system_dtrx: Path, languages: list[str]
) -> dict[str, dict[str, str]]:
    """Generate every language for one example in ONE process -- mirrors
    :func:`reference_example_parity.cmd_bless`'s own loop exactly.

    Args:
        system_dtrx: Absolute path to the example's ``system.dtrx``.
        languages: Registered languages to generate, in the same sorted order
            ``cmd_bless`` uses.

    Returns:
        Mapping of language -> manifest (relative path -> sha256).
    """
    from datrix_language.registration import register_all

    register_all()
    manifests: dict[str, dict[str, str]] = {}
    for language in languages:
        tree = _SCRATCH_ROOT / "combined" / language
        generate_example(system_dtrx, tree, language)
        manifests[language] = build_manifest(tree)
    return manifests


def _diff_summary(
    language: str, combined: dict[str, str], isolated: dict[str, str]
) -> str | None:
    """Return a mismatch report for one language, or ``None`` when identical.

    Args:
        language: The language being compared, for the message.
        combined: Manifest produced by the single-process multi-language run.
        isolated: Manifest produced by that language's own isolated process.

    Returns:
        A report naming every differing/added/removed/changed path, or
        ``None`` when the two manifests are identical.
    """
    if combined == isolated:
        return None
    combined_paths = set(combined)
    isolated_paths = set(isolated)
    missing_in_combined = sorted(isolated_paths - combined_paths)
    extra_in_combined = sorted(combined_paths - isolated_paths)
    changed = sorted(
        p
        for p in combined_paths & isolated_paths
        if combined[p] != isolated[p]
    )
    lines = [
        f"  MODE MISMATCH language={language} "
        f"combined={len(combined)} files isolated={len(isolated)} files",
    ]
    if missing_in_combined:
        lines.append(
            f"    Present in isolated generation but MISSING from the "
            f"single-process multi-language run ({len(missing_in_combined)}):"
        )
        lines.extend(f"      {p}" for p in missing_in_combined[:40])
    if extra_in_combined:
        lines.append(
            f"    Present in the single-process run but missing from "
            f"isolated generation ({len(extra_in_combined)}):"
        )
        lines.extend(f"      {p}" for p in extra_in_combined[:40])
    if changed:
        lines.append(f"    Same path, different content ({len(changed)}):")
        lines.extend(f"      {p}" for p in changed[:40])
    return "\n".join(lines)


def cmd_check(example_relpath: str) -> int:
    """Run the mode-parity comparison for one example, all registered languages.

    Args:
        example_relpath: Path relative to :data:`EXAMPLES_ROOT`.

    Returns:
        Process exit code: 0 = every language's combined-mode manifest equals
        its isolated-mode manifest, 1 = at least one mismatch.
    """
    system_dtrx = EXAMPLES_ROOT / example_relpath / "system.dtrx"
    if not system_dtrx.is_file():
        print(f"ERROR: no system.dtrx at {system_dtrx}", file=sys.stderr)
        return EXIT_USAGE

    languages = sorted(target_languages())
    print(
        f"Bless-mode parity check: {example_relpath} x {len(languages)} "
        f"language(s): {', '.join(languages)}."
    )
    print("Generating combined (single-process, multi-language -- mirrors cmd_bless)...")
    combined = _generate_combined_manifests(system_dtrx, languages)

    problems: list[str] = []
    for language in languages:
        print(f"Generating isolated (fresh process) [{language}]...")
        isolated = _generate_isolated_manifest(system_dtrx, language)
        mismatch = _diff_summary(language, combined[language], isolated)
        if mismatch is not None:
            problems.append(mismatch)
        else:
            print(f"  OK    [{language}] {len(combined[language])} files, identical both modes")

    print()
    if problems:
        print("BLESS-MODE PARITY FAILED -- combined and isolated generation disagree:")
        for p in problems:
            print(p)
        print()
        print(
            "This is the exact defect class that corrupted committed parity baselines: "
            "a single-process, multi-language bless produced different output than "
            "generating each language in isolation. Investigate for a reintroduced "
            "shared-scratch-path or process-global state leak before blessing anything."
        )
        return EXIT_FAIL

    print(
        f"BLESS-MODE PARITY PASSED: all {len(languages)} language(s) produce identical "
        f"manifests whether blessed in one process or generated in isolation."
    )
    return EXIT_OK


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Assert cmd_bless's single-process multi-language generation matches "
            "generating each language in a fully isolated process."
        )
    )
    parser.add_argument(
        "--example",
        default=PARITY_EXAMPLE_RELPATH,
        help="Path relative to datrix/examples/. Defaults to the parity gate's own corpus example.",
    )
    parser.add_argument(
        "--isolated-language",
        default=None,
        help=argparse.SUPPRESS,  # internal: this module's own subprocess entry point
    )
    parser.add_argument("--example-dtrx", default=None, help=argparse.SUPPRESS)
    parser.add_argument("--out", default=None, help=argparse.SUPPRESS)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv if argv is not None else sys.argv[1:])
    if args.isolated_language is not None:
        # Internal subprocess entry point (see _generate_isolated_manifest).
        if args.example_dtrx is None or args.out is None:
            print("ERROR: --isolated-language requires --example-dtrx and --out", file=sys.stderr)
            return EXIT_USAGE
        _run_isolated(Path(args.example_dtrx), args.isolated_language, Path(args.out))
        return EXIT_OK
    return cmd_check(args.example)


if __name__ == "__main__":
    sys.exit(main())
