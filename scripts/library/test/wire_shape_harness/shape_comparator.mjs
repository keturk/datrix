// THE response-shape comparator for the wire-shape round-trip gate.
//
// One implementation, two callers: the gate's real path (run.mjs, feeding it
// the bodies a booted backend actually returned) and the gate's non-vacuity
// self-test (the Python engine, feeding it a synthetic payload plus a
// synthetic interface). Both reach `compareResponseShapes` -- the self-test
// exercises the code that runs, never a copy of it, so severing this function
// turns the self-test red.
//
// How the comparison works, and why it is not `const _: T = response`.
// The generated contract types brand their string aliases (a UUID is
// `string & {readonly [brand]: 'Uuid'}`), precisely so an arbitrary string
// cannot be assigned where a wire shape is expected. A JSON payload is
// therefore NEVER assignable to a generated response interface, and an
// assignment probe would report every route as a mismatch. So the comparator
// compares the two things branding does not obscure, at every node of the
// payload:
//
//   * the PROPERTY-NAME SETS -- every required property of the declared type
//     is present in the payload, and every payload property is declared. This
//     is the check that catches a response field transcribed in the wrong
//     case, which is the defect class this gate exists for.
//   * the VALUE KIND -- string / number / boolean / array / null against the
//     declared type with branding erased.
//
// Both are expressed as TypeScript type-level assertions compiled by the real
// `tsc`, so the declared side is read by the compiler from the generated
// `.ts` sources rather than by a parser of our own that could disagree with
// them. A node whose declared type is `unknown` (the generator's own marker
// for a response the DSL leaves untyped) asserts nothing and is reported by
// the caller as untyped rather than as a pass.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { ensureHarnessNodeEnv, runCommand } from './node_env.mjs';

const TSC_TIMEOUT_MS = 300_000;

/** Emitted once per comparison run; every probe file imports these. */
const PRELUDE_SOURCE = `// Generated by the wire-shape round-trip gate. Not part of any package.
export type KindOf<T> = unknown extends T
  ? "unknown"
  : [T] extends [readonly unknown[]]
    ? "array"
    : [T] extends [string]
      ? "string"
      : [T] extends [number]
        ? "number"
        : [T] extends [boolean]
          ? "boolean"
          : "object";
export type RequiredKeysOf<T> = unknown extends T
  ? never
  : { [K in keyof T]-?: {} extends Pick<T, K> ? never : K }[keyof T];
export type KeysOf<T> = unknown extends T ? PropertyKey : keyof T;
export type ElementOf<T> = unknown extends T
  ? unknown
  : T extends readonly (infer E)[]
    ? E
    : unknown;
// A generic parameter is what makes the indexed access below legal: TypeScript
// narrows K to keyof T inside the true branch only when K is a type parameter.
//
// The inner \`unknown extends T[K]\` guard is load-bearing: \`NonNullable<unknown>\`
// is \`{}\`, NOT \`unknown\`. Without it, descending into a field the generator
// deliberately typed \`unknown\` (its marker for a DSL \`JSON\` value) collapsed
// that field to \`{}\`, whose \`keyof\` is \`never\` -- so every key inside a
// perfectly-correct \`pagination: unknown\` was reported as an undeclared
// property. The whole point of \`unknown\` is that it constrains nothing, and
// every other helper here already honours that; this was the one place the
// marker was silently destroyed on the way down.
export type PropOf<T, K extends PropertyKey> = K extends keyof T
  ? unknown extends T[K]
    ? unknown
    : NonNullable<T[K]>
  : unknown;
export type AssertNever<T extends never> = T;
// Expect<> is what turns a failed comparison into a diagnostic. A comparison
// that fails resolves to an object type carrying both sides, and the
// constraint violation reports it verbatim.
export type Expect<T extends true> = T;
export type KindMatches<Actual extends string, T> = KindOf<T> extends "unknown"
  ? true
  : Actual extends KindOf<T>
    ? true
    : { wireShapeValueKindMismatch: [Actual, KindOf<T>] };
// \`void\` accepts a JSON \`null\` body. That is not a relaxation of the shape
// check: \`void\` is the client type the generator emits for a DSL \`-> Void\`
// endpoint, i.e. the declaration that there is no body to read, and a backend
// answering such a route with a \`null\` body is that same statement on the
// wire. No consumer dereferences it. Reporting it as a mismatch failed two
// correct routes (logout, forgot-password) and would have kept this gate red
// no matter what the generator emitted, since \`void\` is the only honest
// TypeScript type for "no value" and \`null extends void\` is false.
export type NullAllowed<T> = unknown extends T
  ? true
  : [T] extends [void]
    ? true
    : null extends T
      ? true
      : { wireShapeNullNotAllowed: KindOf<T> };
`;

const PRELUDE_FILENAME = '__wire_shape_prelude.ts';

const TSCONFIG = {
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    strict: true,
    skipLibCheck: true,
    noEmit: true,
    forceConsistentCasingInFileNames: true,
  },
  include: ['probes/**/*.ts'],
};

/**
 * @typedef {object} ShapeCase
 * @property {string} caseId Stable identifier the caller uses to match results.
 * @property {string} typeExpression The declared type, with every named type
 *   written as `@{N}.Name` over the Nth entry of `typeFiles`. The placeholder
 *   exists because only this module knows where the probes it writes will
 *   live, and therefore how to reach a contract file from one.
 * @property {string[]} typeFiles Absolute paths of the `.ts` files those
 *   placeholders refer to.
 * @property {unknown} value The payload to compare against that type.
 */

/**
 * @typedef {object} ShapeResult
 * @property {string} caseId
 * @property {boolean} parsedOk
 * @property {string} detail
 */

/** Escape a value as a TypeScript string literal. */
function tsString(value) {
  return JSON.stringify(String(value));
}

/** Turn an absolute `.ts` path into an extensionless module specifier relative to `fromDir`. */
function moduleSpecifier(fromDir, typeFile) {
  const withoutExtension = typeFile.replace(/\.ts$/u, '');
  let relative = path.relative(fromDir, withoutExtension).split(path.sep).join('/');
  if (!relative.startsWith('.')) {
    relative = `./${relative}`;
  }
  return relative;
}

function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Emit the type-level assertions for one payload node and everything under it.
 *
 * Every emitted assertion occupies exactly one line, and every line is
 * recorded against the JSON path it asserts about, so a compiler diagnostic
 * can be reported as "which property, where" instead of as compiler noise.
 *
 * @param {object} state Accumulator: `{lines, lineMap, nextId}`.
 * @param {string} typeExpr TypeScript expression naming the declared type of this node.
 * @param {unknown} value The payload node.
 * @param {string} jsonPath Human-readable path of this node inside the payload.
 */
function emitAssertions(state, typeExpr, value, jsonPath) {
  const id = state.nextId++;
  const alias = `W${id}`;
  push(state, `type ${alias} = ${typeExpr};`, null);

  if (value === null) {
    push(state, `type N${id} = Expect<NullAllowed<${alias}>>;`, {
      jsonPath,
      kind: 'null-not-allowed',
    });
    return;
  }
  if (Array.isArray(value)) {
    push(state, `type K${id} = Expect<KindMatches<"array", ${alias}>>;`, {
      jsonPath,
      kind: 'value-kind',
    });
    value.forEach((element, index) => {
      emitAssertions(state, `ElementOf<${alias}>`, element, `${jsonPath}[${index}]`);
    });
    return;
  }
  if (isPlainObject(value)) {
    push(state, `type K${id} = Expect<KindMatches<"object", ${alias}>>;`, {
      jsonPath,
      kind: 'value-kind',
    });
    const keys = Object.keys(value);
    const actualKeys = keys.length === 0 ? 'never' : keys.map(tsString).join(' | ');
    push(state, `type M${id} = AssertNever<Exclude<RequiredKeysOf<${alias}>, ${actualKeys}>>;`, {
      jsonPath,
      kind: 'missing-required-property',
    });
    push(state, `type U${id} = AssertNever<Exclude<${actualKeys}, KeysOf<${alias}>>>;`, {
      jsonPath,
      kind: 'undeclared-property',
    });
    for (const key of keys) {
      emitAssertions(
        state,
        `PropOf<${alias}, ${tsString(key)}>`,
        value[key],
        `${jsonPath}.${key}`,
      );
    }
    return;
  }
  const kind = typeof value;
  if (kind !== 'string' && kind !== 'number' && kind !== 'boolean') {
    push(state, `type K${id} = Expect<KindMatches<"object", ${alias}>>;`, {
      jsonPath,
      kind: 'value-kind',
    });
    return;
  }
  push(state, `type K${id} = Expect<KindMatches<${tsString(kind)}, ${alias}>>;`, {
    jsonPath,
    kind: 'value-kind',
  });
}

function push(state, line, mapping) {
  state.lines.push(line);
  if (mapping !== null) {
    state.lineMap.set(state.lines.length, mapping);
  }
}

/**
 * Build the probe source for one case.
 *
 * @param {string} probesDir
 * @param {ShapeCase} shapeCase
 * @returns {{fileName: string, source: string, lineMap: Map<number, {jsonPath: string, kind: string}>}}
 */
function buildProbe(probesDir, shapeCase, index) {
  const preludeSpecifier = moduleSpecifier(probesDir, path.join(probesDir, PRELUDE_FILENAME));
  const state = { lines: [], lineMap: new Map(), nextId: 0 };
  push(
    state,
    `import type { AssertNever, ElementOf, Expect, KeysOf, KindMatches, NullAllowed, PropOf, RequiredKeysOf } from ${tsString(preludeSpecifier)};`,
    null,
  );
  const declared = shapeCase.typeExpression.replace(TYPE_PLACEHOLDER_RE, (_match, index) => {
    const typeFile = shapeCase.typeFiles[Number(index)];
    if (typeFile === undefined) {
      throw new Error(
        `Case ${shapeCase.caseId} references type file @{${index}} but supplied only ` +
          `${shapeCase.typeFiles.length}.`,
      );
    }
    return `import(${tsString(moduleSpecifier(probesDir, typeFile))})`;
  });
  emitAssertions(state, declared, shapeCase.value, '$');
  return {
    fileName: `probe_${index}.ts`,
    source: `${state.lines.join('\n')}\n`,
    lineMap: state.lineMap,
  };
}

const TYPE_PLACEHOLDER_RE = /@\{(\d+)\}/gu;

const DIAGNOSTIC_RE = /^(.*?)\((\d+),(\d+)\): (error|warning) (TS\d+): (.*)$/u;

/**
 * Compare every case's payload against its declared generated type.
 *
 * @param {object} job
 * @param {string} job.workDir Scratch directory the probes are written into.
 * @param {string} job.nodeDir Directory holding the pinned harness toolchain.
 * @param {ShapeCase[]} job.cases
 * @returns {Promise<{results: ShapeResult[], compilerOutput: string}>}
 */
export async function compareResponseShapes(job) {
  const { workDir, nodeDir, cases } = job;
  const env = await ensureHarnessNodeEnv(nodeDir);
  const probesDir = path.join(workDir, 'probes');
  await rm(probesDir, { recursive: true, force: true });
  await mkdir(probesDir, { recursive: true });
  await writeFile(path.join(probesDir, PRELUDE_FILENAME), PRELUDE_SOURCE, 'utf8');
  await writeFile(
    path.join(workDir, 'tsconfig.json'),
    `${JSON.stringify(TSCONFIG, null, 2)}\n`,
    'utf8',
  );

  /** @type {Map<string, {caseId: string, lineMap: Map<number, {jsonPath: string, kind: string}>}>} */
  const byProbeFile = new Map();
  for (const [index, shapeCase] of cases.entries()) {
    const probe = buildProbe(probesDir, shapeCase, index);
    const absolute = path.join(probesDir, probe.fileName);
    await writeFile(absolute, probe.source, 'utf8');
    byProbeFile.set(path.resolve(absolute), {
      caseId: shapeCase.caseId,
      lineMap: probe.lineMap,
    });
  }

  const compiled = await runCommand(
    process.execPath,
    [env.tscJs, '--noEmit', '--pretty', 'false', '-p', path.join(workDir, 'tsconfig.json')],
    workDir,
    TSC_TIMEOUT_MS,
  );
  const compilerOutput = `${compiled.stdout}${compiled.stderr}`;

  /** @type {Map<string, string[]>} */
  const failures = new Map();
  const outsideProbes = [];
  for (const rawLine of compilerOutput.split(/\r?\n/u)) {
    const match = DIAGNOSTIC_RE.exec(rawLine.trim());
    if (match === null || match[4] !== 'error') {
      continue;
    }
    const [, file, lineText, , , code, message] = match;
    const resolved = path.resolve(workDir, file);
    const probe = byProbeFile.get(resolved);
    if (probe === undefined) {
      outsideProbes.push(`${file}: ${code}: ${message}`);
      continue;
    }
    const mapping = probe.lineMap.get(Number(lineText));
    const where =
      mapping === undefined
        ? `${code}: ${message}`
        : `${mapping.kind} at ${mapping.jsonPath} (${code}: ${message})`;
    const existing = failures.get(probe.caseId);
    if (existing === undefined) {
      failures.set(probe.caseId, [where]);
    } else {
      existing.push(where);
    }
  }

  const contractProblem =
    outsideProbes.length === 0
      ? ''
      : `the generated contract sources did not compile: ${outsideProbes.join('; ')}`;

  const results = cases.map((shapeCase) => {
    const reasons = failures.get(shapeCase.caseId) ?? [];
    const all = contractProblem === '' ? reasons : [contractProblem, ...reasons];
    return {
      caseId: shapeCase.caseId,
      parsedOk: all.length === 0,
      detail: all.join('; '),
    };
  });
  return { results, compilerOutput };
}

/**
 * CLI entry point: `node shape_comparator.mjs --job <job.json> --out <results.json>`.
 *
 * The gate's non-vacuity self-test drives the comparator through this entry
 * point, so it exercises the exported function above rather than a copy.
 */
async function main(argv) {
  let jobPath = '';
  let outPath = '';
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--job') {
      jobPath = argv[index + 1];
      index += 1;
    } else if (argv[index] === '--out') {
      outPath = argv[index + 1];
      index += 1;
    }
  }
  if (jobPath === '' || outPath === '') {
    process.stderr.write(
      'usage: node shape_comparator.mjs --job <job.json> --out <results.json>\n',
    );
    return 2;
  }
  const job = JSON.parse(await readFile(jobPath, 'utf8'));
  const outcome = await compareResponseShapes(job);
  await writeFile(outPath, `${JSON.stringify(outcome, null, 2)}\n`, 'utf8');
  return 0;
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1].replace(/\\/g, '/')}`).href) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
      process.exitCode = 1;
    },
  );
}
