// The wire-shape round-trip harness: run the generated client against a live
// backend and compare every response against the generated interface.
//
// The client classes are executed AS SHIPPED. The emitted TypeScript is
// compiled with the real `tsc` and loaded into a real Angular injector with a
// real `HttpClient` over `fetch`, so the request each method issues -- its
// URL, its percent-encoded path segments, its query-parameter wire names, its
// body encoding -- is produced by the generated code itself and never by a
// re-implementation of what that code is believed to do.
//
// Every response is then handed to the SHARED comparator in
// `shape_comparator.mjs` -- the same function the gate's non-vacuity
// self-test drives.

import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { register } from 'node:module';
import { pathToFileURL } from 'node:url';

import { ensureHarnessNodeEnv, runCommand } from './node_env.mjs';
import { compareResponseShapes } from './shape_comparator.mjs';
import {
  loadTypescript,
  readClientClasses,
  readRouteManifest,
  renderResponseTypeExpression,
  synthesizeValue,
} from './client_introspection.mjs';

const TSC_TIMEOUT_MS = 300_000;
const REQUEST_TIMEOUT_MS = 30_000;

// Rate-limit pacing, sized against what the emitted gateway declares.
//
// The generated nginx config declares ONE shared zone keyed on the client
// address -- `limit_req_zone $binary_remote_addr zone=rl_default:10m
// rate=100r/m` -- and every route location draws on it with `burst=10 nodelay`.
// 100r/m is one request every 600 ms. Issuing the whole route manifest as fast
// as the harness can therefore lets the burst plus one through and answers
// every remaining route 429: a run in which almost nothing was checked. The
// emitted limit is correct and is not what gets changed; the harness is paced
// to fit inside it.
//
// 700 ms leaves ~14% headroom over the 600 ms the zone refills at, so ordinary
// jitter cannot overdraw it, and costs about 31 s for a 44-route manifest.
const REQUEST_INTERVAL_MS = 700;
const RATE_LIMIT_STATUS = 429;
// The first attempt plus two retries. A route still rate-limited after two
// honoured waits is reported unexercised with its reason, never silently.
const RATE_LIMIT_MAX_ATTEMPTS = 3;
const RATE_LIMIT_MAX_SINGLE_WAIT_MS = 120_000;
const RATE_LIMIT_WAIT_BUDGET_MS = 300_000;
// `Retry-After` is honoured verbatim when the gateway sends one (the emitted
// config sets it on every rate-limited route). A limiter that answers 429
// without the header still has to be waited out, so one full zone window is
// used instead of guessing shorter and burning an attempt.
const RATE_LIMIT_WAIT_WITHOUT_HEADER_MS = 60_000;
const CLIENT_SUBDIR = 'client';
const BUILD_SUBDIR = 'build';
const SHAPE_SUBDIR = 'shape';
const BRIDGE_FILENAME = 'angular_bridge.mjs';
const ROUTE_MANIFEST_RELATIVE = 'libs/api-contract/src/lib/routes/route-manifest.ts';
const CLIENT_GLOB_DIR = 'libs/api-client/src/lib';
const CLIENT_FILE_SUFFIX = '.client.ts';

const EXEC_TSCONFIG = {
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    experimentalDecorators: true,
    // The emitted tree is meant to compile in a strict Angular workspace, so
    // that is the bar it is held to here; the emit is what the harness then
    // executes.
    strict: true,
    skipLibCheck: true,
    noEmitOnError: false,
    declaration: false,
    sourceMap: false,
    rootDir: CLIENT_SUBDIR,
    outDir: BUILD_SUBDIR,
  },
  include: [`${CLIENT_SUBDIR}/**/*.ts`],
};

const BRIDGE_SOURCE = `// Generated by the wire-shape round-trip gate. Re-exports the pinned Angular
// runtime from the directory that owns its node_modules, so the harness and
// the compiled client resolve the identical module instances.
import '@angular/compiler';
export * as core from '@angular/core';
export * as commonHttp from '@angular/common/http';
export * as rxjs from 'rxjs';
`;

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token.startsWith('--')) {
      parsed[token.slice(2)] = argv[index + 1];
      index += 1;
    }
  }
  for (const required of ['client-root', 'base-url', 'node-dir', 'auth-token-file', 'out']) {
    if (parsed[required] === undefined) {
      throw new Error(
        `Missing required argument --${required}. Usage: node run.mjs --client-root <dir> ` +
          `--base-url <url> --node-dir <dir> --auth-token-file <file> --out <results.json>`,
      );
    }
  }
  return parsed;
}

async function listClientFiles(clientDir) {
  const dir = path.join(clientDir, ...CLIENT_GLOB_DIR.split('/'));
  const names = await readdir(dir);
  return names
    .filter((name) => name.endsWith(CLIENT_FILE_SUFFIX))
    .sort()
    .map((name) => path.join(dir, name));
}

/** Compile the copied client tree, returning the compiler's own diagnostics. */
async function compileClient(env, nodeDir) {
  await writeFile(
    path.join(nodeDir, 'tsconfig.exec.json'),
    `${JSON.stringify(EXEC_TSCONFIG, null, 2)}\n`,
    'utf8',
  );
  const compiled = await runCommand(
    process.execPath,
    [env.tscJs, '--pretty', 'false', '-p', path.join(nodeDir, 'tsconfig.exec.json')],
    nodeDir,
    TSC_TIMEOUT_MS,
  );
  const output = `${compiled.stdout}${compiled.stderr}`.trim();
  return {
    ok: compiled.code === 0,
    diagnostics: output === '' ? [] : output.split(/\r?\n/u).filter((line) => line.trim() !== ''),
  };
}

/** Identify the injection token each client class reads its base URL from. */
function baseUrlTokenOf(ts, ngClass, sourceText) {
  const angularModules = new Set(['@angular/core', '@angular/common/http']);
  const source = ts.createSourceFile(
    ngClass.file,
    sourceText,
    ts.ScriptTarget.ES2022,
    true,
    ts.ScriptKind.TS,
  );
  const origins = new Map();
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement) || statement.importClause === undefined) {
      continue;
    }
    const bindings = statement.importClause.namedBindings;
    if (bindings === undefined || !ts.isNamedImports(bindings)) {
      continue;
    }
    for (const element of bindings.elements) {
      origins.set(element.name.text, statement.moduleSpecifier.text);
    }
  }
  let found = null;
  const visit = (node) => {
    if (found !== null) {
      return;
    }
    if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      node.expression.text === 'inject' &&
      node.arguments.length === 1 &&
      ts.isIdentifier(node.arguments[0])
    ) {
      const name = node.arguments[0].text;
      const origin = origins.get(name);
      if (origin !== undefined && !angularModules.has(origin)) {
        found = { name, moduleSpecifier: origin };
        return;
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (found === null) {
    throw new Error(
      `No base-URL injection token found in ${ngClass.file}. Expected the generated client to ` +
        `read its base URL through an injected token declared in its own tree.`,
    );
  }
  return found;
}

/** Load a compiled module out of the build tree by its source path. */
async function importCompiled(nodeDir, sourceFile, clientDir) {
  const relative = path.relative(clientDir, sourceFile).replace(/\.ts$/u, '.js');
  const compiled = path.join(nodeDir, BUILD_SUBDIR, relative);
  return import(pathToFileURL(compiled).href);
}

function withTimeout(promise, label) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      reject(new Error(`${label} did not complete within ${REQUEST_TIMEOUT_MS} ms`));
    }, REQUEST_TIMEOUT_MS);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      },
    );
  });
}

function sleep(milliseconds) {
  return new Promise((resolve) => {
    setTimeout(resolve, milliseconds);
  });
}

/**
 * Serialise requests at the rate the emitted gateway declares.
 *
 * Every route shares one address-keyed zone, so the pacing is run-wide rather
 * than per route: one pacer for the whole manifest.
 */
function createRequestPacer(intervalMs) {
  let nextAllowedAt = 0;
  return async function pace() {
    const now = Date.now();
    if (now < nextAllowedAt) {
      await sleep(nextAllowedAt - now);
    }
    nextAllowedAt = Date.now() + intervalMs;
  };
}

/** A run-wide ceiling on time spent waiting out rate limits. */
function createWaitBudget(totalMs) {
  let remaining = totalMs;
  return {
    spend(milliseconds) {
      if (milliseconds > remaining) {
        return false;
      }
      remaining -= milliseconds;
      return true;
    },
    remaining() {
      return remaining;
    },
  };
}

/**
 * Read the gateway's own `Retry-After` from a rejected response.
 *
 * The emitted config sends it as a whole number of seconds. The header also
 * permits an HTTP date; a value that is not a plain integer is reported as
 * absent so the caller waits a full zone window rather than acting on a
 * misparse.
 */
function retryAfterMs(error) {
  const headers = error?.headers;
  const raw = typeof headers?.get === 'function' ? headers.get('Retry-After') : null;
  if (raw === null || raw === undefined) {
    return null;
  }
  const seconds = Number(String(raw).trim());
  return Number.isInteger(seconds) && seconds >= 0 ? seconds * 1000 : null;
}

function errorMessageOf(error) {
  // An Angular HttpErrorResponse is not an Error subclass, so read its own
  // message before falling back to the generic stringification.
  if (typeof error?.message === 'string') {
    return error.message;
  }
  return error instanceof Error ? error.message : String(error);
}

/**
 * Call one generated method, waiting out the gateway's rate limit if it fires.
 *
 * Returns `{ body, httpStatus, detail }`. `detail` is empty exactly when the
 * call produced a success body; a route the limiter kept rejecting until the
 * retry budget ran out says so in `detail` rather than being reported as an
 * ordinary transport failure.
 */
async function invokeWithRateLimitBudget(invoke, label, pace, budget) {
  const waits = [];
  for (let attempt = 1; ; attempt += 1) {
    await pace();
    try {
      return { body: await withTimeout(invoke(), label), httpStatus: 200, detail: '' };
    } catch (error) {
      const httpStatus = typeof error?.status === 'number' ? error.status : 0;
      const message = errorMessageOf(error);
      const waited = waits.length === 0 ? '' : ` (after honouring Retry-After ${waits.join(', ')} ms)`;
      if (httpStatus !== RATE_LIMIT_STATUS) {
        return {
          body: undefined,
          httpStatus,
          detail:
            httpStatus === 0
              ? `the request did not complete${waited}: ${message}`
              : `the backend answered ${httpStatus}, so no typed success body was ` +
                `returned${waited}: ${message}`,
        };
      }
      const announced = retryAfterMs(error);
      const wait = Math.min(
        announced === null ? RATE_LIMIT_WAIT_WITHOUT_HEADER_MS : announced,
        RATE_LIMIT_MAX_SINGLE_WAIT_MS,
      );
      if (attempt >= RATE_LIMIT_MAX_ATTEMPTS) {
        return {
          body: undefined,
          httpStatus,
          detail:
            `the gateway rate-limited this route on all ${RATE_LIMIT_MAX_ATTEMPTS} attempts` +
            `${waited}, so no typed success body was returned: ${message}`,
        };
      }
      if (!budget.spend(wait)) {
        return {
          body: undefined,
          httpStatus,
          detail:
            `the gateway asked for a ${wait} ms wait but the run-wide rate-limit retry budget ` +
            `has ${budget.remaining()} ms left${waited}, so no typed success body was ` +
            `returned: ${message}`,
        };
      }
      waits.push(wait);
      await sleep(wait);
    }
  }
}

/** Build the argument object one generated method is called with. */
async function buildArguments(ts, method) {
  const args = {};
  const unsupported = [];
  for (const member of method.argsMembers) {
    const synthesized = await synthesizeValue(
      ts,
      member.typeNode,
      method.sourceFile,
      method.importOrigins,
    );
    if (!synthesized.ok) {
      unsupported.push(`${member.name}: ${synthesized.reason}`);
      continue;
    }
    args[member.name] = synthesized.value;
  }
  return { args, unsupported };
}

function routeSignature(httpVerb, routePath) {
  return `${httpVerb.toLowerCase()} ${routePath}`;
}

async function main(argv) {
  const parsed = parseArgs(argv);
  const clientRoot = path.resolve(parsed['client-root']);
  const nodeDir = path.resolve(parsed['node-dir']);
  const baseUrl = parsed['base-url'];
  const outPath = path.resolve(parsed.out);

  // The bearer token arrives in a file rather than on the command line: a
  // credential in an argument vector is readable from the host's process list.
  // It is signed by the gate with the stack's OWN provisioned private key, so
  // the emitted gateway and the emitted services verify it exactly as they
  // verify any other caller's -- no auth check is bypassed, stubbed or relaxed
  // anywhere in this harness. An absent or empty token fails loud: calling the
  // routes unauthenticated instead would report every authenticated route as
  // unexercised and check nothing.
  const authToken = (await readFile(path.resolve(parsed['auth-token-file']), 'utf8')).trim();
  if (authToken === '') {
    throw new Error(
      `The bearer token file ${parsed['auth-token-file']} is empty. Expected the gate to have ` +
        `written a token signed with the stack's provisioned private key before starting the ` +
        `harness; without one every authenticated route answers 401 and nothing is compared.`,
    );
  }

  const env = await ensureHarnessNodeEnv(nodeDir);
  const ts = await loadTypescript(env);

  const clientDir = path.join(nodeDir, CLIENT_SUBDIR);
  await rm(clientDir, { recursive: true, force: true });
  await rm(path.join(nodeDir, BUILD_SUBDIR), { recursive: true, force: true });
  await cp(clientRoot, clientDir, { recursive: true });

  const compileOutcome = await compileClient(env, nodeDir);

  const manifest = await readRouteManifest(
    ts,
    path.join(clientDir, ...ROUTE_MANIFEST_RELATIVE.split('/')),
  );
  const clientFiles = await listClientFiles(clientDir);
  const classes = await readClientClasses(ts, clientFiles);

  // A method name declared twice in one class is not two methods at runtime:
  // the later declaration wins and the earlier one is unreachable. Record it
  // instead of quietly reporting the surviving one twice.
  const shadowed = new Set();
  for (const ngClass of classes) {
    const lastIndexByName = new Map();
    ngClass.methods.forEach((method, index) => lastIndexByName.set(method.name, index));
    ngClass.methods.forEach((method, index) => {
      if (lastIndexByName.get(method.name) !== index) {
        shadowed.add(`${ngClass.className}.${method.name}#${index}`);
      }
    });
  }

  /** Map every (verb, path) to the class/method that serves it. */
  const bySignature = new Map();
  const emittedMethods = [];
  for (const ngClass of classes) {
    ngClass.methods.forEach((method, index) => {
      const signature = routeSignature(method.httpVerb, method.routePath);
      const record = {
        ngClass,
        method,
        index,
        shadowed: shadowed.has(`${ngClass.className}.${method.name}#${index}`),
      };
      emittedMethods.push(record);
      const existing = bySignature.get(signature);
      if (existing === undefined) {
        bySignature.set(signature, [record]);
      } else {
        existing.push(record);
      }
    });
  }

  await writeFile(path.join(nodeDir, BRIDGE_FILENAME), BRIDGE_SOURCE, 'utf8');
  register(new URL('./esm_extension_resolver.mjs', import.meta.url));
  const bridge = await import(pathToFileURL(path.join(nodeDir, BRIDGE_FILENAME)).href);
  const { core, commonHttp, rxjs } = bridge;

  // The Authorization header is attached by a real Angular interceptor rather
  // than by editing the generated client: the emitted classes stay exactly as
  // shipped, and the request each one issues is still built entirely by
  // generated code.
  const bearerInterceptor = (request, next) =>
    next(request.clone({ setHeaders: { Authorization: `Bearer ${authToken}` } }));

  const providers = [
    { provide: core.ɵINJECTOR_SCOPE, useValue: 'root' },
    core.provideZonelessChangeDetection(),
    commonHttp.provideHttpClient(
      commonHttp.withFetch(),
      commonHttp.withInterceptors([bearerInterceptor]),
    ),
  ];
  const instances = new Map();
  for (const ngClass of classes) {
    const sourceText = await readFile(ngClass.file, 'utf8');
    const token = baseUrlTokenOf(ts, ngClass, sourceText);
    const tokenSourceFile = path.resolve(path.dirname(ngClass.file), `${token.moduleSpecifier}.ts`);
    const tokenModule = await importCompiled(nodeDir, tokenSourceFile, clientDir);
    const tokenValue = tokenModule[token.name];
    if (tokenValue === undefined) {
      throw new Error(
        `The compiled base-URL token module for ${ngClass.className} exports no ` +
          `'${token.name}'. Expected the generated token to be exported under that name.`,
      );
    }
    const classModule = await importCompiled(nodeDir, ngClass.file, clientDir);
    const constructor = classModule[ngClass.className];
    if (constructor === undefined) {
      throw new Error(
        `The compiled module for ${ngClass.file} exports no '${ngClass.className}'.`,
      );
    }
    providers.push({ provide: tokenValue, useValue: baseUrl });
    instances.set(ngClass.className, { constructor });
  }
  const parentInjector = core.Injector.create({ providers: [] });
  const injector = core.createEnvironmentInjector(
    [...providers, ...[...instances.values()].map((entry) => entry.constructor)],
    parentInjector,
  );

  /** @type {Array<object>} */
  const rows = [];
  /** @type {Array<{caseId: string, typeFile: string, typeName: string, value: unknown}>} */
  const shapeCases = [];

  const pace = createRequestPacer(REQUEST_INTERVAL_MS);
  const rateLimitBudget = createWaitBudget(RATE_LIMIT_WAIT_BUDGET_MS);

  for (const route of manifest) {
    const signature = routeSignature(route.method, route.path);
    const candidates = (bySignature.get(signature) ?? []).filter((entry) => !entry.shadowed);
    if (candidates.length === 0) {
      const collided = (bySignature.get(signature) ?? []).map(
        (entry) => `${entry.ngClass.className}.${entry.method.name}`,
      );
      rows.push({
        routeKey: route.routeKey,
        route: signature,
        clientClass: '',
        methodName: '',
        invoked: false,
        outcome: 'no-reachable-method',
        parsedOk: false,
        detail:
          collided.length === 0
            ? 'no generated client method issues this route'
            : `the only generated method for this route (${collided.join(', ')}) is shadowed by a ` +
              `later declaration of the same name in its own class, so it is unreachable at runtime`,
      });
      continue;
    }
    const chosen = candidates[0];
    const instance = injector.get(instances.get(chosen.ngClass.className).constructor);
    const { args, unsupported } = await buildArguments(ts, chosen.method);
    if (unsupported.length > 0) {
      rows.push({
        routeKey: route.routeKey,
        route: signature,
        clientClass: chosen.ngClass.className,
        methodName: chosen.method.name,
        invoked: false,
        outcome: 'argument-not-constructible',
        parsedOk: false,
        detail: `no value could be constructed for ${unsupported.join('; ')}`,
      });
      continue;
    }

    const {
      body,
      httpStatus,
      detail: transportDetail,
    } = await invokeWithRateLimitBudget(
      () => rxjs.firstValueFrom(instance[chosen.method.name](args)),
      `${chosen.ngClass.className}.${chosen.method.name}`,
      pace,
      rateLimitBudget,
    );

    if (transportDetail !== '') {
      rows.push({
        routeKey: route.routeKey,
        route: signature,
        clientClass: chosen.ngClass.className,
        methodName: chosen.method.name,
        invoked: true,
        httpStatus,
        outcome: 'unexercised',
        parsedOk: false,
        detail: transportDetail,
      });
      continue;
    }

    const declared = renderResponseTypeExpression(ts, chosen.method);
    if (declared.kind === 'untyped') {
      rows.push({
        routeKey: route.routeKey,
        route: signature,
        clientClass: chosen.ngClass.className,
        methodName: chosen.method.name,
        invoked: true,
        httpStatus,
        outcome: 'untyped',
        parsedOk: false,
        detail: 'the generated method declares Observable<unknown>, so nothing constrains its body',
      });
      continue;
    }
    if (declared.kind === 'unresolved') {
      rows.push({
        routeKey: route.routeKey,
        route: signature,
        clientClass: chosen.ngClass.className,
        methodName: chosen.method.name,
        invoked: true,
        httpStatus,
        outcome: 'response-type-unresolved',
        parsedOk: false,
        detail: declared.reason,
      });
      continue;
    }
    const caseId = `${route.routeKey}|${signature}`;
    shapeCases.push({
      caseId,
      typeExpression: declared.expression,
      typeFiles: declared.typeFiles,
      value: body,
    });
    rows.push({
      routeKey: route.routeKey,
      route: signature,
      clientClass: chosen.ngClass.className,
      methodName: chosen.method.name,
      invoked: true,
      httpStatus,
      outcome: 'pending-shape-check',
      parsedOk: false,
      detail: '',
      caseId,
      responseType: declared.expression,
    });
  }

  let comparison = { results: [], compilerOutput: '' };
  if (shapeCases.length > 0) {
    comparison = await compareResponseShapes({
      workDir: path.join(nodeDir, SHAPE_SUBDIR),
      nodeDir,
      cases: shapeCases,
    });
  }
  const byCase = new Map(comparison.results.map((result) => [result.caseId, result]));
  for (const row of rows) {
    if (row.outcome !== 'pending-shape-check') {
      continue;
    }
    const result = byCase.get(row.caseId);
    if (result === undefined) {
      row.outcome = 'comparator-missing-result';
      row.detail = `the shared comparator returned no result for case ${row.caseId}`;
      continue;
    }
    row.parsedOk = result.parsedOk;
    row.outcome = result.parsedOk ? 'parsed' : 'mismatch';
    row.detail = result.detail;
  }

  const routedSignatures = new Set(manifest.map((route) => routeSignature(route.method, route.path)));
  const unroutedMethods = emittedMethods
    .filter((entry) => !routedSignatures.has(routeSignature(entry.method.httpVerb, entry.method.routePath)))
    .map((entry) => `${entry.ngClass.className}.${entry.method.name}`);

  await mkdir(path.dirname(outPath), { recursive: true });
  await writeFile(
    outPath,
    `${JSON.stringify(
      {
        baseUrl,
        clientCompileOk: compileOutcome.ok,
        clientCompileDiagnostics: compileOutcome.diagnostics,
        emittedMethodCount: emittedMethods.length,
        manifestRouteCount: manifest.length,
        unroutedMethods,
        introspectionFailures: classes.flatMap((ngClass) => ngClass.introspectionFailures),
        rows,
        comparatorOutput: comparison.compilerOutput,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  return 0;
}

main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (error) => {
    process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
    process.exitCode = 1;
  },
);
