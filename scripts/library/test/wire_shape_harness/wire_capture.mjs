// Wire capture for the wire-shape round-trip harness.
//
// The harness calls every generated client method once per route. The typed
// method hands back only the parsed body, but the cross-language comparison
// needs what the backend put ON THE WIRE: its status, its content type, and
// the shape of its body. An Angular HTTP interceptor sees all three on the one
// request the generated method already issues, so capturing there costs no
// second call -- the request is still made by generated code, still paced by
// the harness's own request pacer, still carrying the same bearer token.
//
// A captured body is reduced to its value-free shape (`describeWireShape`)
// inside the interceptor and the value is dropped on the spot. Nothing a
// backend returned -- a token, an identifier, a personal datum -- is held past
// that call, written to the results file, or available to any later log line.

import { writeFile } from 'node:fs/promises';
import { register } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { describeWireShape } from './shape_comparator.mjs';

const BRIDGE_FILENAME = 'angular_bridge.mjs';

const BRIDGE_SOURCE = `// Generated by the wire-shape round-trip gate. Re-exports the pinned Angular
// runtime from the directory that owns its node_modules, so the harness and
// the compiled client resolve the identical module instances.
import '@angular/compiler';
export * as core from '@angular/core';
export * as commonHttp from '@angular/common/http';
export * as rxjs from 'rxjs';
`;

/**
 * Load the pinned Angular runtime from the harness toolchain directory.
 *
 * Everything that touches Angular (the live harness, the generated client
 * classes it compiles, the capture self-test) must resolve the SAME module
 * instances, or an `instanceof HttpResponse` check across two copies of the
 * package silently fails. Re-exporting from the directory that owns
 * `node_modules` is what guarantees one copy.
 *
 * @param {string} nodeDir Directory holding the harness `node_modules`.
 * @returns {Promise<{core: object, commonHttp: object, rxjs: object}>}
 */
export async function loadAngularRuntime(nodeDir) {
  await writeFile(path.join(nodeDir, BRIDGE_FILENAME), BRIDGE_SOURCE, 'utf8');
  register(new URL('./esm_extension_resolver.mjs', import.meta.url));
  const bridge = await import(pathToFileURL(path.join(nodeDir, BRIDGE_FILENAME)).href);
  return { core: bridge.core, commonHttp: bridge.commonHttp, rxjs: bridge.rxjs };
}

/**
 * @typedef {object} WireCapture
 * @property {number} status The HTTP status of the response that arrived.
 * @property {string} contentType Its `Content-Type` header, empty when absent.
 * @property {object} shape The value-free shape of its body.
 */

/**
 * Build the recorder the harness installs as an HTTP interceptor.
 *
 * Call `begin()` immediately before issuing one request and read `captured`
 * from the handle it returns once that request has settled. The interceptor
 * binds to the attempt that was current when the request was subscribed, so a
 * response arriving late for an attempt the harness already gave up on writes
 * into THAT attempt's handle, never into the next attempt's.
 *
 * @param {object} commonHttp The Angular `@angular/common/http` namespace.
 * @param {object} rxjs The `rxjs` namespace the same Angular runtime uses.
 * @returns {{interceptor: Function, begin: () => {captured: WireCapture | null}}}
 */
export function createWireRecorder(commonHttp, rxjs) {
  let current = { captured: null };
  const capture = (attempt, status, headers, body) => {
    attempt.captured = {
      status,
      contentType: headers?.get('content-type') ?? '',
      shape: describeWireShape(body),
    };
  };
  const interceptor = (request, next) => {
    const attempt = current;
    return next(request).pipe(
      rxjs.tap({
        next: (event) => {
          if (event instanceof commonHttp.HttpResponse) {
            capture(attempt, event.status, event.headers, event.body);
          }
        },
        error: (error) => {
          if (error instanceof commonHttp.HttpErrorResponse) {
            capture(attempt, error.status, error.headers, error.error);
          }
        },
      }),
    );
  };
  return {
    interceptor,
    begin() {
      current = { captured: null };
      return current;
    },
  };
}

/**
 * The providers that give the harness a real Angular `HttpClient` over `fetch`.
 *
 * One definition, used by the live harness and by the capture self-test, so the
 * self-test exercises the wiring the live run uses rather than a copy of it.
 *
 * @param {object} core The `@angular/core` namespace.
 * @param {object} commonHttp The `@angular/common/http` namespace.
 * @param {Function[]} interceptors Functional interceptors, outermost first.
 */
export function createHttpClientProviders(core, commonHttp, interceptors) {
  return [
    { provide: core.ɵINJECTOR_SCOPE, useValue: 'root' },
    core.provideZonelessChangeDetection(),
    commonHttp.provideHttpClient(
      commonHttp.withFetch(),
      commonHttp.withInterceptors(interceptors),
    ),
  ];
}
